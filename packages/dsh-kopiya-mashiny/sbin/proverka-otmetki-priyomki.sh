#!/bin/bash
# Сторож ОТМЕТКИ ПРИЁМКИ: отвечает на вопрос «проверяли ли копию вообще»,
# и НЕ отвечает на вопрос «годна ли копия». Завела Искра 25.08.2026 по образцу
# соседней фермы (долг 29/34), но с иным разделением — см. ниже.
#
# 🔴 ЗАЧЕМ ОТДЕЛЬНО ОТ ПРИЁМКИ. «Копия негодна» и «проверка не состоялась» — разные
# новости, и подавать вторую как первую нельзя. Приёмка отвечает за первую и говорит
# сама. Здесь — только вторая: жив ли сам обычай проверять.
#
# 🔴 ЧЕМ ЭТОТ СТОРОЖ ОТЛИЧАЕТСЯ ОТ ОБРАЗЦА (там просто возраст отметки).
# У нас приёмка ЕЖЕДНЕВНАЯ и сама тревожит владельца при негодной копии. Если бы
# здесь тревожил один лишь возраст отметки, то при чужом дефекте в копии (сегодня
# это неразмеченная цель подключения соседа) владелец получал бы ДВЕ тревоги об
# одной причине — а вторая ежедневная тревога о том, что чинить не тебе, приучает
# не читать тревоги. Поэтому различаем:
#   отметка стара, а таймер приёмки СРАБАТЫВАЕТ  -> приёмка жива, вердикт её и её тревога -> 0
#   отметка стара, и таймер приёмки НЕ срабатывает -> обычай проверять умер          -> 1
#   отметки нет и таймер ни разу не срабатывал     -> приёмки ещё не было            -> 2
#
# ЧЕГО НЕ ДЕЛАЕТ (границы, чтобы зелёное не прочли шире):
#   • не открывает копию и не судит о её годности — это proverka-kopii.sh;
#   • не проверяет, что отметка ПРАВДИВА: её пишет приёмка, доверие к ней равно
#     доверию к приёмке. Подделать отметку может любой, у кого есть права;
#   • молчит о старых копиях: отметка всегда про последнюю;
#   • собственную смерть не ловит — его зовёт healthcheck записи реестра, а тот
#     ежедневно гоняет сторож реестров. Наблюдатель живёт снаружи наблюдаемого;
#   • не защита от того, у кого есть права.
#
# КОДЫ: 0 — обычай проверять жив | 1 — проверка не состоялась | 2 — не состоялось измерение
set -uo pipefail

OTMETKA="${BACKUP_VERIFY_STATE:-/var/lib/sadik-backup/proverena.json}"
TAJMER="${BACKUP_VERIFY_TIMER:-backup-verify.timer}"
PREDEL_CHASOV="${PREDEL_OTMETKI_CHASOV:-72}"   # приёмка ежедневная; 72 ч = переживаем
                                               # один-два пропуска, но не неделю молчания

# 🔴 Одно свойство за вызов. `systemctl show -p A -p B --value` печатает значения
# НЕ в порядке аргументов (замерено 25.08: LastTrigger и NextElapse вышли наоборот),
# а --value убирает имена — позиционное чтение врёт молча. Спрашиваем по одному.
svojstvo() { systemctl show "$1" -p "$2" --value 2>/dev/null; }

vyhod() { echo "$2"; exit "$1"; }

TRIG=$(svojstvo "$TAJMER" LastTriggerUSec)
[ "$TRIG" = "n/a" ] && TRIG=""

# сколько часов назад срабатывал таймер приёмки
# 🔴 Формат времени systemd от локали НЕ зависит — замерено 25.08: под ru_RU и под C
# одинаково «Tue 2026-08-25 12:12:43 UTC», и date -d его разбирает. Не «чинить» на
# LC_ALL=C: замер сделан, а лишний слой прячет отказ, если формат когда-нибудь сменится.
# Отказ разбора — СЛЕПОТА, а не «таймер не срабатывал»: неразобранное время означает,
# что мы не измерили, а не что предмета нет. Иначе слепота выдаётся за отказ.
TRIG_CH=""
if [ -n "$TRIG" ]; then
  TRIG_SEC=$(date -u -d "$TRIG" '+%s' 2>/dev/null) \
    || vyhod 2 "СЛЕПОТА: время срабатывания «$TRIG» не разбирается — измерить нечем"
  [ -n "$TRIG_SEC" ] || vyhod 2 "СЛЕПОТА: время срабатывания «$TRIG» не разбирается — измерить нечем"
  TRIG_CH=$(( ( $(date -u '+%s') - TRIG_SEC ) / 3600 ))
fi

if [ ! -r "$OTMETKA" ]; then
  if [ -z "$TRIG" ]; then
    vyhod 2 "СЛЕПОТА: отметки нет и таймер $TAJMER ни разу не срабатывал — приёмки ещё не было"
  fi
  if [ -n "$TRIG_CH" ] && [ "$TRIG_CH" -le "$PREDEL_CHASOV" ]; then
    vyhod 0 "приёмка идёт (таймер срабатывал $TRIG_CH ч назад), но копия ни разу не подтверждена — вердикт и тревога у самой приёмки"
  fi
  vyhod 1 "ОТКАЗ: отметки приёмки нет, таймер $TAJMER не срабатывал ${TRIG_CH:-?} ч — проверка не состоялась"
fi

VOZRAST=$(python3 - "$OTMETKA" <<'PY' 2>/dev/null
import json,sys
from datetime import datetime,timezone
d=json.load(open(sys.argv[1]))
t=datetime.fromisoformat(d["proverena_at"])
print(int((datetime.now(timezone.utc)-t).total_seconds()//3600))
PY
)
IMYA=$(python3 -c "import json,sys;print(json.load(open(sys.argv[1]))['name'])" "$OTMETKA" 2>/dev/null)
[ -n "$VOZRAST" ] || vyhod 2 "СЛЕПОТА: отметка $OTMETKA не разбирается"

if [ "$VOZRAST" -le "$PREDEL_CHASOV" ]; then
  vyhod 0 "копия подтверждена $VOZRAST ч назад ($IMYA), предел $PREDEL_CHASOV ч"
fi

if [ -n "$TRIG_CH" ] && [ "$TRIG_CH" -le "$PREDEL_CHASOV" ]; then
  vyhod 0 "приёмка идёт (таймер срабатывал $TRIG_CH ч назад), но копия не подтверждается $VOZRAST ч — вердикт и тревога у самой приёмки"
fi

vyhod 1 "ОТКАЗ: копия не подтверждалась $VOZRAST ч, таймер $TAJMER не срабатывал ${TRIG_CH:-?} ч — проверка не состоялась"
