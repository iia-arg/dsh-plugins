#!/bin/bash
# Приёмка копии ПО РАСПИСАНИЮ: скачать уехавшее обратно и убедиться, что оно
# открывается. Завела Искра 25.08.2026 (долг 34), по требованию главной:
# «копия собрана → скачана обратно → проверена; иначе через месяц никто не вспомнит,
# что копию можно открыть».
#
# 🔴 ПОЧЕМУ ЭТО ЗАВЕДЕНО ТОЛЬКО СЕЙЧАС, А НЕ ВЧЕРА
# Вчера предмета не было: расписание над несуществующим архивом даёт либо ежедневную
# ложную тревогу (через неделю тревоги перестают читать), либо тихий пропуск — то самое
# ложно-зелёное, ради которого приёмка и писалась. Разделителя между «архива законно
# нет» и «архив не собрался» тогда не существовало. Теперь он есть и назван ниже.
#
# ЧТО ПРОВЕРЯЕТСЯ, ИМЕННО В ТАКОМ ПОРЯДКЕ:
#   1. отметка о последней сборке есть?          нет → см. РАЗДЕЛИТЕЛЬ
#   2. она не протухла (PREDEL_CHASOV)?          протухла → сборка встала (1)
#   1б. она от ПОСЛЕДНЕГО запуска сборки?        нет → сборка идёт (2) или упала (1)
#       последний запуск не старше PREDEL_ZAPUSKA_MINUT?  старше → ночь пропущена (1)
#   (2 стоит ДО 1б с B-N-1466: после 1б отметка не старше запуска ≤ 25 ч, и свежесть 30 ч не срабатывала никогда)
#   3. архив скачивается с Drive по её id?       нет → уехавшего нет либо оно недоступно
#   4. скачанное открывается (proverka-kopii.sh) → единственный принимаемый довод
#
# 🔴 РАЗДЕЛИТЕЛЬ «законно нет» / «не собралось»: LastTriggerUSec таймера сборки.
# Таймер ни разу не срабатывал → сборки ещё не было, это СЛЕПОТА (код 2), а не авария.
# Срабатывал, а отметки нет → тревога о сборке, годность копии НЕ установлена (код 2/6).
# Без такого разделителя механизм пришлось бы либо не заводить, либо мириться с ложью.
#
# ЧЕГО ЭТОТ СТОРОЖ НЕ ДЕЛАЕТ (границы, чтобы зелёное не прочли шире):
#   • проверяет ПОСЛЕДНИЙ архив, а не всю историю на диске: старые копии не трогает
#     и об их годности не высказывается;
#   • не судит о чужой цепи в общей папке — только о своей по отметке;
#   • не проверяет, что архив лежит в правильной подпапке: он берёт файл по id, а
#     не по месту. Разведение цепей сторожит ротация, а не эта проверка;
#   • не защита от того, у кого есть права: любой из шагов снимается одной командой;
#   • НЕ отвечает на вопрос «состоялась ли приёмка вообще»: на него отвечает
#     возраст отметки $OTMETKA_PROVERKI, и это ОТДЕЛЬНАЯ запись реестра. Две разные
#     новости — «копия негодна» и «проверка не состоялась» — нельзя подавать одной;
#   • собственную смерть не ловит — её ловит сторож машины, в SERVICES которого
#     внесён этот таймер. Наблюдатель за смертью обязан жить снаружи наблюдаемого.
#
# КОДЫ: 0 passed+checkpoint | 1 failed | 2 unknown | 4 passed без checkpoint
# 5 failed+notification failed | 6 unknown+notification failed | 7 passed без checkpoint+notification failed | 8 partial
# 9 incomplete: восстановима, путей из реестра нет ни в копии, ни на машине (B-N-2101; при недоставке — 9 и notification=failed)
# 3 зарезервирован: прежний общий отказ уведомления; больше не выдаётся.
set -uo pipefail

OTMETKA="${BACKUP_STATE:-/var/lib/sadik-backup/last.json}"
TAJMER="${BACKUP_TIMER:-sadik-backup.timer}"
SBORSHCHIK="${BACKUP_BIN:-/usr/local/sbin/sadik-backup.py}"
PRIYOMKA="${PRIYOMKA_BIN:-/usr/local/sbin/proverka-kopii.sh}"
ALERT="${AGENT_ALERT_BIN:-/usr/local/bin/agent-alert}"
PREDEL_CHASOV="${PREDEL_CHASOV-30}"   # сборка ежедневная; 30 ч = сутки + запас на разброс
SLUZHBA="${BACKUP_SERVICE:-sadik-backup.service}"
YUNIT_PRIYOMKI="${BACKUP_VERIFY_SERVICE:-backup-verify.service}"   # чей TimeoutStartSec — потолок сроков звеньев
# B-N-741: 1500 мин = промежуток между запусками 24 ч + разброс таймера 5 мин + запас 55 мин. При приёмке
# в 06:15–06:20 пропущенная ночь даёт не меньше 27 ч 10 мин (1630). Меняется расписание сборки — пересчитать.
PREDEL_ZAPUSKA_MINUT="${PREDEL_ZAPUSKA_MINUT-1500}"
OTMETKA_PROVERKI="${BACKUP_VERIFY_STATE:-/var/lib/sadik-backup/proverena.json}"

RUKA="$(id -un)"
skazat() {  # тревога владельцу; молчание неотличимо от поломки, поэтому говорим и о неудаче
  local tekst="$1"
  if [ -x "$ALERT" ]; then
    out=$("$ALERT" "$tekst" 2>&1); rc=$?
    [ $rc -eq 0 ] && echo "  сказано человеку" || echo "  🔴 тревога НЕ доставлена (код $rc): ${out:-причина не названа}"
    return $rc
  fi
  echo "  🔴 отправщик $ALERT недоступен — тревога осталась в журнале"; return 1
}
NOTIFICATION=not_required
DECLARED_CODE=""
RAB=""
vyhod() { echo "$2"; DECLARED_CODE="$1"; exit "$1"; }
itog_priyomki() {
  local raw=$? code verdict checkpoint
  trap - EXIT
  code="${DECLARED_CODE:-2}"
  case "$code" in
    0) verdict=passed; checkpoint=confirmed ;;
    1) verdict=failed; checkpoint=not_attempted ;;
    2) verdict=unknown; checkpoint=not_attempted ;;
    4) verdict=passed; checkpoint=unconfirmed ;;
    8) verdict=partial; checkpoint=not_attempted ;;
    9) verdict=incomplete; checkpoint=not_attempted ;;
    *) code=2; verdict=unknown; checkpoint=not_attempted ;;
  esac
  if [ "$NOTIFICATION" = failed ]; then
    case "$code" in 1) code=5;; 2) code=6;; 4) code=7;; esac
  fi
  if [ -z "$DECLARED_CODE" ]; then
    printf 'СЛЕПОТА: неожиданный выход проверки, raw_rc=%s; предмет=%q\n' "$raw" "$OTMETKA"
  fi
  if [ -n "$RAB" ]; then rm -rf -- "$RAB"; fi
  printf 'BACKUP_RESULT verdict=%s checkpoint=%s notification=%s code=%s предмет=%q\n' \
    "$verdict" "$checkpoint" "$NOTIFICATION" "$code" "${IMYA:-$OTMETKA}"
  exit "$code"
}
trap itog_priyomki EXIT
# Отсутствие переменной использует штатное 30; явно пустое/негодное — не умолчание.
if ! [[ "$PREDEL_CHASOV" =~ ^[1-9][0-9]{0,5}$ ]]; then
  vyhod 2 "СЛЕПОТА: PREDEL_CHASOV должен быть положительным целым (1..999999), предмет=$OTMETKA"
fi
if ! [[ "$PREDEL_ZAPUSKA_MINUT" =~ ^[1-9][0-9]{0,5}$ ]]; then
  vyhod 2 "СЛЕПОТА: PREDEL_ZAPUSKA_MINUT должен быть положительным целым (1..999999), предмет=$OTMETKA"
fi

# ── Отметка о САМОЙ приёмке ──────────────────────────────────────────────────
# 🔴 Зачем она, если есть журнал: журнал ротируется по месту (умолчания journald),
# и глубина хранения не гарантирована. Без отметки на вопрос «когда копию последний
# раз ОТКРЫВАЛИ» отвечать нечем, а «таймер жив» — это намерение, а не факт: служба
# может каждый день честно выходить слепотой, и снаружи это выглядит работой.
#
# 🔴 ПЕРЕЧИТЫВАЕМ ЗАПИСАННОЕ. Урок соседней фермы 25.08: их инструмент напечатал
# «ОТМЕТКА ОБНОВЛЕНА» и вышел нулём, не посмотрев, легла ли она (каталога не было).
# Механизм против ложно-зелёного сам дал ложно-зелёное. Поэтому здесь: записать →
# перечитать → сверить, и при расхождении НЕ говорить «зелено».
zapisat_otmetku() {  # $1 — имя архива, $2 — id на Drive
  local kat; kat=$(dirname "$OTMETKA_PROVERKI")
  mkdir -p "$kat" 2>/dev/null || { echo "  ⚠️ каталог $kat не заводится"; return 1; }
  local kogda; kogda=$(date -u '+%Y-%m-%dT%H:%M:%S+00:00')
  # 🔴 B-N-846 (25.09.2026, Михалыч): запись — во ВРЕМЕННЫЙ файл того же каталога, затем mv (rename
  # атомарен на одной ФС). Было: printf прямо в отметку — обрыв посреди записи оставлял обрезанный
  # JSON, и сторож отметки читал его как СЛЕПОТУ. Теперь читатель видит либо прежнюю, либо новую целиком.
  # Права 644 — как у прежней отметки (mktemp даёт 600). Обрыв ДО mv оставляет только временный файл
  # .proverena.json.XXXXXX рядом; читатели его не открывают.
  local vrem; vrem=$(mktemp "$kat/.$(basename "$OTMETKA_PROVERKI").XXXXXX" 2>/dev/null) || { echo "  ⚠️ временный файл в $kat не создан"; return 1; }
  printf '{\n  "proverena_at": "%s",\n  "name": "%s",\n  "drive_id": "%s",\n  "ruka": "%s"\n}\n' \
    "$kogda" "$1" "$2" "$RUKA" > "$vrem" 2>/dev/null || { rm -f "$vrem"; echo "  ⚠️ запись $vrem не прошла"; return 1; }
  chmod 644 "$vrem" && mv -f "$vrem" "$OTMETKA_PROVERKI" || { rm -f "$vrem"; echo "  ⚠️ перенос в $OTMETKA_PROVERKI не прошёл"; return 1; }
  # перечитать ТЕМ ЖЕ разбором, каким её будет читать сторож возраста
  local nazad
  nazad=$(python3 -c "import json,sys;d=json.load(open(sys.argv[1]));print(d['proverena_at'],d['name'])" "$OTMETKA_PROVERKI" 2>/dev/null) || {
    echo "  ⚠️ отметка записана, но не разбирается обратно"; return 1; }
  [ "$nazad" = "$kogda $1" ] || { echo "  ⚠️ перечитанное не совпало: «$nazad»"; return 1; }
  echo "  отметка приёмки обновлена: $OTMETKA_PROVERKI ($kogda)"
  return 0
}
# 🔴 Недоставленная тревога — это НЕ отработавший сторож, а молчащий. Поэтому
# неудача доставки отражается кодами 5/6/7, сохраняя вердикт; юнит попадает в --failed.
# Иначе «сказать не смог» выглядело бы как «сказать было нечего».
skazat_ili_upast() {
  if skazat "$1"; then NOTIFICATION=sent; else NOTIFICATION=failed; fi
  # Не терять уже установленный вердикт при отказе доставки.
}

echo "приёмка копии по расписанию | рука: $RUKA | $(date -u '+%F %T UTC')"

# ── 1. Отметка ───────────────────────────────────────────────────────────────
if [ ! -r "$OTMETKA" ]; then
  trig=$(systemctl show "$TAJMER" -p LastTriggerUSec --value 2>/dev/null)
  if [ -z "$trig" ] || [ "$trig" = "n/a" ]; then
    vyhod 2 "СЛЕПОТА: отметки нет и таймер $TAJMER ни разу не срабатывал — сборки ещё не было"
  fi
  skazat_ili_upast "🔴 копия sadik: таймер сборки срабатывал ($trig), а отметки $OTMETKA нет — сборка падает молча"
  vyhod 2 "СЛЕПОТА: сборка запускалась, отметки нет; годность не установлена"
fi

# Один строгий разбор отметки: ноль/пусто/неверная дата не превращаются в возраст0.
META=$(python3 - "$OTMETKA" <<'PYMETA'
import json,sys,datetime
try:
 d=json.load(open(sys.argv[1])); ident=d['drive_id']; name=d['name']; ts=d['completed_at']
 if not all(isinstance(v,str) and v.strip() and not any(ord(c)<32 for c in v) for v in (ident,name,ts)): raise ValueError('пустое/негодное поле')
 if ident.strip()=='0' or name in ('.','..','0') or '/' in name or '\\' in name: raise ValueError('негодный id/имя')
 t=datetime.datetime.fromisoformat(ts.replace('Z','+00:00'))
 if t.tzinfo is None: raise ValueError('нет часового пояса')
 age=(datetime.datetime.now(datetime.timezone.utc)-t).total_seconds()
 if age<0: raise ValueError('дата из будущего')
 size=d['size_bytes']  # B-H-1427: размер нужен проверке места; нет его — места не проверить ⇒ слепота
 if type(size) is not int or size<=0: raise ValueError('size_bytes не положительное целое')
 print(ident);print(name);print(int(age//3600));print(ts);print(int(t.timestamp()));print(size)
except Exception as e:
 print('неверная отметка: '+str(e),file=sys.stderr);sys.exit(2)
PYMETA
) || vyhod 2 "СЛЕПОТА: отметка $OTMETKA не разбирается"
mapfile -t META_FIELDS <<< "$META"
[ "${#META_FIELDS[@]}" -eq 6 ] || vyhod 2 "СЛЕПОТА: неверный формат отметки $OTMETKA"
ID=${META_FIELDS[0]}; IMYA=${META_FIELDS[1]}; VOZRAST=${META_FIELDS[2]}; SNYATA=${META_FIELDS[3]}; SDELANA=${META_FIELDS[4]}; RAZMER=${META_FIELDS[5]}
echo "  последняя копия: $IMYA | id $ID | возраст $VOZRAST ч"

# ── 2. Свежесть ──────────────────────────────────────────────────────────────
# 🔴 B-N-1466 (03.10.2026, Заря): раньше стояла ПОСЛЕ 1б и была недостижима при умолчаниях — дойти до неё можно было,
# только если запуск не позже отметки и не старше PREDEL_ZAPUSKA_MINUT (1500), т.е. возраст отметки ≤ 25 ч < 30.
# Протухшая копия уходила под чужим именем: «не дала копии» (1), «ночь пропущена» (1) или «НЕ ГОТОВО» (2, если
# очередная сборка как раз шла — годная копия старше 30 ч пряталась за «неизвестно»). Теперь — до 1б.
# Ночная картина сохраняется: сборка 03:0x идёт, отметка прошлой ночи ~24 ч < 30 ⇒ 1б ⇒ «НЕ ГОТОВО» (2);
# сборку держит TimeoutStartSec=3h, дольше activating она не бывает.
# ⚠️ ЧЕГО НЕ РАЗЛИЧАЕТ: при отметке старше 30 ч причина (упала / не запускалась / идёт) в итог не попадает — только «протухла».
if [ "$VOZRAST" -gt "$PREDEL_CHASOV" ]; then
  skazat_ili_upast "🔴 копия sadik не обновлялась $VOZRAST ч (предел $PREDEL_CHASOV) — сборка встала. Последняя: $IMYA"
  vyhod 1 "ОТКАЗ: копия протухла ($VOZRAST ч)"
fi

# ── 1б. Копия ЭТОГО цикла ────────────────────────────────────────────────────
# 🔴 B-N-741: 24.09 04:04Z приёмка дала ЗЕЛЕНО по копии 23.09, хотя сборка 03:04 упала 'oom-kill', а её
# перезапуск шёл 03:59–04:53. Возраст отметки (24 ч) этого не различал: вчерашняя годная выглядит свежей.
# Различает момент ПОСЛЕДНЕГО ЗАПУСКА: запуск позже отметки — значит, копии этого цикла ещё нет.
# Запуск = позднейший из «таймер срабатывал» и «служба стартовала»: ручной запуск таймер не отмечает.
# ⚠️ Result одной не судим: при ActiveState=activating в ней лежит итог ПРОШЛОГО прогона (замер 24.09: success).
declare -A S=()
while IFS='=' read -r k v; do S[$k]=$v; done < <(systemctl show "$SLUZHBA" --timestamp=unix \
  -p ActiveState -p Result -p ExecMainStartTimestamp 2>/dev/null)
PUSK=0
t=${S[ExecMainStartTimestamp]:-}; t=${t#@}
[[ "$t" =~ ^[0-9]+$ ]] && PUSK=$t
# LastTriggerUSec не слушает --timestamp=unix — печатает дату словами; «n/a» и пустое не разбираем
# (date -d '' даёт полночь сегодня с кодом 0).
trig=$(systemctl show "$TAJMER" -p LastTriggerUSec --value 2>/dev/null)
if [ -n "$trig" ] && [ "$trig" != "n/a" ] && t=$(date -u -d "$trig" +%s 2>/dev/null) && [ "$t" -gt "$PUSK" ]; then
  PUSK=$t
fi
if [ "$PUSK" -eq 0 ]; then
  skazat_ili_upast "⚠️ копия sadik: момент последнего запуска сборки не установлен ($SLUZHBA, $TAJMER) — копия ли это цикла, неизвестно"
  vyhod 2 "СЛЕПОТА: момент последнего запуска сборки не установлен"
fi
KOGDA=$(date -u -d "@$PUSK" '+%F %T UTC')
if [ "$PUSK" -gt "$SDELANA" ]; then
  if [ "${S[ActiveState]:-}" = activating ]; then
    skazat_ili_upast "⚠️ копия sadik: сборка, пущенная $KOGDA, ещё идёт — копия цикла НЕ ГОТОВА, приёмка не проводилась. Последняя готовая: $IMYA"
    vyhod 2 "НЕ ГОТОВО: сборка с $KOGDA ещё идёт; $IMYA — копия прошлого цикла"
  fi
  skazat_ili_upast "🔴 копия sadik: сборка, пущенная $KOGDA, копии НЕ ДАЛА (${S[ActiveState]:-?}, result ${S[Result]:-?}). Последняя готовая: $IMYA"
  vyhod 1 "ОТКАЗ: сборка с $KOGDA не дала копии (${S[ActiveState]:-?}, result ${S[Result]:-?})"
fi
VOZRAST_ZAPUSKA=$(( ($(date +%s) - PUSK) / 60 ))
echo "  последний запуск сборки: $KOGDA ($VOZRAST_ZAPUSKA мин назад), копия от него"
if [ "$VOZRAST_ZAPUSKA" -gt "$PREDEL_ZAPUSKA_MINUT" ]; then
  skazat_ili_upast "🔴 копия sadik: сборка не запускалась $VOZRAST_ZAPUSKA мин (предел $PREDEL_ZAPUSKA_MINUT) — ночь пропущена. Последняя: $IMYA"
  vyhod 1 "ОТКАЗ: сборка не запускалась $VOZRAST_ZAPUSKA мин"
fi

# ── 2б. Место ДО скачивания ──────────────────────────────────────────────────
# 🔴 B-H-1427 (02.10.2026, Заря): архив качается в /tmp, а proverka-kopii.sh распаковывает его ЦЕЛИКОМ в
# mktemp -d (${TMPDIR:-/tmp}) — на sadik оба на корне. 02.10: архив 27,4 ГБ + распаковка (дошла до 10 из 38,4 ГБ)
# опустили корень до 4–5 % свободного; не убей юнит срок — 100 % и отказ записей у всех агентов. Места не мерил никто.
# НУЖНО = S (скачать) + 1,5·S (распаковать) + 5 % объёма ФС (запас), S — size_bytes из отметки сборки.
#   1,5: несжатое/архив по замеру 02.10 — 26,02/18,97 = 1,37 (копия 01.10) и 38,44/27,43 = 1,40 (02.10), +0,1 на сдвиг состава.
#   5 %: пик приёмки не опускает ФС ниже 5 % — agent-watchdog (порог 10 %) закричит, но записи у агентов не откажут.
# Распаковка на другой ФС, чем /tmp, — каждая ФС меряется своей долей. Не хватает — ОТКАЗ кодом 2 с числами, ничего не качаем.
# ⚠️ НЕ ЛОВИТ: чужие записи во время приёмки сверх запаса; ручной запуск proverka-kopii.sh мимо этого сторожа;
#    S из отметки, а не с Drive (размер уехавшего не сверяется); полку /backups и сборку 03:03Z не стережёт.
# 🔴 B-H-1427 (C2, 02.10.2026, Заря): приёмка, которая читает архив ПОТОКОМ (proverka-kopii.sh с модулем .potok.py),
# кладёт на диск не 1,4·S, а ключ, хранилище, патчи, манифест, указатель членов и одну группу баз на время проверки.
# Замер 02.10: модель по перечню копии 27,4 ГБ — одновременно извлечено ≤ 0,54 ГБ баз + 0,8 МБ прочего; подставной
# архив 1,68 ГБ — пик рабочего каталога 66–101 МБ (база 100 МБ) против 1 678 МБ у прежней. Доля S/20 (1,37 ГБ при
# 27,4) — в 2,5 раза выше замера; не меньше 1 ГБ — для малых копий с крупной базой.
# Формула выбирается по УСТРОЙСТВУ приёмки, а не по договорённости о порядке монтажа: вернут прежнюю
# proverka-kopii.sh (откат одного файла) — вернётся и 1,5·S, а не корень на 100 %.
if grep -qF "<<'PYPOTOK'" "$PRIYOMKA" 2>/dev/null; then
  RASPAK=$(( RAZMER / 20 )); [ "$RASPAK" -lt 1000000000 ] && RASPAK=1000000000
  CHTO_RASPAK="потоковая проверка S/20, не меньше 1 ГБ"
else
  RASPAK=$(( RAZMER * 3 / 2 )); CHTO_RASPAK="распаковка 1,5·S"
fi
gb() { awk -v b="$1" 'BEGIN{printf "%.1f", b/1e9}'; }
proverit_mesto() {  # $1 каталог, $2 нужно байт без запаса, $3 что именно
  local svob obem zapas nuzhno
  read -r svob obem < <(df -P -B1 "$1" 2>/dev/null | awk 'NR==2{print $4, $2}')
  [[ "${svob:-}" =~ ^[0-9]+$ && "${obem:-}" =~ ^[0-9]+$ ]] || vyhod 2 "СЛЕПОТА: свободное место на $1 не измерено (df) — приёмка не начата"
  zapas=$(( obem / 20 )); nuzhno=$(( $2 + zapas ))
  echo "  место на $1: нужно $(gb $nuzhno) ГБ ($3 + запас 5 % $(gb $zapas)), свободно $(gb $svob) ГБ"
  if [ "$svob" -lt "$nuzhno" ]; then
    skazat_ili_upast "🔴 копия sadik: приёмку $IMYA НЕ начинаю — на $1 нужно $(gb $nuzhno) ГБ ($3 + запас 5 %), свободно $(gb $svob) ГБ. Скачано 0 Б; копия НЕ принята"
    vyhod 2 "ОТКАЗ ПО МЕСТУ: на $1 нужно $nuzhno Б, свободно $svob Б — приёмка не начата, годность не установлена"
  fi
}
if [ "$(stat -c %d /tmp)" = "$(stat -c %d "${TMPDIR:-/tmp}")" ]; then
  proverit_mesto /tmp $(( RAZMER + RASPAK )) "архив $(gb $RAZMER) + $CHTO_RASPAK $(gb $RASPAK)"
else
  proverit_mesto /tmp "$RAZMER" "архив $(gb $RAZMER)"
  proverit_mesto "${TMPDIR:-/tmp}" "$RASPAK" "$CHTO_RASPAK $(gb $RASPAK)"
fi

# ── 2в. Срок от размера ──────────────────────────────────────────────────────
# 🔴 B-N-1435 (C3, 02.10.2026, Заря): 02.10 приёмку убил TimeoutStartSec=1200 — одно скачивание 27,4 ГБ шло 1121 с.
# Убийство юнитом минует и тревогу, и итог (B-H-561). Теперь срок у КАЖДОГО долгого звена — формулой от S, и звено
# гасит сам сторож с тревогой; потолок юнита — только страховка от зависания вне звеньев.
#   скачивание: 120 с + S / 12 МБ/с — худший замер 26.09–02.10 15,1 МБ/с (27.09), запас ×1,25;
#   приёмка:    120 с + S / 60 МБ/с — поток 02.10: 27,4 ГБ за 191–192 с (143 МБ/с, nice 10/idle), запас ×2,4.
# Срок звена не больше остатка до потолка юнита минус 120 с на тревогу и итог. Потолок читается у systemd, а не
# записан числом: сменят юнит — сроки поедут с ним. Потолок не прочитан или infinity — звено ограничено формулой.
# ⚠️ НЕ ЛОВИТ: зависание вне звеньев (systemctl show, запись отметки, тревога) — там остаётся потолок юнита;
#    скорость ниже 12 МБ/с на ВСЁМ скачивании — честный отказ по сроку, а не «копия плоха».
SROK_SKACH=$(( 120 + RAZMER / 12000000 ))
SROK_PRIYOMKI=$(( 120 + RAZMER / 60000000 ))
POTOLOK=$(systemctl show "$YUNIT_PRIYOMKI" -p TimeoutStartUSec --value 2>/dev/null | python3 -c "
import re,sys
z=sys.stdin.read().strip(); ed={'d':86400,'h':3600,'min':60,'s':1,'ms':0.001,'us':0.000001}
ch=re.findall(r'(\d+)\s*(d|h|min|ms|us|s)\b', z)
print(int(sum(int(n)*ed[e] for n,e in ch)) if ch else 0)" 2>/dev/null)
[[ "${POTOLOK:-}" =~ ^[0-9]+$ ]] || POTOLOK=0
srok_zvena() {  # $1 — срок по формуле; печатает срок с учётом потолка; 1 — потолок уже исчерпан
  local f=$1 ost
  if [ "$POTOLOK" -gt 0 ]; then
    ost=$(( POTOLOK - SECONDS - 120 ))
    [ "$ost" -le 0 ] && return 1
    [ "$ost" -lt "$f" ] && f=$ost
  fi
  echo "$f"
}
echo "  сроки от размера $(gb $RAZMER) ГБ: скачивание $SROK_SKACH с, приёмка $SROK_PRIYOMKI с; потолок $YUNIT_PRIYOMKI ${POTOLOK} с (0 — не прочитан)"
po_sroku() {  # $1 — звено, $2 — срок; тревога ДО убийства юнитом
  skazat_ili_upast "🔴 копия sadik: звено «$1» ($IMYA) не уложилось в $2 с (срок от размера $(gb $RAZMER) ГБ, потолок юнита $POTOLOK с) — звено погашено, копия НЕ принята"
  vyhod 2 "СЛЕПОТА ПО СРОКУ: звено «$1» не уложилось в $2 с — годность не установлена"
}
# B-N-1435 (хвост, Вениамин): код 137 — это И «срок истёк, звено не вышло по TERM и timeout добил его KILL», И KILL извне
# (OOM-убийца, чужая рука). По коду их не развести, поэтому «не уложилось» на 137 не говорим — говорим «убито».
po_ubito() {  # $1 — звено, $2 — срок
  skazat_ili_upast "🔴 копия sadik: звено «$1» ($IMYA) убито (срок истёк и добито KILL, либо KILL извне — проверь журнал ядра на OOM); срок был $2 с — копия НЕ принята"
  vyhod 2 "СЛЕПОТА: звено «$1» убито (срок истёк и добито KILL, либо KILL извне — проверь журнал ядра на OOM) — годность не установлена"
}

# ── 3. Скачивание ────────────────────────────────────────────────────────────
# Во временном архиве лежит закрытый БЕСПАРОЛЬНЫЙ ключ от всего хранилища.
# Каталог 0700 и уборка в trap — не аккуратность, а условие: копия, оставленная
# в общем каталоге, раздаёт то, что бережёт.
RAB=$(mktemp -d /tmp/priyomka-kopii.XXXXXX) || vyhod 2 "СЛЕПОТА: не завести временный каталог"
chmod 700 "$RAB"
# Уборка и итог выполняются общим EXIT trap.
ARH="$RAB/$IMYA"
SROK=$(srok_zvena "$SROK_SKACH") || po_sroku "скачивание" 0
timeout --kill-after=30 "$SROK" "$SBORSHCHIK" --skachat "$ID" "$ARH" >"$RAB/skach.log" 2>&1; RC_SK=$?
case "$RC_SK" in 124) po_sroku "скачивание" "$SROK" ;; 137) po_ubito "скачивание" "$SROK" ;; esac
if [ "$RC_SK" -ne 0 ]; then
  skazat_ili_upast "🔴 копия sadik: архив $IMYA не скачивается с Drive (id $ID). Уехавшее недоступно."
  echo "  --- вывод скачивания ---"; tail -3 "$RAB/skach.log"
  vyhod 2 "СЛЕПОТА: скачать не удалось, годность архива неизвестна"
fi
echo "  скачано: $(stat -c %s "$ARH") Б"

# ── 4. Единственный принимаемый довод ────────────────────────────────────────
# Время снятия копии передаётся ЯВНО из отметки сборки: приёмка сверяет им
# возраст реестра. Без этого «нет в копии» не отличает «внесено в реестр после
# снятия» от «пропало» — 06.09 это дало «7 из 74» на исправной копии.
# SNYATA взята из того же проверенного снимка отметки, что ID и IMYA.
SROK=$(srok_zvena "$SROK_PRIYOMKI") || po_sroku "приёмка" 0
# 🔴 B-N-1775 (07.10.2026, Михалыч; нашла Аврора): «снята» = СТАРТ СБОРКИ этой копии (PUSK из 1б; дойти сюда можно только при
#   PUSK ≤ SDELANA, т.е. копия — от этого запуска), а НЕ completed_at (конец выгрузки на Drive). 07.10: сборка 03:00:58Z, строка
#   реестра /var/log/podyom-uzla внесена 03:10:43Z, выгрузка кончилась 03:45:06Z — по completed_at реестр вышел «старше копии», и
#   приёмка сказала «КОПИЯ НЕПОЛНА … не восстановима» вместо «внесено после снятия — не различается» (код 2). Старт — консервативно:
#   всё, что внесено в реестр после старта сборки, могло в копию не попасть.
#   ЧЕГО НЕ ЛОВИТ: правку реестра ДО старта, которую сборщик всё же не взял, — это и есть «пропало», его и ловит приёмка.
SNYATA_SBORKI=$(date -u -d "@$PUSK" '+%FT%T+00:00' 2>/dev/null) || SNYATA_SBORKI=""
if [ -n "$SNYATA_SBORKI" ]; then
  echo "  снята (старт сборки этой копии): $SNYATA_SBORKI · выгрузка закончена: $SNYATA"
  timeout --kill-after=30 "$SROK" "$PRIYOMKA" --kopiya-snyata "$SNYATA_SBORKI" "$ARH" >"$RAB/priyomka.log" 2>&1; RC=$?
else
  echo "  ⚠️ момент старта сборки не разобран — возраст реестра против копии не сверяется"
  timeout --kill-after=30 "$SROK" "$PRIYOMKA" "$ARH" >"$RAB/priyomka.log" 2>&1; RC=$?
fi
sed 's/^/  | /' "$RAB/priyomka.log"
case "$RC" in 124) po_sroku "приёмка" "$SROK" ;; 137) po_ubito "приёмка" "$SROK" ;; esac
case "$RC" in
  0) if zapisat_otmetku "$IMYA" "$ID"; then
       vyhod 0 "ЗЕЛЕНО: уехавшее открывается ($IMYA)"
     fi
     # Копия годна — это установлено. Но следа не осталось, значит сторож возраста
     # отметки завтра закричит «проверка не состоялась», хотя она состоялась.
     # Проверка пройдена, учёт не подтверждён: отдельный код4 (или7 при отказе уведомления).
     skazat_ili_upast "⚠️ копия sadik ОТКРЫЛАСЬ ($IMYA), но отметка приёмки $OTMETKA_PROVERKI не сохранена — следующая проверка возраста соврёт"
     vyhod 4 "УЧЁТ НЕ ПОДТВЕРЖДЁН: копия прошла проверку, отметка не сохранена" ;;
  2) skazat_ili_upast "⚠️ копия sadik: приёмка НЕ СОСТОЯЛАСЬ на $IMYA — проверка не смогла измерить, копия не подтверждена"
     vyhod 2 "СЛЕПОТА: приёмка не состоялась" ;;
  # B-N-2101 r2 (ворота Вениамина 04:58Z): «не восстановима» — только не читается / ключ не поднялся / базы не открылись.
  # Отказ по составу (приёмка печатает «КОПИЯ НЕПОЛНА») — «неполна»: секреты при этом открылись. Код и тревога те же.
  1) if grep -qF 'КОПИЯ НЕПОЛНА' "$RAB/priyomka.log"; then
       skazat_ili_upast "🔴 копия sadik НЕПОЛНА: $(grep -m1 -F 'КОПИЯ НЕПОЛНА' "$RAB/priyomka.log" | sed 's/^ *//')  (архив $IMYA)"
       vyhod 1 "ОТКАЗ: копия неполна — данных, объявленных реестром, в ней нет (перечень выше)"
     fi
     skazat_ili_upast "🔴 копия sadik НЕГОДНА: $(grep -m1 '🔴' "$RAB/priyomka.log" || echo 'приёмка отказала')  (архив $IMYA)"
     vyhod 1 "ОТКАЗ: копия не восстановима" ;;
  # B-N-2101: восстановима (секреты, базы, ACL, подключения прошли), но пути из разметки нет ни в копии, ни на машине.
  # Не «НЕГОДНА»: копия взяла всё, что было. Тревога остаётся (юнит failed, код 9): реестр или машину надо чинить.
  3) skazat_ili_upast "🟠 копия sadik ВОССТАНОВИМА, но НЕПОЛНА ПО СОСТАВУ — в реестре есть, на машине нет: $(awk '/^🟠 НЕПОЛНА ПО СОСТАВУ/{f=1;next} f&&/^    /{print;next} f{exit}' "$RAB/priyomka.log" | tr -s ' ' | paste -sd ',' | cut -c1-600)  (архив $IMYA)"
     vyhod 9 "НЕПОЛНА ПО СОСТАВУ: копия восстановима; путей из реестра нет ни в копии, ни на машине (перечень выше)" ;;
  8) vyhod 8 "ЧАСТИЧНО: выбранный профиль проверен, полная приёмка $IMYA не проводилась" ;;
  *) skazat_ili_upast "⚠️ приёмка $IMYA вернула неожиданный код $RC; годность не установлена"
     vyhod 2 "СЛЕПОТА: неожиданный код дочернего процесса $RC" ;;
esac
