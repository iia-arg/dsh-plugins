#!/usr/bin/env bash
# svodka-sostoyaniya — ОДИН снимок: что в бою, что на диске, что в реестре, у обоих узлов.
#
# ЗАЧЕМ. 04.09.2026 четверо полдня спорили числами, и все были правы: каждый снимал свой срез
# в свой момент своим способом. Лечение не в дисциплине писем, а в одном приборе, который
# снимает ВСЕ разряды разом и печатает момент первой строкой.
#
# 🔴 ТРИ РАЗРЯДА, КОТОРЫЕ НЕЛЬЗЯ ПОДМЕНЯТЬ ДРУГ ДРУГОМ:
#   БОЙ     — что процесс сказал о себе при старте (журнал службы). Правда о работающем.
#   ДИСК    — что поедет при СЛЕДУЮЩЕМ подъёме (разрешение имени из профиля службы).
#   РЕЕСТР  — что получит посторонний по метке. К бою отношения не имеет вовсе.
# Совпадение всех трёх — редкость, а не норма. Расхождение само по себе НЕ дефект: дефект —
# когда его не назвали.
set -uo pipefail
echo "машина: $(hostname)   время: $(date -u '+%Y-%m-%d %H:%M:%SZ') UTC"
echo

# Слепота хоть по одному узлу — исход всей сводки: молчание не должно читаться
# как «состояние снято». Ведёт себя как «нельзя», по нашему общему правилу.
SLEPOTA=0

srez_uzla() {
  local imya="$1" sluzhba="$2" profil="$3"
  local pid start
  # 🔴 ПОДАВЛЕННЫЙ ПОТОК ОШИБОК ДЕЛАЕТ ПУСТОТУ НЕОТЛИЧИМОЙ ОТ ОТВЕТА (класс Михалыча,
  # 06.09.2026, пойман им на себе). У `--value` успех печатает голое значение, отказ —
  # НИЧЕГО: пустая строка значит сразу три разных вещи — службы нет · прав нет · команды
  # нет. Прежде здесь стояло `2>/dev/null`, и «MainPID , старт ?» читалось как «служба не
  # работает», хотя означало бы «мне не видно». Отличие от нашего прежнего правила про
  # пустой ответ: там пустота была ЧЕСТНОЙ, здесь мы САМИ удаляли признак отказа.
  # Поэтому: код возврата читается, при отказе замер повторяется БЕЗ подавления.
  local vyvod kod
  vyvod=$(sudo -n systemctl show "$sluzhba" -p MainPID -p ActiveEnterTimestamp --value 2>&1); kod=$?
  if [ "$kod" -ne 0 ]; then
    echo "── $imya ($sluzhba)"
    echo "   🔴 СЛЕПОТА: состояние службы не читается (код $kod)."
    echo "   systemctl сказал: $(printf '%s' "$vyvod" | head -2 | tr '\n' ' ')"
    echo "   Это НЕ значит «служба не работает»: значит её не видно ЭТОЙ рукой."
    SLEPOTA=1
    return 0
  fi
  pid=$(printf '%s\n' "$vyvod" | sed -n '1p')
  start=$(printf '%s\n' "$vyvod" | sed -n '2p')
  echo "── $imya ($sluzhba, MainPID ${pid:-?}, старт ${start:-?})"
  echo "   БОЙ (журнал текущей загрузки):"
  local zhurnal kodzh
  zhurnal=$(sudo -n journalctl -u "$sluzhba" --since "${start:-2026-01-01}" --no-pager 2>&1); kodzh=$?
  if [ "$kodzh" -ne 0 ]; then
    echo "      🔴 СЛЕПОТА: журнал не читается (код $kodzh): $(printf '%s' "$zhurnal" | head -1)"
    echo "      Пустой список ниже был бы про ПРАВА, а не про пакеты."
    SLEPOTA=1
  else
    printf '%s\n' "$zhurnal" \
      | grep -oE '\[dsh-[a-z-]+ [0-9][^]]*\]' | sort -u | sed 's/^/      /' | head -12
  fi
  echo "   ДИСК (что поедет при следующем подъёме):"
  # 🔴 ЗОВЁМ ГОТОВЫЙ ПРИБОР, А НЕ ПИШЕМ ЗАНОВО. Первая редакция этой строки повторила ошибку,
  # которую я чинила часом раньше в том же приборе (`return` вне функции в `node -e`). Урок,
  # живущий только в памяти, повторяется; урок, вынесенный в файл, — нет.
  # 🔴 ИМЕНА — ИЗ КОНФИГА ПРОФИЛЯ, А НЕ СПИСКОМ В ЭТОЙ СТРОКЕ. Найдено 05.09.2026: здесь
  # стояли ДВА имени, зашитые рукой, и разряд ДИСК молчал про остальные девять. Расхождение
  # restore (на диске a18, в бою a17) прибор не показал вовсе — не потому что сравнил и
  # промолчал, а потому что не смотрел. Это третий за сутки случай одного класса: перечень,
  # записанный рукой, отвечает про себя, а читается как ответ про предмет.
  # ГДЕ НЕ ПРИМЕНЯЕТСЯ: имена берутся из ОБЪЯВЛЕННОГО в конфиге. Плагин, подключённый мимо
  # конфига, здесь не виден вовсе — и об этом сказано числом, а не молчанием.
  local imena
  imena=$(sudo -n grep -hoE "^[[:space:]]*-?[[:space:]]*name:[[:space:]]*[A-Za-z0-9@/._-]+" \
            "$profil/cordis.patch.yml" 2>/dev/null | sed 's/.*name:[[:space:]]*//' | sort -u | tr '\n' ' ')
  if [ -z "$imena" ]; then
    echo "      🔴 СЛЕПОТА: конфиг профиля не прочитан ($profil/cordis.patch.yml)."
    echo "         Имена плагинов взять неоткуда. Это НЕ «расхождений нет»."
    SLEPOTA=1   # №2 аудита A-N-1948: строка слепоты без флага давала исход 0 — сводка читалась снятой
  else
    echo "      (имён из конфига: $(echo $imena | wc -w))"
    # №2 аудита A-N-1948 (10.10.2026): прибор — из пакета dsh-pribory; без него или при его отказе блок был
    # молча пуст и сводка выглядела снятой. Теперь — СЛЕПОТА с причиной. Годный ответ прибора: код 0 и строка
    # «корень разрешения:» (priznak-vzyatiya.mjs печатает её всегда); иначе — не ответ. Путь подменяем только стендом.
    local pv="${SVODKA_PRIZNAK:-/usr/local/libexec/svodka/priznak-vzyatiya.mjs}" pvyv pkod
    if ! sudo -n test -f "$pv"; then
      echo "      🔴 СЛЕПОТА: признак взятия не снят — нет $pv (пакет dsh-pribory). Это НЕ «расхождений нет»."; SLEPOTA=1
    else
      # shellcheck disable=SC2086
      pvyv=$(sudo -n node "$pv" "$profil" $imena 2>/dev/null); pkod=$?
      if [ "$pkod" -ne 0 ] || ! printf '%s\n' "$pvyv" | grep -q '^корень разрешения:'; then
        # shellcheck disable=SC2086
        echo "      🔴 СЛЕПОТА: признак взятия не снят — $pv код $pkod: $(sudo -n node "$pv" "$profil" $imena 2>&1 | tail -1 | cut -c1-160)"; SLEPOTA=1
      else
        printf '%s\n' "$pvyv" | grep -v '^корень' | sed 's/^  /      /'
      fi
    fi
  fi
}

srez_uzla "Искра"     "iskra.service" "/opt/iskra/.dsh/profiles/web"
echo
srez_uzla "Петрович"  "petrovich.service"   "/opt/petrovich/.dsh/profiles/web"
echo
# B-N-749 (24.09): клоны Искры.
srez_uzla "Заря"      "zarya.service"  "/opt/zarya/.dsh/profiles/web"
echo
srez_uzla "Аврора"    "avrora.service" "/opt/avrora/.dsh/profiles/web"
echo
# 🔴 РАЗРЯД «РЕЕСТР (что получит посторонний)» СНЯТ 09.09.2026 — НЕ ЗАБЫТ.
# Печатал dist-tags четырёх пакетов через `npm view`. Снят по слову владельца
# (Александр: «никто кроме нас этим не пользуется, оттуда никто ничего не
# поставит»; 06.09 отменены сверка версий опубликованного и поиск дыр в
# выпущенном). Проверен критерием Забавы: нужна ли сеть, чтобы ответить? Да.
# Исчезает ли цель без наружного? Да — фигуры «посторонний, ставящий по имени
# из реестра» не существует. Оба ответа → отменён, предмета нет.
# ⚠️ ГРАНИЦА: снят разряд ПРО РЕЕСТР, а не всякий «посторонний». Локальный
# посторонний — другой предмет и живёт (см. vylozhit-peredachu.sh, где
# проверяется чтение файлов от чужого пользователя ЭТОЙ машины).
echo "── ЧЕТВЁРТЫЙ РАЗРЯД: ВЕРДИКТЫ ПРИЁМКИ (что признано годным)"
# 🔴 ЗАЧЕМ ЗДЕСЬ. 04.09.2026 я трижды подняла тревогу «в бою непринятое» — и все три
# раза она была ложной: вердикт существовал, лежал в дереве и не был спрошен. Замер
# был верен, вывод логичен, не хватало ОДНОГО разряда. Пока вердикты снимались
# отдельной командой, спрашивать их надо было ПОМНИТЬ — а помнят не всегда.
# Теперь один вызов даёт четыре разряда сразу: бой, диск, реестр, вердикт.
# ⚠️ ГРАНИЦА: показывает вердикты, ОТПРАВЛЕННЫЕ в origin, и только последние по окну.
# Вердикт, лежащий у приёмщика локально, сюда не попадёт — видно по рубежу репозитория.
PRIBOR_VERDIKTOV=/usr/local/libexec/svodka/verdikty-priyomki.sh
if [ -x "$PRIBOR_VERDIKTOV" ]; then
  bash "$PRIBOR_VERDIKTOV" 14 2>&1 | sed 's/^/   /'
  KODY_VERDIKTOV=("${PIPESTATUS[@]}")
  if [ "${KODY_VERDIKTOV[0]}" -ne 0 ] || [ "${KODY_VERDIKTOV[1]}" -ne 0 ]; then
    echo "   СЛЕПОТА: $PRIBOR_VERDIKTOV — код помощника ${KODY_VERDIKTOV[0]}, оформления ${KODY_VERDIKTOV[1]}; четвёртый разряд не снят" >&2
    SLEPOTA=1
  fi
else
  echo "   СЛЕПОТА: прибор вердиктов $PRIBOR_VERDIKTOV не найден или не исполняется — четвёртый разряд не снят" >&2
  SLEPOTA=1
fi
echo
echo "🔴 БОЙ ≠ ДИСК ≠ РЕЕСТР по построению. Называя версию, называйте РАЗРЯД."
echo "   А прежде чем звать что-то непринятым — смотрите четвёртый разряд выше."

if [ "$SLEPOTA" -ne 0 ]; then
  echo
  echo "🔴 ИСХОД 2 — СЛЕПОТА: хотя бы один разряд не читался ЭТОЙ рукой (см. строки выше)."
  echo "   Пустые места в сводке — про доступ, а не про состояние машины."
  exit 2
fi
