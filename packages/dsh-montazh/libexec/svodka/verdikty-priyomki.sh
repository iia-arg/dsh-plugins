#!/usr/bin/env bash
# verdikty-priyomki.sh — вердикты приёмки СНИМАЮТСЯ ЗАМЕРОМ, а не помнятся из письма.
#
# ЗАЧЕМ. 04.09.2026 четыре раза подряд решение принималось по вердикту, о котором
# знали не все: письмо о приёмке шло дольше, чем менялся предмет. При этом вердикты
# ВСЁ ЭТО ВРЕМЯ ложились в репозиторий коммитами приёмщика — то есть место, где их
# можно снять замером, уже существовало, и им никто не пользовался.
#
# ЧТО ДЕЛАЕТ: печатает последние коммиты приёмки (docs: …) из origin/master, где
# названы версия, сумма и исход. Первой строкой — время съёма и рубеж репозитория.
#
# ЧЕГО НЕ ДЕЛАЕТ: не судит, принята ли версия, которая у вас на диске. Сверку
# версии и суммы делает тот, кто спрашивает: своего перечня принятого здесь нет
# намеренно — второй перечень разошёлся бы с вердиктом молча.
#
# ГРАНИЦА: показывает то, что ОТПРАВЛЕНО в origin. Вердикт, лежащий у приёмщика
# локально, сюда не попадёт — и это видно по рубежу: если он старше вашего вопроса,
# ответ может быть неполон.

set -u
REPO=/opt/iskra/workspace/dsh-plugins
# ═══ ПРАВКА 07.09.2026 (п.384 свода, решение координатора 02:37): ВЕРДИКТ ОПОЗНАЁТСЯ ПО ФАЙЛУ
# РАЗБОРА В КОММИТЕ, а не по имени автора. Признак по имени слеп, как только разбор коммитит
# другая рука (решение 02:37: коммитит автор дерева). Автор печатается СПРАВОЧНО.
# Ключ --lokalno: источник HEAD вместо origin/master — при закрытых публикациях origin отстаёт
# по построению, и «вердиктов нет» описывало бы сеть, а не приёмку. Источник печатается.
# 🔴 УМОЛЧАНИЕ — ЛОКАЛЬНОЕ ДЕРЕВО, А НЕ origin (09.09.2026, поручение Забавы).
# ЗАМЕР, ради которого меняется умолчание: origin/master замер на 6da4993 от 06.09 11:16 — за
# два часа до запрета публикации, локально впереди 63 коммита. Канал приёмки мёртв третьи сутки,
# и прибор с умолчанием origin отвечал бы про СЕТЬ, а не про приёмку. Прежнее поведение
# осталось ключом --origin: оно ещё понадобится, когда запрет снимут.
N=12; VETKA=HEAD
for d in "$@"; do case "$d" in --lokalno) VETKA=HEAD;; --origin) VETKA=origin/master;; ''|*[!0-9]*) ;; *) N=$d;; esac; done
PRIZNAK_PUTI='(^|/)(docs/verdikty/|OT-VENIAMINA-verdikt)'   # файл разбора: путь или форма имени
# 🔴 ВТОРОЙ ИСТОЧНИК: ВЕРДИКТЫ ПРИХОДЯТ ФАЙЛАМИ, А НЕ КОММИТАМИ (замер 09.09.2026).
# ЗАЧЕМ. Смены origin→HEAD было бы МАЛО, и это главное в сегодняшней находке: файлов разбора
# в истории git — НОЛЬ в ОБОИХ источниках, а в рабочем каталоге их 77 (OT-VENIAMINA-*).
# Вердикт кладут файлом, коммитом его не проводят. Прибор, ищущий только в git, отвечал бы
# «не найдено» вечно и был бы при этом формально исправен — он честно называл маску и окно.
# ⇒ Источников ДВА, и каждый печатает свой итог отдельно. Смешивать их в одно число нельзя:
# «найдено 3» без указания, где именно, снова сделает предмет неизмеримым со стороны.
# ⚠️ ГРАНИЦА: каталог просматривается НЕ рекурсивно и только по маске имени. Вердикт, положенный
# в подкаталог или под другим именем, невидим — маска печатается рядом с числом, менять её здесь.
KATALOG_VERDIKTOV="${VERDIKTY_KATALOG:-/opt/iskra/workspace}"
MASKA_FAJLOV='OT-VENIAMINA-*'

echo "снято: $(date -u '+%Y-%m-%d %H:%M:%S UTC') на $(hostname)"
[ -d "$REPO/.git" ] || { echo "СЛЕПОТА: репозитория нет: $REPO" >&2; exit 2; }

if ! git -C "$REPO" fetch --quiet 2>/dev/null; then
  echo "⚠️  свежесть НЕ обновлена: fetch не прошёл. Ниже — то, что было получено раньше."
fi

rubezh=$(git -C "$REPO" log $VETKA -1 --format='%h %ci' 2>/dev/null)
if [ -z "$rubezh" ]; then
  # Причина обязана быть названа: пустота от git чаще всего про ПРАВА читающего,
  # а не про предмет. Самый частый случай — чужой владелец каталога.
  prichina=$(git -C "$REPO" log $VETKA -1 --oneline 2>&1 | head -2)
  echo "СЛЕПОТА: ветка $VETKA не читается." >&2
  echo "  git сказал: $prichina" >&2
  echo "  Если это про владельца каталога — снимается у ЧИТАЮЩЕГО, одной строкой:" >&2
  echo "    git config --global --add safe.directory $REPO" >&2
  echo "  Это НЕ значит «вердиктов нет»: значит их не видно ВАМИ." >&2
  exit 2
fi
# 🔴 ВОЗРАСТ РУБЕЖА — В ПЕРВЫХ СТРОКАХ И ЧИСЛОМ (правка 05.09.2026, просьба Забавы).
# Граница «ответ неполон, если рубеж старше вопроса» БЫЛА написана в шапке — и всё
# равно не сработала: её надо ВСПОМНИТЬ в момент чтения ответа. Дата рубежа этого не
# даёт: «23:54:51Z» читается как «свежий», пока не вычтешь в уме. Возраст числом бьёт
# в глаза, вычитать нечего.
rubezh_ts=$(git -C "$REPO" log $VETKA -1 --format='%ct' 2>/dev/null)
if [ -n "$rubezh_ts" ]; then
  vozrast=$(( $(date -u +%s) - rubezh_ts ))
  if   [ "$vozrast" -lt 3600 ];  then vstr="$(( vozrast / 60 )) мин"
  elif [ "$vozrast" -lt 86400 ]; then vstr="$(( vozrast / 3600 )) ч $(( (vozrast % 3600) / 60 )) мин"
  else                                vstr="$(( vozrast / 86400 )) сут"
  fi
  echo "рубеж $VETKA: $rubezh   ВОЗРАСТ: $vstr назад"
  # Час взят не как порог годности, а как порог ЗАМЕТНОСТИ: вердикты у нас ложатся
  # десятками в час, и рубеж старше часа почти наверняка не видел свежих.
  if [ "$vozrast" -ge 3600 ]; then
    echo "⚠️  рубеж старше часа: ответ ниже МОЖЕТ БЫТЬ НЕПОЛОН — вердикты, легшие после"
    echo "    $rubezh, сюда не попали. Это не «их нет», это «их не видно отсюда»."
  fi
else
  echo "рубеж $VETKA: $rubezh   ВОЗРАСТ: не снят (время коммита не прочиталось)"
fi
echo

# 🔴 СЧЁТ ПО АВТОРУ, А НЕ ПО СЛОВУ (правка 05.09.2026, найдено прогоном).
# Прежняя редакция искала слова accept|принят|verdict|вердикт в ЛЮБОМ коммите — и
# засчитывала вердиктами МОИ СОБСТВЕННЫЕ выпуски, где эти слова стоят в описании
# работы («набор пересобран на ПРИНЯТЫХ версиях», «found by acceptance»).
# Замер на живом окне из 12: «вердиктов 3», настоящий — ОДИН.
# Ошибка шла в опасную сторону: счёт завышался моей же рукой, и «вердиктов 3»
# читалось как «приёмка активна», подтверждая приёмку тем, кого она проверяет.
# Вердикт пишет ПРИЁМЩИК — значит признак это АВТОР коммита, а не слово в тексте.
RAB_OSHIBKA=$(mktemp -t verdikty-oshibka-XXXXXX)
# Коммиты окна с перечнем изменённых файлов: блок = «%h|%an|%s», затем пути, затем пустая строка.
syroe=$(git -C "$REPO" log "$VETKA" -"$N" --format='%x01%h|%an|%s' --name-only 2>"$RAB_OSHIBKA")
KOD_LOG=$?
if [ "$KOD_LOG" != 0 ]; then
  echo "🔴 СЛЕПОТА: журнал коммитов не прочитан (код $KOD_LOG) — про ЧТЕНИЕ, не про вердикты." >&2
  sed 's/^/   git: /' "$RAB_OSHIBKA" >&2; rm -f "$RAB_OSHIBKA"; exit 2
fi
rm -f "$RAB_OSHIBKA"
# Разбор блоков одним awk: коммит → есть ли файл, подходящий под PRIZNAK_PUTI.
razbor=$(printf '%s\n' "$syroe" | awk -v re="$PRIZNAK_PUTI" '
  /^\x01/ { if (h!="") print h "|" a "|" s "|" (est?"VERDIKT":"net") "|" f;
            sub(/^\x01/,""); split($0,p,"|"); h=p[1]; a=p[2]; s=$0; sub(/^[^|]*\|[^|]*\|/,"",s); est=0; f=""; next }
  NF==0 { next }
  { if ($0 ~ re) { est=1; f=(f==""?$0:f", "$0) } }
  END { if (h!="") print h "|" a "|" s "|" (est?"VERDIKT":"net") "|" f }')
verdikty=$(printf '%s\n' "$razbor" | awk -F'|' '$4=="VERDIKT"')
najdeno=$(printf '%s' "$verdikty" | grep -c .)
echo "источник: $VETKA   признак вердикта: файл разбора по маске $PRIZNAK_PUTI   окно: $N коммитов"
if [ "$najdeno" -gt 0 ]; then
  printf '%s\n' "$verdikty" | awk -F'|' '{printf "  %s  %s\n      файл: %s   (автор коммита, справочно: %s)\n", $1, $3, $5, $2}'
  echo "вердиктов ПРИЁМКИ в окне: $najdeno"
else
  echo "вердиктов приёмки в последних $N коммитах НЕ НАЙДЕНО (ни одного коммита с файлом разбора)."
  echo "Это НЕ значит «ничего не принято»: значит их нет в этом окне/источнике. Шире: $0 40 [--lokalno]"
fi
# Контроль негодного признака в обе стороны — печатается, чтобы слепота была видна:
po_imeni=$(printf '%s\n' "$razbor" | awk -F'|' 'tolower($2) ~ /veniamin/ && $4!="VERDIKT"' | grep -c .)
[ "$po_imeni" -gt 0 ] && echo "⚠️  коммитов автора veniamin БЕЗ файла разбора: $po_imeni — прежний прибор счёл бы их вердиктами; теперь нет."
chuzhie=$(printf '%s\n' "$verdikty" | awk -F'|' 'tolower($2) !~ /veniamin/' | grep -c .)
[ "$chuzhie" -gt 0 ] && echo "ℹ️  вердиктов, закоммиченных НЕ приёмщиком (по файлу видны): $chuzhie — прежний прибор их не видел."
echo "ГРАНИЦА: вердиктом считается коммит, меняющий файл под маской выше. Разбор, положенный мимо маски, невидим — маска названа, менять её здесь."

# ═══ ИСТОЧНИК 2: ВЕРДИКТЫ-ФАЙЛЫ ═══════════════════════════════════════════════
echo ""
echo "источник 2: каталог $KATALOG_VERDIKTOV   маска: $MASKA_FAJLOV   (не рекурсивно)"
if [ ! -d "$KATALOG_VERDIKTOV" ]; then
  echo "  СЛЕПОТА: каталога нет — это «смотреть негде», а не «вердиктов нет»"
  fajlov=0; svezhih=0
else
  fajlov=$(find "$KATALOG_VERDIKTOV" -maxdepth 1 -name "$MASKA_FAJLOV" -type f 2>/dev/null | grep -c . || true)
  # Свежесть считается от суток, а не «за сегодня»: сутки — окно, не календарь.
  svezhih=$(find "$KATALOG_VERDIKTOV" -maxdepth 1 -name "$MASKA_FAJLOV" -type f -mtime -1 2>/dev/null | grep -c . || true)
  if [ "$fajlov" -eq 0 ]; then
    echo "  вердиктов-файлов НЕ НАЙДЕНО. Это про эту маску и этот каталог, не про приёмку вообще."
  else
    echo "  вердиктов-файлов: $fajlov · за последние сутки: $svezhih"
    find "$KATALOG_VERDIKTOV" -maxdepth 1 -name "$MASKA_FAJLOV" -type f -printf '%T@ %TY-%Tm-%Td %TH:%TM  %f\n' 2>/dev/null \
      | sort -rn | head -5 | cut -d' ' -f2- | sed 's/^/    /'
  fi
fi

# 🔴 ИТОГ ПО КАЖДОМУ ИСТОЧНИКУ ОТДЕЛЬНО, А НЕ ОДНИМ ЧИСЛОМ. Сложенные вместе, они снова
# сделали бы предмет неизмеримым: «найдено 3» не говорит, где смотрели и где пусто.
echo ""
# 🔴 ЗНАМЕНАТЕЛЬ ОБЯЗАТЕЛЕН (добавка принята 09.09.2026). Ноль вердиктов БЕЗ числа
# прочитанного неотличим от нуля по НЕВЕРНОМУ ПУТИ — за сутки поймали три таких нуля подряд.
# «Вердиктов 0» может значить «их нет», «смотрели не туда» и «читать не смогли»: снаружи
# одинаково. Число прочитанного разводит первое от двух остальных.
PROCHITANO_KOMMITOV=$(git -C "$REPO" log $VETKA -n "$N" --format='%H' 2>/dev/null | grep -c . || echo 0)
PROCHITANO_FAJLOV=${fajlov:-0}
echo "ПРОЧИТАНО: коммитов $PROCHITANO_KOMMITOV (окно $N) · файлов в каталоге $PROCHITANO_FAJLOV"
echo "ИТОГ: источников объявлено 2 · git($VETKA): вердиктов $najdeno из $PROCHITANO_KOMMITOV прочитанных · файлы($KATALOG_VERDIKTOV): $fajlov"
if [ "$najdeno" -eq 0 ] && [ "$fajlov" -eq 0 ]; then exit 2; fi
exit 0
