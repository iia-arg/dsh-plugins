#!/bin/bash
# Канарейка перед рестартом живой службы.
#
# ЧТО ДЕЛАЕТ. Поднимает рядом короткоживущую копию платформы — тот же код, те же
# настройки — и смотрит, стартует ли она и отвечает ли. Копия упала — рестарт
# боевой службы ОТМЕНЯЕТСЯ, причина называется человеку.
#
# 🔴 ЧЕГО НЕ ДЕЛАЕТ И НЕ БУДЕТ ДЕЛАТЬ: не перезапускает боевую службу ни при каком
# исходе. Зелёная канарейка — это разрешение человеку, а не команда машине.
# Автоматический рестарт по зелёной пробе превратил бы страховку в источник
# рестартов, то есть ровно в то, от чего она защищает.
#
# 🔴 ГДЕ НЕ ПРИМЕНЯЕТСЯ:
#   * рестарт ради освобождения памяти — там предмет не «поднимется ли код», а
#     «сколько занято»; проба ответит «зелено» и не решит ничего;
#   * рестарт по тревоге сторожа — служба уже не работает, ждать пробы значит
#     продлевать простой; сторож обязан поднимать сразу;
#   * первая установка на чистой машине — копировать нечего.
#
# 🔴 ЧЕГО ЭТОТ КЛАСС НЕ ЛОВИТ ВООБЩЕ:
#   * порчу данных: копия стартует на копии дома, боевые сессии не читает;
#   * медленную деградацию — течь памяти, замедление, редкие отказы: проба живёт
#     секунды;
#   * поведение под нагрузкой и целостность внешних каналов: они намеренно
#     отключены (см. ниже), иначе копия стала бы вторым живым агентом.
#
# 🔴 ЧТО ИМЕННО ОТКЛЮЧЕНО У КОПИИ И ПОЧЕМУ. Эфемерная копия наследует ЛИЧНОСТЬ
# боевого и потому конкурирует с ним за всякую сущность, которую нельзя иметь
# дважды одновременно. Опрос бота, ящик писем, каталог обмена — второй владелец
# ОТНИМАЕТ их у первого, а не делит с ним. Проверено дорого: копия с боевым токеном
# вышибла у живой службы опрос Telegram («Conflict: terminated by other getUpdates
# request»). То есть защита без границы произвела ровно тот вред, от которого
# защищала.
#
# Поэтому подменяемое объявлено ДАННЫМИ — edinstvennye-sushchnosti.json рядом, с
# причиной у каждой записи. Список ПОДЛЕЖИТ ПОПОЛНЕНИЮ: заводя в профиле новую
# такую настройку, впишите её туда, иначе копия отнимет её молча. Нет файла или
# список пуст — канарейка ОТКАЗЫВАЕТСЯ поднимать копию: проба без изоляции опаснее
# отсутствия пробы.
#
# Цена честная и названа: канал связи копией НЕ проверяется.
#
# 🔴 ЗАПУСК СНАРУЖИ — ТОЛЬКО С ЯВНЫМ KANAREJKA_DOM. Дом берётся из $HOME
# запускающего: под другим пользователем канарейка пойдёт искать чужое дерево и
# честно даст слепоту, но время будет потрачено. Правило: KANAREJKA_DOM=<дом агента>.
#
# Коды: 0 копия поднялась | 1 копия не поднялась (рестарт отменить) | 2 проверить нечем.
set -uo pipefail

PROFIL=${1:-web}
DOM_BOEVOJ=${KANAREJKA_DOM:-$HOME}
APP=${KANAREJKA_APP:-$DOM_BOEVOJ/app}
SROK=${KANAREJKA_SROK:-40}

VREMENNYJ=$(mktemp -d /tmp/kanarejka-XXXXXX) || { echo "СЛЕПОТА: временный каталог не создан"; exit 2; }
PID=""
uborka() {
  if [ -n "$PID" ] && kill -0 "$PID" 2>/dev/null; then
    kill "$PID" 2>/dev/null
    for _ in $(seq 1 20); do kill -0 "$PID" 2>/dev/null || break; sleep 0.2; done
    kill -9 "$PID" 2>/dev/null
  fi
  rm -rf "$VREMENNYJ"
}
# Гасим и убираем при ЛЮБОМ выходе, включая обрыв самой канарейки: копия, пережившая
# пробу, — это второй агент, о котором никто не знает.
trap uborka EXIT INT TERM

echo "канарейка: профиль $PROFIL, боевой дом $DOM_BOEVOJ, дерево платформы $APP"

BIN="$APP/node_modules/@deepseek-ai/dsh/lib/bin.js"
[ -f "$BIN" ] || { echo "СЛЕПОТА: не найден вход платформы $BIN — проверять нечего"; exit 2; }
ISHODNYJ="$DOM_BOEVOJ/.dsh/profiles/$PROFIL/cordis.patch.yml"
[ -f "$ISHODNYJ" ] || { echo "СЛЕПОТА: не найден слой профиля $ISHODNYJ"; exit 2; }

# Копия дома: только слои настроек. Сессии НЕ копируются — копии незачем читать
# боевую переписку, а объём журналов сделал бы пробу дорогой.
mkdir -p "$VREMENNYJ/.dsh/profiles/$PROFIL" "$VREMENNYJ/spool" "$VREMENNYJ/a2a/out"
cp "$ISHODNYJ" "$VREMENNYJ/.dsh/profiles/$PROFIL/cordis.patch.yml"
# 🔴 БЕЗ ЭТОГО КОПИЯ ПАДАЕТ ВСЕГДА. Плагины резолвятся ОТ КАТАЛОГА ПРОФИЛЯ, а не от
# дерева платформы: у профиля свой node_modules с ссылками на наши плагины. Первая
# редакция канарейки его не копировала — копия падала на загрузке дерева плагинов
# каждый раз, а вердикт был ЗЕЛЁНЫЙ (см. ниже про признак готовности).
if [ -d "$DOM_BOEVOJ/.dsh/profiles/$PROFIL/node_modules" ]; then
  cp -a "$DOM_BOEVOJ/.dsh/profiles/$PROFIL/node_modules" "$VREMENNYJ/.dsh/profiles/$PROFIL/"
  # 🔴 УТВЕРЖДЕНИЕ ПРИВЕДЕНО К ИЗМЕРЕННОМУ (06.09.2026). Стояло «код тот же, что в бою» —
  # а измерено было ровно то, что ссылки скопированы С ДИСКА. Диск и бой расходятся всякий
  # раз, когда правка сделана после последнего старта процесса: у меня в этот день на диске
  # было шесть пакетов новее боевых. Значит канарейка проверяла НЕ ТО, ЧТО РАБОТАЕТ, а то,
  # что уедет в бой при следующем старте, — и это полезно, но называлось неверно.
  # Класс общий (Михалыч, тот же день, независимо, на своём стороже): диск читается одной
  # командой, бой требует журнала, и потому диск подставляется вместо боя.
  # ⚠️ Признак выбора лечения: бой узнать МОЖНО в том же заходе — значит не оговорку в
  # шапке, а вторую величину в ответе.
  echo "  ссылки на плагины скопированы ($(ls "$VREMENNYJ/.dsh/profiles/$PROFIL/node_modules" | wc -l) шт.) — код С ДИСКА, тот, что уедет в бой при следующем старте"
  # Доизмерение: что процесс называл при последнем подъёме. Расходится с диском — говорим.
  # A-N-1562 (04.10.2026, Заря): номер в обеих формах — 0.1.0-alpha.N и X.Y.Z (перенумерация); имя с дефисом
  # (kompakt-dsh) и хвост после номера (секретарь: «[… V <время>]») прежний регекс не ловил — строка сводится к
  # «[имя номер]». tail -20 снят: при двух формах номеров строк больше двадцати, и срез молча терял пакеты.
  perenum() {
    if [[ $1 =~ ^0\.1\.0-alpha\.([0-9]+)$ ]]; then echo "1.1.$((10#${BASH_REMATCH[1]}))"
    elif [[ $1 =~ ^([0-9]+)\.([0-9]+)\.([0-9]+)$ ]]; then echo "$((10#${BASH_REMATCH[1]}+1)).${BASH_REMATCH[2]}.${BASH_REMATCH[3]}"; fi
  }
  ta_zhe_versiya() {   # равны, или одна — перенумерация другой
    [ "$1" = "$2" ] && return 0
    local p; p=$(perenum "$1"); [ -n "$p" ] && [ "$p" = "$2" ] && return 0
    p=$(perenum "$2"); [ -n "$p" ] && [ "$p" = "$1" ]
  }
  BOEVYE=$(journalctl -u "${KANAREJKA_SLUZHBA:-iskra.service}" --since "-24h" --no-pager 2>/dev/null \
           | grep -oE '\[dsh-pamyat-[a-z]+(-[a-z]+)* [0-9]+\.[0-9]+\.[0-9]+(-alpha\.[0-9]+)?( [^]]*)?\]' \
           | sed -E 's/^(\[[^ ]+ [^ ]+)( [^]]*)?\]$/\1]/' | sort -u)
  if [ -z "$BOEVYE" ]; then
    echo "  ⚠️ ЧТО В БОЮ — НЕ ЗНАЮ: строк подъёма в журнале за сутки нет. Это про мой запрос,"
    echo "     а не про то, что бой пуст: канарейка судит о ДИСКЕ и об этом сказала выше."
  else
    RASHOD=0; ZHDUT=0
    for KAT in "$VREMENNYJ/.dsh/profiles/$PROFIL/node_modules"/dsh-pamyat-*; do
      [ -e "$KAT/package.json" ] || continue
      IMYA=$(basename "$KAT")
      VER=$(node -p "require('$KAT/package.json').version" 2>/dev/null) || continue
      echo "$BOEVYE" | grep -qF "[$IMYA $VER]" && continue
      DRUGAYA=""
      while read -r V; do [ -n "$V" ] && ta_zhe_versiya "$V" "$VER" && DRUGAYA=$V; done \
        < <(echo "$BOEVYE" | sed -n "s/^\[$IMYA \([^]]*\)\]\$/\1/p")
      if [ -n "$DRUGAYA" ]; then
        ZHDUT=$((ZHDUT+1)); echo "  ⚠️ $IMYA: на диске $VER, в журнале подъёма $DRUGAYA — номер другой формы, код тот же (перенумерация A-N-1562) — ждёт подъёма"
      else
        RASHOD=$((RASHOD+1)); echo "  🔴 диск ≠ бой: $IMYA на диске $VER, в журнале подъёма этой версии нет"
      fi
    done
    if [ "$RASHOD" -eq 0 ] && [ "$ZHDUT" -eq 0 ]; then echo "  диск и бой сошлись по всем пакетам памяти: канарейка судит о том же коде, что работает"
    elif [ "$RASHOD" -eq 0 ]; then echo "  диск и бой сошлись по коду; у $ZHDUT пакет(ов) номер в журнале другой формы — ждут подъёма"; fi
  fi
else
  echo "СЛЕПОТА: у профиля нет node_modules — плагины копии не найдёт, проверять нечего"; exit 2
fi
[ -f "$DOM_BOEVOJ/.dsh/cordis.patch.yml" ] && cp "$DOM_BOEVOJ/.dsh/cordis.patch.yml" "$VREMENNYJ/.dsh/"

# Подмена внешних адресов. Каждая — с причиной в журнале пробы, чтобы читающий
# видел, ЧТО именно у копии отключено, и не считал зелёное проверкой канала.
KOPIYA="$VREMENNYJ/.dsh/profiles/$PROFIL/cordis.patch.yml"
# 🔴 СЛОЁВ ДВА, И ДОМАШНИЙ ПЕРЕБИВАЕТ ПРОФИЛЬНЫЙ. Подмена в одном месте оставила бы
# боевое значение действующим — в другом слое. Поэтому правим все слои копии.
SLOI=("$KOPIYA")
[ -f "$VREMENNYJ/.dsh/cordis.patch.yml" ] && SLOI+=("$VREMENNYJ/.dsh/cordis.patch.yml")

# 🔴 БЕЗ ВЕТКИ «КЛЮЧА НЕТ» ЭТО БЫЛА ЗАЩИТА НА УДАЧЕ (блокер ворот 02.09.2026).
# Прежняя редакция при отсутствии ключа молча ничего не делала: ни строки, ни
# отказа — а копия поднималась с боевым умолчанием. Молчащая подмена и удавшаяся
# выглядели одинаково. Теперь исходов ровно два: подменено с контролем либо отказ.
podmenit() {
  local kluch=$1 novoe=$2 zachem=$3 esli_net=$4 pochemu_net=$5
  local nashli=0
  for f in "${SLOI[@]}"; do
    grep -qE "^\s*$kluch:" "$f" || continue
    nashli=1
    sed -i -E "s|^(\s*)$kluch:.*$|\1$kluch: $novoe|" "$f"
    # Контроль ПОСЛЕ подмены: sed мог не совпасть, права могли не дать записать,
    # значение могло уехать в другую строку. «Команда отработала» и «значение
    # заменилось» — разные утверждения.
    if ! grep -qF "$kluch: $novoe" "$f"; then
      echo "🔴 ОТКАЗ: подмена $kluch в $(basename "$f") НЕ УДАЛАСЬ — подъём с боевой сущностью запрещён."
      exit 2
    fi
    if grep -qE "^\s*$kluch:" "$f" && grep -E "^\s*$kluch:" "$f" | grep -qv "$novoe"; then
      echo "🔴 ОТКАЗ: в $(basename "$f") остались непеределанные вхождения $kluch — подъём запрещён."
      exit 2
    fi
    echo "  подменено $kluch -> $novoe ($zachem)"
  done
  [ "$nashli" = 1 ] && return 0
  if [ "$esli_net" = bezopasno ]; then
    echo "  $kluch в слоях не задан — подменять нечего, и это безопасно: $pochemu_net"
    return 0
  fi
  echo "🔴 ОТКАЗ: $kluch не задан ни в одном слое, а отсутствие ключа НЕ означает"
  echo "   отсутствия сущности: $pochemu_net"
  echo "   Либо задайте ключ в слое, либо объявите в списке esli_net: bezopasno с причиной."
  exit 2
}
SPISOK=${KANAREJKA_SPISOK:-$(dirname "$0")/edinstvennye-sushchnosti.json}
if [ ! -f "$SPISOK" ]; then
  echo "🔴 ОТКАЗ: нет списка единственных сущностей ($SPISOK). Копию без изоляции не поднимаю:"
  echo "   она отнимет у боевого то, ради сохранности чего эта проба и заводилась."
  exit 2
fi
CHISLO=$(python3 -c "
import json,sys
try:
    d=json.load(open('$SPISOK'))
    print(len(d.get('podmenit') or []))
except Exception as e:
    print(0)") || CHISLO=0
if [ "${CHISLO:-0}" -lt 1 ]; then
  echo "🔴 ОТКАЗ: список единственных сущностей пуст или негоден ($SPISOK)."
  echo "   Пустой список изоляции неотличим от изоляции — но не изолирует ничего."
  exit 2
fi
echo "изоляция копии (из $SPISOK, записей $CHISLO):"
while IFS=$'\t' read -r kluch chem pochemu esli_net pochemu_net; do
  [ -n "$kluch" ] || continue
  podmenit "$kluch" "$(eval echo "$chem")" "$pochemu" "$esli_net" "$pochemu_net"
done < <(python3 -c "
import json
d=json.load(open('$SPISOK'))
for z in d['podmenit']:
    print('\t'.join([z['kluch'], z['chem'], z['pochemu'],
                      z.get('esli_net','otkaz'), z.get('esli_net_pochemu','причина не объявлена')]))
")

# 🔴 ПРОВЕРКА РЕЗУЛЬТАТА, А НЕ СПИСКА. Список решает «не забыть», но не решает
# «не пропустить»: убери из него запись — и копия молча пойдёт с боевым адресом
# (поймано порчей 02.09.2026, канарейка дала зелёное с боевым токеном). Поэтому
# после подмен смотрим, не осталось ли в копии профиля путей ЗА ПРЕДЕЛЫ временного
# каталога. Забытая запись и новая настройка, о которой никто не подумал, дают
# отказ одинаково — а объявленные читаемые (их копия не отнимает) пропускаются.
CHITAEMYE=$(python3 -c "
import json
d=json.load(open('$SPISOK'))
print('|'.join(z['kluch'] for z in d.get('chitaemye') or []) or 'НЕТ_ТАКОГО_КЛЮЧА')")
# 🔴 ПО ОДНОМУ ФАЙЛУ ЗА РАЗ. При нескольких файлах grep печатает ИМЯ ФАЙЛА в начале
# строки, а имя это лежит внутри временного каталога — и фильтр «выкинуть строки с
# временным каталогом» съедал ВСЁ подряд. Проверка становилась слепой и говорила
# «чужих адресов нет» о чём угодно. Поймано стендом 02.09.2026.
CHUZHIE=""
for f in "${SLOI[@]}"; do
  najd=$(grep -nE '^\s*[a-zA-Z_]+:\s*/' "$f" \
    | grep -vE "^[0-9]+:\s*($CHITAEMYE):" \
    | grep -vF "$VREMENNYJ" || true)
  [ -n "$najd" ] && CHUZHIE="$CHUZHIE$(basename "$f"): $najd"$'\n'
done
if [ -n "$CHUZHIE" ]; then
  echo "🔴 ОТКАЗ: в копии профиля остались чужие адреса — копию не поднимаю."
  echo "   Либо впишите ключ в podmenit (сущность отнимается), либо в chitaemye (только читается):"
  printf '%s\n' "$CHUZHIE" | sed 's/^/     /'
  exit 2
fi
echo "  проверка результата: чужих адресов в копии профиля не осталось"

# Свободный порт спрашиваем у ядра, а не выбираем на глаз: занятый порт дал бы
# красную канарейку на исправном коде.
PORT=$(python3 -c "
import socket
s=socket.socket(); s.bind(('127.0.0.1',0)); print(s.getsockname()[1]); s.close()") || {
  echo "СЛЕПОТА: свободный порт не получен"; exit 2; }
echo "канарейка: порт $PORT, срок ожидания $SROK с"

VYVOD="$VREMENNYJ/vyvod.txt"

# 🔴 ПРИЧИНА СТОИТ В НАЧАЛЕ ВЫВОДА, А ХВОСТ — СТЕК ВЫЗОВОВ РАНТАЙМА. Голый `tail`
# показывает «at async …» и прячет саму ошибку: имя ненайденного модуля уходит выше
# экрана, и его приходится доставать отдельной командой (куплено монтажом 02.09.2026).
# Второй экземпляр того же класса: в канарейке ШЛЮЗА это вылечено, здесь не было.
# ГДЕ НЕ ПРИМЕНЯЕТСЯ: приём не разбирает отказ и не судит о нём — он только ставит
# причину ПЕРЕД хвостом и не даёт полному выводу исчезнуть вместе с временным каталогом.
prichinu_i_hvost() {
  echo "причина (первая строка с ошибкой):"
  { grep -m1 -E '^[A-Za-z]*Error|Cannot find package|ERR_MODULE_NOT_FOUND' "$VYVOD" \
    || head -3 "$VYVOD"; } | sed 's/^/    /'
  echo "последние строки копии:"
  tail -12 "$VYVOD" | sed 's/^/    /'
  # Временный каталог уберётся при выходе — полный вывод надо СПАСТИ сейчас,
  # иначе разбирать отказ будет не по чему.
  # B-N-1575: имя через mktemp (O_EXCL, 600), а не предсказуемое «-$$.log»: заранее положенное на предсказуемом
  # имени срывало сохранение лога молча; на машине без protected_symlinks — ещё и запись по ссылке.
  SPASENO=$(mktemp "/tmp/kanarejka-restarta-otkaz-$$-XXXXXX.log" 2>/dev/null) \
    && cp "$VYVOD" "$SPASENO" 2>/dev/null && echo "полный вывод копии сохранён: $SPASENO" \
    || { [ -n "${SPASENO:-}" ] && rm -f -- "$SPASENO"; echo "лог отказа НЕ сохранён" >&2; }
}
# 🔴 СЕКРЕТ МОЖНО ЗАДАТЬ В ОБХОД СЛОЁВ — переменной окружения. Копия наследует
# окружение запускающего, поэтому переменные связи гасятся явно: иначе подмена в
# слоях есть, а токен приходит мимо неё.
DSH_TELEGRAM_BOT_TOKEN= TELEGRAM_BOT_TOKEN= \
HOME="$VREMENNYJ" DSH_HOME="$VREMENNYJ/.dsh" \
  node "$BIN" web --port "$PORT" >"$VYVOD" 2>&1 &
PID=$!

# 🔴 ПРИЗНАК ГОТОВНОСТИ — НЕ «ПОРТ ОТВЕТИЛ». Платформа поднимает веб РАНЬШЕ, чем
# грузит дерево плагинов: порт отдаёт 200 за доли секунды, а падение на плагинах
# приходит следом. Первая редакция ловила ответ порта и объявляла успех — зелёное
# на копии, которая умирала через мгновение. Поймано неправдоподобной быстротой
# (0,77 с на старт платформы) и проверкой вывода копии, а не кодом ответа.
# Поэтому: дождались ответа -> ЖДЁМ УСТОЙЧИВОСТИ -> проверяем, что процесс ЖИВ и
# в выводе нет фатальной ошибки.
USTOJ=${KANAREJKA_USTOJ:-6}
podnyalsya=нет
kod=000
for _ in $(seq 1 $((SROK * 2))); do
  if ! kill -0 "$PID" 2>/dev/null; then break; fi
  kod=$(curl -s --noproxy '*' -o /dev/null -m 2 -w '%{http_code}' "http://127.0.0.1:$PORT/" 2>/dev/null)
  if [ "$kod" != "000" ] && [ -n "$kod" ]; then podnyalsya=да; break; fi
  sleep 0.5
done
if [ "$podnyalsya" = да ]; then
  echo "канарейка: порт ответил ($kod), жду ${USTOJ} с на устойчивость"
  sleep "$USTOJ"
  if ! kill -0 "$PID" 2>/dev/null; then
    podnyalsya=нет
    echo "🔴 копия ответила и умерла в течение ${USTOJ} с — веб поднимается раньше плагинов"
  elif grep -qE 'plugin tree failed to load|failed to apply loader entry' "$VYVOD"; then
    podnyalsya=нет
    echo "🔴 копия жива, но дерево плагинов НЕ загрузилось"
  fi
fi

if [ "$podnyalsya" = да ]; then
  echo
  echo "ИТОГО: копия поднялась и ответила (порт $PORT, код $kod)"
  # 🔴 ЗЕЛЁНОЕ ОБЯЗАНО НАЗЫВАТЬ, ЧТО ИМЕННО ПОДНЯЛОСЬ (03.09.2026). Раньше вывод копии
  # показывался ТОЛЬКО при неудаче: канарейка отвечала «поднялась» на том, что платформа
  # вернула 200, — а упавший или молча не смонтированный плагин в этот ответ умещался.
  # Поймано при монтаже restore: канарейка зелёная, а следа модуля в её выводе ни одного,
  # и отличить «поднялся молча» от «не поднялся» было нечем.
  # ГРАНИЦА: отсутствие следа НЕ означает отказ — не всякий модуль печатает при подъёме.
  # Это перечень услышанного, а не список смонтированного; список знает только cordis.
  netSleda=нет
  # 🔴 ИМЯ МОЖЕТ ИДТИ С ВЕРСИЕЙ. Правило фермы 03.09.2026: каждая строка модуля несёт имя
  # И версию — «[dsh-pamyat-core 0.1.0-alpha.13]». Прежний шаблон ждал имя БЕЗ пробела и
  # таких строк не видел вовсе: канарейка честно печатала «следы: claude-oauth mcp-bridge»,
  # умалчивая о поднявшихся ядре, секретаре, restore и пробнике. Правка формата у одного
  # сломала разбор у другого — тот же класс, что в тот же день со сводкой учёта.
  sledy=$(grep -oE '^\[[a-zA-Z0-9_-]+( [^]]+)?\]' "$VYVOD" 2>/dev/null \
          | sed -E 's/^\[([a-zA-Z0-9_-]+).*/\1/' | sort -u | tr '\n' ' ')
  echo "следы модулей в выводе копии: ${sledy:-НИ ОДНОГО}"
  if [ -n "${KANAREJKA_ZHDU:-}" ]; then
    # Ожидаемые модули задаются вызывающим: канарейка не знает, что мы сейчас монтируем.
    # Пусто — проверка не делается вовсе и об этом не молчится.
    for m in $KANAREJKA_ZHDU; do
      if grep -q "^\[$m\]" "$VYVOD" 2>/dev/null; then
        echo "  ✓ $m — след подъёма есть"
      else
        echo "  🔴 $m — следа подъёма НЕТ (ждали его по KANAREJKA_ZHDU)"
        # 🔴 СВОЙ ФЛАГ, А НЕ podnyalsya=нет. Первая редакция сбрасывала общий флаг —
        # и управление уходило в ветку таймаута, которая печатала «за N с копия не
        # ответила на порту», хотя копия ОТВЕТИЛА. Отказ называл чужую причину:
        # читающий пошёл бы искать беду со стартом вместо ненайденного модуля.
        netSleda=да
      fi
    done
    # 🔴 КОГО ЖДАТЬ МОЖНО, А КОГО НЕТ — ЗНАНИЕ ЖИВЁТ ЗДЕСЬ, А НЕ В ПЕРЕПИСКЕ
    # (замер 03.09.2026, прогон каждого модуля в отдельном процессе с боевой
    # настройкой). Из шести слоёв памяти след при ИСПРАВНОЙ работе подают двое:
    #   dsh-pamyat-restore  — безусловная строка подъёма
    #   dsh-pamyat-core     — но только пока стоит otvechayushchegoNet: true;
    #                         уберут — замолчит, след держится на настройке
    # Молчат при исправной работе: omega, secretary, byudzhet, nudzh. У них крик
    # привязан к БЕДЕ — «предел не задан», «связь отказала», «сводка потеряна».
    #
    # 🔴 ОТСЮДА СОБЛАЗН, КОТОРЫЙ НАЗЫВАЮ, ЧТОБЫ ЕГО НЕ БЫЛО: механизм, чьё
    # единственное свидетельство существования — жалоба, подтверждается тем хуже,
    # чем лучше настроен. Оставлять беду ради следа НЕЛЬЗЯ, даже «временно».
    # Лечение — безусловная строка подъёма у самого модуля, а не наша порча.
    #
    # Поэтому в KANAREJKA_ZHDU кладут только кричащих. Ложное «шесть из шести»
    # хуже честного «два»: оно превращает канарейку в вечно-зелёного судью.
  else
    echo "  (KANAREJKA_ZHDU не задан — поимённо никого не ждали; список выше только для чтения)"
    echo "  подсказка: поимённо можно ждать только тех, кто кричит при ИСПРАВНОЙ работе."
    # 🔴 ЗДЕСЬ СТОЯЛ ПЕРЕЧЕНЬ ОТ 04.09.2026 И УСПЕЛ ПРОТУХНУТЬ (правка 06.09.2026).
    # Он называл молчащими omega, byudzhet и nudzh — а 06.09 закрыт долг 66, и строку
    # подъёма печатают ВСЕ ШЕСТЬ пакетов памяти. Перечень в подсказке стареет молча:
    # читающий взял бы его как список и не стал бы ждать троих, которые уже кричат.
    # Поэтому здесь названо ПРАВИЛО и КОМАНДА, которой список снимается СЕЙЧАС, а не
    # число, верное на день написания.
    echo "  Список снимается замером, а не памятью — он меняется с каждым выпуском:"
    echo "      node /opt/agent-plugins/node_modules/dsh-pamyat-storozha/bin/proba-sleda-podyoma.mjs"
    echo "  Кто в нём «ok» — того можно ждать поимённо; «FAIL» значит, что пакет молчит"
    echo "  при исправном подъёме, и ожидание его имени сделает канарейку вечно-красной."
  fi
  if [ "$netSleda" = да ]; then
    echo
    echo "🔴 РЕСТАРТ ОТМЕНЯЕТСЯ: копия поднялась и ответила, но ожидаемый модуль не подал следа."
    echo "   Это НЕ отказ старта: платформа жива, порт ответил $kod. Причина в другом —"
    echo "   модуль либо не смонтирован, либо молчит при подъёме. Различить можно только"
    echo "   вывод копии прочитав; разбор ниже."
    prichinu_i_hvost
    exit 1
  fi
  echo "🔴 РЕСТАРТ НЕ СДЕЛАН И НЕ БУДЕТ: зелёная канарейка — разрешение человеку, а не команда."
  echo "   Копией НЕ проверены: канал связи (токен отключён), приём писем, работа под нагрузкой."
  exit 0
fi

echo
if kill -0 "$PID" 2>/dev/null; then
  prichina="за $SROK с копия не ответила на порту $PORT (процесс ещё жив — старт не завершился)"
else
  wait "$PID" 2>/dev/null; kodvyhoda=$?
  prichina="копия умерла, код выхода $kodvyhoda"
fi
echo "🔴 РЕСТАРТ ОТМЕНЯЕТСЯ: $prichina"
prichinu_i_hvost
exit 1
