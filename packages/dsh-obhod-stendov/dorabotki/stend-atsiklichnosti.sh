#!/bin/bash
# Приёмка устройства двух учётов машины: граф измерения содержимого обязан быть БЕЗ ПЕТЕЛЬ.
#
# Зачем это отдельный стенд, а не строка в чужом. Оба учёта по отдельности проверяются
# своими средствами (--check и verify), но НИ ОДИН из них не отвечает на вопрос
# «а не меряем ли мы друг друга по кругу». Взаимное измерение содержимого не сходится
# никогда: каждое сведение меняет оба отпечатка и порождает новое расхождение. Снаружи
# это выглядит как «учёт вечно красный», и лечится обычно тем, что сведение бросают —
# то есть обе опоры молча выключаются.
#
# Коды: 0 сошлось · 1 расхождение · 2 слепота (проверить не удалось)
#
# ══ РАМКА ЭТОГО СТЕНДА (что он смотрит и чего НЕ смотрит) ═══════════════════
# Границы установлены замером 24.08, а не написаны по памяти. Пока рамка не
# объявлена, с ней нельзя спорить: чтобы возразить, надо сперва заметить, что
# она есть, — а стенд всё это время честно зеленеет обо всём, что за ней.
#
# СМОТРИТ ровно четыре объекта: $SH, $MAN, $REG и agents.yaml (последний —
#   жёстким путём в проверке 1). 🔴 Список объектов графа задан здесь РУКАМИ,
#   а не выведен из учётов. Заведут пятый учётный файл — стенд промолчит,
#   и молчание будет неотличимо от «петли нет». Сверять при заведении нового
#   учёта; на 24.08 учётных объектов ровно эти четыре (замерено по
#   /etc/agent-registry + dorabotki/).
#
# 🔴 ПРОВЕРКА 5 НАПОЛОВИНУ БОЕВАЯ. `"$SH" --check` идёт по подменённому пути,
#   а `agent-plugins verify` — ВСЕГДА по боевому: путь реестра зашит у него
#   константой (agent-plugins:43, переопределений 0 — замерено). Значит при
#   прогоне на копиях строка «первый учёт: код 0» относится к БОЕВОЙ машине,
#   а не к копии. Не дефект стенда, а свойство инструмента (долг 13), но
#   читать вывод проверки 5 как «копия здорова» нельзя.
#
# ПРОВЕРКА 3 идёт на МОДЕЛИ во временном каталоге, не на предмете. Она
#   доказывает свойство схемы (взаимное измерение не сходится, одностороннее
#   сходится) и НИЧЕГО не говорит о состоянии машины.
#
# ПРОВЕРКА 4 опирается на то, что манифест бесшапочный: строка = позиция
#   (замер 24.08: 57 строк, 0 комментариев и пустых). Появится заголовок или
#   комментарий — покраснеет на исправном учёте.
#
# НЕ ПРОВЕРЯЕТ вовсе:
#   · верно ли ТО, ЧТО записано в учётах, — это `verify` и `--check`;
#   · согласованную подмену (файл и его эталон правят разом) — она требует
#     подставного предмета у первого учёта, которого нет (долг 13);
#   · права, владельца и целость самих учётных файлов;
#   · граф измерения ВНЕ этих четырёх объектов: сторожа, скиллы, документы
#     процедур в него не входят и здесь не рассматриваются.
set -u
# 🔴 ДВА РАЗНЫХ ПОНЯТИЯ, и их смешение даёт ложно-красное (поймано порчей 24.08):
#   SH/MAN/REG      — ОТКУДА ЧИТАТЬ предмет. Подменяются, чтобы гонять стенд на копиях.
#   NAME_SH/...     — ЧТО ЗАПИСАНО в самих учётах. Это всегда боевые пути: граф описывает
#                     боевые объекты, а не тот адрес, по которому стенд их сегодня открыл.
# Слив их воедино красит исправный предмет при любом перенаправлении — проверка отвечает
# тогда на вопрос «совпал ли адрес чтения с записанным», а не «мерит ли учёт этот файл».
SH=${SH:-/opt/iskra/workspace/dorabotki/nashi-dorabotki.sh}
MAN=${MAN:-/opt/iskra/workspace/dorabotki/manifest.txt}
REG=${REG:-/etc/agent-registry/plugins.yaml}
NAME_SH=${NAME_SH:-/opt/iskra/workspace/dorabotki/nashi-dorabotki.sh}
NAME_MAN=${NAME_MAN:-/opt/iskra/workspace/dorabotki/manifest.txt}
NAME_REG=${NAME_REG:-/etc/agent-registry/plugins.yaml}
ok=0; fail=0; slep=0
zeleno(){ printf '  ok   %s\n' "$1"; ok=$((ok+1)); }
krasno(){ printf '  FAIL %s\n' "$1"; fail=$((fail+1)); }
slepo() { printf '  СЛЕПОТА %s\n' "$1"; slep=$((slep+1)); }

for f in "$SH" "$MAN" "$REG"; do
  [ -r "$f" ] || { slepo "не читается предмет: $f"; }
done
[ $slep -gt 0 ] && { echo "стенд не может измерять — предметы недоступны"; exit 2; }

echo "== 1. КТО КОГО МЕРИТ (стрелки графа, снято с боевых файлов) =="
# манифест ведёт файл, если в списке скрипта есть строка КЛАСС|путь|
vedet_manifest(){ grep -qE "^[ABCDE]\|$1\|" "$SH"; }
# реестр ведёт файл, если путь стоит в installed_check какой-нибудь записи
vedet_reestr(){ python3 - "$REG" "$1" <<'PY'
import sys,yaml
reg,path=sys.argv[1],sys.argv[2]
d=yaml.safe_load(open(reg)) or {}
items=(d.get('plugins') or [])+(d.get('services') or [])
sys.exit(0 if any(path in str(it.get('installed_check','')) for it in items) else 1)
PY
}
vedet_manifest "$NAME_REG"        && zeleno "манифест мерит СОДЕРЖИМОЕ реестра ($REG)" \
                             || krasno "реестр вмешательств не мерится никем — подмена пройдёт молча"
vedet_reestr "$NAME_SH"           && zeleno "реестр мерит ИНСТРУМЕНТ второго учёта ($SH)" \
                             || krasno "скрипт второго учёта вне обоих учётов"
vedet_manifest /etc/agent-registry/agents.yaml && zeleno "манифест мерит содержимое реестра агентов" \
                             || krasno "agents.yaml остался без опоры"

echo "== 2. ТОЧКА РАЗРЫВА ЦИКЛА =="
# manifest.txt меняется при КАЖДОМ сведении. Если его начать мерить — сведение перестанет сходиться.
if vedet_reestr "$NAME_MAN"; then
  krasno "manifest.txt внесён в реестр — сведение перестанет сходиться (см. проверку 3)"
elif grep -qE "^[ABCDE]\|$NAME_MAN\|" "$SH"; then
  krasno "manifest.txt внесён сам в себя — учёт мерит собственный вывод"
else
  zeleno "manifest.txt не мерится ничем — цикл разорван здесь"
fi
# 🔴 ПОПРАВКА 07.09.2026. Прежде проба звучала «скрипт не должен мерить сам себя» и с
# 06.09 краснела на ИСПРАВНОМ учёте: в тот день самопокрытие завели НАМЕРЕННО — до него
# один из двух учётов себя не сверял вовсе. Проба отстала от решения и стала ложным
# красным, а ложное красное учит не смотреть.
# ЧТО ОНА ОХРАНЯЛА НА САМОМ ДЕЛЕ: «испорченный измеритель врал бы про себя». Это верно
# ровно тогда, когда СНАРУЖИ его не сверяет никто. Значит признак не «мерит ли себя», а
# «есть ли ВТОРАЯ РУКА» — реестр /etc/agent-registry ведёт этот же файл.
if grep -qE "^[A-Z]\|$NAME_SH\|" "$SH"; then
  if vedet_reestr "$NAME_SH"; then
    zeleno "скрипт мерит себя, и это законно: снаружи его сверяет реестр ($REG) — вторая рука есть"
  else
    krasno "скрипт мерит сам себя, а ВНЕШНЕГО сторожа нет: подмена вместе с эталоном пройдёт молча"
  fi
else
  zeleno "скрипт себя не мерит: его отпечаток снимает реестр, инструмент внешний"
fi

echo "== 3. СХОДИМОСТЬ, доказанная моделью, а не рассуждением =="
T=$(mktemp -d) || { slepo "нет временного каталога"; echo "итог: не измерено"; exit 2; }
trap 'rm -rf "$T"' EXIT
# взаимное: A хранит отпечаток B, B хранит отпечаток A
printf 'x: 1\nB: PUSTO\n' > "$T/A"; printf 'A|PUSTO\n' > "$T/B"
soshlos=нет
for i in $(seq 1 12); do
  hb=$(md5sum "$T/B"|cut -c1-8); sed -i "s/^B: .*/B: $hb/" "$T/A"
  ha=$(md5sum "$T/A"|cut -c1-8); printf 'A|%s\n' "$ha" > "$T/B"
  [ "$(sed -n 's/^B: //p' "$T/A")" = "$(md5sum "$T/B"|cut -c1-8)" ] && { soshlos=да; break; }
done
[ "$soshlos" = нет ] && zeleno "взаимное измерение не сошлось за 12 сведений — петля действительно не сходится" \
                     || krasno "модель сошлась: проверка 3 больше ничего не доказывает, менять модель"
# одностороннее
printf 'x: 1\n' > "$T/A2"; printf 'A2|PUSTO\n' > "$T/B2"
ha=$(md5sum "$T/A2"|cut -c1-8); printf 'A2|%s\n' "$ha" > "$T/B2"
[ "$(cut -d'|' -f2 "$T/B2")" = "$(md5sum "$T/A2"|cut -c1-8)" ] && zeleno "односторонняя стрелка сходится с первого шага" \
                     || krasno "не сошлась даже односторонняя — врёт сама модель, а не предмет"

echo "== 4. СОСТАВ: список и манифест об одном и том же =="
# 🔴 ПОПРАВКА 07.09.2026. Прежде сравнивались ДВА ЦЕЛЫХ ЧИСЛА: позиции перечня против
# ВСЕХ строк манифеста. Так нельзя: в манифесте живут разряды, которых в перечне нет ПО
# ПОСТРОЕНИЮ — их строит сам код при прогоне (P — сумма пакета, заведён 05.09; Q —
# документы процедур, 06.09). С 05.09 проба краснела ВСЕГДА на исправном учёте, и число
# 347 в её крике вдобавок включало шапку файла, а не только позиции.
# ГОДНЫЙ ПРИЗНАК: сверять ПОКЛАССНО те разряды, что объявлены в перечне, а динамические
# называть отдельной строкой И ЧИСЛОМ. Разряды берутся у самого перечня, а не вписаны
# сюда: вписанный список повторил бы ту же беду при следующем новом разряде.
klassy_spiska=$(grep -oE '^[A-Z]\|' "$SH" | tr -d '|' | sort -u)
poz=$(grep -cE '^[A-Z]\|' "$SH")
if [ "$poz" -eq 0 ]; then
  krasno "в списке НОЛЬ позиций — учёт был бы зелен потому, что не ведёт ничего"
else
  rashod=0; svedeno=0; din0=""; dinN0=0
  for k in $klassy_spiska; do
    # B-N-1768 (07.10, Аврора): разряд бывает СМЕШАННЫМ (Q: 1 строка в перечне, остальные дописывает обход каталогов кодом) —
    #   сверяем в манифесте только ПУТИ ИЗ ПЕРЕЧНЯ; остаток разряда — «строит КОД», называется числом ниже, а не красным.
    a=$(grep -cE "^$k\|" "$SH"); b=$(grep -E "^$k\|" "$SH" | cut -d'|' -f1,2 | grep -cFxf - <(cut -d'|' -f1,2 "$MAN"))
    ost=$(( $(grep -cE "^$k\|" "$MAN") - b )); [ "$ost" -gt 0 ] && { din0="$din0$k(+остаток) "; dinN0=$((dinN0 + ost)); }
    svedeno=$((svedeno+1))
    if [ "$a" != "$b" ]; then
      krasno "разряд $k: в перечне $a, в манифесте $b — учёт ведёт не то, что объявлено (не сведено?)"
      rashod=$((rashod+1))
    fi
  done
  din="$din0"; dinN=$dinN0
  for k in $(grep -oE '^[A-Z]\|' "$MAN" | tr -d '|' | sort -u); do
    case " $(echo $klassy_spiska) " in
      *" $k "*) ;;
      *) din="$din$k "; dinN=$((dinN + $(grep -cE "^$k\|" "$MAN")));;
    esac
  done
  [ "$rashod" -eq 0 ] && zeleno "поклассно сошлось: разрядов перечня $svedeno, позиций $poz; строит КОД (в перечне их нет по построению): ${din:-нет} — $dinN позиций"
fi

echo "== 5. ОБА УЧЁТА ОТВЕЧАЮТ ЗЕЛЁНЫМ ПРЯМО СЕЙЧАС =="
vyvod2=$("$SH" --check 2>&1); k2=$?
# 19.10 (наряд Забавы 04:58Z): при коде ≠ 0 — ПРЕДМЕТ рядом с причиной. Ночной отчёт берёт строку FAIL; без предмета
# «правка не сведена?» нельзя разобрать задним числом (ночь 18.10 так и осталась без ответа). Сначала печатается реальная разница manifest.txt, затем предметный guard (ПИШЕТ-ПОДЪЁМ, обещанный --kontrol, ХОЗЯИН, ПАРА).
# Справочные progon/dvojniki не объясняют код отказа; неизвестная причина названа прямо и дополнена хвостом. Счёт проверок не меняется.
predmet2=""; n2=0; prichina2=""
if [ $k2 != 0 ]; then
  # progon и dvojniki печатают красное как справку и не меняют код --check.
  # Сначала предмет реального отказа: diff манифеста либо конечный guard.
  predmet2=$(printf '%s\n' "$vyvod2" | grep -E '^[-+][A-Z]\|' || true)
  if [ -n "$predmet2" ]; then
    prichina2="разница manifest.txt"
  else
    predmet2=$(printf '%s\n' "$vyvod2" | grep -E '^но |^НЕТ МАНИФЕСТА:|^СЛЕПОТА:|^ОТКАЗ:|^ПАРА |^[[:space:]]*🔴 (ХОЗЯИН|ПИШЕТ-ПОДЪЁМ:|обещан контроль, а файла нет:|описание обещает --kontrol, в коде его НЕТ:)|^    [^ ]+:[^ ]+ /' || true)
    prichina2="отказ проверки"
  fi
  if [ -z "$predmet2" ]; then
    prichina2="причина кода $k2 не выделена"
    predmet2=$(printf '%s\n' "$vyvod2" | tail -n 5)
  fi
  n2=$(printf '%s\n' "$predmet2" | grep -c . || true)
fi
/usr/local/bin/agent-plugins verify >/dev/null 2>&1; k1=$?
# B-N-1768: код 2 учёта — «проверить не удалось» (под iskra verify не читает /etc/agent-secrets и дом alfa) — СЛЕПОТА, не FAIL.
if [ $k2 = 0 ]; then zeleno "второй учёт: код 0"; elif [ $k2 = 2 ]; then slepo "второй учёт: код 2 — не измерено"; else krasno "второй учёт: код $k2 · $prichina2 · строк $n2, первая: $(printf '%s\n' "$predmet2" | head -n 1 | cut -c1-160)"; fi
[ $k2 != 0 ] && printf '%s\n' "$predmet2" | head -n 30 | sed 's/^/         | /'
if [ $k1 = 0 ]; then zeleno "первый учёт: код 0"; elif [ $k1 = 2 ]; then slepo "первый учёт: код 2 — не измерено (права учётки?)"; else krasno "первый учёт: код $k1"; fi

echo
echo "итог: ok=$ok fail=$fail слепота=$slep"

# Канарейка: ТОЧНОЕ число проверок, не «не меньше». Порог слеп к убыли ровно
# того размера, который умещается в запас, и выглядит строже, чем работает:
# «не меньше» звучит как требование, а действует как разрешение.
# Замерено 25.08.2026 приёмом «сверься с соседом того же вида»: канарейка была
# у 3 стендов из 13. Вырезанный раздел проходил кодом 0 — выпотрошенный стенд
# отчитывался успехом.
ZHDYOM_PROVEROK=10
if [ $((ok+fail+slep)) -ne $ZHDYOM_PROVEROK ]; then
  echo "СЛЕПОТА: проверок $((ok+fail+slep)), а стенд состоит из $ZHDYOM_PROVEROK — часть не состоялась."
  echo "         Меняли стенд намеренно? Поправьте ZHDYOM_PROVEROK и скажите, почему."
  exit 2
fi
[ $slep -gt 0 ] && exit 2
[ $fail -gt 0 ] && exit 1
exit 0
