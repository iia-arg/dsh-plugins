#!/bin/bash
# Приёмка хранилища секретов /etc/agent-secrets.
# Коды: 0 всё сошлось | 1 расхождение | 2 слепота (проверить не удалось)
#
# 🔴 ГРАНИЦА ОХВАТА — о чём стенд НЕ высказывается. Замерено 25.08.2026, команда
# рядом с каждым пунктом. Зелёный означает ровно это и ничего больше.
#
#   1. ХРАНИЛИЩЕ ЗАПОЛНЕНО, НО ИМ НИКТО НЕ ПОЛЬЗУЕТСЯ. Ни один потребитель не
#      переведён: юниты и слой профиля читают ИСХОДНЫЕ файлы напрямую
#      (GATEWAY_TOKEN_FILE, tokenFile), а
#        sudo -n grep -rlc 'agent-secrets|pass show' /etc/systemd/system/*.service …
#      даёт пусто. Стенд отвечает «секрет лежит и читается предназначенной рукой»,
#      а НЕ «служба берёт его отсюда». Пока перевода нет, зелёный означает лишь
#      «есть чем восстановить», и снимать исходники по нему нельзя.
#
#   2. ЗНАЧЕНИЕ С ИСХОДНИКОМ НЕ СВЕРЯЕТСЯ. Стенд не читает /etc/claude-oauth/token
#      и прочие исходные файлы вовсе (grep по этому файлу: ни одного упоминания).
#      Значит устаревшее содержимое ветки — сменили токен в файле, а в хранилище
#      осталось прежнее — отсюда не видно. Разовая сверка хешами делалась при
#      перекладке 24.08; постоянной проверки на это нет.
#
#   3. РАЗГРАНИЧЕНИЕ МЕЖДУ АГЕНТАМИ СТРУКТУРНО ГОТОВО, НО НЕ ДЕЙСТВУЕТ. Все пять
#      .gpg-id называют один и тот же ключ (sudo -n find /etc/agent-secrets -name
#      .gpg-id -exec cat). Стенд доказывает, что ПОСТОРОННИЙ не прочтёт; что один
#      агент машины не прочтёт ветку другого, он проверить сейчас не может —
#      второго ключа не существует.
#
#   4. ПРОТИВ РУКИ С sudo ЭТО НЕ ЗАЩИТА, и стенд её не измеряет. Ключи без
#      парольной фразы, значит защита ветки равна защите ~/.gnupg владельца ключа.
#      Разграничение действует между непривилегированными потребителями.
# Значения секретов НЕ печатаются никогда — только вердикты и хеши сверки.
set -o pipefail
export LC_ALL=C.UTF-8          # правило сравнения не должно зависеть от локали запускающего

STORE=${STORE:-/etc/agent-secrets}
GROUP=agent-secrets
KLYUCH=${KLYUCH:-iskra@sadik.local}
GNUPG=${GNUPG:-/opt/iskra/.gnupg}

ok=0; fail=0; blind=0
OK(){   printf '  ok    %-46s %s\n' "$1" "$2"; ok=$((ok+1)); }
FAIL(){ printf '  FAIL  %-46s %s\n' "$1" "$2"; fail=$((fail+1)); }
BLIND(){ printf '  ?     %-46s СЛЕПОТА: %s\n' "$1" "$2"; blind=$((blind+1)); }

# читает секрет предназначенной рукой; новый процесс — так читает НАСТОЯЩИЙ потребитель,
# который всегда запускается заново и получает группу из /etc/group.
chitat(){ timeout 30 sg "$GROUP" -c "GNUPGHOME='$GNUPG' PASSWORD_STORE_DIR='$STORE' pass show '$1'" 2>/dev/null; }

# Каталог хранилища читается только членами группы. Членство выдаётся при СТАРТЕ
# процесса, поэтому живой процесс, которому группу дали позже, её не имеет.
# Проверяем не признак членства, а способность читать — и если не можем,
# перезапускаем себя новым процессом в группе. Так же читает настоящий потребитель:
# служба и скрипт всегда стартуют заново. Флаг STEND_V_GRUPPE рвёт цикл, если
# и после перезапуска доступа нет.
if ! ls "$STORE" >/dev/null 2>&1 && [ -z "$STEND_V_GRUPPE" ] && [ -d "$STORE" ]; then
  # Проверяем способность войти в группу ДО exec: exec заменяет процесс, и если sg
  # откажет (рука не член группы), скрипт умрёт его кодом 1 — то есть слепота
  # будет выдана за расхождение. Ровно та беда, которую этот стенд и ловит.
  # 🔴 НЕ проверять способность через `sg ... -c true`: для НЕ-члена группы sg не
  # отказывает, а спрашивает пароль группы — в неинтерактивном запуске (служба, cron,
  # приёмка списком) это вешает стенд навсегда. Проверено: процесс висел 2 минуты.
  # Годный вопрос — числится ли рука в группе по /etc/group: именно это определяет,
  # получит ли группу НОВЫЙ процесс. И timeout как страховка на всякий иной случай.
  if getent group "$GROUP" | cut -d: -f4 | tr ',' '\n' | grep -qx "$(id -un)"; then
    export STEND_V_GRUPPE=1
    # 🔴 $0 обязан быть АБСОЛЮТНЫМ: sg запускает команду через `sh -c`, и относительное
    # имя (форма вызова `bash stend-...sh` без пути) там не находится — стенд отвечал 127,
    # то есть слепотой, неотличимой в списке приёмки от отказа хранилища. Три формы вызова
    # из четырёх работали, и потому дефект не был виден до прогона приёмки списком.
    SAM=$(readlink -f "$0")
    exec timeout 60 sg "$GROUP" -c "STEND_V_GRUPPE=1 STORE='$STORE' KLYUCH='$KLYUCH' GNUPG='$GNUPG' '$SAM'"
  fi
  # войти в группу не вышло — не перезапускаемся; ниже проверка доступа даст СЛЕПОТУ
fi

echo "== приёмка хранилища секретов =="
echo "   рука: $(id -un)   хранилище: $STORE   $(date -u '+%F %T UTC')"
echo

# --- 0. можно ли вообще мерить ---
[ -d "$STORE" ] || { BLIND "хранилище на месте" "нет каталога $STORE"; echo; echo "итог: слепота"; exit 2; }
command -v pass >/dev/null || { BLIND "инструмент pass" "не установлен"; echo; exit 2; }
ls "$STORE" >/dev/null 2>&1 || { BLIND "доступ к хранилищу" "рука $(id -un) не входит в $GROUP и перезапуск не помог"; echo; echo "итог: слепота"; exit 2; }
getent group "$GROUP" >/dev/null || { BLIND "группа $GROUP" "не заведена"; echo; exit 2; }
[ -d "$GNUPG" ] || { BLIND "связка ключей" "нет $GNUPG"; echo; exit 2; }

# --- 1. права: второй слой (от ПОРЧИ) ---
prava=$(stat -c'%a %U:%G' "$STORE" 2>/dev/null)
case "$prava" in
  "2750 root:$GROUP") OK "права хранилища" "$prava" ;;
  *) FAIL "права хранилища" "ожидалось 2750 root:$GROUP, получено: $prava" ;;
esac
# setgid обязателен: без него новые файлы берут группу СОЗДАТЕЛЯ, и слой прав тихо отмирает
for d in $(find "$STORE" -mindepth 1 -maxdepth 1 -type d 2>/dev/null); do
  p=$(stat -c'%a %G' "$d")
  case "$p" in "2750 $GROUP") ;; *) FAIL "setgid ветки ${d#$STORE/}" "$p"; continue ;; esac
done
# Пустое множество не бывает успехом: ноль проверенных веток означает, что
# проверять было нечего, а не что всё в порядке.
n_vetok=$(find "$STORE" -mindepth 1 -maxdepth 1 -type d 2>/dev/null | wc -l)
if [ "$n_vetok" -eq 0 ]; then BLIND "setgid и группа на ветках" "веток не найдено — проверять нечего"
elif [ "$fail" = 0 ]; then OK "setgid и группа на всех ветках" "проверено веток: $n_vetok"; fi

# --- 2. перечень получателей ---
n_gpgid=$(find "$STORE" -name .gpg-id 2>/dev/null | wc -l)
if [ "$n_gpgid" -ge 1 ]; then OK "файлы .gpg-id" "найдено $n_gpgid"; else FAIL ".gpg-id" "нет ни одного"; fi
find "$STORE" -name .gpg-id 2>/dev/null | while read -r f; do
  [ -s "$f" ] || echo "  FAIL  пустой .gpg-id: ${f#$STORE/}"
done | grep -q FAIL && FAIL "непустые .gpg-id" "есть пустые" || OK "непустые .gpg-id" "все содержат получателя"

# --- 3. ключ получателя на месте ---
if GNUPGHOME="$GNUPG" gpg --list-secret-keys "$KLYUCH" >/dev/null 2>&1; then
  OK "приватный ключ получателя" "$KLYUCH в $GNUPG"
else
  BLIND "приватный ключ получателя" "$KLYUCH не найден в $GNUPG"
fi

# --- 4. каждый секрет читается предназначенной рукой ---
mapfile -t zapisi < <(cd "$STORE" && find . -name '*.gpg' | sed 's|^\./||; s|\.gpg$||' | sort)
if [ "${#zapisi[@]}" -eq 0 ]; then BLIND "записи хранилища" "ни одной записи .gpg — проверять нечего"; fi
for z in "${zapisi[@]}"; do
  v=$(chitat "$z")
  if [ -n "$v" ]; then OK "читается: $z" "$(printf '%s' "$v" | wc -c) байт"
  else FAIL "читается: $z" "пустой ответ или отказ расшифровки"; fi
done

# --- 5. слой прав: посторонний не входит ---
# B-N-1768 (07.10, Аврора; находка 04.10 при A-N-1518 «У2»): отказ САМОГО sudo (NoNewPrivileges в оболочке агента/bwrap, нет
#   записи в sudoers) читался как «nobody не вошёл / не расшифровал» — ложное зелёное шагов 5–6. Сперва: исполняется ли nobody вообще.
if sudo -n -u nobody true >/dev/null 2>&1; then NOBODY=1; else NOBODY=0; fi
if [ "$NOBODY" = 0 ]; then
  BLIND "посторонний не входит" "sudo -n -u nobody не исполняется ($(id -un)) — отказ был бы про sudo, а не про права"
elif sudo -n -u nobody ls "$STORE" >/dev/null 2>&1; then
  FAIL "посторонний не входит" "nobody ПРОЧИТАЛ каталог"
else
  OK "посторонний не входит" "nobody -> Permission denied"
fi

# --- 6. слой криптографии: даже получив файл, посторонний не расшифрует ---
obr=$(cd "$STORE" && find . -name '*.gpg' | head -1)
if [ -n "$obr" ]; then
  T=$(mktemp -d); cp "$STORE/${obr#./}" "$T/p.gpg" 2>/dev/null
  chmod 755 "$T"; chmod 644 "$T/p.gpg"
  if [ "$NOBODY" = 0 ]; then
    BLIND "криптослой" "sudo -n -u nobody не исполняется — отказ расшифровки был бы про sudo, а не про ключ"
  elif sudo -n -u nobody env GNUPGHOME="$T/n" HOME="$T" gpg --batch --decrypt "$T/p.gpg" >/dev/null 2>&1; then
    FAIL "криптослой" "посторонний РАСШИФРОВАЛ файл"
  else
    # контроль зрячести: тот же файл тем же способом обязан открыться СВОИМ ключом,
    # иначе отказ выше означал бы битый файл, а не отсутствие ключа
    if GNUPGHOME="$GNUPG" gpg --batch --decrypt "$T/p.gpg" >/dev/null 2>&1; then
      OK "криптослой" "чужому отказ, своим открылся — отказ про ключ, не про файл"
    else
      BLIND "криптослой" "своим ключом тоже не открылось — проверка недостоверна"
    fi
  fi
  rm -rf "$T"
fi

# --- 7. границы записаны в самом хранилище ---
if [ -s "$STORE/CHITAT-PERVYM.md" ] && grep -q 'НЕ ДЕЙСТВУЕТ' "$STORE/CHITAT-PERVYM.md" 2>/dev/null; then
  OK "границы записаны в хранилище" "$(wc -c <"$STORE/CHITAT-PERVYM.md") байт"
else
  FAIL "границы записаны в хранилище" "нет CHITAT-PERVYM.md или в нём не назван раздел границ"
fi

echo
echo "итог: ok=$ok fail=$fail слепота=$blind"

# Канарейка: ТОЧНОЕ число проверок, не «не меньше». Порог слеп к убыли ровно
# того размера, который умещается в запас, и выглядит строже, чем работает:
# «не меньше» звучит как требование, а действует как разрешение.
# Замерено 25.08.2026 приёмом «сверься с соседом того же вида»: канарейка была
# у 3 стендов из 13. Вырезанный раздел проходил кодом 0 — выпотрошенный стенд
# отчитывался успехом.
# 🔴 Канарейка здесь СЧИТАЕТСЯ, а не задана числом, и это решение.
# Раздел 4 даёт по одной проверке на каждый секрет: при 7 записях стенд состоял
# из 15 проверок, при 263 — из 271. Константа 15 стала бы красить исправный стенд
# при каждом законном пополнении хранилища, а красное, которое всегда красное,
# перестают читать. База 8 — проверки, не зависящие от числа записей.
# 🔴 Число записей берётся С ДИСКА отдельным find, а НЕ из массива zapisi:
# возьми его из массива — и вырезание раздела 4 обнулило бы разом и факт,
# и ожидание, то есть канарейка ослепла бы ровно к той порче, ради которой стоит.
BAZA_PROVEROK=8
ZHDYOM_PROVEROK=$(( BAZA_PROVEROK + $(find "$STORE" -name '*.gpg' 2>/dev/null | wc -l) ))
if [ $((ok+fail+blind)) -ne $ZHDYOM_PROVEROK ]; then
  echo "СЛЕПОТА: проверок $((ok+fail+blind)), а стенд состоит из $ZHDYOM_PROVEROK — часть не состоялась."
  echo "         Меняли стенд намеренно? Поправьте ZHDYOM_PROVEROK и скажите, почему."
  exit 2
fi
[ "$fail" -gt 0 ] && exit 1
[ "$blind" -gt 0 ] && exit 2
exit 0
