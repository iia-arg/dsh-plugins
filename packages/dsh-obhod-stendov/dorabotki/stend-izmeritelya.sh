#!/usr/bin/env bash
# Приёмка измерителя ожидаемого размера копии (ozhidaemyj-razmer.py).
#
# Гоняет УСТАНОВЛЕННЫЙ измеритель, а данные подставляет через AGENTS_REGISTRY:
# проверять надо то, что исполняется, на данных, которые можно испортить.
# Боевой /etc/agent-registry/agents.yaml не трогается ни разу.
#
# Коды: 0 сошлось | 1 расхождение | 2 слепота (проверить не удалось).
#
# 🔴 ГДЕ НЕ ПРИМЕНЯЕТСЯ — границы ОХВАТА, не воздействия:
#   * не проверяет ВЕРНОСТЬ самих чисел размера: du берётся как есть, и что
#     он посчитал правильно, здесь не доказывается ничем;
#   * не проверяет, что разметка ОСМЫСЛЕННА (нужное в klast, ненужное в
#     ne_klast) — только что она непротиворечива и что образцам есть предмет;
#   * не проверяет скрипт копии: его нет, и пока нет адресата — измерять
#     нечего. Зелёный здесь означает «мерка непротиворечива», а не
#     «копия делается правильно»;
#   * конфликт ищется по РАСКРЫТЫМ путям, поэтому образец, под который на
#     диске сейчас ничего не попало, спорным не назовётся — он назовётся
#     образцом без предмета, это другая строка и другой повод;
#   * подставная разметка строится из БОЕВОЙ копией. Разойдись боевая
#     структура с ожидаемой — стенд скажет СЛЕПОТА, а не «сошлось».
set -uo pipefail
export LC_ALL=C.UTF-8

IZM="${IZMERITEL_BIN:-/opt/iskra/workspace/dorabotki/ozhidaemyj-razmer.py}"
ok=0; bad=0; slep=0
sud(){ case "$1" in
    ok)   ok=$((ok+1));   printf '  ok    %-46s %s\n' "$2" "$3" ;;
    fail) bad=$((bad+1)); printf '  FAIL  %-46s %s\n' "$2" "$3" ;;
    *)    slep=$((slep+1)); printf '  СЛЕПОТА %-44s %s\n' "$2" "$3" ;;
  esac; }

[[ -r "$IZM" ]] || { echo "СЛЕПОТА: нет $IZM"; exit 2; }
command -v python3 >/dev/null || { echo "СЛЕПОТА: нет python3"; exit 2; }

T=$(mktemp -d /tmp/stend-izm.XXXXXX) || { echo "СЛЕПОТА: нет временного каталога"; exit 2; }
trap 'rm -rf "$T"' EXIT
sudo -n cat /etc/agent-registry/agents.yaml > "$T/orig.yaml" 2>/dev/null \
  || { echo "СЛЕПОТА: боевой реестр не прочитан — подставные данные не из чего строить"; exit 2; }

echo "== приёмка измерителя: $IZM =="

# Сборщик подставных разметок. Строится ИЗ БОЕВОЙ: подставная разметка,
# написанная с нуля, проверяла бы устройство, которого на машине нет.
sobrat(){ # выход  правка-питоном-над-словарём-kopiya
  python3 - "$T/orig.yaml" "$1" "$2" <<'PY'
import yaml, sys
src, out, pravka = sys.argv[1], sys.argv[2], sys.argv[3]
d = yaml.safe_load(open(src))
naiden = False
for ag in d.get('agenty', []):
    if 'iskra' in str(ag.get('imya', '')):
        k = ag['namerenie']['kopiya']
        exec(pravka, {}, {'k': k})
        naiden = True
        break
if not naiden:
    sys.exit(9)          # структура разошлась — слепота, а не «сошлось»
yaml.safe_dump(d, open(out, 'w'), allow_unicode=True, sort_keys=False)
PY
}

progon(){ # реестр -> код в $KOD, вывод в $VYVOD
  VYVOD=$(AGENTS_REGISTRY="$1" python3 "$IZM" 2>&1); KOD=$?
}

# ── 1. Боевая разметка: обязан посчитать и НЕ найти конфликта ───────────────
progon "$T/orig.yaml"
# база для пробы 3: сколько путей вычитается на ЖИВОЙ разметке (там конфликты есть законно, #269)
BAZA_VYCHTET=$(grep -oE 'ВЫЧТЕТ [0-9]+' <<<"$VYVOD" | grep -oE '[0-9]+' || echo 0)
if [[ $KOD -eq 0 ]] && grep -q 'ожидаемый размер' <<<"$VYVOD"; then
  sud ok "боевая разметка считается" "код=0, $(grep -o 'x[0-9.]*' <<<"$VYVOD" | head -1)"
else
  sud fail "боевая разметка НЕ посчиталась" "код=$KOD $(printf %s "$VYVOD" | LC_ALL=C.utf8 sed -e 's/\(.\{0,70\}\).*/\1/')"
fi

# ── 2. Законная вложенность НЕ конфликт ────────────────────────────────────
# klast «app/package-lock.json» внутри ne_klast «app» — намеренная разметка.
# Если стенд покраснеет здесь, лечение конфликта съело нужное.
if grep -q 'app/package-lock.json' <<<"$(sudo -n cat /etc/agent-registry/agents.yaml)"; then
  sud ok "вложенность klast внутри ne_klast есть в боевой" "и прогон 1 дал код 0"
else
  sud slep "вложенности в боевой нет" "случай не проверен на настоящих данных"
fi

# ── 3. Буквальный конфликт: тот же путь в обоих списках ────────────────────
sobrat "$T/bukv.yaml" "k['ne_klast_prichina']['workspace/dorabotki']='ПОДСТАВНОЙ'"
if [[ $? -ne 0 ]]; then sud slep "сборка буквального конфликта" "структура разошлась"; else
  # 🔴 25.09.2026: ДОГОВОР #269 (20.09) — конфликт больше не ОТКАЗ, а СВЕДЕНИЕ (сборщик вычитает ne_klast, исход
  # детерминирован). Стенд ждал отказа и краснел с 20.09 — 3 FAIL, которых никто не видел: стенд никто не зовёт.
  progon "$T/bukv.yaml"
  # Имя пути в перечне не ищется: перечень режется до 12 по алфавиту, а на живой разметке конфликтов уже десятки.
  # Признак — РАЗНОСТЬ: подставной конфликт добавляет ровно один вычитаемый путь к живой базе.
  VYCHTET=$(grep -oE 'ВЫЧТЕТ [0-9]+' <<<"$VYVOD" | grep -oE '[0-9]+' || echo 0)
  if [[ $KOD -eq 0 ]] && [[ "$VYCHTET" -eq $((BAZA_VYCHTET + 1)) ]]; then
    sud ok "буквальный конфликт назван сведением" "код=0, вычитаемых $BAZA_VYCHTET → $VYCHTET"
  else
    sud fail "буквальный конфликт НЕ назван" "код=$KOD, вычитаемых $BAZA_VYCHTET → $VYCHTET (ждали +1)"
  fi
  # сумма при конфликте печатается, но с оговоркой, что она завышена на вычитаемое
  if grep -q 'ожидаемый размер' <<<"$VYVOD" && grep -q 'СУММА НИЖЕ ЗАВЫШЕНА' <<<"$VYVOD"; then
    sud ok "при конфликте сумма с оговоркой" "«ЗАВЫШЕНА» названо"
  else
    sud fail "при конфликте сумма без оговорки" "читатель примет завышенную сумму за точную"
  fi
fi

# ── 4. Масочный конфликт: буквального пересечения образцов НЕТ ─────────────
# Ради этого случая сравниваются раскрытые ПУТИ, а не строки образцов.
sobrat "$T/maski.yaml" "k['klast'].append('workspace/d*'); k['ne_klast_prichina']['workspace/*ki']='ПОДСТАВНОЙ'"
if [[ $? -ne 0 ]]; then sud slep "сборка масочного конфликта" "структура разошлась"; else
  # сперва доказать, что буквального пересечения действительно нет
  bukv=$(AGENTS_REGISTRY="$T/maski.yaml" /usr/local/bin/agent-registry pole iskra kopiya --json 2>/dev/null \
        | python3 -c "import json,sys; d=json.load(sys.stdin); print(len(set(d['klast'])&set(d['ne_klast_prichina'].keys())))" 2>/dev/null)
  if [[ "$bukv" == "0" ]]; then
    sud ok "у масочного случая буквального пересечения нет" "строк-совпадений: 0"
  else
    sud slep "масочный случай оказался и буквальным" "совпадений: $bukv — проверка не о том"
  fi
  progon "$T/maski.yaml"
  if [[ $KOD -eq 0 ]] && grep -q 'СВЕДЕНИЕ: сборщик ВЫЧТЕТ' <<<"$VYVOD"; then
    sud ok "масочный конфликт назван сведением" "код=0 (#269)"
  else
    sud fail "масочный конфликт НЕ пойман" "код=$KOD — сравниваются строки, а не пути"
  fi
fi

# ── 5. Образец без предмета на диске ───────────────────────────────────────
sobrat "$T/nikuda.yaml" "k['klast'].append('takogo-puti-net-20260825')"
if [[ $? -ne 0 ]]; then sud slep "сборка образца-в-никуда" "структура разошлась"; else
  progon "$T/nikuda.yaml"
  if [[ $KOD -eq 1 ]] && grep -q 'takogo-puti-net-20260825' <<<"$VYVOD"; then
    sud ok "образец без предмета назван" "код=1, имя в выводе"
  else
    sud fail "образец без предмета не назван" "код=$KOD"
  fi
fi

# ── 5б. Маска без совпадения — признак, а не слепота (25.09.2026) ─────────────
# Сторож покрытия считает её «не находкой» (проба F15 его стенда); измеритель прежде давал код 1, и сторож
# называл это «разметка противоречива». Буквальный путь в никуда (проба 5) по-прежнему код 1.
sobrat "$T/maska.yaml" "k['klast'].append('*.net-takogo-rasshireniya-20260925')"
if [[ $? -ne 0 ]]; then sud slep "сборка маски без совпадения" "структура разошлась"; else
  progon "$T/maska.yaml"
  if [[ $KOD -eq 0 ]] && grep -q 'маска без совпадения сегодня' <<<"$VYVOD" && grep -q 'net-takogo-rasshireniya-20260925' <<<"$VYVOD"; then
    sud ok "маска без совпадения названа, код не поднят" "код=0"
  else
    sud fail "маска без совпадения поднимает код или молчит" "код=$KOD"
  fi
fi

# ── 6. Слепота отделена от расхождения ─────────────────────────────────────
progon "$T/net-takogo-fajla.yaml"
if [[ $KOD -eq 2 ]]; then
  sud ok "нет реестра -> слепота" "код=2, а не 1 и не 0"
else
  sud fail "нет реестра -> код $KOD" "слепота выдана за расхождение или за успех"
fi

# ── 7. Боевой реестр не тронут ─────────────────────────────────────────────
if sudo -n cmp -s /etc/agent-registry/agents.yaml "$T/orig.yaml"; then
  sud ok "боевой реестр не тронут" "побайтно тот же"
else
  sud fail "боевой реестр ИЗМЕНИЛСЯ за прогон" "стенд портит предмет"
fi

echo
echo "проверок: $((ok+bad+slep))   ok=$ok  FAIL=$bad  СЛЕПОТА=$slep"

# Канарейка: ТОЧНОЕ число, не «не меньше». Порог слеп к убыли ровно того
# размера, который умещается в запас, и при этом выглядит строже точного
# значения: «не меньше» звучит как требование, а работает как разрешение.
# Проверено порчей 25.08.2026: вырезанный раздел дал 7 проверок и код 0 —
# то есть выпотрошенный стенд отчитывался успехом.
ZHDYOM_PROVEROK=10   # 25.09: +проба 5б (маска без совпадения)
if [[ $((ok+bad+slep)) -ne $ZHDYOM_PROVEROK ]]; then
  echo "СЛЕПОТА: проверок $((ok+bad+slep)), а стенд состоит из $ZHDYOM_PROVEROK — часть не состоялась."
  echo "         Меняли стенд намеренно? Поправьте ZHDYOM_PROVEROK и скажите, почему."
  exit 2
fi
[[ $slep -gt 0 ]] && exit 2
[[ $bad  -gt 0 ]] && exit 1
exit 0
