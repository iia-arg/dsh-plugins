#!/usr/bin/env bash
# СТЕНД: курьер писем `tell-komu` — ПОВЕДЕНИЕ, а не полезность писем.
#
# 🔴 ЗАЧЕМ ЗАВЕДЁН (06.09.2026). Курьер ПРАВИТ ЖИВОЕ — кладёт письма в щель, откуда их
# забирает сборщик координатора, — и до сего дня не имел ни стенда, ни встроенного
# самопрогона. Его две проверки («завершение без версии», «шапка называет тех, кому
# письмо не уйдёт») заведены в тот же день и проверялись ручными прогонами, которые
# нигде не остались: проверка была, сторожа не было, и следующая правка сломала бы их
# ТИХО. Класс назван приёмкой: предмет, лежащий ВНЕ пакета, в ворота выпуска не попадает
# по устройству — спрашивать надо не «прошёл ли ворота», а «что вообще не может в них
# попасть».
#
# 🔴 ЧТО ЭТОТ СТЕНД НЕ ПРОВЕРЯЕТ (границы, читать вместе с итогом):
# — НЕ проверяет доставку. «Положено» и «доставлено» — разные вещи, и сам курьер это
#   печатает. Сборщик координатора здесь не участвует ни одной веткой;
# — НЕ судит о содержимом писем: предупреждения курьера — про форму, и стенд про них же;
# — НЕ трогает БОЕВУЮ щель: пути подменяются (ZABAVA_TELL_DIR, A2A_ZERKALO). Один
#   прогон 06.09.2026 ушёл в боевую щель именно потому, что имена переменных были взяты
#   из головы, а не у предмета — здесь они взяты у предмета;
# — НЕ проверяет обрезку длинных писем и разбор адресатов сверх перечня ADRESATY.
#
# КОДЫ: 0 сошлось | 1 расхождение | 2 слепота (проверить не удалось)
set -uo pipefail
export LC_ALL=C.UTF-8

ZHDYOM_PROVEROK=12

KURYER="${STEND_KURYER:-/usr/local/bin/tell-komu}"

ok=0; fail=0; slep=0
sud() {
  case "$1" in
    ok)   ok=$((ok+1));   printf '  ok   %s\n' "$2" ;;
    fail) fail=$((fail+1)); printf '  FAIL %s\n' "$2"; [ $# -ge 3 ] && printf '       сырьё: %s\n' "$3" ;;
    slep) slep=$((slep+1)); printf '  СЛЕПОТА %s\n' "$2" ;;
  esac
}

[ -x "$KURYER" ] || { echo "СЛЕПОТА: не исполняется $KURYER — стенд смотрит не туда"; exit 2; }

RAB="$(mktemp -d -p /opt/iskra/workspace stend-kurera-XXXXXX)" || { echo "СЛЕПОТА: mktemp не удался"; exit 2; }
trap 'rm -rf "$RAB" 2>/dev/null' EXIT
SHCHEL="$RAB/tell"; ZERK="$RAB/polnye"; mkdir -p "$SHCHEL" "$ZERK"
# B-N-1156 (28.09, Искра): с A-N-668 курьер кладёт только в щели из /etc/a2a/tell-shcheli.list; подставная
# щель объявляется ПРОБОЙ (A2A_TELL_PROBA=1 + A2A_TELL_LIST) — иначе все пробы годного письма отказывают,
# и стенд краснел на здоровом бою (ok 7 из 12). Перечень пробы — одна строка, только наша щель.
PERECHEN="$RAB/tell-shcheli.list"; printf '%s stend-kurera\n' "$SHCHEL" > "$PERECHEN"

# Один вызов курьера на подменённых путях.
# 🔴 ВЫВОД ИДЁТ В ФАЙЛ, А НЕ ЧЕРЕЗ ПОДСТАНОВКУ. Первая редакция делала
# `OUT="$(zvat …)"`, а код клала в переменную ВНУТРИ функции — и стенд падал на
# `KOD: unbound variable`: подстановка команд исполняется в ПОДОБОЛОЧКЕ, её
# переменные наружу не выходят. Тот же корень, что у «конвейер съел код возврата»:
# код принадлежит не тому, у кого его спрашивают. Здесь код — возврат самой функции,
# а вывод читается из файла; смешивать их в одном выражении больше нечем.
VYVOD="$RAB/vyvod.txt"
zvat() {
  local fajl="$1"
  A2A_TELL_PROBA=1 A2A_TELL_LIST="$PERECHEN" ZABAVA_TELL_DIR="$SHCHEL" A2A_ZERKALO="$ZERK" "$KURYER" "$fajl" > "$VYVOD" 2>&1
}
pismo() { # pismo <имя> <тело...>
  local imya="$1"; shift
  printf '%s\n' "$@" > "$RAB/$imya"
  printf '%s' "$RAB/$imya"
}
v_shcheli() { ls -1 "$SHCHEL" 2>/dev/null | grep -c . ; }

# ── 1. Адресат не распознан в имени -> ОТКАЗ, письма в щели нет ───────────────
F="$(pismo 'bez-adresata.txt' 'тело')"
zvat "$F"; KOD=$?; OUT="$(cat "$VYVOD")"
if [ "$KOD" = 3 ] && [ "$(v_shcheli)" = 0 ]; then
  sud ok "имя без адресата: отказ кодом 3, щель пуста"
else
  sud fail "имя без адресата: ждали код 3 и пустую щель" "код=$KOD, в щели $(v_shcheli)"
fi

# ── 2. Файла нет вовсе -> ОТКАЗ ──────────────────────────────────────────────
zvat "$RAB/dlya-veniamina-net-takogo.txt"; KOD=$?; OUT="$(cat "$VYVOD")"
if [ "$KOD" = 3 ] && [ "$(v_shcheli)" = 0 ]; then
  sud ok "файла нет: отказ кодом 3"
else
  sud fail "файла нет: ждали код 3" "код=$KOD"
fi

# ── 3. Годное письмо -> положено, зеркало есть, штамп укладки дописан ────────
F="$(pismo 'dlya-veniamina-proba-stenda.txt' 'Искра -> Вениамину. Замер по предмету.' 'Числа ниже.')"
zvat "$F"; KOD=$?; OUT="$(cat "$VYVOD")"
if [ "$KOD" = 0 ] && [ "$(v_shcheli)" = 1 ]; then
  sud ok "годное письмо: положено, код 0"
else
  sud fail "годное письмо: ждали код 0 и одно письмо в щели" "код=$KOD, в щели $(v_shcheli)"
fi
# Курьер дописывает к имени время укладки и pid (…-<ГГГГММДДTччммссZ>-<pid>.txt) — ищем по основе, ровно один.
ZF="$(compgen -G "$ZERK/dlya-veniamina-proba-stenda-*.txt" || true)"; SF="$(compgen -G "$SHCHEL/dlya-veniamina-proba-stenda-*.txt" || true)"
if [ -n "$ZF" ] && [ "$(printf '%s\n' "$ZF" | grep -c .)" = 1 ]; then
  sud ok "зеркало письма сохранено"
else
  sud fail "зеркала письма нет — доказательства отправленного не остаётся"
fi
if [ -n "$SF" ] && grep -q 'положено в щель' "$SF" 2>/dev/null; then
  sud ok "штамп укладки дописан В ТЕЛО (машиной, не рукой автора)"
else
  sud fail "штампа укладки в теле нет: получатель не отличит свежее письмо от лежалого" \
           "файл: ${SF:-нет}; $(tail -2 "${SF:-/dev/null}" 2>/dev/null | tr '\n' ' ')"
fi

# ── 4/5. ПАРА про «сделано без версии»: кричит там и молчит здесь ────────────
rm -f "$SHCHEL"/* "$ZERK"/*
F="$(pismo 'dlya-veniamina-sdelano-bez-nomera.txt' 'Правка сделана, предмет закрыт.')"
zvat "$F"; KOD=$?; OUT="$(cat "$VYVOD")"
if printf '%s' "$OUT" | grep -q 'БЕЗ ВЕРСИИ И СУММЫ'; then
  sud ok "«сделано» без номера: предупреждение есть"
else
  sud fail "«сделано» без номера: предупреждения НЕТ — слово покроет разное содержимое" "$OUT"
fi
if [ "$KOD" = 0 ] && [ "$(v_shcheli)" = 1 ]; then
  sud ok "предупреждение НЕ отказ: письмо всё равно положено"
else
  sud fail "предупреждение превратилось в отказ — бывает завершение без версии" "код=$KOD"
fi
# 🔴 ВТОРАЯ СТОРОНА ПАРЫ ОБЯЗАТЕЛЬНА: стенд без неё узаконил бы «кричать всегда»,
# и цена ложного крика стала бы невидимой.
rm -f "$SHCHEL"/* "$ZERK"/*
F="$(pismo 'dlya-veniamina-sdelano-s-nomerom.txt' 'Выпущена alpha.58, сумма 7d585ad81f5bc4d3. Сделано.')"
zvat "$F"; KOD=$?; OUT="$(cat "$VYVOD")"
if printf '%s' "$OUT" | grep -q 'БЕЗ ВЕРСИИ И СУММЫ'; then
  sud fail "«сделано» С номером и суммой: предупреждение ЛОЖНОЕ" "$OUT"
else
  sud ok "«сделано» с номером и суммой: молчит — ложного крика нет"
fi

# ── 6/7. ПАРА про шапку, называющую тех, кому письмо не уйдёт ───────────────
rm -f "$SHCHEL"/* "$ZERK"/*
F="$(pismo 'dlya-veniamina-s-kopiyami.txt' 'Искра -> Вениамину (копия Забаве, Михалычу).' 'тело')"
zvat "$F"; KOD=$?; OUT="$(cat "$VYVOD")"
if printf '%s' "$OUT" | grep -q 'ШАПКА НАЗЫВАЕТ ТЕХ'; then
  sud ok "шапка обещает копии: предупреждение есть (названные считались бы извещёнными)"
else
  sud fail "шапка обещает копии, а курьер молчит: адресат ровно один" "$OUT"
fi
rm -f "$SHCHEL"/* "$ZERK"/*
F="$(pismo 'dlya-veniamina-bez-kopij.txt' 'Искра -> Вениамину. Замер ниже.' 'тело')"
zvat "$F"; KOD=$?; OUT="$(cat "$VYVOD")"
if printf '%s' "$OUT" | grep -q 'ШАПКА НАЗЫВАЕТ ТЕХ'; then
  sud fail "шапка НИКОГО чужого не называет, а предупреждение есть — ложный крик" "$OUT"
else
  sud ok "шапка без чужих имён: молчит"
fi

# ── 8. Нет права записи в щель -> отказ, а не тихая потеря письма ────────────
rm -f "$SHCHEL"/* "$ZERK"/*
chmod 500 "$SHCHEL"
F="$(pismo 'dlya-veniamina-shchel-zakryta.txt' 'тело')"
zvat "$F"; KOD=$?; OUT="$(cat "$VYVOD")"
chmod 700 "$SHCHEL"
if [ "$KOD" = 3 ]; then
  sud ok "щель без права записи: отказ кодом 3, а не тихая потеря"
else
  sud fail "щель без права записи: ждали код 3" "код=$KOD; вывод: $OUT"
fi
# 🔴 ВТОРАЯ ПРОБА ЗАВЕДЕНА ПОРЧЕЙ, А НЕ ЗАМЫСЛОМ. Порча «снять проверку права записи»
# оставила стенд ЗЕЛЁНЫМ: код 3 приходил и без неё — из следующей ветки («не собрать
# письмо рядом со щелью»). Защита двойная, и это хорошо; негодной была ПРОБА — она
# называла причину, которую не измеряла. Один код возврата у двух разных ветвей: проба
# по коду не различает их и зеленеет не про то.
if printf '%s' "$OUT" | grep -q 'нет права записи'; then
  sud ok "отказ НАЗЫВАЕТ свою причину (право записи), а не просто отказывает"
else
  sud fail "отказ не называет причину: разбирающий пойдёт чинить не ту ветку" "$OUT"
fi

# ── ИТОГ ────────────────────────────────────────────────────────────────────
VSEGO=$((ok+fail+slep))
echo
printf 'ИТОГ: ok %d · расхождений %d · слепот %d (проверок %d)\n' "$ok" "$fail" "$slep" "$VSEGO"
# 🔴 ГРАНИЦА — В ВЫВОДЕ, А НЕ В ШАПКЕ: шапку читают, когда читают шапку, а на число
# смотрят всегда. Иначе «10 из 10» прочтут как «курьер работает верно».
echo 'ГРАНИЦА: стенд стережёт ПОВЕДЕНИЕ курьера (кладёт ли, куда, что говорит, чем отказывает),'
echo '         а НЕ доставку и НЕ верность его предупреждений по существу письма.'
if [ "$VSEGO" != "$ZHDYOM_PROVEROK" ]; then
  echo "🔴 КАНАРЕЙКА: ждали $ZHDYOM_PROVEROK проверок, исполнилось $VSEGO — часть проб не дошла до суда"
  exit 2
fi
[ "$slep" -gt 0 ] && exit 2
[ "$fail" -gt 0 ] && exit 1
exit 0
