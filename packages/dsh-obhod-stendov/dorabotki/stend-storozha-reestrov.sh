#!/bin/bash
# Стенд сторожа реестров. Прогоняется списком — годится и при установке, и ПОСЛЕ
# обновления: отвечает на вопрос «сторож ещё умеет краснеть?».
#
# ПРЕДМЕТ — УСТАНОВЛЕННЫЙ ФАЙЛ, а не копия рядом со стендом: таймер запускает
# именно его. Переопределяется переменной SUT — она нужна, чтобы проверить сам
# стенд на умение краснеть, подсунув ему нарочно испорченный сторож.
#
# ПОДСТАВНЫЕ ДАННЫЕ СТЕНД ДЕЛАЕТ СЕБЕ САМ, во временном каталоге: копию реестра
# с испорченным отпечатком, копию с испорченной проверкой живости, копию с
# проверкой-мигалкой, инструмент со сменившимися словами. Настоящие реестр,
# тревоги и состояние сторожа при этом НЕ ТРОГАЮТСЯ: подставляются через
# REGWD_STATE, REGWD_ALERT, REGWD_CONF и подставного отправителя.
#
# 🔴 ЧЕЛОВЕКУ СТЕНД НЕ ПИШЕТ НИ РАЗУ — отправитель подставной, он кладёт текст
# в файл. Иначе прогон приёмки означал бы четырнадцать тревог владельцу.
#
# Код возврата: 0 — все случаи сошлись, 1 — хоть один разошёлся, 2 — не на чем
# гонять (нет предмета или нет инструментов реестра).
#
# 🔴 ГРАНИЦЫ ОХВАТА — о чём этот стенд молчит (дописано 24.08, по правилу
# «рамку пишет тот, у кого файл сейчас в руках»):
#   * он проверяет, что сторож УМЕЕТ покраснеть и сказать человеку, и НЕ
#     проверяет, что он это делает по расписанию: таймер, его время и
#     доставку настоящему адресату стенд не трогает вовсе;
#   * подставные реестры здесь МАЛЕНЬКИЕ и сделаны под конкретный случай.
#     Поведение сторожа на боевом реестре в 39 записей отсюда не следует;
#   * стенд ничего не говорит про ВТОРОЙ учёт (манифест доработок) сверх
#     одного случая «реестр доработок покраснел» — устройство графа учётов
#     проверяет stend-atsiklichnosti.sh, а не этот;
#   * предел молчания сторожа (сколько суток тишины считать бедой) стенд
#     проверяет на подставном состоянии, а не выдержкой реального времени:
#     что счётчик суток верен на длинной дистанции, отсюда не следует;
#   * зелёный ответ означает «сторож ещё умеет краснеть», а НЕ «на машине
#     всё в порядке». Второе — вопрос самих учётов, их надо звать отдельно.
#   * 🔴 СТЕНД НАПОЛОВИНУ БОЕВОЙ, и это его главная граница. Сторож зовёт
#     настоящий `nashi-dorabotki.sh --check` (у него путь манифеста свой,
#     подстановкой MANIFEST_REAL он не сдвигается), поэтому в НЕСВЕДЁННОМ
#     состоянии машины пять случаев из четырнадцати краснеют на исправном
#     стенде и исправном стороже. Замерено 24.08 подстановкой устаревшего
#     манифеста: несведено — 9/5, сведено — 14/0, манифест возвращён побайтно.
#     Значит гнать этот стенд надо ПОСЛЕ сведения учётов, а его красноту
#     сперва читать как «учёт не сведён», и только потом как «сторож сломан».
#     🔴 ИСТОЧНИКОВ У ЭТОЙ ГРАНИЦЫ ДВА, А НЕ ОДИН (дополнено 28.08.2026).
#     Сторож зовёт не только учёты, но и ЖИВОСТЬ записей. Красная живость даёт
#     те же самые пять красных при ЗЕЛЁНЫХ учётах — то есть по числам 9/5
#     отличить одно от другого НЕЛЬЗЯ. Замерено 28.08 20:39: оба учёта код 0,
#     живость 3 красных (omega-memory.service остановлена для планового
#     обновления чужой рукой + две знаемые слепоты записей, отказывающихся
#     отвечать за чужую руку), стенд 9/5. Числа совпали с записанными 24.08
#     случайно — причина была другая.
#     ПОРЯДОК ЧТЕНИЯ КРАСНОТЫ, три звена вместо двух:
#       1) учёты не сведены     -> `verify` и `nashi-dorabotki.sh --check`;
#       2) живость красная      -> `agent-plugins list --health`, и спросить,
#          не идёт ли ПЛАНОВОЕ обслуживание (остановленная служба выглядит
#          как упавшая: сторож не различает обслуживание и поломку);
#       3) и только потом       -> стенд урезан или сторож сломан.
set -u
SUT="${SUT:-/usr/local/sbin/registry-watchdog.sh}"
# №5 аудита 16: реестр — REESTR, иначе PLUGINS_REGISTRY (так его подаёт progon-na-podstave.sh), иначе умолчание пакета.
REESTR="${REESTR:-${PLUGINS_REGISTRY:-/etc/agent-registry/plugins.yaml}}"
INSTRUMENT="${INSTRUMENT:-/usr/local/bin/agent-plugins}"
MANIFEST_REAL="${MANIFEST_REAL:-/opt/iskra/workspace/dorabotki/manifest.txt}"

[ -x "$SUT" ] || { echo "СЛЕПОТА: нет предмета $SUT — гонять нечего" >&2; exit 2; }
[ -r "$REESTR" ] && [ -x "$INSTRUMENT" ] || { echo "СЛЕПОТА: нет реестра или инструмента — стенд недоказателен" >&2; exit 2; }

D=$(mktemp -d /tmp/stend-storozha.XXXXXX) || exit 2
trap 'rm -rf "$D"' EXIT
S="$D/state"; mkdir -p "$S"

# ── подставной отправитель: кладёт текст в файл, код возврата задаётся снаружи
cat > "$D/otpravitel" <<'EOF'
#!/bin/bash
printf '%s\n' "$*" > "$(dirname "$0")/soobshenie.txt"
exit "${FAKE_ALERT_RC:-0}"
EOF
chmod +x "$D/otpravitel"

# ── инструмент реестра, смотрящий в подставной файл
kopiya_instrumenta() { # <куда> <какой реестр>
  # 🔴 Прежде подмена делалась sed-правкой КОПИИ инструмента по строке
  # `REGISTRY = "..."`. 24.08 эта строка в инструменте изменилась — путь стал
  # браться из окружения, — якорь пропал, и стенд честно сказал СЛЕПОТА вместо
  # тихой проверки боевого реестра. Подмена предмета правкой чужого кода хрупка
  # по построению: она держится на буквальной строке в файле, который правит
  # кто-то другой, и ломается молча, если проверять факт подмены нечем.
  # Теперь путь объявлен самим инструментом (PLUGINS_REGISTRY), и гоняется
  # УСТАНОВЛЕННЫЙ инструмент, а не его изменённая копия.
  printf '#!/bin/bash\nexport PLUGINS_REGISTRY=%q\nexec %q "$@"\n' "$2" "$INSTRUMENT" > "$1"
  chmod +x "$1"
  # Факт подмены проверяем ДЕЙСТВИЕМ, а не чтением обёртки: инструмент сам
  # называет в stderr путь, из которого взял реестр.
  "$1" list 2>&1 >/dev/null | grep -qF "$2" || { echo "СЛЕПОТА: не удалось перенаправить инструмент на $2 — стенд недоказателен" >&2; exit 2; }
  chmod +x "$1"
}
# отпечаток одной записи испорчен -> verify обязан покраснеть
sed 's/^    fingerprint: "\(.*\)"$/    fingerprint: "0000000000000dead"/' "$REESTR" > "$D/reestr-otpechatok.yaml"
kopiya_instrumenta "$D/ap-otpechatok" "$D/reestr-otpechatok.yaml"
# реестр не разбирается как YAML -> СЛЕПОТА, а не расхождение (код инструмента 2 с аудита 16; прежде 1)
{ cat "$REESTR"; printf '\n  это: [не YAML\n'; } > "$D/reestr-slomannyj.yaml"
kopiya_instrumenta "$D/ap-slomannyj" "$D/reestr-slomannyj.yaml"
# первая проверка живости всегда красная. B-N-1064 (26.09, Аврора): код 3, а не 1 — у agent-plugins код 1 = «ДОЛОЖИЛ НАХОДКУ»
# (доклад работающей проверки, сторож не краснеет), молчание — чужой код/таймаут; с exit 1 случаи 6–7 краснели на исправном стороже.
python3 - "$REESTR" "$D/reestr-zhivost.yaml" <<'PY'
import sys
s=open(sys.argv[1],encoding='utf-8').read()
i=s.find('    healthcheck:'); j=s.find('\n',i)
open(sys.argv[2],'w',encoding='utf-8').write(s[:i]+'    healthcheck: "echo стенд-не-отвечает; exit 3"'+s[j:])
PY
kopiya_instrumenta "$D/ap-zhivost" "$D/reestr-zhivost.yaml"
# первая проверка живости красная ТОЛЬКО с первого раза
python3 - "$REESTR" "$D/reestr-migalka.yaml" "$D" <<'PY'
import sys
s=open(sys.argv[1],encoding='utf-8').read(); d=sys.argv[3]
i=s.find('    healthcheck:'); j=s.find('\n',i)
hc=('    healthcheck: "if [ -e %s/migala ]; then echo стенд-со-второй-ответила; '
    'else touch %s/migala; echo стенд-занята; exit 3; fi"') % (d,d)
open(sys.argv[2],'w',encoding='utf-8').write(s[:i]+hc+s[j:])
PY
kopiya_instrumenta "$D/ap-migalka" "$D/reestr-migalka.yaml"
# инструмент со сменившимися словами: канарейка формы обязана заметить
cat > "$D/chuzhaja-forma" <<'EOF'
#!/bin/bash
echo "  плагин-один   1.0"
echo "  alive: да"
echo "всего записей: 31   файл: /где-то"
EOF
chmod +x "$D/chuzhaja-forma"
# манифест доработок с испорченной суммой — №21 аудита 16: только если учёт доработок задан (DORABOTKI_CMD) и манифест
# читается; иначе случай 13 ПРОПУСКАЕТСЯ С ИМЕНЕМ, и канарейка ниже ждёт на одну проверку меньше.
SLUCHAJ13=1
if [ -z "${DORABOTKI_CMD:-}" ] || [ ! -r "$MANIFEST_REAL" ]; then
  SLUCHAJ13=0
else
  sed '2s/|[0-9a-f]\{32\}$/|0000000000000000000000000000dead/' "$MANIFEST_REAL" > "$D/manifest-porcha.txt"
fi

ok=0; bad=0
proverka() { # имя ожид_код факт_код [подстрока] [файл]
  local imya="$1" ozh="$2" fakt="$3" podstr="${4:-}" gde="${5:-}" beda=""
  [ "$ozh" != "$fakt" ] && beda="код $fakt, ждали $ozh"
  if [ -n "$podstr" ] && ! grep -qF "$podstr" "$gde" 2>/dev/null; then
    beda="${beda:+$beda; }нет строки «$podstr» в $(basename "$gde")"
  fi
  if [ -z "$beda" ]; then ok=$((ok+1)); printf '  ok   %s\n' "$imya"
  else bad=$((bad+1)); printf '  FAIL %s — %s\n' "$imya" "$beda"
    # B-N-1874: сырьё провала копится здесь и печатается после итога. Иначе причины не восстановить: vyvod.txt
    # затирает следующий случай, а $D снимается на выходе (trap выше) — 08.10 18:55–19:2xZ FAIL 1,2,3,6 «код 2»
    # остались без причины. Не сразу под FAIL: обходчик берёт в сводку первые 5 строк с ❌|FAIL|Error|СЛЕПОТА,
    # а в хвосте сторожа бывает «СЛЕПОТА» — он вытеснил бы имена следующих провалов.
    if [ -s "$D/vyvod.txt" ]; then { echo "  — $imya:"; tail -n 15 "$D/vyvod.txt" | sed 's/^/       | /'; } >> "$D/syrjo.txt"; fi
  fi
}
zapusk() {
  rm -f "$D/soobshenie.txt"
  env REGWD_STATE="$S" REGWD_ALERT="$D/otpravitel" REGWD_CONF=/dev/null "$@" "$SUT" > "$D/vyvod.txt" 2>&1
  echo $?
}

echo "СТЕНД сторожа реестров"
echo "  предмет: $SUT ($(sha256sum "$SUT" | cut -c1-16))"
echo "  подставные данные: $D"

# B-N-1073 (26.09.2026, Аврора; слово Забавы): случаи 1,2,7,9,10 ждут 0 и 3,6,13 ждут 1 при НАСТОЯЩИХ прочих проверках — то есть
# требуют зелёной машины. Чужое окно монтажа (26.09: B-N-1054, B-D-008, B-N-1065, B-N-1069) делало их красными: FAIL сторожа по
# виду при исправном стороже. Поэтому сначала один прогон, как случай 1, но в своём каталоге состояния (случай 1 — «первый запуск»).
# Не 0 — стенд НЕ судит сторожа: СЛЕПОТА с причиной, код 2. Случаи 4,5,8,11,12 от машины не зависят (ждут 2), но и их не гоняем:
# частичный прогон спорит с точным счётом проверок ниже и читался бы как вердикт. ЧЕГО НЕ ЛОВИТ: машину, покрасневшую уже ПОСЛЕ этой пробы.
# B-N-1874: на деле это ОКНА МОНТАЖА посреди прогона (08.10 20:18–20:33Z: stop agent-watchdog.timer, монтажи B-N-1877 и
# A-N-1870 — чистый кандидат дал 10/4). Такой FAIL — про машину, не про сторожа: его причину называет блок «сырьё провалов».
mkdir -p "$D/state-proba"
# B-N-2064 (4), 15.10: при не-зелёной машине — ПОЛНЫЙ перечень расхождений. 14.10 02:12Z стенд напечатал три строки вердикта
#   («реестр доработок: РАСХОЖДЕНИЙ НАЙДЕНО») и не назвал предмет: сторож сворачивает подробности в вердикте, а поимённые
#   строки («-X|путь|сумма») кладёт в блок «── сырьё:», который режет RAW_LINES=14 / RAW_CHARS=200. Здесь отсечки сняты
#   (только для этой пробы; на код сторожа они не влияют), печатаются все строки вердикта и весь блок сырья.
#   ЧЕГО НЕ ЛОВИТ: машину, покрасневшую уже ПОСЛЕ пробы (как и прежде); подробности, которых сторож не кладёт в сырьё.
predv=$(env REGWD_STATE="$D/state-proba" REGWD_ALERT="$D/otpravitel" REGWD_CONF=/dev/null RAW_LINES=100000 RAW_CHARS=4000 "$SUT" 2>&1); k=$?
rm -f "$D/soobshenie.txt"
if [ "$k" -ne 0 ]; then
  echo "СЛЕПОТА: машина не зелёная (сторож код $k) — случаи не гонялись, о стороже стенд ничего не говорит. Причина:"
  # Сторож пишет и «  СЛЕПОТА ПРОВЕРОК: …» (живость) — прежний образец «СЛЕПОТА:» его не брал, и «Причина:» печаталась пустой
  # (находка 14.10). Ничего не нашлось — итог сторожа и последние строки, а не пустота.
  pr=$(printf '%s\n' "$predv" | grep -E '^  (РАСХОЖДЕНИЕ|СЛЕПОТА)( ПРОВЕРОК)?:')
  [ -n "$pr" ] || pr=$( { printf '%s\n' "$predv" | grep -E '^сторож реестров:'; echo "  (строка причины не распознана — хвост вывода сторожа:)"; printf '%s\n' "$predv" | tail -5; } )
  printf '%s\n' "$pr"
  syr=$(printf '%s\n' "$predv" | sed -n '/^── сырьё:/,$p')
  if [ -n "$syr" ]; then echo "  перечень расхождений целиком (сырьё сторожа, $(printf '%s\n' "$syr" | grep -c .) строк):"; printf '%s\n' "$syr"
  else echo "  (блока «── сырьё:» в выводе сторожа нет — перечня нет)"; fi
  exit 2
fi
echo "  машина зелёная (предварительный прогон сторожа: код 0)"

k=$(zapusk);                                    proverka "1. первый запуск на зелёной машине" 0 "$k" "повод: заведён" "$D/vyvod.txt"
k=$(zapusk);                                    proverka "2. второй запуск — молчит" 0 "$k" "человеку не сказано" "$D/vyvod.txt"
k=$(zapusk VERIFY_CMD="sudo -n $D/ap-otpechatok verify" HEALTH_CMD="$D/ap-otpechatok list --health")   # B-N-1819: сторож зовёт verify через sudo -n (conf:11) — от iskra dsh-compact-outcomes непроверяема → код 2 вместо 1
                                                proverka "3. расхождение в реестре машины" 1 "$k" "РАСХОЖДЕНИЙ:" "$D/soobshenie.txt"
k=$(zapusk VERIFY_CMD="$D/net-takogo-fajla verify")
                                                proverka "4. слепота: инструмента нет" 2 "$k" "код 127" "$D/vyvod.txt"
k=$(zapusk VERIFY_CMD="$D/ap-slomannyj verify")
                                                proverka "5. слепота: реестр не разбирается (код 1, но НЕ расхождение)" 2 "$k" "СЛЕПОТА: реестр машины" "$D/vyvod.txt"
k=$(zapusk HEALTH_CMD="$D/ap-zhivost list --health")
                                                proverka "6. живость красная обе попытки" 1 "$k" "обе попытки" "$D/soobshenie.txt"   # B-N-1064: сторож пишет «молчат N из M (обе попытки…)», слово «НЕ ОТВЕЧАЮТ» он снял (:357)
rm -f "$D/migala"
k=$(zapusk HEALTH_CMD="$D/ap-migalka list --health")
                                                proverka "7. живость мигнула — повтор гасит ложную тревогу" 0 "$k" "со второй все ответили" "$D/vyvod.txt"
k=$(zapusk HEALTH_CMD="$D/chuzhaja-forma");     proverka "8. канарейка формы живости" 2 "$k" "форма вывода не узнана" "$D/vyvod.txt"
date -d '5 days ago' +%s > "$S/last-run.stamp"
k=$(zapusk);                                    proverka "9. разрыв: прогонов не было 5 суток" 0 "$k" "но был перерыв" "$D/soobshenie.txt"
date -d '8 days ago' +%s > "$S/last-spoke.stamp"; date +%s > "$S/last-run.stamp"
k=$(zapusk);                                    proverka "10. отчёт о живости после долгого молчания" 0 "$k" "сторож реестров жив" "$D/soobshenie.txt"
date -d '8 days ago' +%s > "$S/last-spoke.stamp"; cp "$S/last-spoke.stamp" "$D/otmetka-do"
k=$(zapusk FAKE_ALERT_RC=1);                    proverka "11. тревога не доставлена" 2 "$k" "отметку не ставлю" "$D/vyvod.txt"
if cmp -s "$D/otmetka-do" "$S/last-spoke.stamp"; then ok=$((ok+1)); echo "  ok   11а. отметка не сдвинулась после недоставленной тревоги"
else bad=$((bad+1)); echo "  FAIL 11а. отметка сдвинулась после недоставленной тревоги"; fi
k=$(env REGWD_STATE="$S" REGWD_ALERT="$D/net-pomoshnika" REGWD_CONF=/dev/null "$SUT" > "$D/vyvod.txt" 2>&1; echo $?)
                                                proverka "12. помощника тревог нет вовсе" 2 "$k" "человеку НЕ сказано" "$D/vyvod.txt"
if [ "$SLUCHAJ13" = 1 ]; then
  k=$(zapusk MANIFEST="$D/manifest-porcha.txt");  proverka "13. реестр доработок покраснел" 1 "$k" "реестр доработок" "$D/vyvod.txt"
else
  echo "  ПРОПУСК 13. реестр доработок покраснел — учёт доработок не задан (DORABOTKI_CMD пуст или нет $MANIFEST_REAL)"
fi

echo
echo "сошлось: $ok, разошлось: $bad"
if [ -s "$D/syrjo.txt" ]; then echo "сырьё провалов (хвост вывода сторожа, до 15 строк на случай):"; cat "$D/syrjo.txt"; fi

# Канарейка: ТОЧНОЕ число проверок, не «не меньше». Порог слеп к убыли ровно
# того размера, который умещается в запас, и выглядит строже, чем работает:
# «не меньше» звучит как требование, а действует как разрешение.
# Замерено 25.08.2026 приёмом «сверься с соседом того же вида»: канарейка была
# у 3 стендов из 13. Вырезанный раздел проходил кодом 0 — выпотрошенный стенд
# отчитывался успехом.
ZHDYOM_PROVEROK=$(( 13 + SLUCHAJ13 ))   # №21 аудита 16: 14 со случаем 13, 13 — когда он пропущен с именем
if [ $((ok+bad)) -ne $ZHDYOM_PROVEROK ]; then
