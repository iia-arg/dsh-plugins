#!/usr/bin/env bash
# Стенд сверщика публикаций. Карты и живые копии — ПОДСТАВНЫЕ; проверяется разбор карты и правила сверки,
# а не доступность реестра.
# СЕТИ В ОБХОДЕ НЕТ (B-N-908, 25.09.2026, Аврора; решение Забавы 20:13Z — вместо прежнего «В СЕТЬ ХОДИТ», B-N-868).
#   * Репозиторий полных прогонов — ВРЕМЕННЫЙ клон дерева (git clone --shared, origin = локальный путь дерева):
#     `git fetch origin` сверщика идёт по диску, в GitHub не ходит и в .git боевого клона НЕ пишет. Сторона репозитория
#     — HEAD дерева, как и прежде (незакоммиченное не сверяется).
#   * Реестр progon2 — ПОДСТАВНОЙ файл той же формы, что ответ registry.npmjs.org (метаданные + архив, file://).
#     Прежде progon2 ходил в живой реестр, а опубликованный subscription-gateway 0.1.5 ≠ репозиторию при запрете
#     публикации (06.09) — проба была красной ВСЕГДА по внешней причине, и её перестали бы читать.
#     Живой поход в реестр — только явным ключом SVERKA_ZHIVOJ_REESTR=1, не в обходе.
#   * progon/VYV_POKR: реестр — закрытый порт 127.0.0.1:9 (петля, наружу не выходит), как было.
#   ЧЕГО НЕ ЛОВИТ: расхождение ЖИВОГО реестра с репозиторием — это не стенд, а боевой прогон сверщика.
#
# Коды: 0 сошлось | 1 расхождение | 2 слепота.
#
# ГДЕ НЕ ПРИМЕНЯЕТСЯ:
#   * не проверяет работу с настоящим реестром — это боевой прогон, он делается
#     отдельно и виден по строке «опубл. <версия>» в выводе сверщика;
#   * не судит, ВЕРНА ли карта: она может называть не тот живой путь, и сверка
#     будет честно сверять не то. Верность карты проверяет человек;
#   * не ловит согласованную правку живого, карты и репозитория разом.
set -u
PREDMET="${SVERSHCHIK:-/opt/iskra/workspace/dorabotki/proverit-publikacii.py}"
ok=0; bad=0; slep=0
sud() { if [ "$1" = "ok" ]; then ok=$((ok+1)); else bad=$((bad+1)); echo "FAIL $2: $3"; fi; }
slepo() { slep=$((slep+1)); echo "СЛЕПОТА $1: $2"; }

[ -f "$PREDMET" ] || { echo "СЛЕПОТА: предмета нет по пути $PREDMET"; exit 2; }
python3 -c "import ast,sys; ast.parse(open('$PREDMET').read())" 2>/dev/null \
  && sud ok "предмет разбирается" "" || sud bad "предмет разбирается" "синтаксис сломан"

# --- 1. Правила сверки логики второй копии --------------------------------
V=$(python3 - "$PREDMET" <<'PY'
import sys, importlib.util
spec = importlib.util.spec_from_file_location('sv', sys.argv[1])
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
print('poyasnenie_proshcheno', m.tolko_logika(b'const a = 1\n// odno') == m.tolko_logika(b'const a = 1\n// drugoe'))
print('logika_pojmana',       m.tolko_logika(b'const a = 1') != m.tolko_logika(b'const a = 2'))
print('pustye_proshcheny',    m.tolko_logika(b'const a = 1\n\n\n') == m.tolko_logika(b'const a = 1'))
print('kanarejka',            m.kanarejka())
print('summa_ustojchiva',     m.summa(b'x') == m.summa(b'x'))
print('summa_razlichaet',     m.summa(b'x') != m.summa(b'y'))
PY
)
for pravilo in poyasnenie_proshcheno logika_pojmana pustye_proshcheny kanarejka summa_ustojchiva summa_razlichaet; do
  echo "$V" | grep -q "^$pravilo True$" && sud ok "$pravilo" "" || sud bad "$pravilo" "$(echo "$V" | grep "^$pravilo")"
done

# --- 1а. Канарейка сверщика зависит от ДАННЫХ, а не отвечает «да» ----------
# 🔴 Проверять результат канарейки мало: заглушённая вернёт «да» и пройдёт.
# Ловится только структурно — в её теле обязаны звучать настоящие сравнения.
TELO=$(python3 - "$PREDMET" <<'PY2'
import sys, re
t = open(sys.argv[1]).read()
i = t.index('def kanarejka(')
j = t.index('\ndef ', i + 1)
print(t[i:j])
PY2
)
echo "$TELO" | grep -q 'return True' && sud bad "канарейка не заглушена" "в теле стоит return True — она отвечает да при любых данных"   || sud ok "канарейка не заглушена" ""
echo "$TELO" | grep -q 'summa(' && sud ok "канарейка опирается на настоящую сверку сумм" ""   || sud bad "канарейка опирается на настоящую сверку сумм" "она не зовёт summa — проверяет не то"
echo "$TELO" | grep -q 'tolko_logika(' && sud ok "канарейка проверяет и правило второй копии" ""   || sud bad "канарейка проверяет и правило второй копии" "правило логики не охвачено"

# --- 2. Разбор карты: пара имён «живое -> в архиве» ------------------------
grep -q "'->' in zapis" "$PREDMET" && sud ok "пара имён живое→архив разбирается" "" \
  || sud bad "пара имён живое→архив разбирается" "разбора пары нет — сверка скажет «файла нет в архиве»"

# --- 3. Исходы объявлены поимённо ------------------------------------------
for sluchaj in 'К1' 'К2' 'К3' 'К4' 'К5' 'К6' 'К7'; do
  grep -q "$sluchaj " "$PREDMET" && sud ok "случай $sluchaj назван" "" \
    || sud bad "случай $sluchaj назван" "исход без имени неразличим в отчёте"
done

# --- 4. Порядок вывода: итог ПЕРЕД канарейкой ------------------------------
IT=$(grep -n 'ИТОГО: сверено пар' "$PREDMET" | head -1 | cut -d: -f1)
KA=$(grep -n 'канарейка поймана' "$PREDMET" | head -1 | cut -d: -f1)
if [ -n "$IT" ] && [ -n "$KA" ]; then
  [ "$IT" -lt "$KA" ] && sud ok "итог печатается перед канарейкой" "" \
    || sud bad "итог печатается перед канарейкой" "числа после приговора читают не все"
else slepo "порядок вывода" "не нашла обеих строк"; fi

# --- 5. Границы объявлены в самом инструменте ------------------------------
for granica in 'не публикует' 'не видит незакоммиченного' 'бессилен против'; do
  grep -q "$granica" "$PREDMET" && sud ok "граница «$granica» объявлена" "" \
    || sud bad "граница «$granica» объявлена" "необъявленная граница неоспорима"
done

# --- 6. Карта — данные, а не код -------------------------------------------
KARTA="${KARTA_STEND:-/opt/iskra/workspace/dorabotki/karta-publikacij.yaml}"
[ -f "$KARTA" ] && sud ok "карта лежит отдельным файлом" "" || sud bad "карта лежит отдельным файлом" "нет $KARTA"
python3 -c "
import yaml,sys
d=yaml.safe_load(open('$KARTA'))
sys.exit(0 if d.get('pakety') and d.get('repozitorij') else 1)" 2>/dev/null \
  && sud ok "карта разбирается и не пуста" "" || sud bad "карта разбирается и не пуста" "разбор не удался"
grep -qE "zhivoj:.*/" "$KARTA" && sud ok "в карте есть живые пути" "" || sud bad "в карте есть живые пути" "нечего сверять"
# Пути в самом ИНСТРУМЕНТЕ быть не должно: он едет наружу, карта — нет.
n=$(grep -cE "'/opt/[a-z]" "$PREDMET")
[ "$n" = "0" ] && sud ok "в инструменте нет вписанных живых путей" "" \
  || sud bad "в инструменте нет вписанных живых путей" "$n штук — они принадлежат карте"

# --- 7. Допуск объявленных замен -------------------------------------------
# 🔴 Допуск нужен, чтобы сверка не была вечно красной на известном преобразовании
# (живое зовётся частным именем, наружу едет нейтральное). Но допуск, прикрывающий
# ЛИШНЕЕ, хуже его отсутствия: он гасит настоящее расхождение и выглядит зелёным.
Z=$(python3 - "$PREDMET" <<'PY3'
import sys, importlib.util
spec = importlib.util.spec_from_file_location('sv', sys.argv[1])
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
zam = [{'bylo': 'staroe-imya', 'stalo': 'novoe-imya'}]
posle, prim = m.primenit_zameny(b'const name = "staroe-imya"', zam)
print('zamena_primenilas', posle == b'const name = "novoe-imya"')
print('primenivshiesya_nazvany', prim == {'staroe-imya'})
# замена, которой в тексте нет, НЕ числится применившейся — на этом стоит
# правило «список обязан убывать»
_, prim2 = m.primenit_zameny(b'nichego pohozhego', zam)
print('nenuzhnaya_ne_chislitsya', prim2 == set())
# допуск не трогает НИЧЕГО сверх перечисленного
posle3, _ = m.primenit_zameny(b'staroe-imya i sosednyaya stroka', zam)
print('lishnee_ne_tronuto', b'sosednyaya stroka' in posle3)
PY3
)
for pravilo in zamena_primenilas primenivshiesya_nazvany nenuzhnaya_ne_chislitsya lishnee_ne_tronuto; do
  echo "$Z" | grep -q "^$pravilo True$" && sud ok "$pravilo" "" || sud bad "$pravilo" "$(echo "$Z" | grep "^$pravilo")"
done
# Проверка по ПАКЕТУ, а не по файлу: замена может законно жить только в коде и
# отсутствовать в манифесте. Судить о ненужности по одному файлу нельзя.
# Ловим не НАЛИЧИЕ слова (оно останется в соседней строке и при снятом механизме),
# а обе половины работы: накопитель обязан ЗАПОЛНЯТЬСЯ и ЧИТАТЬСЯ в решении.
zap=$(grep -c 'prim_vsego |= ' "$PREDMET" || true)
cht=$(grep -c 'not in prim_vsego' "$PREDMET" || true)
[ "$zap" != "0" ] && [ "$cht" != "0" ] \
  && sud ok "ненужность судится по пакету" "" \
  || sud bad "ненужность судится по пакету" "накопитель: заполняется $zap, читается $cht — судит по файлу"
# Исход переименован 01.09 в «ДОПУСК ПЕРЕЖИЛ ПРИЧИНУ»: имя должно говорить, ЧТО
# случилось (причина истекла), а не только что делать.
grep -q 'ДОПУСК ПЕРЕЖИЛ ПРИЧИНУ' "$PREDMET" \
  && sud ok "ненужная замена объявляется" "" \
  || sud bad "ненужная замена объявляется" "список замен будет копиться молча"

# --- 8. Сторона реестра берётся прямым запросом ----------------------------
# 🔴 Штатная команда отвечает из кэша и врёт ПРОТИВОРЕЧИВО: старая версия при новых
# размере и числе файлов. Устаревшее заметно, противоречивое читается как поломка
# предмета и подталкивает публиковать повторно. Прецедент 01.09.2026.
n=$(grep -vE '^\s*#' "$PREDMET" | grep -c "subprocess.run(\['npm'" || true)
[ "$n" = "0" ] && sud ok "реестр не через штатную команду" "" \
  || sud bad "реестр не через штатную команду" "$n вызовов npm — ответ будет из кэша"
grep -q 'REESTR_BAZA' "$PREDMET" && sud ok "база реестра объявлена" "" \
  || sud bad "база реестра объявлена" "адрес зашит в вызове"
grep -q "метка «" "$PREDMET" && sud ok "взятая метка печатается" "" \
  || sud bad "взятая метка печатается" "непонятно, что именно сверялось"

# --- 9. Обнаружение стороны, а не только расхождения -----------------------
# 🔴 Канарейка ловит, что сверщик ВИДИТ подставное расхождение. Она не ловит, что
# он правильно НАХОДИТ стороны. Прецедент 01.09.2026: карта была составлена по
# клону, отставшему на девять дней; трёх пакетов в той копии не было, и сверщик
# уверенно доложил «в репозитории пакета НЕТ» с числом «18 расхождений» —
# выглядел работающим тем убедительнее, чем сильнее врал.
N=$(python3 - "$PREDMET" <<'PY4'
import sys, importlib.util, os, tempfile, json
spec = importlib.util.spec_from_file_location('sv', sys.argv[1])
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
with tempfile.TemporaryDirectory() as d:
    kat = os.path.join(d, 'packages', 'katalog-bez-pristavki')
    os.makedirs(kat)
    json.dump({'name': 'dsh-imya-s-pristavkoj'}, open(os.path.join(kat,'package.json'),'w'))
    # ищем по МАНИФЕСТУ: каталог зовётся иначе, чем пакет
    print('nahodit_po_manifestu',
          m.najti_v_repozitorii(d, 'dsh-imya-s-pristavkoj') == 'packages/katalog-bez-pristavki')
    # несуществующего НЕ находит — иначе «нашёл» ничего не значит
    print('nesushchestvujushchij_ne_naiden',
          m.najti_v_repozitorii(d, 'dsh-net-takogo-xyzzy') is None)
    # каталог без манифеста не считается пакетом
    os.makedirs(os.path.join(d,'packages','bez-manifesta'))
    print('bez_manifesta_ne_paket',
          m.najti_v_repozitorii(d, 'bez-manifesta') is None)
PY4
)
for pravilo in nahodit_po_manifestu nesushchestvujushchij_ne_naiden bez_manifesta_ne_paket; do
  echo "$N" | grep -q "^$pravilo True$" && sud ok "$pravilo" "" || sud bad "$pravilo" "$(echo "$N" | grep "^$pravilo")"
done
# Поиск — по манифесту, а не по угадыванию имени. Правило «снять dsh-» сегодня
# работает на всех четырёх пакетах, но это догадка; манифест — факт.
grep -q "get('name') == npm_imya" "$PREDMET" \
  && sud ok "поиск по манифесту, не по имени каталога" "" \
  || sud bad "поиск по манифесту, не по имени каталога" "ищет угадыванием — правило может не совпасть"
# При null в карте обязана быть ПОПЫТКА найти, иначе «нет стороны» и «не умею
# искать» неразличимы — ровно то, против чего писан К4.
grep -q 'КАРТА ГОВОРИТ НЕТ, А ОН ЕСТЬ' "$PREDMET" \
  && sud ok "null в карте проверяется поиском" "" \
  || sud bad "null в карте проверяется поиском" "карта объявляет отсутствие без проверки"
# Для ВТОРОЙ копии поиск не делается: своего места в репозитории у неё нет законно.
# 🔴 БЫЛО ГРЕПОМ ПО КОДУ (`repo and istochnik`) — проба стерегла РАСКЛАДКУ, а не
# смысл: правка, улучшившая поведение, роняла её (04.09.2026). Проверяем поведением
# ниже, на подставном корне, где карта говорит про копию `v_repozitorii: null`.

# --- 10. Свежесть клона ----------------------------------------------------
# Пока свежесть не названа, всё сказанное о «репозитории» относится к локальной
# копии. Это не придирка: именно отставший клон и породил ложный доклад.
grep -q 'def svezhest_klona' "$PREDMET" \
  && sud ok "свежесть клона проверяется" "" \
  || sud bad "свежесть клона проверяется" "выводы о репозитории будут про копию"
# Ловим не НАЛИЧИЕ имени (оно останется при снятом условии), а обе половины:
# признак обязан ВЫСТАВЛЯТЬСЯ по настоящему условию и ЧИТАТЬСЯ в коде возврата.
vyst=$(grep -c 'if beda_sv or otstal:' "$PREDMET" || true)
chit=$(grep -c 'if klon_negoden:' "$PREDMET" || true)
[ "$vyst" != "0" ] && [ "$chit" != "0" ] \
  && sud ok "негодный клон влияет на код возврата" "" \
  || sud bad "негодный клон влияет на код возврата" "выставляется $vyst, читается $chit — отчёт зелёный при неверном предмете"
# К7 — про пару живое<->реестр. Незакоммиченная работа не должна поднимать К7:
# это обычное состояние, а не подмена под той же версией.
grep -q "'живое↔реестр' in s\[1\]" "$PREDMET" \
  && sud ok "К7 судит только по живое-реестр" "" \
  || sud bad "К7 судит только по живое-реестр" "К2 поднимет ложный К7"

# --- 11. Разряды замен: сроки жизни не смешиваются ------------------------
# 🔴 Список исключений с неразличимыми сроками жизни гниёт целиком: через полгода
# никто не отличит «ждёт снятия» от «вечное» — и либо снимать перестанут все, либо
# снесут вечное вместе с временным.
grep -q "razryad == 'postoyannoe'" "$PREDMET" \
  && sud ok "постоянная замена исключена из проверки переживания" "" \
  || sud bad "постоянная замена исключена из проверки переживания" "вечный ложный красный"
grep -q 'РАЗРЯД НЕ ОБЪЯВЛЕН' "$PREDMET" \
  && sud ok "замена без разряда — беда, а не умолчание" "" \
  || sud bad "замена без разряда — беда, а не умолчание" "умолчание снова смешает сроки"
grep -q 'ДОПУСК ПЕРЕЖИЛ ПРИЧИНУ' "$PREDMET" \
  && sud ok "переживший допуск назван своим именем" "" \
  || sud bad "переживший допуск назван своим именем" "снятие некому потребовать"
# Условие снятия печатается в самой строке беды: без него читатель не знает,
# ЧТО должно было случиться, чтобы замену убрать.
grep -q 'uslovie_snyatiya' "$PREDMET" \
  && sud ok "условие снятия читается из карты" "" \
  || sud bad "условие снятия читается из карты" "беда без условия — требование без адреса"
# В карте у КАЖДОЙ замены обязан быть разряд — проверяем данные, а не только код.
KARTA="${KARTA_STEND:-/opt/iskra/workspace/dorabotki/karta-publikacij.yaml}"
bez=$(python3 -c "
import yaml,sys
d=yaml.safe_load(open('$KARTA'))
n=sum(1 for p in d['pakety'] for z in (p.get('zameny') or []) if not z.get('razryad'))
print(n)" 2>/dev/null || echo '?')
[ "$bez" = "0" ] && sud ok "в карте у каждой замены есть разряд" "" \
  || sud bad "в карте у каждой замены есть разряд" "без разряда: $bez"

# --- 12. Строка покрытия ---------------------------------------------------
# 🔴 Вердикт говорит про ПАКЕТ, а сверяются отдельные файлы. Разрыв между
# областью проверки и областью утверждения обязан быть виден В САМОМ ВЕРДИКТЕ,
# а не в чьей-то памяти: правило исполняет тот, кто о нём помнит, а формат — сам.
grep -q 'проверено файлов' "$PREDMET" \
  && sud ok "строка покрытия печатается" "" \
  || sud bad "строка покрытия печатается" "область утверждения не видна"
# Числа не выдуманы: X копится по фактически сверенным файлам.
zap=$(grep -c 'svereno_fajlov.add' "$PREDMET" || true)
chit=$(grep -c 'len(svereno_fajlov)' "$PREDMET" || true)
[ "$zap" != "0" ] && [ "$chit" != "0" ] \
  && sud ok "X считается по сверенным, а не назначен" "" \
  || sud bad "X считается по сверенным, а не назначен" "копится $zap, читается $chit"
# Список «вне проверки» — это то, чего мы НЕ смотрели; без него число без адреса.
grep -q 'вне проверки' "$PREDMET" \
