#!/usr/bin/env bash
# Приёмка блока 4 сторожа реестров — наблюдения за сторожем машины.
#
# ЧТО ПРОВЕРЯЕТ. Что взаимное наблюдение зрячее: три признака ловят три разные
# беды, слепота отделена от расхождения, а зелёный цвет не выдаётся на порче.
#
# 🔴 ТЕКСТ БЕРЁТСЯ ИЗ УСТАНОВЛЕННОГО ФАЙЛА — стенд запускает /usr/local/sbin/
# registry-watchdog.sh, а не свою копию логики. Стенд, проверяющий пересказ, а не
# предмет, зеленеет ровно тогда, когда предмет уже разошёлся с пересказом.
#
# 🔴 ЦЕНА ПРОГОНА. Проверка «настоящая порча» на секунды ОСТАНАВЛИВАЕТ таймер
# сторожа машины и возвращает его обратно (возврат в trap, то есть и при обрыве).
# В это окно машина без сторожа — до 10 секунд. Отключается: BEZ_PORCHI_PREDMETA=1.
# Человеку стенд не пишет НИ РАЗУ: подставной помощник тревоги складывает текст в
# файл. Иначе прогон приёмки означал бы пачку тревог владельцу.
#
# ───────────────────────────────────────────────────────────────────────────
# 🔴 ГРАНИЦА ОХВАТА — о чём этот стенд НЕ высказывается. Зелёный цвет означает
# ровно то, что внутри этих границ, и ничего больше. Каждая замерена 25.08.2026,
# команда замера приведена рядом.
#
# 1. ТОЛЬКО БЛОК 4. Предмет — наблюдение за сторожем машины. Блоки 1-3 сторожа
#    реестров (сверка учётов, живость записей, предел молчания) здесь не
#    проверяются вовсе — их предмет у stend-storozha-reestrov.sh. Зелёный тут НЕ
#    означает «сторож реестров исправен».
#
# 2. ТОЛЬКО ОДНА СТРЕЛКА ИЗ ДВУХ. Проверяется, что сторож реестров замечает беды
#    соседа. Обратная — что сторож машины заметит смерть сторожа реестров — не
#    проверяется ни здесь, ни где-либо ещё:
#      grep -rln 'watchdog.conf\|agent-watchdog.sh' /opt/iskra/workspace/dorabotki/stend-*.sh
#    (25.08.2026: пусто). Обратная стрелка держится на одной строке
#    registry-watchdog.timer в SERVICES файла /etc/agent-watchdog/watchdog.conf,
#    и её сохранность стережёт только реестр вмешательств, отпечатком настройки.
#
# 3. ДОСТАВКА ТРЕВОГИ НЕ ПРОВЕРЯЕТСЯ. REGWD_ALERT подставляется нарочно (см.
#    «цена прогона» выше), значит про настоящий /usr/local/bin/agent-alert стенд
#    не говорит ничего: дойдёт ли тревога до человека — известно только из
#    сквозного боевого прогона, а не отсюда.
#
# 4. ПОРОГИ НЕ СВЕРЯЮТСЯ С ПЕРИОДОМ ТАЙМЕРА. PEER_FRESH_MIN=15 и
#    PEER_MIN_PER_DAY=250 — литералы в сторожа; 250 выведено из
#    OnUnitActiveSec=5min (288 заходов в сутки), но ничем с ним не связано:
#      grep -rlE 'PEER_MIN_PER_DAY|OnUnitActiveSec' *.sh /usr/local/sbin/registry-watchdog.sh
#    (25.08.2026: только сам сторож, ни одного стенда). Сменят период на 15 мин —
#    заходов станет 96, сторож начнёт краснеть ЕЖЕДНЕВНО и законно по своей
#    арифметике, а этот стенд останется зелёным: он проверяет, что признак
#    срабатывает, а не что порог осмыслен для нынешнего расписания.
#
# 5. ОДНОВРЕМЕННАЯ СМЕРТЬ ОБОИХ СТОРОЖЕЙ не ловится никем — наблюдателя вне
#    машины нет и, по решению владельца от 24.08.2026, не будет. Взаимное
#    наблюдение понижает вероятность незамеченной смерти, но не устраняет её;
#    задержка к тому же несимметрична (сосед видит нашу смерть за 5 минут, мы
#    его — на следующем суточном прогоне).
# ───────────────────────────────────────────────────────────────────────────
# ТРИ КОДА: 0 — всё сошлось; 1 — проверка не прошла; 2 — стенд не смог измерить.
# ZHIVAYA-MASHINA: останавливает и запускает БОЕВОЙ agent-watchdog.timer (порча предмета, :251-264; возврат в trap)
# B-N-1929 (Заря; условия Вениамина 10:36Z): ключ --zhivaya-mashina — ПЕРВЫМ действием; без него ОТКАЗ-ZHIVAYA-MASHINA и код 2,
#   НИЧЕГО не позвано (ни sudo, ни systemctl). Ночной обход и ворота выпуска ключ НЕ подают; недельный (vse-stendy-nedelnye.sh) —
#   явно и поимённо своим строкам. Вручную: bash $0 --zhivaya-mashina. Ключ убирается из доводов, остальные — как прежде.
_ZM=0; _DOV=(); for _a in "$@"; do if [ "$_a" = --zhivaya-mashina ]; then _ZM=1; else _DOV+=("$_a"); fi; done
if [ "$_ZM" != 1 ]; then echo "ОТКАЗ-ZHIVAYA-MASHINA: останавливает и запускает БОЕВОЙ agent-watchdog.timer (порча предмета, :251-264; возврат в trap) — нужен --zhivaya-mashina. Ничего не тронуто."; exit 2; fi
set -- "${_DOV[@]+"${_DOV[@]}"}"
set -uo pipefail
# RU: Стенд меряет через sudo. Нет sudo (оболочка агента в bwrap с NoNewPrivs, нет прав) — СЛЕПОТА, код 2, а не ложное красное.
# EN: The test measures through sudo. No sudo (an agent shell in bwrap with NoNewPrivs, no rights) — BLIND, exit 2, not a false red.
sudo -n true 2>/dev/null || { echo "СЛЕПОТА: нет sudo (NoNewPrivs $(awk '/^NoNewPrivs/{print $2}' /proc/self/status)) — стенд меряет через sudo, исход был бы ложным"; exit 2; }
export LC_ALL=C.UTF-8

STOROZH="${STOROZH:-/usr/local/sbin/registry-watchdog.sh}"
PEER_TIMER_REAL="${PEER_TIMER_REAL:-agent-watchdog.timer}"
BEZ_PORCHI_PREDMETA="${BEZ_PORCHI_PREDMETA:-0}"

ok=0; fail=0; slep=0
T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT
printf '#!/bin/bash\nprintf "%%s\\n" "$1" >> "%s/skazano.txt"\n' "$T" > "$T/alert"
chmod +x "$T/alert"; : > "$T/skazano.txt"

[ -x "$STOROZH" ] || { echo "СЛЕПОТА: нет исполняемого сторожа $STOROZH"; exit 2; }

# Отметка времени начала: по ней потом видно, трогал ли стенд боевое состояние.
NACHALO=$(date +%s)

# Прогон сторожа с подставным состоянием и подставным помощником тревоги.
# Возвращает код в R_KOD, вывод в R_OUT.
progon() {
  R_OUT="$(REGWD_STATE="$T/state" REGWD_ALERT="$T/alert" env "$@" bash "$STOROZH" 2>&1)"
  R_KOD=$?
}

# 🔴 СУДИМ ПО СВОЕМУ ПРЕДМЕТУ, А НЕ ПО ОБЩЕМУ КОДУ (правка 28.08.2026).
# Стенд проверяет ОДИН блок сторожа — взаимное наблюдение за соседом. Общий
# код сторожа поднимает любое расхождение, в том числе чужое: живость чужой
# рукой, неразмеченный дом соседа. 28.08 сторож краснел законно из-за чужого
# дома — и стенд краснел на ИСПРАВНОМ предмете. Ложно-красное, которое стало
# бы постоянным: тревога о чужом дефекте уходит владельцу ежедневно.
# Теперь «чисто» значит «нет расхождения ПРО СОСЕДА», а не «код 0».
# ГДЕ НЕ ДЕЙСТВУЕТ: подмена ослабляет проверку доставки — если блок соседа
# найдёт беду, но сторож почему-то выйдет нулём, стенд этого не заметит.
# Поэтому там, где ждём беду, код проверяется отдельно и обязан быть НЕ 0.
sosed_razoshelsya() { printf '%s' "$R_OUT" | grep -q 'РАСХОЖДЕНИЕ: сторож машины:'; }

# proverka <имя> <ожидаемый код> <образец в выводе> [переменные...]
proverka() {
  local imya="$1" zhdem="$2" obrazec="$3"; shift 3
  progon "$@"
  if [ "$zhdem" = "0" ]; then
    if sosed_razoshelsya; then
      echo "FAIL $imya: блок соседа нашёл расхождение там, где его быть не должно"
      printf '%s\n' "$R_OUT" | grep -E 'РАСХОЖДЕНИЕ: сторож машины:' | sed 's/^/      /'
      fail=$((fail+1)); return
    fi
  elif [ "$zhdem" = "2" ]; then
    # 🔴 СЛЕПОТА — не расхождение: измерить не удалось, и расхождения про
    # соседа быть НЕ должно. Здесь судим кодом и текстом, а не признаком.
    if [ "$R_KOD" != "2" ]; then
      echo "FAIL $imya: код $R_KOD, ждали 2 (слепота)"
      fail=$((fail+1)); return
    fi
  else
    if ! sosed_razoshelsya; then
      echo "FAIL $imya: блок соседа НЕ нашёл расхождения, а должен был"
      printf '%s\n' "$R_OUT" | grep -E 'сторож машины:' | sed 's/^/      /'
      fail=$((fail+1)); return
    fi
    if [ "$R_KOD" = "0" ]; then
      echo "FAIL $imya: расхождение про соседа найдено, но сторож вышел кодом 0 — беда не дойдёт"
      fail=$((fail+1)); return
    fi
  fi
  # 🔴 ОБРАЗЕЦ — СПИСОК ПУТЕЙ, А НЕ ОДНА ФОРМУЛИРОВКА. Сторож сообщает об одной
  # и той же беде РАЗНЫМИ путями: строкой блока соседа либо живостью записи
  # («НЕ ОТВЕЧАЕТ: inactive»). Какой сработает первым — плавает, а проверка,
  # привязанная к тексту одного пути, ложно краснеет при срабатывании другого
  # (замер 25.08: стенд 17/1 при исправном предмете, повтор 18/0 через десять
  # минут). Судим предмет: «сказал о беде хоть каким-нибудь путём».
  # Пути разделяются знаком @@ — он без особого смысла в оболочке, в отличие
  # от %% и |, которые пришлось бы экранировать внутри ${}.
  najden=1
  ostatok="$obrazec"
  while [ -n "$ostatok" ]; do
    kusok="${ostatok%%@@*}"
    if printf '%s' "$R_OUT" | grep -qF "$kusok"; then najden=0; break; fi
    case "$ostatok" in *@@*) ostatok="${ostatok#*@@}";; *) ostatok="";; esac
  done
  if [ "$najden" != 0 ]; then
    echo "FAIL $imya: код верный ($R_KOD), но ни один из путей не найден: «$obrazec»"
    printf '%s\n' "$R_OUT" | grep -E 'сторож машины:|РАСХОЖДЕНИЕ:|СЛЕПОТА:' | sed 's/^/      /'
    fail=$((fail+1)); return
  fi
  echo "ok   $imya"
  ok=$((ok+1))
}

echo "── блок есть в установленном файле"
for anchor in 'PEER_ENABLED' 'PEER_DONE_MSGID' 'peer_itog' 'сторож машины: таймер'; do
  if grep -qF "$anchor" "$STOROZH"; then echo "ok   якорь «$anchor» на месте"; ok=$((ok+1))
  else echo "FAIL якорь «$anchor» пропал из $STOROZH — блок 4 снят или переписан"; fail=$((fail+1)); fi
done

echo "── имя соседа задано дважды — литералы обязаны сходиться"
# 🔴 Найдено 25.08.2026. PEER_TIMER_REAL здесь и PEER_TIMER в сторожа — ДВА
# независимых литерала с одним значением. Разойдутся молча: стенд остановит один
# таймер, сторож посмотрит на другой, и «настоящая порча» проверит не тот предмет,
# оставшись зелёной. Источник правды — сторож: он и есть предмет проверки.
STOROZH_TIMER="$(sed -n 's/^PEER_TIMER="\${PEER_TIMER:-\([^}]*\)}".*/\1/p' "$STOROZH" | head -1)"
if [ -z "$STOROZH_TIMER" ]; then
  echo "СЛЕПОТА: не нашла умолчание PEER_TIMER в $STOROZH — сверить имена нечем"
  slep=$((slep+1))
elif [ "$STOROZH_TIMER" != "$PEER_TIMER_REAL" ]; then
  echo "FAIL имя соседа разошлось: стенд портит «$PEER_TIMER_REAL», сторож смотрит на «$STOROZH_TIMER»"
  fail=$((fail+1))
else
  echo "ok   имя соседа сходится с умолчанием сторожа ($STOROZH_TIMER)"
  ok=$((ok+1))
fi

echo "── исправная машина"
proverka "чисто: зелено" 0 "сторож машины: таймер active" PEER_ENABLED=1
# Текст предмета изменён 28.08 (порог считается от загрузки), образец —
# под новую формулировку. Строка предмета участвует здесь в ЛОГИКЕ, а не
# только печатается: меняя её, надо править и стенд.
proverka "чисто: заходы посчитаны" 0 "заходов " PEER_ENABLED=1

echo "── три признака ловят три разные беды"
# Сосед, который ходит редко и по-настоящему: свежесть и полнота обязаны покраснеть.
#
# 🔴 ФИКСТУРА ВЫБИРАЕТСЯ ЗАМЕРОМ, А НЕ ИМЕНЕМ. Здесь стоял литерал
# apt-daily.service — и 24.08 в 18:57 стенд покраснел на ИСПРАВНОМ сторо́же:
# apt-daily отработал за 14 минут до прогона, то есть оказался свежим, и признак
# свежести законно промолчал. Расписание чужой службы мне не подвластно, значит
# литерал в фикстуре — это ставка на чужой распорядок. Ищем службу, у которой
# последний заход заведомо старше порога; не нашли — СЛЕПОТА, а не FAIL:
# «сейчас нечем воспроизвести» и «предмет сломан» — разные утверждения.
STARSHE_MIN=20
DONE_MSGID=39f53479d3a045ac8e11786248231fbf
REDKIJ=""
for kandidat in logrotate.service dpkg-db-backup.service fstrim.service \
                systemd-tmpfiles-clean.service man-db.service apt-daily.service; do
  posl=$(journalctl -u "$kandidat" --since "-24 hours" "MESSAGE_ID=$DONE_MSGID" \
         --no-pager -o short-unix 2>/dev/null | tail -1 | cut -d. -f1)
  [ -n "$posl" ] || continue
  vozrast=$(( ( $(date +%s) - posl ) / 60 ))
  if [ "$vozrast" -ge "$STARSHE_MIN" ]; then
    REDKIJ="$kandidat"
    echo "     фикстура «редкий сосед»: $kandidat, последний заход $vozrast мин назад"
    break
  fi
done
if [ -z "$REDKIJ" ]; then
  echo "СЛЕПОТА: нет службы, ходившей за сутки и при этом старше $STARSHE_MIN мин —"
  echo "         воспроизвести «редкого соседа» сейчас нечем. Это НЕ значит, что признаки сломаны."
  slep=$((slep+2))
else
  proverka "редкий сосед: свежесть" 1 "числится живым, а не работает" PEER_UNIT="$REDKIJ"
  proverka "редкий сосед: полнота"  1 "работает рывками"              PEER_UNIT="$REDKIJ"
fi
proverka "таймера нет"            1 "не активен"                    PEER_TIMER=net-takogo-storozha.timer
proverka "журнала нет: СЛЕПОТА"   2 "не читается или пуст"          PEER_UNIT=net-takoj-sluzhby.service
proverka "признак сломан"         1 "заходов 0"                     PEER_DONE_MSGID=00000000000000000000000000000000

echo "── выключатель"
proverka "PEER_ENABLED=0 молчит" 0 "реестр машины:" PEER_ENABLED=0
if progon PEER_ENABLED=0; printf '%s' "$R_OUT" | grep -q 'сторож машины:'; then
  echo "FAIL PEER_ENABLED=0: блок всё равно печатал вердикт о соседе"; fail=$((fail+1))
else
  echo "ok   PEER_ENABLED=0: о соседе ни строки"; ok=$((ok+1))
fi

echo "── боевое состояние стендом не тронуто"
# 🔴 Это не формальность. Если подстановка REGWD_STATE/REGWD_ALERT не сработает,
# стенд начнёт писать отметки в боевое состояние и слать тревоги ЖИВОМУ человеку —
# и прогон приёмки станет пачкой ложных писем. Признак настоящий: боевые отметки
# обязаны остаться нетронутыми, а подставной файл — наоборот, получить строки.
BOEVOE="${BOEVOE:-/var/lib/registry-watchdog}"
skazano=$(wc -l < "$T/skazano.txt")
if [ "$skazano" -lt 1 ]; then
  echo "FAIL подставной помощник не получил НИ ОДНОЙ строки — либо тревоги ушли мимо него, либо сторож молчал везде"
  fail=$((fail+1))
elif [ ! -d "$BOEVOE" ]; then
  echo "СЛЕПОТА: нет боевого состояния $BOEVOE — не с чем сверять, что стенд его не тронул"
  slep=$((slep+1))
else
  svezhee="$(find "$BOEVOE" -newermt "@$NACHALO" -print 2>/dev/null | head -3)"
  if [ -n "$svezhee" ]; then
    echo "FAIL стенд тронул БОЕВОЕ состояние: $(printf '%s' "$svezhee" | tr '\n' ' ')"
    fail=$((fail+1))
  else
    echo "ok   боевое состояние не тронуто, тревоги ушли в подставной файл ($skazano строк)"
    ok=$((ok+1))
  fi
fi

if [ "$BEZ_PORCHI_PREDMETA" = "1" ]; then
  echo "── настоящая порча предмета ПРОПУЩЕНА (BEZ_PORCHI_PREDMETA=1) — покрытие неполное"
  slep=$((slep+1))
else
  echo "── настоящая порча предмета: останавливаю $PEER_TIMER_REAL и возвращаю"
  vernut() { sudo -n systemctl start "$PEER_TIMER_REAL" >/dev/null 2>&1; }
  trap 'vernut; rm -rf "$T"' EXIT
  if ! sudo -n systemctl stop "$PEER_TIMER_REAL" >/dev/null 2>&1; then
    echo "СЛЕПОТА: не удалось остановить $PEER_TIMER_REAL — порча предмета не проверена"
    slep=$((slep+1))
  else
    sostoyanie="$(systemctl is-active "$PEER_TIMER_REAL" 2>&1)"
    if [ "$sostoyanie" = "active" ]; then
      echo "СЛЕПОТА: таймер остался active после stop — порча не состоялась"; slep=$((slep+1))
    else
      # Два пути одной беды: строка блока соседа либо живость записи. См. proverka().
      proverka "порча предмета: таймер остановлен" 1 "не активен@@НЕ ОТВЕЧАЕТ" PEER_ENABLED=1
    fi
    vernut
    sleep 1
    vozvrat="$(systemctl is-active "$PEER_TIMER_REAL" 2>&1)"
    if [ "$vozvrat" = "active" ]; then
      echo "ok   возврат: $PEER_TIMER_REAL снова active"; ok=$((ok+1))
      proverka "после возврата снова зелено" 0 "сторож машины: таймер active" PEER_ENABLED=1
    else
      echo "FAIL 🔴 ВОЗВРАТ НЕ СОСТОЯЛСЯ: $PEER_TIMER_REAL = $vozvrat — машина осталась без сторожа, поднять руками"
      fail=$((fail+1))
    fi
  fi
  trap 'rm -rf "$T"' EXIT
fi

echo
echo "итог: сошлось $ok, не прошло $fail, не измерено $slep"

# Канарейка: ТОЧНОЕ число проверок, не «не меньше». Порог слеп к убыли ровно
# того размера, который умещается в запас, и выглядит строже, чем работает:
# «не меньше» звучит как требование, а действует как разрешение.
# Замерено 25.08.2026 приёмом «сверься с соседом того же вида»: канарейка была
# у 3 стендов из 13. Вырезанный раздел проходил кодом 0 — выпотрошенный стенд
# отчитывался успехом.
ZHDYOM_PROVEROK=18
if [ $((ok+fail+slep)) -ne $ZHDYOM_PROVEROK ]; then
