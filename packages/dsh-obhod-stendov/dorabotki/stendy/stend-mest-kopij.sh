# Коды — договор обходчика: 0 зелёное · 1 расхождение · 2 слепота. Проба даёт 3 на слепоту — здесь это 2.
set -u
[ $# -eq 0 ] || { echo "СЛЕПОТА: стенд зовётся без доводов (получено: $*)"; exit 2; }
P="${PROBA_MEST_KOPIJ:-/opt/iskra/workspace/dorabotki/stendy/proba-kopij.sh}"   # подмена — только для стенда обёртки
[ -r "$P" ] || { echo "СЛЕПОТА: нет пробы $P"; exit 2; }
