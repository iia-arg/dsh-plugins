#!/bin/bash
# ЧИТАТЕЛЬ ОТ ROOT ПО РАСПИСАНИЮ (obhod 3.1.87; условие (3) Вениамина к a2a-bus 3.1.5, наряд Забавы 16.10 02:11:58Z).
# Зачем: с a2a-bus 3.1.5 обратная сверка у не-root руки пишет «граница» на родителе закрытого ящика (0700) — iskra (суточный
#   registry-watchdog, User=iskra) их больше не видит. Полную сверку даёт только root; этот стенд — её зовущий в ночном обходе
#   (строка области @root). Признак: `agent-registry verify` от root — код 0 и в итоге НЕТ «НЕ ПРОВЕРЕНО». Красное — с именами
#   строк «расхождение»/«СЛЕПОТА».
# КОДЫ: 0 — сошлось; 1 — расхождение или «не проверено» у root (с именами); 2 — слепота стенда (не root, нет инструмента,
#   неизвестный код verify, пустой вывод).
# ⚠️ ЧЕГО НЕ ЛОВИТ: то, чего не сверяет сам agent-registry (это его область, не стенда); беду, возникшую после ночного прогона
#   (до следующего — сутки); строки «граница» у root не ожидаются и не судятся отдельно.
# Подстановка реестра для проб: AGENTS_REGISTRY (переменная самого agent-registry). Боевые файлы стенд не меняет.
set -u
AR="${AGENT_REGISTRY_BIN:-/usr/local/bin/agent-registry}"
[ "$(id -u)" = 0 ] || { echo "СЛЕПОТА: стенд читает от root (строка области @root), а запущен от $(id -un)"; exit 2; }
[ -x "$AR" ] || { echo "СЛЕПОТА: нет $AR"; exit 2; }
OUT=$(timeout 90 "$AR" verify 2>&1); K=$?   # 3.1.88 (LOW Вениамина): ≤100 с при пределе стенда в обходе 120 с; замер ≈7 с; 124 — СЛЕПОТА ниже
[ -n "$OUT" ] || { echo "СЛЕПОТА: verify ничего не вывел (код $K)"; exit 2; }
ITOG=$(printf '%s\n' "$OUT" | grep -v '^[[:space:]]*$' | tail -1)
imena() { printf '%s\n' "$OUT" | grep -E '^  [^ ].* (расхождение|СЛЕПОТА) ' | sed 's/^ *//' | cut -c1-200; }
case "$K" in
  0) if printf '%s' "$ITOG" | grep -qF 'НЕ ПРОВЕРЕНО'; then
       echo "FAIL verify от root: код 0, но в итоге «НЕ ПРОВЕРЕНО»: $ITOG"; imena; exit 1; fi
     echo "ok   verify от root: $ITOG"; exit 0 ;;
  1|2) echo "FAIL verify от root (код $K): $ITOG"; imena; exit 1 ;;
  *) echo "СЛЕПОТА: verify от root — неизвестный код $K: $ITOG"; exit 2 ;;
esac
