/**
 * Тепло записи — мера СПРОСА: пользуются ею или нет.
 *
 * 🔴 ГЛАВНОЕ, И ЭТО ГРАНИЦА, А НЕ ОГОВОРКА: СЕГОДНЯ ТЕПЛО НИ НА ЧТО НЕ ВЛИЯЕТ.
 * Оно вычисляется и печатается, но НЕ участвует в порядке и НИЧЕГО НЕ ОТСЕКАЕТ.
 * Это прибор, а не правило. Причина не в осторожности, а в двух замерах:
 *
 *  (1) ПОРЯДОК ПО ТЕПЛУ ТОЖДЕСТВЕН ПОРЯДКУ ПО СВЕЖЕСТИ. Замер 04.09.2026 на 31
 *      живой записи: различий позиций НОЛЬ. И это не совпадение выборки, а
 *      устройство: счётчика касаний в схеме `zapisi` НЕТ НИ ОДНОГО ПОЛЯ, поэтому
 *      тепло здесь — чистая функция возраста, монотонно убывающая. Ранжирование
 *      по монотонной функции возраста и есть ранжирование по возрасту.
 *      Пока касаний не считают, тепло как ПОРЯДОК — это свежесть под другим именем,
 *      то есть третий порядок, неотличимый от первого. Заводить его значило бы
 *      завести выбор между двумя одинаковыми ответами.
 *
 *  (2) ПОРОГ НЕ ОТСЕКАЕТ НИЧЕГО. На тех же 31 записи тепло 0.9184…1.0000 при
 *      предлагаемом пороге «холодной» 0.25. Вся история памяти — 1,7 суток при
 *      полураспаде 14 суток: мера не может различить то, что короче её шага.
 *
 * ⚠️ КОГДА ЭТО ПЕРЕСТАНЕТ БЫТЬ ВЕРНЫМ — назвать заранее, иначе граница переживёт
 * свою причину и следующий сочтёт тепло вечно бесполезным:
 *   • появится счётчик касаний → тепло перестанет совпадать со свежестью, и тогда
 *     оно осмысленно как ВХОД в порядок (не как третий порядок — см. п.1);
 *   • история дорастёт до трёх полураспадов (42 суток) → распределение станет
 *     наблюдаемым, и порог можно будет назначить ПО НЕМУ, а не по рассуждению.
 * До этих двух событий числа ниже — гипотезы, помеченные гипотезами.
 */

/** Полураспад. ГИПОТЕЗА: на живом корпусе не проверен и проверен быть не может —
 *  история короче полураспада. Не отсекает ничего, поэтому безвреден. */
export const POLURASPAD_MS = 14 * 24 * 3600 * 1000;

/** Порог «холодной». ГИПОТЕЗА. Сегодня ниже него НЕ ПОПАДАЕТ НИ ОДНА запись —
 *  число печатается, чтобы это было видно, а не чтобы по нему судить. */
export const POROG_HOLODNOJ = 0.25;

/** Прибавка за касание. Веса НЕТ намеренно: касаний никто не считает, и подбирать
 *  число вслепую значило бы выдать рассуждение за замер. Включить ВМЕСТЕ со
 *  счётчиком касаний, не раньше. */
export const VES_KASANIYA = 0;

/**
 * Тепло записи: рождается ПОЛНЫМ и остывает.
 *
 * 🔴 Рождается полным, а не с нуля. Иначе всё холодное с рождения, и механизм,
 * заведённый хранить, съедает то, что должен хранить в первый же день.
 *
 * Возвращает число 0..1 либо null — «тепло не измерялось». Это ТРЕТЬЕ состояние,
 * не «холодная» и не ошибка: у записи без даты рождения тепла нет, а не ноль.
 * Тот же довод, что для веры: пустота — не ноль.
 */
export function teplo(zapis, teper = Date.now()) {
  // 🔴 ДВА ИМЕНИ ОДНОГО ПОЛЯ НА ГРАНИЦЕ ПАКЕТОВ (найдено замером 05.09.2026).
  // Ядро называет время рождения `sozdano`, а слой восстановления, отдавая записи сюда,
  // переименовывает его в `kogda` (его decide читает именно так). Прибор тепла читал
  // только `sozdano` — и в бою печатал «измерено 0, не измерено 10».
  // 🔴 ЧЕМ ЭТО ХУЖЕ ПРОСТО ОШИБКИ: число выглядело свойством ДАННЫХ («у записей нет даты»),
  // а было свойством ПРИБОРА. Прибор, заведённый копить наклон для будущего порога, не
  // измерил ни одной записи с самого своего появления — и молчал об этом, потому что
  // «не измерено» у него законный третий исход.
  // ⚠️ ГРАНИЦА: синоним принимается ЗДЕСЬ, в одном месте, и называется в коде. Плодить
  // его дальше нельзя: третье имя того же поля мы уже не заметим.
  const sozdano = Number(zapis?.sozdano ?? zapis?.kogda);
  if (!Number.isFinite(sozdano) || sozdano <= 0) return null;
  const vozrast = teper - sozdano;
  if (!(vozrast >= 0)) return 1;             // из будущего — считаем свежайшей, а не отрицательной
  return 2 ** (-vozrast / POLURASPAD_MS);
}

/** Распределение тепла по списку. Прибор ставится РАНЬШЕ порога: пока порог не
 *  назначен, единственное, что можно честно сделать, — печатать числа при каждом
 *  отборе, чтобы через месяц наклон появился из боя, а не из выдумки. */
export function raspredelenie(zapisi, teper = Date.now()) {
  const znacheniya = [];
  let neizmereno = 0;
  for (const z of zapisi ?? []) {
    const t = teplo(z, teper);
    if (t === null) neizmereno++; else znacheniya.push(t);
  }
  // 🔴 ТРИ ВХОДА ТЕПЛА СЧИТАЮТСЯ ПОРОЗНЬ (ворота В6 приёмки). Пока вход один — возраст, —
  // «тепло» есть свежесть под другим именем, и назвать его теплом значит соврать словом.
  // Числа абсолютные: сколько записей ИМЕЮТ счётчик касаний, сколько касались хоть раз,
  // когда касались в последний раз. Доля не печатается: знаменатель растёт, и доля тем
  // благополучнее, чем дольше не чинишь.
  // ⚠️ ГРАНИЦА: касания на тепло НЕ ВЛИЯЮТ, пока вес равен нулю (VES_KASANIYA). Эти три
  // числа — наблюдение, а не вход в формулу; когда вес включат, здесь появится и он.
  let s_polem = 0, kasalis = 0, poslednee = null;
  for (const z of zapisi ?? []) {
    const k = z?.kasanij;
    if (k === null || k === undefined) continue;
    s_polem++;
    if (Number(k) > 0) kasalis++;
    const p = Number(z?.poslednee_kasanie);
    if (Number.isFinite(p) && p > 0 && (poslednee === null || p > poslednee)) poslednee = p;
  }
  znacheniya.sort((a, b) => a - b);
  const n = znacheniya.length;
  return {
    izmereno: n,
    neizmereno,
    kasanij_pole_est: s_polem,
    kasalis_hot_raz: kasalis,
    poslednee_kasanie: poslednee,
    ves_kasaniya: VES_KASANIYA,
    min: n ? znacheniya[0] : null,
    mediana: n ? znacheniya[n >> 1] : null,
    max: n ? znacheniya[n - 1] : null,
    holodnyh: znacheniya.filter((v) => v < POROG_HOLODNOJ).length,
    porog: POROG_HOLODNOJ,
    poluraspad_sutok: POLURASPAD_MS / (24 * 3600 * 1000),
    vliyaet_na_otbor: false,   // 🔴 читается вызывающим и печатается: см. шапку файла
  };
}
