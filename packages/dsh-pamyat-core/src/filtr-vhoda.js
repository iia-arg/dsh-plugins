function entropiya(s) {
  const schet = new Map();
  for (const z of s) schet.set(z, (schet.get(z) ?? 0) + 1);
  let e = 0;
  for (const n of schet.values()) { const p = n / s.length; e -= p * Math.log2(p); }
  return e;
}
