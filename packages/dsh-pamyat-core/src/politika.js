/**
 * Политика записи: какие классы знаний пишутся сами, а какие — только с
 * подтверждения человека.
 *
 * ЗАЧЕМ. Не всякое знание равноценно. Общефермовые ограничения и навыки
 * действуют на других агентов, поэтому пишутся ТОЛЬКО с подтверждения; рабочие
 * заметки агента о себе — сами. Решение по классам, а не по одному глобальному
 * переключателю: переключатель заставляет выбирать между «всё спрашивать» и
 * «ничего не спрашивать», и на практике выбирают второе.
 *
 * 🔴 ГЛАВНОЕ РАЗЛИЧЕНИЕ, КОТОРОЕ ЗДЕСЬ СОХРАНЯЕТСЯ. Ядро платформы уже отличает
 * человеческое «нет» от ОТСУТСТВИЯ канала подтверждения: в его же словах —
 * «три не-грант исхода отказывают с РАЗНЫМИ причинами, чтобы модель могла
 * отличить человеческое "нет" от отсутствующего канала подтверждения»
 * (dsh-tools 0.1.1-rc.2, lib/types/index.d.ts, описание serviceAsk).
 * Наш слой обязан это различие ПРОНЕСТИ, а не схлопнуть в «не записали»:
 * «человек отказал» — это решение, «канала нет» — это поломка установки.
 * Схлопнешь — и сломанная установка будет выглядеть как осторожный человек.
 *
 * ГДЕ НЕ ПРИМЕНЯЕТСЯ. Здесь нет самой записи и нет обращения к подтверждению:
 * этот модуль только РЕШАЕТ и объясняет решение. Исполняет вызывающий.
 */

/** Классы, которые по умолчанию требуют подтверждения. */
export const KLASSY_SPRASHIVAT = Object.freeze(['ogranichenie', 'navyk']);

/**
 * Решить, как поступить с записью данного класса.
 *
 * @param {string} klass          класс знания
 * @param {object} nastrojka      { sprashivat?: string[], avtomaticheski?: string[] }
 * @returns {{reshenie:'auto'|'ask', pochemu:string}}
 */
export function reshitPoKlassu(klass, nastrojka = {}) {
  if (!klass || typeof klass !== 'string') {
    const e = new Error('dsh-pamyat: класс знания не задан — решать нечего');
    e.code = 'PAMYAT_NET_KLASSA';
    throw e;
  }
  // 🔴 ПУСТОЙ СПИСОК — ЭТО НЕ «НИКОГО НЕ СПРАШИВАТЬ» (правка после ворот 02.09).
  // Было: `?? KLASSY_SPRASHIVAT` — пустой массив проходил как заданное значение,
  // и ВСЕ классы, включая общефермовые, становились автоматическими. Молчаливое
  // ослабление защиты от опечатки в настройке: обещано «пусто = умолчание».
  // Чтобы отключить спрашивание намеренно, это придётся сделать явно и видно.
  const zadano = Array.isArray(nastrojka.sprashivat) ? nastrojka.sprashivat : null;
  const sprashivat = (zadano && zadano.length > 0) ? zadano : KLASSY_SPRASHIVAT;
  if (sprashivat.includes(klass)) {
    return { reshenie: 'ask', pochemu: 'класс «' + klass + '» действует за пределами этого агента' };
  }
  return { reshenie: 'auto', pochemu: 'класс «' + klass + '» — рабочая память самого агента' };
}

/**
 * Истолковать исход подтверждения, полученный от ядра.
 *
 * 🔴 ИСХОДЫ ЗДЕСЬ — БУКВАЛЬНЫЕ ЛИТЕРАЛЫ ЯДРА, вычитанные из его исходника
 * (dsh-tools 0.1.1-rc.2, lib/index.js:3303-3350), а не придуманные нами:
 *   allowed-once  — разрешено
 *   rejected      — «the user rejected» — РЕШЕНИЕ ЧЕЛОВЕКА
 *   cancelled     — «approval was cancelled» — прервано, НЕ отказ человека
 *   unavailable   — «no approval channel is available» — ПОЛОМКА установки
 * 🔴 РАЗДЕЛЕНИЕ, БЕЗ КОТОРОГО СЛЕДУЮЩИЙ ПАКЕТ БУДЕТ ЖДАТЬ НЕСУЩЕСТВУЮЩЕГО.
 * Выше — ЧЕТЫРЕ литерала, которые ядро действительно возвращает.
 * Ниже — ТРИ имени, которые ядро НЕ возвращает никогда: их подставляет
 * вызывающий, описывая ситуацию, до службы подтверждения не дошедшую.
 * Ядро эти случаи различает раньше, в тексте причины, а не отдельным значением.
 *   not-supported  — наше имя для «requires approval (not yet supported)»
 *   no-agent       — наше имя для «no agent to route it through»
 *   ne-predyavleno — наше имя: вызывающий вообще не спрашивал подтверждения
 *
 * 🔴 ПОЧЕМУ ЭТО ПЕРЕПИСАНО (правка после ворот аудита 02.09). В первой редакции
 * всё, кроме гранта, ложилось в «человек не разрешил». Тогда `unavailable` —
 * дословно отсутствие канала, то есть ПОЛОМКА — записывался как решение
 * человека. То есть ровно то, ради недопущения чего писался пакет, происходило
 * на стыке с ядром. Стенд этого не ловил, потому что проверял литерал
 * 'denied', которого у ядра НЕТ ВОВСЕ: проба зеленела на подставном значении.
 *
 * 🔴 НЕИЗВЕСТНЫЙ ИСХОД — ОТКАЗ С КОДОМ, А НЕ «ЧЕЛОВЕК». Если ядро однажды
 * добавит шестой исход, мы обязаны это заметить, а не молча записать его как
 * человеческое «нет». Молчаливое присвоение чужой природы — та же ошибка, что
 * и схлопывание, только отложенная.
 */
const PRIRODY = Object.freeze({
  'rejected':      { priroda: 'otkazano-chelovekom', pochemu: 'человек не разрешил запись. Знание НЕ СОХРАНЕНО.' },
  'cancelled':     { priroda: 'otmeneno',            pochemu: 'подтверждение прервано до ответа. Это НЕ отказ: спросите снова.' },
  'unavailable':   { priroda: 'net-kanala',          pochemu: 'канал подтверждения ОТСУТСТВУЕТ. Это поломка установки, а НЕ чьё-либо решение: подключите службу подтверждения либо переведите класс в автоматические. Знание НЕ СОХРАНЕНО.' },
  'not-supported': { priroda: 'net-sluzhby',         pochemu: 'служба подтверждения в этой сборке НЕ ПОДДЕРЖИВАЕТСЯ. Поломка установки, а не решение. Знание НЕ СОХРАНЕНО.' },
  'no-agent':      { priroda: 'net-agenta',          pochemu: 'вызов идёт вне агента, спросить некого и записать в журнал агента нечего. Поломка установки, а не решение.' },
  // 🔴 НАШЕ имя, не исход ядра. Заведено после ворот 02.09: раньше отсутствие
  // подтверждения подставлялось как 'unavailable', то есть «канала нет». Это
  // схлопывание в другую сторону — исправная установка, где вызывающий просто
  // не спросил, выглядела поломкой. Лечится там, где возникло.
  'ne-predyavleno': { priroda: 'ne-predyavleno',    pochemu: 'подтверждение НЕ ПРЕДЪЯВЛЕНО: класс требует спросить человека, а вызывающий не спрашивал. Это НЕ отказ и НЕ поломка — вызовите подтверждение и передайте его исход.' },
});

export function istolkovatPodtverzhdenie(ishod, kanalEst = true) {
  if (!kanalEst) {
    return { zapisyvat: false, ...PRIRODY['unavailable'] };
  }
  if (ishod === 'allowed-once') {
    return { zapisyvat: true, priroda: 'razresheno', pochemu: 'человек разрешил запись' };
  }
  const znakomyj = PRIRODY[ishod];
  if (znakomyj) return { zapisyvat: false, ...znakomyj };

  const e = new Error(
    'dsh-pamyat: неизвестный исход подтверждения «' + String(ishod) + '». ' +
    'Записывать нельзя, и приписывать его человеку тоже нельзя: природа неизвестна. ' +
    'Вероятно, ядро платформы добавило исход — обновите разбор.'
  );
  e.code = 'PAMYAT_NEIZVESTNYJ_ISHOD';
  throw e;
}
