/**
 * dsh-pamyat-nudzh — РАСХОДНЫЙ учёт: сколько контекста уже съедено и не пора ли
 * подтолкнуть к компакту.
 *
 * Что поднимать обратно в разговор — НЕ его дело: это соседний слой (бюджет).
 * Здесь эта работа намеренно не задваивается.
 *
 * 🔴 ГЛАВНОЕ ПРО ЧЕСТНОСТЬ ЭТОГО ПАКЕТА, ЧИТАТЬ ДО ИСПОЛЬЗОВАНИЯ.
 * Число расхода приходит от провайдера НЕ ВСЕГДА: в контракте компакции поле
 * помечено «Provider-reported token usage … WHEN EMITTED» и необязательно.
 * Значит наш итог по построению НЕПОЛОН. Поэтому пакет НИКОГДА не говорит
 * «израсходовано X» — он говорит «НЕ МЕНЬШЕ X, учтено N вызовов, M без числа».
 *
 * Отсюда несимметричное правило, которое и делает пакет годным:
 *   • «уже не меньше порога» — утверждение ЧЕСТНОЕ, его можно делать;
 *   • «ещё далеко, места хватает» — утверждение НЕЧЕСТНОЕ на неполных данных,
 *     и пакет его НЕ ДЕЛАЕТ.
 * 🔴 Следствие, которое легко упустить: МОЛЧАНИЕ НУДЖА НЕ ОЗНАЧАЕТ ЗАПАСА.
 * Строить на его молчании решение нельзя — оно значит лишь «порог по учтённой
 * части не перейдён», а неучтённая часть неизвестна.
 *
 * 🔴 ЗНАЕМОЕ ПРО ВЫВОД. Кричит только через `console.error`, развилки нет:
 * `ctx.logger` в cordis 4.0.1 есть, вызов проходит, но встроенный приёмник
 * кладёт строку в кольцевой буфер внутри процесса и наружу не отдаёт.
 * Способ перепроверить — стенд `stend-krik-zvuchit` (отдельный процесс, живой
 * Context, ожидание строки в его stderr).
 */
import z from '@deepseek-ai/schemastery';
import { zavestiSchet, raskhodVyzova } from './schet.js';

export const name = 'dsh-pamyat-nudzh';

export const Config = z.object({
  /** Предел контекста в токенах провайдера. 0 — предел неизвестен. */
  predel: z.number().default(0),
  /** Доля предела, после которой пора подталкивать. */
  dolyaTrevogi: z.number().default(0.8),
});

function krik(soobshchenie) {
  console.error('[dsh-pamyat-nudzh] ' + soobshchenie);
}

export function apply(ctx, config = {}) {
  const predel = config.predel ?? 0;
  const dolya = config.dolyaTrevogi ?? 0.8;
  const schet = zavestiSchet();
  let trevogaPodana = false;

  if (predel === 0) {
    krik('предел контекста НЕ ЗАДАН (predel: 0): расход считается, но подтолкнуть ' +
         'к компакту пакет не сможет — не с чем сравнивать. Это настройка, а не поломка.');
  }

  const sluzhba = {
    /** Учесть расход одного вызова. usage отсутствует — это незнание, не ноль. */
    uchest(usage) {
      schet.uchest(usage);
      const i = schet.itog();
      if (predel > 0 && !trevogaPodana && i.neMenshe >= predel * dolya) {
        trevogaPodana = true;
        krik('пора подтолкнуть к компакту: израсходовано НЕ МЕНЬШЕ ' + i.neMenshe +
             ' из ' + predel + ' (порог ' + Math.round(dolya * 100) + '%). ' +
             opisaniePolnoty(i) + ' Настоящий расход может быть только БОЛЬШЕ.');
      }
      return i;
    },

    /** Итог. Всегда нижняя оценка, всегда с указанием полноты. */
    itog() { return schet.itog(); },

    /** Расход одного вызова, без накопления. */
    raskhodVyzova,

    /**
     * Ответ на вопрос «можно ли ещё?» — намеренно НЕ булев.
     * Утверждать «места хватает» на неполных данных пакет не вправе, поэтому
     * возвращается либо «порог перейдён», либо «неизвестно» с причиной.
     */
    hvatitLi() {
      const i = schet.itog();
      if (predel === 0) {
        return { sostoyanie: 'neizvestno', pochemu: 'предел не задан',
                 uchtenoVyzovov: i.uchtenoVyzovov, bezChisla: i.bezChisla };
      }
      if (i.neMenshe >= predel * dolya) {
        return { sostoyanie: 'porog-pereyden', neMenshe: i.neMenshe, predel,
                 uchtenoVyzovov: i.uchtenoVyzovov, bezChisla: i.bezChisla };
      }
      // 🔴 Числа полноты отдаются ПОЛЯМИ, а не только строкой: «неизвестно»
      // должно быть с мерой, иначе вызывающий не может решить, насколько
      // сильно он не знает. Строка — человеку, поля — коду.
      return {
        sostoyanie: 'neizvestno',
        pochemu: i.polnyj
          ? 'по учтённой части порог не перейдён; все вызовы учтены, но провайдер мог не прислать число по части из них ранее'
          : 'по учтённой части порог не перейдён, НО ' + i.bezChisla + ' вызовов без числа — сколько они стоили, неизвестно',
        neMenshe: i.neMenshe,
        predel,
        uchtenoVyzovov: i.uchtenoVyzovov,
        bezChisla: i.bezChisla,
      };
    },
  };

  ctx.provide('nudzhPamyati', sluzhba);

  // 🔴 СЧИТАЕТ САМ, А НЕ ЖДЁТ, ПОКА ЕГО ПОЗОВУТ.
  // Служба без названного потребителя молчит всегда, и её молчание неотличимо
  // от исправной работы. Поэтому расход снимается прямо с потока событий.
  //
  // Событие выбрано по контракту платформы (dsh-session, types.d.ts): `usage`
  // несёт `assistant/message` — «carries the step's usage when the adapter
  // reported token accounting … usage is absent when the adapter reported none».
  // Отсюда же прямое подтверждение нашего правила: ОТСУТСТВИЕ ЧИСЛА — НЕ НОЛЬ,
  // это молчание адаптера, и оно считается отдельно.
  //
  // ⚠️ Считаем и сообщения С ПУСТЫМ содержимым: по контракту бывает
  // «empty-content assistant/message (which exists only to host usage)» —
  // пропустить их как «пустые» значило бы потерять ровно ту часть расхода,
  // ради которой событие и отправлено.
  ctx.on('session/event', (session, event) => {
    // Весь обработчик внутри защищённого блока: мы в ЧУЖОМ потоке событий,
    // и наше исключение оборвало бы обработку у других подписчиков.
    try {
      if (!event) return;
      // 🔴 ДВА события, а не одно. Второе легко забыть, и тогда компакт выходит
      // БЕСПЛАТНЫМ: сводку пишет та же модель, её расход приходит в
      // `compaction/summary.data.usage` (dsh-compaction). Пропустить его —
      // значит занижать расход ровно в тот момент, когда он подскочил.
      // 🔴 ПОЛЕЗНАЯ НАГРУЗКА ЛЕЖИТ В `data` — У ОБОИХ СОБЫТИЙ.
      // По контракту SessionEvent = { type, seq, time, data }; `usage` живёт
      // внутри data, а не рядом с type. 03.09 здесь стояло `event.usage` для
      // assistant/message при верном `event.data?.usage` в соседней строке:
      // две строки, написанные подряд, и только одна верна. В бою это значило
      // бы, что 412 из 412 вызовов уходят в «без числа», порог не переходится
      // никогда, а нудж молчит — и молчание у него ЗАКОННОЕ по устройству,
      // поэтому неотличимо от работы. Немота, добытая через данные, а не через
      // вывод.
      if (event.type !== 'assistant/message' && event.type !== 'compaction/summary') return;
      const usage = event.data?.usage;
      // ⚠️ ПРЕРВАННЫЙ вызов (`interrupted: true`) считается наравне: модель
      // успела поработать, расход состоялся, и он оплачен. Не считать его
      // значило бы прятать самые дорогие обрывы.
      sluzhba.uchest(usage);
    } catch (e) {
      krik('не смог учесть расход по событию: ' + (e?.message ?? e) +
           '. Учёт НЕПОЛОН сверх обычного — этот вызов не посчитан вовсе.');
    }
  });
}

function opisaniePolnoty(i) {
  return i.polnyj
    ? 'Учтены все ' + i.uchtenoVyzovov + ' вызовов.'
    : 'Учтено ' + i.uchtenoVyzovov + ' вызовов, ещё ' + i.bezChisla + ' БЕЗ ЧИСЛА от провайдера.';
}
