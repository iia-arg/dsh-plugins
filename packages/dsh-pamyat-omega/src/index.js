/**
 * dsh-pamyat-omega — долговременный слой памяти агента поверх внешнего
 * хранилища знаний, доступного по MCP.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ПАКЕТОМ. Оперативный слой (пакет ядра) переживает сессию, но
 * живёт на одной машине и не связывает знания между агентами. Долговременное
 * хранилище это решает — и при этом НЕОБЯЗАТЕЛЬНО: у части установок его нет
 * вовсе, и память обязана работать без него. Отдельный пакет и есть форма этой
 * необязательности: не поставил — нет ни кода, ни настроек, ни обещаний.
 *
 * 🔴 ПОЧЕМУ НАСТРОЙКИ ЗДЕСЬ, А НЕ В ЯДРЕ (урок 02.09, оплаченный воротами).
 * Сначала ключи этого слоя стояли в схеме ЯДРА — «чтобы потом не переделывать».
 * Ядро их описывало, но не исполняло: включение проходило молча, память
 * объявляла себя доступной, слоя не было. Конфиг, объявленный раньше кода, —
 * тихий ноль: «настройка не доехала» становится неотличима от «выключено».
 * ПРАВИЛО: ключ живёт в том пакете, который его ИСПОЛНЯЕТ. Конфиг — описание
 * возможностей, а не планов.
 *
 * ЧТО ЗДЕСЬ ЕСТЬ: связь с хранилищем и подтверждение доставки. Политики записи,
 * дистилляции и инъекции контекста здесь нет — это другие пакеты семейства.
 */
import z from '@deepseek-ai/schemastery';
import { sozdatSvyaz } from './svyaz.js';
import { istolkovatOtvet } from './podtverzhdenie.js';

export const name = 'dsh-pamyat-omega';

export const Config = z.object({
  /**
   * Адрес точки хранилища.
   * 🔴 Завершающий слэш обязателен: без него служба отвечает перенаправлением с
   * пустым телом, и это выглядит как её молчание. Проверено живым запросом.
   */
  adres: z.string(),
  /** Предел ожидания ответа, мс. */
  tajmautMs: z.number().default(10000),
});

/**
 * 🔴 КЛЮЧА «сверять ли содержимое» ЗДЕСЬ НЕТ — И ЭТО ПРАВКА ПО ЖИВОЙ ПРОБЕ.
 * Он был, с умолчанием «сверять». Проба показала, что при `false` подтверждение
 * отвечает «доставлено» на ЧУЖУЮ запись — и объясняет это словами «содержимое
 * сходится», хотя сверки не было вовсе. То есть ключ не «ослаблял строгость»,
 * а включал уверенную ложь.
 * Сверка содержимого закрывает ДВА разных события сразу:
 *   — слияние похожих записей (хранилище вернуло опознаватель чужой записи);
 *   — столкновение префиксов (в ответе опознаватель укорочен до восьми знаков,
 *     а восемь шестнадцатеричных знаков — конечное множество: при росте базы
 *     префиксы неизбежно совпадут).
 * Второе я бы не заметил без вопроса со стороны: защита выглядела одной, а
 * событий за ней два — наш класс «защита, закрывающая часть класса, гасит
 * вопрос обо всём классе».
 * Поэтому сверка обязательна и настройкой не является.
 */

/**
 * 🔴 ЧТО НАМЕРЕННО НЕ НАСТРАИВАЕТСЯ:
 * 1. Имена инструментов хранилища — чужой протокол, читается в его описании.
 * 2. Признак «записи нет» в ответе — тоже чужой протокол.
 * 3. Правило «не знаю ≠ не доставлено». Настраиваемое схлопывание исходов
 *    означает, что кто-то однажды его включит и получит уверенную ложь.
 * 4. Сверка содержимого при подтверждении — см. выше: без неё «доставлено»
 *    становится правдой про чужую запись.
 */
export function apply(ctx, config = {}) {
  let svyaz = null;
  let prichinaOtkaza = null;
  try {
    svyaz = sozdatSvyaz({ adres: config.adres, tajmautMs: config.tajmautMs });
  } catch (e) {
    prichinaOtkaza = e;
    // 🔴 ОДИН путь вывода. Здесь была развилка «если ctx.logger.error есть → в
    // него», и обоснование к ней было ЛОЖНЫМ: я писал «дефект спит, потому что
    // платформа логгер не даёт». Логгер cordis 4.0.1 ДАЁТ — но его встроенный
    // экспортер копит сообщения в буфер, а DSH экспортера не ставит. Значит
    // дефект не спал: ветка logger выбиралась всегда, и отказ провайдера
    // («долговременная память недоступна») в бою был НЕМЫМ.
    // Правка от двойной печати была верна, а причина к ней — выдумана; ложная
    // причина и укрыла настоящий дефект. Замер сделан на воротах 03.09.
    console.error('[dsh-pamyat-omega] ' + e.message);
  }

  ctx.provide('pamyatDolgovremennaya', {
    dostupna() { return prichinaOtkaza === null; },
    pochemuNedostupna() { return prichinaOtkaza ? prichinaOtkaza.message : null; },

    /**
     * Сохранить знание и вернуть исход ДОСТАВКИ, а не отправки.
     * Возвращает { sostoyanie, id, pochemu }, где sostoyanie —
     * dostavleno | ne-najdeno | ne-udalos-proverit.
     */
    async sohranit({ soderzhim, tip = 'memory', metadannye = {}, kto = null }) {
      if (prichinaOtkaza) {
        return { sostoyanie: 'ne-udalos-proverit', id: null, pochemu: prichinaOtkaza.message };
      }
      if (!soderzhim) {
        const e = new Error('dsh-pamyat-omega: нечего сохранять — пустое содержимое');
        e.code = 'OMEGA_PUSTOE_ZNANIE';
        throw e;
      }
      const zapis = await svyaz.pozvat('omega_store', {
        content: soderzhim, event_type: tip, metadata: metadannye,
        ...(kto ? { entity_id: kto } : {}),
      });
      if (!zapis.udalos) {
        return { sostoyanie: 'ne-udalos-proverit', id: null, pochemu: zapis.pochemu };
      }
      const najden = String(zapis.tekst).match(/mem-[0-9a-f]+/);
      if (!najden) {
        return {
          sostoyanie: 'ne-udalos-proverit', id: null,
          pochemu: 'хранилище ответило без опознавателя записи — проверить доставку нечем. Ответ: ' +
                   String(zapis.tekst).slice(0, 150),
        };
      }
      const id = najden[0];
      // 🔴 Доставку подтверждаем ОТДЕЛЬНЫМ чтением по опознавателю, а не тем,
      // что запись «отправилась»: ответ инструмента и состояние хранилища —
      // разные утверждения.
      const chtenie = await svyaz.pozvat('omega_call', {
        tool: 'omega_memory', args: { action: 'similar', memory_id: id },
      });
      if (!chtenie.udalos) {
        return { sostoyanie: 'ne-udalos-proverit', id, pochemu: chtenie.pochemu };
      }
      const itog = istolkovatOtvet(chtenie.tekst, id, soderzhim);
      return { sostoyanie: itog.sostoyanie, id, pochemu: itog.pochemu };
    },
  });
}
