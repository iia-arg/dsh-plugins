/**
 * dsh-pamyat-omega — долговременный слой памяти агента поверх внешнего
 * хранилища знаний, доступного по MCP.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ПАКЕТОМ. Оперативный слой (пакет ядра) переживает сессию, но
 * живёт на одной машине и не связывает знания между агентами. Долговременное
 * хранилище это решает — и при этом НЕОБЯЗАТЕЛЬНО: у части установок его нет
 * вовсе, и память обязана работать без него. Отдельный пакет и есть форма этой
 * необязательности: не поставил — нет ни кода, ни настроек, ни обещаний.
 *
 * 🔴 ПОЧЕМУ НАСТРОЙКИ ЗДЕСЬ, А НЕ В ЯДРЕ (урок 02.09, оплаченный воротами).
 * Сначала ключи этого слоя стояли в схеме ЯДРА — «чтобы потом не переделывать».
 * Ядро их описывало, но не исполняло: включение проходило молча, память
 * объявляла себя доступной, слоя не было. Конфиг, объявленный раньше кода, —
 * тихий ноль: «настройка не доехала» становится неотличима от «выключено».
 * ПРАВИЛО: ключ живёт в том пакете, который его ИСПОЛНЯЕТ. Конфиг — описание
 * возможностей, а не планов.
 *
 * ЧТО ЗДЕСЬ ЕСТЬ: связь с хранилищем и подтверждение доставки. Политики записи,
 * дистилляции и инъекции контекста здесь нет — это другие пакеты семейства.
 */
import { createRequire } from 'node:module';
import z from '@deepseek-ai/schemastery';
import { sozdatSvyaz } from './svyaz.js';
import { istolkovatOtvet } from './podtverzhdenie.js';

export const name = 'dsh-pamyat-omega';

// 🔴 Версия читается ИЗ СВОЕГО package.json, а не пишется константой: константа при
// следующем выпуске утверждала бы номер, которому предмет уже не соответствует —
// прибор, врущий уверенно. Правило фермы 03.09.2026: каждая строка модуля несёт
// имя И версию, иначе редакцию, которую держит процесс, приходится угадывать.
function versiyaPaketa() {
  try { return createRequire(import.meta.url)('../package.json').version ?? 'версия неизвестна' }
  catch { return 'версия неизвестна' }
}

export const Config = z.object({
  /**
   * Адрес точки хранилища.
   * 🔴 Завершающий слэш обязателен: без него служба отвечает перенаправлением с
   * пустым телом, и это выглядит как её молчание. Проверено живым запросом.
   */
  adres: z.string(),
  /** Предел ожидания ответа, мс. */
  tajmautMs: z.number().default(10000),
});

/**
 * 🔴 КЛЮЧА «сверять ли содержимое» ЗДЕСЬ НЕТ — И ЭТО ПРАВКА ПО ЖИВОЙ ПРОБЕ.
 * Он был, с умолчанием «сверять». Проба показала, что при `false` подтверждение
 * отвечает «доставлено» на ЧУЖУЮ запись — и объясняет это словами «содержимое
 * сходится», хотя сверки не было вовсе. То есть ключ не «ослаблял строгость»,
 * а включал уверенную ложь.
 * Сверка содержимого закрывает ДВА разных события сразу:
 *   — слияние похожих записей (хранилище вернуло опознаватель чужой записи);
 *   — столкновение префиксов (в ответе опознаватель укорочен до восьми знаков,
 *     а восемь шестнадцатеричных знаков — конечное множество: при росте базы
 *     префиксы неизбежно совпадут).
 * Второе я бы не заметил без вопроса со стороны: защита выглядела одной, а
 * событий за ней два — наш класс «защита, закрывающая часть класса, гасит
 * вопрос обо всём классе».
 * Поэтому сверка обязательна и настройкой не является.
 */

/**
 * 🔴 ЧТО НАМЕРЕННО НЕ НАСТРАИВАЕТСЯ:
 * 1. Имена инструментов хранилища — чужой протокол, читается в его описании.
 * 2. Признак «записи нет» в ответе — тоже чужой протокол.
 * 3. Правило «не знаю ≠ не доставлено». Настраиваемое схлопывание исходов
 *    означает, что кто-то однажды его включит и получит уверенную ложь.
 * 4. Сверка содержимого при подтверждении — см. выше: без неё «доставлено»
 *    становится правдой про чужую запись.
 */
export function apply(ctx, config = {}) {
  let svyaz = null;
  let prichinaOtkaza = null;
  try {
    svyaz = sozdatSvyaz({ adres: config.adres, tajmautMs: config.tajmautMs });
  } catch (e) {
    prichinaOtkaza = e;
    // 🔴 ОДИН путь вывода. Здесь была развилка «если ctx.logger.error есть → в
    // него», и обоснование к ней было ЛОЖНЫМ: я писал «дефект спит, потому что
    // платформа логгер не даёт». Логгер cordis 4.0.1 ДАЁТ — но его встроенный
    // экспортер копит сообщения в буфер, а DSH экспортера не ставит. Значит
    // дефект не спал: ветка logger выбиралась всегда, и отказ провайдера
    // («долговременная память недоступна») в бою был НЕМЫМ.
    // Правка от двойной печати была верна, а причина к ней — выдумана; ложная
    // причина и укрыла настоящий дефект. Замер сделан на воротах 03.09.
    console.error('[' + name + ' ' + versiyaPaketa() + '] ' + e.message);
  }

  // 🔴 БЕЗУСЛОВНЫЙ СЛЕД ПОДЪЁМА. Прежде пакет говорил ТОЛЬКО при беде — то есть при
  // исправной работе был неотличим от несмонтированного, и «громкость, привязанная к
  // беде, исчезала вместе с бедой». Строка называет и адрес: без него «слой доступен»
  // не отвечает на вопрос, к какому хранилищу.
  console.error('[' + name + ' ' + versiyaPaketa() + '] подъём: адрес ' +
    (config.adres ?? 'НЕ ЗАДАН') + ', предел ожидания ' + (config.tajmautMs ?? 10000) + ' мс' +
    (prichinaOtkaza ? ' — связь НЕ создана, см. строку выше' : ''));

  ctx.provide('pamyatDolgovremennaya', {
    dostupna() { return prichinaOtkaza === null; },
    pochemuNedostupna() { return prichinaOtkaza ? prichinaOtkaza.message : null; },

    /**
     * Сохранить знание и вернуть исход ДОСТАВКИ, а не отправки.
     * Возвращает { sostoyanie, id, pochemu }, где sostoyanie одно из пяти:
     *
     *   dostavleno          запись найдена по опознавателю, содержимое сходится
     *   ne-najdeno          спросили — хранилище отвечает, что записи нет
     *   ne-otpravleno       связи не было ДО вызова: отправки не случилось
     *   moglo-dojti-bez-id  вызов начался, опознавателя нет — проверить нечем
     *   moglo-dojti-id-est  опознаватель есть, подтвердить чтением не вышло
     *
     * 🔴 ПОЧЕМУ ПЯТЬ, А НЕ ТРИ (правка 04.09.2026). Прежде четыре разных случая
     * возвращали `ne-udalos-proverit`, и потребитель не мог решить главного:
     * МОЖНО ЛИ ПОВТОРЯТЬ ЗАПИСЬЮ. Повтор при «связи не было» безопасен, повтор
     * при «вызов начался» создаёт второй экземпляр знания — и этот дубль
     * невидим: он выглядит как знание и растворяется в поиске. Состояние теперь
     * называет не только незнание, но и способ его разрешить.
     */
    async sohranit({ soderzhim, tip = 'memory', metadannye = {}, kto = null }) {
      // 🔴 `ne-otpravleno` ставится ТОЛЬКО здесь — когда связи не было ДО вызова.
      // Стоит вызову начаться, состояние становится `moglo-dojti-*`, даже при
      // мгновенной ошибке: мы уже не знаем, что успело дойти до хранилища.
      // Разница не косметическая: `ne-otpravleno` РАЗРЕШАЕТ повтор записью,
      // `moglo-dojti-*` его запрещает. Спутать — значит завести невидимый дубль
      // знания, а дубль хуже недоставки: недоставку видно по очереди, дубль
      // выглядит как знание.
      if (prichinaOtkaza) {
        return { sostoyanie: 'ne-otpravleno', id: null, pochemu: prichinaOtkaza.message };
      }
      if (!soderzhim) {
        const e = new Error('dsh-pamyat-omega: нечего сохранять — пустое содержимое');
        e.code = 'OMEGA_PUSTOE_ZNANIE';
        throw e;
      }
      const zapis = await svyaz.pozvat('omega_store', {
        content: soderzhim, event_type: tip, metadata: metadannye,
        ...(kto ? { entity_id: kto } : {}),
      });
      if (!zapis.udalos) {
        // Вызов НАЧАЛСЯ и оборвался: запись могла лечь до обрыва. Опознавателя нет,
        // значит проверить нечем и повторять записью НЕЛЬЗЯ.
        return {
          sostoyanie: 'moglo-dojti-bez-id', id: null,
          pochemu: 'вызов начался и оборвался: ' + zapis.pochemu +
                   '. Запись могла лечь до обрыва, опознавателя нет — повтор записью создал бы дубль.',
        };
      }
      const najden = String(zapis.tekst).match(/mem-[0-9a-f]+/);
      if (!najden) {
        return {
          sostoyanie: 'moglo-dojti-bez-id', id: null,
          pochemu: 'хранилище ответило без опознавателя записи — проверить доставку нечем. Ответ: ' +
                   String(zapis.tekst).slice(0, 150),
        };
      }
      const id = najden[0];
      // 🔴 Доставку подтверждаем ОТДЕЛЬНЫМ чтением по опознавателю, а не тем,
      // что запись «отправилась»: ответ инструмента и состояние хранилища —
      // разные утверждения.
      const chtenie = await svyaz.pozvat('omega_call', {
        tool: 'omega_memory', args: { action: 'similar', memory_id: id },
      });
      if (!chtenie.udalos) {
        // Опознаватель ЕСТЬ — значит вопрос «легло ли» разрешим чтением, а не
        // второй записью. Это и есть дешёвый выход: повторяем ПРОВЕРКОЙ.
        return {
          sostoyanie: 'moglo-dojti-id-est', id,
          pochemu: 'запись отправлена и опознаватель получен, но подтвердить чтением не вышло: ' +
                   chtenie.pochemu + '. Повторять записью нельзя — сперва спросить по опознавателю.',
        };
      }
      const itog = istolkovatOtvet(chtenie.tekst, id, soderzhim);
      // 🔴 Толкование даёт три исхода, и «не знаю» здесь означает не то же, что до
      // отправки: опознаватель уже на руках. Переводим его в состояние, которое
      // говорит, ЧТО ДЕЛАТЬ, а не только чего мы не знаем.
      if (itog.sostoyanie === 'ne-udalos-proverit') {
        return { sostoyanie: 'moglo-dojti-id-est', id, pochemu: itog.pochemu };
      }
      return { sostoyanie: itog.sostoyanie, id, pochemu: itog.pochemu };
    },

    /**
     * Спросить хранилище, легла ли запись — БЕЗ повторной записи.
     * Возвращает { sostoyanie, pochemu }: est | net | ne-proveryali.
     *
     * 🔴 ТРЕТИЙ ИСХОД ОБЯЗАТЕЛЕН. «Не смогли спросить» и «записи нет» — разные
     * ответы с противоположным лечением: первый оставляет запись в очереди,
     * второй разрешает повтор записью. Схлопни их в `net` — и недоступность
     * хранилища начнёт молча плодить дубли.
     *
     * 🔴 ОБРАЗЕЦ СОДЕРЖИМОГО ОБЯЗАТЕЛЕН, И ЭТО НЕ ФОРМАЛЬНОСТЬ. Опознаватель в
     * ответе усечён до восьми знаков, а восемь шестнадцатеричных знаков —
     * конечное множество: при росте базы префиксы совпадут. Плюс хранилище
     * умеет слить нашу запись с похожей и вернуть опознаватель ЧУЖОЙ. Без
     * образца толкование ответа честно отвечает «не знаю» — то есть проверка,
     * вызванная без него, НЕ МОЖЕТ сказать «est» никогда, сколько её ни зови.
     * Поэтому отсутствие образца — отдельный отказ, а не тихое «ne-proveryali».
     */
    async proverit({ id, obrazec = null } = {}) {
      if (!id) {
        return { sostoyanie: 'ne-proveryali', pochemu: 'проверка вызвана без опознавателя записи' };
      }
      if (!obrazec) {
        return {
          sostoyanie: 'ne-proveryali',
          pochemu: 'проверка вызвана без образца содержимого: сверить, наша ли это запись, нечем. ' +
                   'Опознаватель в ответе усечён, одного совпадения по нему мало.',
        };
      }
      if (prichinaOtkaza) {
        return { sostoyanie: 'ne-proveryali', pochemu: prichinaOtkaza.message };
      }
      const chtenie = await svyaz.pozvat('omega_call', {
        tool: 'omega_memory', args: { action: 'similar', memory_id: id },
      });
      if (!chtenie.udalos) {
        return { sostoyanie: 'ne-proveryali', pochemu: chtenie.pochemu };
      }
      const itog = istolkovatOtvet(chtenie.tekst, id, obrazec);
      if (itog.sostoyanie === 'dostavleno') return { sostoyanie: 'est', pochemu: itog.pochemu };
      if (itog.sostoyanie === 'ne-najdeno') return { sostoyanie: 'net', pochemu: itog.pochemu };
      return { sostoyanie: 'ne-proveryali', pochemu: itog.pochemu };
    },
  });
}
