/**
 * Подтверждение доставки знания в долговременное хранилище.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Требование владельца дословно: «главное — чтобы
 * знания не застревали, точно переходили и там хранились». Значит отправка не
 * равна доставке, и подтверждение — самостоятельный предмет со своими исходами.
 *
 * 🔴 ТРИ ИСХОДА, А НЕ ДВА. Первая редакция возвращала true/false и ловила все
 * ошибки в false: это схлопывало «связь упала» и «записи нет» — беды с разным
 * лечением, — и лгало, потому что при обрыве мы не знаем ничего.
 *   dostavleno         — запись найдена по опознавателю и содержимое сходится
 *   ne-najdeno         — хранилище ответило, что такой записи нет
 *   ne-udalos-proverit — мы НЕ ЗНАЕМ: связь, разбор, отказ или ответ не о том
 *
 * 🔴 ЧЕМ ПОДТВЕРЖДАЕМ. Читаем ПО ОПОЗНАВАТЕЛЮ. Первая редакция искала его
 * семантическим поиском по тексту — а в тексте его нет вовсе, так что успешная
 * запись давала «не подтвердилось».
 *
 * ФАКТЫ О ЖИВОМ ХРАНИЛИЩЕ (сняты с работающей службы 02.09.2026,
 * omega-memory 1.5.13; проверены дважды, двумя разными людьми):
 *   1. Отсутствие записи: строка ровно вида  Memory `mem-XXXXXXXX` not found.
 *   2. В ответе опознаватель УСЕЧЁН до восьми знаков: `mem-dfc9d075` при полном
 *      mem-dfc9d0754cc9. Сверка полного вхождения дала бы ложное «не доставлено».
 *   3. По усечённому опознавателю хранилище НЕ находит запись — нужен полный.
 *      Отсюда важное: столкновение префиксов НЕ может подменить запись, оно
 *      бьёт только по текстовой сверке.
 *   4. Ответ ОБРЕЗАЕТСЯ ПО ДЛИНЕ (около сотни знаков), ПЕРЕНОСЫ СОХРАНЯЯ.
 *      🔴 Ранее здесь стояло обоснование «хранилище схлопывает переносы» — оно
 *      ЛОЖНО и опровергнуто сырым ответом. Правка от него не меняется, но
 *      ложное обоснование живёт дольше правки: следующий построит на нём ещё что-то.
 */

/** Точный шаблон отсутствия. Не «где-то есть слова not found»: они бывают и
 *  внутри нашего же знания — в технических записях это обычное дело. */
const SHABLON_NET = /^Memory\s+`mem-[0-9a-f]+`\s+not found\.?\s*$/im;

/**
 * Запись, ради которой всё: именно она описывает НАШУ запись. Остальной ответ —
 * список похожих, у каждой свой опознаватель и свой текст.
 *
 * 🔴 ГРАНИЦА ЗАХВАТА ОБЯЗАТЕЛЬНА (правка после ворот 02.09). Было `([\s\S]*)$`
 * с флагом m — жадная группа забирала ВЕСЬ хвост ответа, включая список похожих.
 * Тогда наш текст, лежащий в похожей записи, попадал в «содержимое Source» и
 * давал ложное «доставлено» про ЧУЖУЮ запись.
 * 🔴 Моя проба этого не ловила и была зелёной ПО ДРУГОЙ ПРИЧИНЕ: в ней Source
 * стоял с чужим опознавателем, и разбор падал на ветке опознавателя, не дойдя
 * до содержимого. Зелёная проба, проверявшая не то, что заявлено.
 * Содержимое Source МНОГОСТРОЧНО (в живом ответе есть перенос и пустая строка),
 * поэтому границей служит начало следующей записи списка, а не конец строки.
 *
 * 🔴 ВНЕШНИЙ КОНТРАКТ, КОТОРЫЙ СТЕНД НЕ ПОЙМАЕТ. Граница опирается на РАЗМЕТКУ
 * чужой службы: сегодня она печатает список как «## N.» и заголовки как «# »,
 * и только эти формы здесь и разбираются. Похожая запись, поданная маркером
 * «- \`mem-…\`», границу пройдёт — на живой службе такой формы нет, потому
 * случай и не воспроизводится (проверено ответом работающего хранилища 03.09).
 * Но разметку меняем не мы: сменится она — SHABLON_SOURCE надо ПЕРЕМЕРИТЬ
 * живым ответом, а не поправить по догадке. Стенд промолчит: его эталоны
 * останутся в старой разметке и будут зелёными.
 */
const SHABLON_SOURCE =
  /\*\*Source:\*\*\s*`(mem-[0-9a-f]+)`\s*[—-]?\s*([\s\S]*?)(?=\n\s*\d+\.\s*`mem-|\n#{1,6}\s|$)/;

/** Пробелы и переносы к одному виду — ответ обрезан по длине, перенос мог
 *  попасть в середину нашего образца. */
function rovno(t) {
  return String(t).replace(/\s+/g, ' ').trim();
}

/**
 * @param {string} otvet      сырой текст ответа хранилища
 * @param {string} id         полный опознаватель, выданный при записи
 * @param {string} fragment   начало нашего содержимого; ОБЯЗАТЕЛЕН
 */
export function istolkovatOtvet(otvet, id, fragment = null) {
  if (typeof otvet !== 'string' || otvet.trim() === '') {
    return {
      sostoyanie: 'ne-udalos-proverit',
      pochemu: 'хранилище вернуло пустой ответ. Доставлено знание или нет — НЕИЗВЕСТНО.',
    };
  }
  if (SHABLON_NET.test(otvet)) {
    return {
      sostoyanie: 'ne-najdeno',
      pochemu: 'хранилище отвечает, что записи ' + id + ' у него нет. Знание НЕ доставлено.',
    };
  }
  if (!fragment) {
    return {
      sostoyanie: 'ne-udalos-proverit',
      pochemu:
        'подтверждение вызвано без образца содержимого — сверить, наша ли это запись, нечем. ' +
        'Опознаватель в ответе усечён, поэтому одного совпадения по нему мало.',
    };
  }
  // 🔴 Разбираем ТОЛЬКО строку Source. Раньше искали по всему ответу — а в нём
  // ещё пять похожих записей со своими опознавателями и текстами, и совпадение
  // могло прийти из чужой. Защита выглядела одной, событий за ней два.
  const najden = otvet.match(SHABLON_SOURCE);
  if (!najden) {
    return {
      sostoyanie: 'ne-udalos-proverit',
      pochemu:
        'в ответе нет строки Source — описания той самой записи. Ответ не о том, ' +
        'о чём спрашивали; считать это подтверждением нельзя.',
    };
  }
  const [, opoznavatelSource, tekstSource] = najden;
  if (!id.startsWith(opoznavatelSource)) {
    return {
      sostoyanie: 'ne-udalos-proverit',
      pochemu:
        'в строке Source стоит опознаватель ' + opoznavatelSource + ', а спрашивали про ' + id +
        '. Ответ описывает не нашу запись.',
    };
  }
  const obrazec = rovno(fragment).slice(0, 40);
  if (!rovno(tekstSource).includes(obrazec)) {
    return {
      sostoyanie: 'ne-najdeno',
      pochemu:
        'запись с таким опознавателем есть, но её содержимое не совпадает с нашим. ' +
        'Вероятно, хранилище слило нашу запись с похожей и вернуло опознаватель ЧУЖОЙ. ' +
        'Считать доставленным нельзя: под этим опознавателем лежит не наше знание.',
    };
  }
  return { sostoyanie: 'dostavleno', pochemu: 'запись найдена по опознавателю, содержимое сходится' };
}
