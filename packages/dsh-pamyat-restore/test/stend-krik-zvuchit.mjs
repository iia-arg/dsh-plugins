// Стенд «крик звучит»: доходит ли громкая строка модуля до НАСТОЯЩЕГО stderr.
//
// Коды: 0 сошлось | 1 расхождение | 2 слепота (проверить не удалось).
//
// 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ СТЕНД, КОГДА ЕСТЬ test-restore. Ответ ИЗМЕРЕН тремя порчами
// 03.09.2026, а не выведен из общих соображений — первая формулировка («новый
// стенд ловит немоту, старый нет») замером НЕ ПОДТВЕРДИЛАСЬ:
//
//   порча                                test-restore      этот стенд
//   крик в немой приёмник                красный, 4        красный, 2
//   вывод отложен на следующий такт      красный, 4        ЗЕЛЁНЫЙ
//   поток заглушен ВНУТРИ процесса       ЗЕЛЁНЫЙ           красный, 2
//
// Читается так. Первая строка: немоту ловят ОБА — test-restore перехватывает
// настоящий process.stderr.write и спрашивает «ушло ли в поток», а не «вызвана ли
// функция вывода»; для такого вопроса немой путь уже красный.
// Вторая: старый стенд краснеет на ИСПРАВНОМ поведении — отложенный вывод доходит,
// он просто читает буфер синхронно. Это его ложная тревога, а не находка.
// Третья и единственная, ради которой стенд существует: проба, живущая в одном
// процессе с предметом, ставит свой перехват ПОВЕРХ чужой глушилки и не видит,
// что реальный поток мёртв. Отдельный процесс это видит.
//
// Отсюда честная польза, без красивости: стенд ловит случай, когда вывод перехвачен
// чем-то ВНУТРИ процесса — соседним плагином, транспортом службы, своей же отладкой.
// Здесь подделок нет ни одной:
//   отдельный процесс -> настоящий cordis Context -> реальный дескриптор 2.
//
// 🔴 ЭТО НЕ ПАРАНОЙЯ, А КУПЛЕННЫЙ УРОК (03.09.2026, разбор немого отказа у соседей):
// стенд на самодельном логгере ТРЕБОВАЛ немого пути — «через логгер 1, в консоль 0».
// Почини кто-нибудь код вслепую, стенд бы покраснел и сказал «ты сломал». Проверка
// может закреплять дефект как норму и при этом выглядеть защитой.
//
// ГДЕ НЕ ПРИМЕНЯЕТСЯ: не проверяет ни одну ветку поведения модуля — только то, что
// его голос слышен. Что именно он говорит и когда — дело test-restore.mjs.
import { spawn } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// Корень ПАКЕТА, а не каталога стенда: стенд лежит в test/, предмет в src/,
// а дочерний процесс запускается с cwd в корне — там разрешается cordis.
import { createHash as __hash } from 'node:crypto'
import { readFileSync as __chitat } from 'node:fs'
import { fileURLToPath as __put } from 'node:url'
// 🔴 ПРИБОР НАЗЫВАЕТ СЕБЯ (03.09.2026, условие ворот). Стенд правится на месте, и
// два прогона «тем же стендом» бывают двумя разными приборами — на этом за ночь
// дважды разошлись числа у соседей. Своя сумма в каждом прогоне делает вопрос
// «чем мерили» проверяемым, а не памятным.
console.log(`стенд: ${__put(import.meta.url).split('/').pop()} сумма ${
  __hash('sha256').update(__chitat(__put(import.meta.url))).digest('hex').slice(0, 16)}`)
const KORNI = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const PREDMET = process.env.PREDMET || path.join(KORNI, 'src/index.js')

let ok = 0, bad = 0
const t = (n, c, s) => { if (c) { ok++; console.log(`ok   ${n}`) } else { bad++; console.log(`FAIL ${n}\n     ${s ?? ''}`) } }

// 🔴 КОД ДОЧЕРНЕГО ПРОЦЕССА ИДЁТ ЧЕРЕЗ --input-type=module -e, БЕЗ ФАЙЛА.
// Первая редакция писала временный файл рядом с предметом (cordis разрешается от
// реального пути, и во временном каталоге его не найти). Это сломалось на живом
// узле: каталог смонтированного плагина принадлежит root, и стенд честно ослеп с
// EACCES. У поставившего пакет каталог тоже может быть только для чтения — стенд,
// требующий права записи в предмет, у него не запустится вовсе.
// Резолв при -e идёт от cwd, поэтому дочерний процесс запускается с cwd в каталоге
// пакета; файлов не создаётся ни одного.
const kod = (davatSluzhbu) => `
import { Context } from '@deepseek-ai/cordis'
const mod = await import(${JSON.stringify(PREDMET)})
const root = new Context()
${davatSluzhbu ? `await root.plugin({ name: 'agents-stub', inject: [], apply(ctx) { ctx.provide('agents', { create(){}, resume(){} }) } })
await new Promise((r) => setTimeout(r, 100))` : '// службу НЕ даём: модуль обязан остаться в ожидании'}
const fork = await root.plugin(mod, { restoreEnabled: true, welcomeEnabled: true })
await new Promise((r) => setTimeout(r, 250))
console.log('SOSTOYANIE=' + fork?.state)
`

const pusk = (davatSluzhbu) => new Promise((resolve) => {
  const p = spawn(process.execPath, ['--input-type=module', '-e', kod(davatSluzhbu)], { cwd: KORNI })
  let out = '', err = ''
  p.stdout.on('data', (d) => { out += d })
  p.stderr.on('data', (d) => { err += d })
  p.on('close', (code) => resolve({ out, err, code }))
  setTimeout(() => p.kill('SIGKILL'), 15000)
})

let r
try { r = await pusk(true) } catch (e) {
  console.log(`СЛЕПОТА: дочерний процесс не запустился: ${e?.message ?? e}`); process.exit(2)
}
if (!/SOSTOYANIE=/.test(r.out)) {
  // 🔴 ПРИЧИНА СЛОВАМИ, А НЕ СЫРЫМ ВЫВОДОМ (03.09.2026). Код здесь был верный —
  // 2, «проверять нечем», — но причина шла машинной: получатель читал
  // «ERR_MODULE_NOT_FOUND» и всё равно не знал, что ему делать. Это ПОЛОВИНА
  // лечения: рядом, в stend-restore.mjs, я час назад сделала полный отказ словами
  // и не перенесла на соседний файл того же каталога.
  // Класс мой же и я требовала его от других: место, которое только что сделал,
  // не ощущается как «место, где может быть та же болезнь» — оно ощущается готовым.
  const netModulya = /ERR_MODULE_NOT_FOUND|Cannot find package/.test(r.err)
  const imya = (r.err.match(/Cannot find package '([^']+)'/) ?? [])[1]
  console.log(`СЛЕПОТА: предмет не поднялся в отдельном процессе (код ${r.code}) — ${
    netModulya ? 'не установлены зависимости пакета' : 'причина ниже'}.`)
  if (netModulya) {
    console.log(`  Не найдено: ${imya ?? '(имя не разобралось)'}`)
    console.log('  Выполните `npm install` в каталоге пакета и повторите.')
    console.log('  Стенд гонялся на cordis 4.0.1 и schemastery 3.18.1.')
  } else {
    console.log(`  stderr: ${r.err.slice(0, 400)}`)
  }
  process.exit(2)
}

console.log('=== 1. Модуль поднимается в настоящем контексте ===')
const sostoyanie = (r.out.match(/SOSTOYANIE=(\d+)/) ?? [])[1]
t('плагин активен, а не ждёт службу (состояние 2)', sostoyanie === '2', `состояние ${sostoyanie}`)

console.log('\n=== 2. Крик доходит до РЕАЛЬНОГО дескриптора 2 ===')
// 🔴 Проба сверяет строку С МАНИФЕСТОМ, а не с шаблоном имени: правило фермы 03.09.2026 —
// каждая строка несёт имя И версию, и версия читается из package.json, а не пишется
// константой. Константа при следующем выпуске утверждала бы номер, которому предмет уже не
// соответствует. Прежде проба ждала имя без номера и охраняла старый формат — при правке
// она честно покраснела, и это верное поведение: правка предмета и правка проверки идут парой.
const versiyaVManifeste = JSON.parse(
  __chitat(new URL('../package.json', import.meta.url), 'utf-8')).version
t('строка подъёма пришла в настоящий stderr и несёт ВЕРСИЮ ИЗ МАНИФЕСТА',
  r.err.includes(`[dsh-pamyat-restore ${versiyaVManifeste}] подъём:`),
  'ждали версию ' + versiyaVManifeste + ', пришло: ' + JSON.stringify(r.err.slice(0, 200)))
t('строка несёт значения настроек, а не одно имя', /restore=true/.test(r.err) && /welcome=true/.test(r.err), r.err.slice(0, 200))
t('крик пришёл именно в stderr, а не в stdout', !/подъём:/.test(r.out), r.out.slice(0, 200))

console.log('\n=== 3. Контроль зрячести: без службы крика быть НЕ ДОЛЖНО ===')
// Без этого «строка есть» ничего не доказывает: она могла бы приходить всегда,
// в том числе от несмонтированного модуля, и проверка выше была бы мнимой.
const r2 = await pusk(false)
t('без службы agents модуль молчит', !/\[dsh-pamyat-restore\] подъём:/.test(r2.err), r2.err.slice(0, 200))
t('и остаётся в ожидании, а не падает', /SOSTOYANIE=0/.test(r2.out), r2.out.slice(0, 120))

const ZHDYOM = 6
console.log(`\nИТОГО: сошлось ${ok}, расхождений ${bad}`)
if (bad > 0) process.exit(1)
if (ok + bad !== ZHDYOM) {
  console.log(`СЛЕПОТА: проверок ${ok + bad}, а стенд состоит из ${ZHDYOM} — часть не состоялась.`)
  process.exit(2)
}
process.exit(0)
