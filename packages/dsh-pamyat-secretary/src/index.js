/**
 * dsh-pamyat-secretary — секретарь компакции: снимает знание с того, что
 * вот-вот станет недостижимым.
 *
 * ЗАЧЕМ. Компакция заменяет кусок истории одной сводкой; затёртое агенту больше
 * не видно. Среди затёртого бывают решения владельца, ограничения и обещания.
 * Секретарь ловит событие сводки и кладёт её в долговременную память С
 * VERBATIM-ССЫЛКОЙ на затенённый диапазон — чтобы знание можно было потом
 * проверить по журналу сессии, а не верить ему на слово.
 *
 * 🔴 ШОВ — СОБЫТИЯ СЕССИИ, А НЕ ОТДЕЛЬНЫЕ ХУКИ. По типам платформы
 * (dsh-compaction 0.1.1-rc.2) `compaction/start|summary|end` объявлены в
 * SessionEventMap, то есть приходят как события СЕССИИ. План описывал их как
 * самостоятельные хуки — это оказалось неточностью пересказа, проверено чтением
 * d.ts. Подписка идёт на `session/event` с отбором по типу.
 *
 * 🔴 INJECT ОБЯЗАТЕЛЕН. На боевом контексте (плагин под runtime) чтение
 * `ctx.<служба>` без объявления в `inject` БРОСАЕТ: «cannot get property "X"
 * without inject» — это не догадка, это живой отказ в бою 02.09 и перемер на
 * cordis 4.0.1 из каталога стенда. На голом контексте оно молча отдаёт пустоту,
 * поэтому проба, поставленная на корневом Context, зелена по неверной причине.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Своей компакции не делаем и штатную не трогаем: событие
 * наблюдаем, в ход не вмешиваемся.
 *
 * 🔴 ДВЕ РАЗНЫЕ РАБОТЫ, А НЕ ЗАМЕНА ОДНОЙ ДРУГОЙ (03.09.2026, Э4).
 * Штатная сводка платформы кладётся как была — она ОПЕРАТИВНАЯ и остаётся
 * локально. Дистилляция снимает с того же среза ЗНАНИЯ (решения, уроки,
 * ограничения) отдельной дешёвой моделью и пишет их своими классами. Прежняя
 * редакция этой шапки говорила «дистилляция — следующий шаг слоя»; шаг сделан,
 * строка сохранена бы как призрак — текст, переживший код, который он объяснял.
 */
import z from '@deepseek-ai/schemastery';
import { razobratSvodku } from './razbor-sobytiya.js';
import { distillirovat } from './distill-shov.js';

export const name = 'dsh-pamyat-secretary';

/** Потребляем службу памяти ядра. Без объявления боевой контекст бросит. */
export const inject = ['pamyat'];

export const Config = z.object({
  /** Класс, которым записывается сводка компакции. */
  klass: z.string().default('svodka-kompakcii'),
  /**
   * Записывать ли сводки. Выключение — законное состояние узла (например, пока
   * идёт отладка), но оно ГРОМКОЕ: молчаливо выключенный секретарь неотличим
   * от сломанного.
   */
  vklyuchen: z.boolean().default(true),

  // ═══ ДИСТИЛЛЯЦИЯ ЗНАНИЙ ОТДЕЛЬНОЙ МОДЕЛЬЮ (Э4, решение владельца 03.09.2026) ═══
  // 🔴 ВЫКЛЮЧЕНА ПО УМОЛЧАНИЮ. Механизм ходит к ПЛАТНОМУ чужому API: включённый
  // молча у получателя, он тратил бы его деньги без спроса. Включение — осознанный
  // шаг, и без ключа он всё равно откажет вслух.
  distillyaciya: z.boolean().default(false),
  /** Файл журнала сессии. Пустой — дистилляция откажет с названной причиной. */
  putZhurnala: z.string().default(''),
  /** Ключ: файл 0600 либо запись pass. Никогда не аргумент команды. */
  klyuchFajl: z.string().default(''),
  klyuchPass: z.string().default(''),
  model: z.string().default('deepseek-v4-flash'),
  // 🔴 Числа с запасом: модель ДУМАЮЩАЯ, рассуждение съедает бюджет. Замер на живом
  // диапазоне: 8000 не хватило (stop_reason=max_tokens, блока text нет), 32000 хватило.
  maxTokenovTem: z.number().default(32000),
  maxTokenovStati: z.number().default(4000),
  /** Пределы расхода, объявленные числами: механизм платный. */
  predelTem: z.number().default(12),
  predelZnakov: z.number().default(200000),
  minTokenov: z.number().default(2000),
});

/**
 * Сказать громко — ОДНИМ предсказуемым путём.
 *
 * 🔴 НАХОДКА 03.09, стоившая трёх ложно-красных проб: `ctx.logger` у платформы
 * ЕСТЬ и без объявления в `inject` (это встроенная служба cordis), он функция,
 * и у него есть `.error`. Вызов проходит без ошибки — но сообщение НЕ ПОЯВЛЯЕТСЯ
 * в стандартном потоке: у службы свой транспорт, и в нашей сборке он никуда не
 * выводит. То есть «доложил» и «услышали» — разные утверждения, и разошлись они
 * молча: код отрабатывал, стенд видел тишину.
 * Поэтому пишем в обычный поток ВСЕГДА, а службу не трогаем: у публикуемого
 * пакета вывод обязан быть предсказуемым, а не зависеть от чужой настройки
 * транспорта. У службы stdout попадает в системный журнал — не пропадёт.
 * (В ядре это же записано в README как знаемое про вывод.)
 */
function krik(soobshchenie) {
  console.error('[dsh-pamyat-secretary] ' + soobshchenie);
}

export function apply(ctx, config = {}) {
  if (config.vklyuchen === false) {
    krik('секретарь ВЫКЛЮЧЕН настройкой: сводки компакции записываться не будут');
    return;
  }

  ctx.on('session/event', (session, event) => {
    // 🔴 ВЕСЬ обработчик внутри защищённого блока, включая разбор и запись.
    // Мы в чужом потоке событий: наше исключение оборвало бы обработку событий
    // ДРУГИХ подписчиков. Место сбоя обязано быть внутри, а не снаружи.
    try {
      if (!event || event.type !== 'compaction/summary') return;

      const razobrano = razobratSvodku(event.data, { seansId: session?.id ?? 'session' });
      if (!razobrano.godno) {
        // Не тихий пропуск: событие пришло, а знание не сняли — это надо знать.
        krik('сводка компакции НЕ записана: ' + razobrano.pochemu);
        return;
      }

      const z = razobrano.znanie;
      const pamyat = ctx.pamyat;
      if (!pamyat) {
        krik('служба памяти недоступна — сводка компакции ПОТЕРЯНА. ' +
                  'Знание было снято, но записать его некуда.');
        return;
      }
      pamyat.zapisat({
        klass: config.klass ?? 'svodka-kompakcii',
        soderzhim: z.soderzhim,
        istochnik: z.istochnik,
      });

      // 🔴 ДИСТИЛЛЯЦИЯ ИДЁТ СЛЕДОМ И НЕ ЖДЁТСЯ. Мы в чужом потоке событий; один
      // заход занимает минуты (замер: выбор тем 72 с, каждая статья 18 с). Ждать
      // здесь значило бы держать компакт и всех остальных подписчиков.
      // Штатная сводка уже записана выше — она оперативная и остаётся локально;
      // дистилляция снимает ЗНАНИЯ, и это разные вещи, а не замена одного другим.
      if (config.distillyaciya) {
        distillirovat({
          putZhurnala: config.putZhurnala,
          dannye: event.data,
          seansId: session?.id ?? 'session',
          nastrojka: {
            model: config.model, maxTokenovTem: config.maxTokenovTem,
            maxTokenovStati: config.maxTokenovStati, predelTem: config.predelTem,
            predelZnakov: config.predelZnakov, minTokenov: config.minTokenov,
            klyuch: { fajlKlyucha: config.klyuchFajl || null, zapisPass: config.klyuchPass || null },
          },
          krik,
          zapisat: (zn) => pamyat.zapisat(zn),
        }).catch((e) => krik('дистилляция оборвалась: ' + (e?.message ?? e)));
      }
    } catch (e) {
      krik('секретарь не смог обработать событие компакции: ' + (e?.message ?? e) +
                '. Сводка НЕ записана.');
    }
  });
}
