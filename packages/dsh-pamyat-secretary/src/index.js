  //   порог 4000 → 4 статьи из 12 не дописаны (stop_reason=max_tokens), выход 37 864
  //   порог 8000 → 0 отказов из 12, выход 33 760 — МЕНЬШЕ, чем при низком пороге
  // Занижение не экономит, а сжигает: упёршийся вызов тратит весь бюджет на рассуждение,
