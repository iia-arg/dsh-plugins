/**
 * Сказать громко — ОДНИМ предсказуемым путём.
 *
 * 🔴 НАХОДКА 03.09, стоившая трёх ложно-красных проб: `ctx.logger` у платформы
 * ЕСТЬ и без объявления в `inject` (это встроенная служба cordis), он функция,
 * и у него есть `.error`. Вызов проходит без ошибки — но сообщение НЕ ПОЯВЛЯЕТСЯ
 * в стандартном потоке: у службы свой транспорт, и в нашей сборке он никуда не
 * выводит. То есть «доложил» и «услышали» — разные утверждения, и разошлись они
 * молча: код отрабатывал, стенд видел тишину.
 * Поэтому пишем в обычный поток ВСЕГДА, а службу не трогаем: у публикуемого
 * пакета вывод обязан быть предсказуемым, а не зависеть от чужой настройки
 * транспорта. У службы stdout попадает в системный журнал — не пропадёт.
 * (В ядре это же записано в README как знаемое про вывод.)
 */
// 🔴 ВЕРСИЯ ЧИТАЕТСЯ ИЗ СВОЕГО package.json, А НЕ ПИШЕТСЯ КОНСТАНТОЙ. Константа при
// следующем выпуске утверждала бы номер, которому предмет уже не соответствует, — прибор,
// врущий уверенно. Отсюда же и граница: не прочиталось — говорим «версия неизвестна», а не
// молчим и не подставляем последнюю известную.
const versiya = (() => {
  try { return createRequire(import.meta.url)('../package.json').version ?? 'версия неизвестна'; }
  catch { return 'версия неизвестна'; }
})();

// Имя И версия в каждой строке: по журналу должно быть видно не только КТО сказал, но и
// КАКАЯ редакция это сказала. Без номера строка подъёма не различает редакции, а мы за день
// трижды получали в процессе не тот код, что на диске.
function krik(soobshchenie) {
  console.error('[dsh-pamyat-secretary ' + versiya + '] ' + soobshchenie);
}

// Ленивая загрузка ядра: держим её ЗДЕСЬ, а не в шапке, чтобы отсутствие ядра не рушило
// монтаж пакета — оно нужно только в миг записи сводки, и отказ там называется вслух.
// 🔴 ЗАГРУЖАЕТСЯ ПРИ МОНТАЖЕ, А НЕ В МИГ ЗАПИСИ. Обработчик события компакции
// СИНХРОННЫЙ намеренно (мы в чужом потоке событий и не ждём), поэтому ждать импорт
// в нём нельзя. Готовим заранее; не успело или не нашлось — маска не делается, и это
// говорится вслух, а не превращается в «маскировать было нечего».
let _yadro = null, _yadroOtkaz = null;
function gotovitYadro() {
  import('dsh-pamyat-core/src/filtr-vhoda.js')
    .then((m) => { _yadro = m; })
    .catch((e) => { _yadroOtkaz = e?.message ?? String(e); });
}

export function apply(ctx, config = {}) {
  gotovitYadro();
  if (config.vklyuchen === false) {
    krik('секретарь ВЫКЛЮЧЕН настройкой: сводки компакции записываться не будут');
    return;
  }

  // 🔴 БЕЗУСЛОВНЫЙ СЛЕД ПОДЪЁМА. До 03.09.2026 секретарь говорил только при выключении
  // и при беде — то есть при исправной работе был неотличим от несмонтированного, а
  // включение дистилляции нечем было подтвердить до первого компакта. Механизм, чьё
  // единственное свидетельство существования — жалоба, подтверждается тем хуже, чем
  // лучше он настроен.
  //
  // Строка называет НЕ «включено/выключено», а СОСТОЯНИЕ ГОТОВНОСТИ по каждому условию:
  // одного ключа distillyaciya мало, без пути к журналу и ключа заход не начнётся, и
  // это выглядело бы как «включили, и оно молчит».
  {
    const d = config.distillyaciya === true;
    const zhurnalEst = Boolean(config.putZhurnala);
    // 🔴 ЧИТАЕМ ТЕ ЖЕ ПОЛЯ, ЧТО И ПОТРЕБИТЕЛЬ. Прежде здесь стояло config.klyuch?.fajlKlyucha —
    // вложенный объект, которого в схеме НЕТ ВОВСЕ: схема объявляет klyuchFajl и klyuchPass
    // плоско, а вызов (ниже) читает именно их. То есть проверка и потребитель читали одно
    // поле разными путями, и признак говорил «НЕ ГОТОВА» при исправном механизме.
    //
    // Два дурных исхода, оба вероятны: пойти чинить работающее — или успокоиться «не
    // включилось», пока заходы идут и счёт капает. Второй хуже: механизм работает молча
    // при выключенном по приборам состоянии.
    //
    // 🔴 И ЛОЖНАЯ ПОДСКАЗКА УЖЕ СТОИЛА ОШИБКИ: строка ниже советовала завести
    // «klyuch.zapisPass», и профиль 04.09.2026 был написан по ней — вложенным полем,
    // которого схема не принимает. Подсказка, называющая несуществующее поле, не просто
    // бесполезна: она учит писать неверно.
    const klyuchNazvan = Boolean(config.klyuchFajl || config.klyuchPass || config.klyuchOkruzhenie);
    const gotova = d && zhurnalEst && klyuchNazvan;
    // 🔴 ПРИБОР НАЗЫВАЕТ ИСТОЧНИК, А НЕ ТОЛЬКО ФАКТ. «Ключ назван» не отвечает на вопрос
    // «откуда он взят», а источников теперь три, и ведут они себя по-разному: файл может
    // исчезнуть, `pass` требует своего хранилища, окружение живёт только у этого процесса.
    // Разбирающему отказ важно знать, ГДЕ смотреть. Печатается ИМЯ источника — значение
    // ключа не печатается никогда и нигде.
    // 🔴 НЕСКОЛЬКО ИСТОЧНИКОВ — НЕ МОЛЧАТЬ. Порядок задан (файл → pass → окружение), но
    // молчаливый выбор одного из двух заданных читался бы как «взято то, что я имел в виду».
    const zadano = [config.klyuchFajl && 'klyuchFajl', config.klyuchPass && 'klyuchPass',
                    config.klyuchOkruzhenie && 'klyuchOkruzhenie'].filter(Boolean);
    if (zadano.length > 1) {
      krik('источников ключа задано несколько (' + zadano.join(', ') +
           '); порядок файл → pass → окружение, будет взят ПЕРВЫЙ из заданных. ' +
           'Это не отказ, но лишний источник стоит убрать: он выглядит действующим');
    }
    const istochnikKlyucha = config.klyuchFajl ? 'файл ' + config.klyuchFajl
      : config.klyuchPass ? 'pass ' + config.klyuchPass
      : config.klyuchOkruzhenie ? 'окружение ' + config.klyuchOkruzhenie
      : null;
    krik('подъём: класс «' + (config.klass ?? 'svodka-kompakcii') + '», дистилляция ' +
         (!d ? 'ВЫКЛЮЧЕНА настройкой (сводки пишутся, знания не извлекаются)'
             : gotova ? 'взведена: модель ' + (config.model ?? '—') + ', журнал задан, ключ из '
                          + istochnikKlyucha
             : 'ВКЛЮЧЕНА, НО НЕ ГОТОВА — заход не начнётся: ' +
               (zhurnalEst ? '' : 'не задан putZhurnala; ') +
               (klyuchNazvan ? '' : 'не назван источник ключа (klyuchFajl, klyuchPass или klyuchOkruzhenie)')));
  }

  ctx.on('session/event', (session, event) => {
    // 🔴 ВЕСЬ обработчик внутри защищённого блока, включая разбор и запись.
    // Мы в чужом потоке событий: наше исключение оборвало бы обработку событий
    // ДРУГИХ подписчиков. Место сбоя обязано быть внутри, а не снаружи.
    try {
      if (!event || event.type !== 'compaction/summary') return;

      const razobrano = razobratSvodku(event.data, { seansId: session?.id ?? 'session' });
      if (!razobrano.godno) {
        // Не тихий пропуск: событие пришло, а знание не сняли — это надо знать.
        krik('сводка компакции НЕ записана: ' + razobrano.pochemu);
        return;
      }

      const z = razobrano.znanie;
      const pamyat = ctx.pamyat;
      if (!pamyat) {
        krik('служба памяти недоступна — сводка компакции ПОТЕРЯНА. ' +
                  'Знание было снято, но записать его некуда.');
        return;
      }
      // 🔴 ОТКАЗ ЗАПИСИ СВОДКИ БОЛЬШЕ НЕ ОБРЫВАЕТ ДИСТИЛЛЯЦИЮ (долг 114, 05.09.2026).
      // Замер в бою: за сутки 3 компакта из 5 дали отказ фильтра на сводке, и вместе
      // со сводкой не состоялась НИ ОДНА дистилляция — она стоит ниже в том же try,
      // и исключение до неё просто не доходило. То есть терялась не одна запись,
      // а весь итог компакта: 0 сводок И 0 знаний за три компакта подряд.
      // Причина отказа наша собственная: мы обсуждаем формы секретов ОБРАЗЦАМИ,
      // образцы попадают в сводку, фильтр видит объявленный секрет и отклоняет ВСЁ.
      // 🔴 МАСКА ОБРАЗЦОВ ДО ЗАПИСИ (решение координатора 05.09.2026, развилка 4а).
      // Принять потерю нельзя: тема не разовая, мы работаем над фильтром постоянно, и
      // «сводки о фильтре теряются всегда» означало бы, что знание о самой частой нашей
      // работе не сохраняется никогда. Маскируется ТОЛЬКО значение после слова-объявления.
      // Подмена ОБЪЯВЛЯЕТСЯ: маска видна (***) и число замен идёт в громкую строку —
      // иначе через месяц правленую сводку не отличить от исходной.
      let dlyaZapisi = z.soderzhim, maska = null;
      if (config.maskirovatObrazcy !== false) {
        try {
          if (!_yadro) {
            throw new Error(_yadroOtkaz
              ? 'ядро фильтра не загрузилось: ' + _yadroOtkaz
              : 'ядро фильтра ещё не готово (импорт не завершился к мигу записи)');
          }
          const m = zamaskirovat(z.soderzhim, _yadro);
          if (m.zameneno > 0) {
            dlyaZapisi = m.tekst;
            maska = m;
            krik('в сводке замаскировано значений: ' + m.zameneno + ' (классы: ' +
                 m.klassy.join(', ') + '). Слово-объявление и форма сохранены, заменено ' +
                 'ТОЛЬКО значение. Текст записи ОТЛИЧАЕТСЯ от исходной сводки — исходная ' +
                 'целиком лежит в журнале сеанса по seq источника.' +
                 (m.upyorsya ? ' 🔴 МАСКА УПЁРЛАСЬ В ПРЕДЕЛ: замаскировано не всё.' : ''));
          }
        } catch (e) {
          // Не смогли маскировать — говорим вслух и идём дальше: отказ маски не должен
          // молча превращаться в «маскировать было нечего».
          krik('🔴 маска образцов не отработала (' + (e?.message ?? e) + '); ' +
               'запись пойдёт как есть, и фильтр может её отклонить.');
        }
      }
      try {
        pamyat.zapisat({
          klass: config.klass ?? 'svodka-kompakcii',
          soderzhim: dlyaZapisi,
          istochnik: z.istochnik,
        });
      } catch (e) {
        // 🔴 ЗНАНИЕ НЕ ТЕРЯЕМ, НО И В ПАМЯТЬ НЕ ПУСКАЕМ. Сводка уходит в отдельный
        // файл с узкими правами: память остаётся чистой (фильтр отработал верно),
        // а текст перестаёт исчезать безвозвратно.
        // ПОЧЕМУ НЕ «пропустить с пометкой»: пометка положила бы настоящий секрет
        // в память, если он там есть. Фильтр не различает образец и настоящее —
        // и не должен: это его устройство, а не изъян.
        // ПОЧЕМУ НЕ «заменить место меткой»: подмена меняет текст МОЛЧА, и через
        // сутки никто не отличит правленую сводку от исходной.
        // 🔴 УМОЛЧАНИЯ У ПУТИ НЕТ НАМЕРЕННО. Подставить свой каталог молча значило бы
        // писать текст сводки туда, где хозяин пакета его не ждёт и о правах не знает.
        // Ключ не задан — текст НЕ сохраняется, и это говорится вслух с именем ключа,
        // а не выглядит как «сохранили куда-то».
        try {
          const kat = config.putOtklonennyh;
          if (!kat) {
            throw new Error('путь не задан: задайте ключ putOtklonennyh — '
              + 'умолчания нет намеренно, чтобы не писать в чужой каталог молча');
          }
          mkdirSync(kat, { recursive: true, mode: 0o700 });
          const imya = `${kat}/svodka-${Date.now()}.txt`;
          writeFileSync(imya, String(z.soderzhim ?? ''), { mode: 0o600 });
          krik('сводка ОТКЛОНЕНА фильтром (' + (e?.message ?? e) + '). '
             + 'Текст сохранён вне памяти: ' + imya + ' — знание не потеряно, '
             + 'память не запачкана. Дистилляция ПРОДОЛЖАЕТСЯ.');
        } catch (e2) {
          // 🔴 ДВОЙНОЙ ОТКАЗ НАЗЫВАЕТСЯ ЦЕЛИКОМ: иначе «сводка потеряна» будет
          // неотличимо от «сохранена куда-то».
          krik('🔴 сводка отклонена фильтром (' + (e?.message ?? e) + ') И НЕ СОХРАНЕНА ('
             + (e2?.message ?? e2) + ') — текст ПОТЕРЯН. Дистилляция продолжается.');
        }
      }

      // 🔴 ДИСТИЛЛЯЦИЯ ИДЁТ СЛЕДОМ И НЕ ЖДЁТСЯ. Мы в чужом потоке событий; один
      // заход занимает минуты (замер: выбор тем 72 с, каждая статья 18 с). Ждать
      // здесь значило бы держать компакт и всех остальных подписчиков.
      // Штатная сводка уже записана выше — она оперативная и остаётся локально;
      // дистилляция снимает ЗНАНИЯ, и это разные вещи, а не замена одного другим.
      if (config.distillyaciya) {
        distillirovat({
          putZhurnala: config.putZhurnala,
          dannye: event.data,
          seansId: session?.id ?? 'session',
          nastrojka: {
            model: config.model, maxTokenovTem: config.maxTokenovTem,
            maxTokenovStati: config.maxTokenovStati, predelTem: config.predelTem,
            predelZnakov: config.predelZnakov, minTokenov: config.minTokenov,
            klyuch: { fajlKlyucha: config.klyuchFajl || null, zapisPass: config.klyuchPass || null,
                      peremennayaOkruzheniya: config.klyuchOkruzhenie || null },
          },
          krik,
          zapisat: (zn) => pamyat.zapisat(zn),
        }).catch((e) => krik('дистилляция оборвалась: ' + (e?.message ?? e)));
      }
    } catch (e) {
      krik('секретарь не смог обработать событие компакции: ' + (e?.message ?? e) +
                '. Сводка НЕ записана.');
    }
  });
}
