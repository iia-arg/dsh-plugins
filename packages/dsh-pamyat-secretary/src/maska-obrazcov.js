/**
 * Маскировка ОБРАЗЦОВ секретов в тексте сводки — решение координатора 05.09.2026.
 *
 * 🔴 ЗАЧЕМ. Мы постоянно работаем над фильтром входа и пишем формы секретов ДОСЛОВНО.
 * Образцы попадают в сводку компакта, фильтр видит объявленный секрет и отклоняет её
 * целиком. За сутки так потеряно 4 сводки из 6. Принять потерю нельзя: тема не разовая,
 * и правило «сводки о фильтре теряются всегда» означало бы, что знание о САМОЙ ЧАСТОЙ
 * нашей работе не сохраняется никогда.
 *
 * 🔴 ПРАВИЛА БЕРУТСЯ У ЯДРА, СВОЕЙ КОПИИ ЗДЕСЬ НЕТ. Маска идёт по тем же находкам, что
 * даёт `najti_sekret` ядра: копия правил разошлась бы с ядром в первый же день — этот
 * класс у нас уже стоил трёх разошедшихся списков.
 *
 * ГРАНИЦА, названная координатором и исполненная буквально: маскируется ТОЛЬКО ЗНАЧЕНИЕ
 * после слова-объявления. Слово, форма, окружающий текст не трогаются — иначе маска съест
 * сам разбор, ради которого сводка и пишется.
 *
 * 🔴 ПОДМЕНА ОБЪЯВЛЯЕТСЯ. Мой довод против маскировки был «текст меняется молча, и через
 * месяц правленую сводку не отличить от исходной». Он снят не отказом от маски, а тем,
 * что маска ВИДНА (`***`) и число замен возвращается наружу — запись скажет о себе сама.
 *
 * ЧЕГО НЕ ДЕЛАЕТ:
 *   • не маскирует то, что ядро НЕ считает запирающим (пометки остаются как есть):
 *     маска — не «на всякий случай», а ровно против того, что рвёт запись;
 *   • не защищает от НАСТОЯЩЕГО секрета в сводке: он тоже будет замаскирован, и это
 *     верно, но знание о нём тогда не попадёт в память — так и задумано;
 *   • не трогает текст вне значений.
 */

/** Предел проходов: защита от правила, которое находит одно и то же на месте маски. */
const PREDEL = 200;

/**
 * @param {string} tekst
 * @param {{najti_sekret: Function, zapiraet: Function}} yadro функции ЯДРА, не копии
 * @returns {{tekst: string, zameneno: number, klassy: string[], upyorsya: boolean}}
 */
export function zamaskirovat(tekst, yadro) {
  if (typeof tekst !== 'string' || !tekst) return { tekst, zameneno: 0, klassy: [], upyorsya: false };
  if (!yadro || typeof yadro.najti_sekret !== 'function' || typeof yadro.zapiraet !== 'function') {
    // Без ядра маскировать нечем. Молчаливый пропуск здесь дал бы «замен 0» —
    // неотличимо от «нечего было маскировать».
    throw new Error('маска образцов: ядро не отдало najti_sekret/zapiraet — маскировать нечем');
  }
  let t = tekst, n = 0, upyorsya = false;
  const klassy = new Set();
  for (let i = 0; i < PREDEL; i++) {
    const r = yadro.najti_sekret(t);
    if (!r || !yadro.zapiraet(r.klass)) break;
    const p = r.pozicia;
    if (!Number.isInteger(p) || p < 0 || p >= t.length) { upyorsya = true; break; }
    // 🔴 ПОЗИЦИЯ ЯДРА УКАЗЫВАЕТ НА НАЧАЛО ВСЕГО СОВПАДЕНИЯ, А НЕ ЗНАЧЕНИЯ.
    // Проверено пробой: для «pwd=Hunter22xy» позиция стоит на «p». Маскируя от неё,
    // мы съедали и слово-объявление — то есть нарушали границу «слово и форма
    // сохраняются», ради которой маска и разрешена. Ищем разделитель и маскируем ПОСЛЕ.
    const kon = (() => { let k = p; while (k < t.length && !/[\s"'`]/.test(t[k])) k++; return k; })();
    const kusok = t.slice(p, kon);
    const razd = kusok.search(/[:=]/);
    // Разделителя нет — значит совпадение не вида «слово=значение» (структурный ключ,
    // энтропия). Маскируем целиком: там нечего сохранять, кроме самого факта.
    const nachalo = razd === -1 ? p : p + razd + 1;
    // Кавычка сразу после разделителя принадлежит форме, а не значению.
    let s = nachalo;
    while (s < kon && /["'`]/.test(t[s])) s++;
    if (s >= kon) { upyorsya = true; break; }
    t = t.slice(0, s) + '***' + t.slice(kon);
    n++; klassy.add(r.klass);
    if (i === PREDEL - 1) upyorsya = true;
  }
  return { tekst: t, zameneno: n, klassy: [...klassy].sort(), upyorsya };
}
