import Schema from '@deepseek-ai/schemastery'
import { execFileSync } from 'node:child_process'
import { vidKonca, rashod, davlenie, dlitelnost } from './vidy-szhatiya.js'

export const name = 'dsh-pamyat-storozha'
export const inject = []

export const Config = Schema.object({
  /** Куда, кроме журнала, отдавать оповещение. Пусто — только журнал. */
  komandaStoka: Schema.string().default(''),
  /** Ступени тревоги по заполнению. Нудж держит свою (0.8) отдельно и независимо. */
  stupeni: Schema.array(Schema.number()).default([0.85, 0.9]),
  /**
   * ЗАПАСНОЙ предел контекста в токенах. Основной источник — платформа
   * (см. oknoModeli): она объявляет окно вместе с маршрутом модели. Это число
   * берётся, только если платформа окна не назвала, и в строке тревоги честно
   * помечается как «платформой не подтверждено». 0 — доли нет вовсе, и это ГОВОРИТСЯ.
   */
  predel: Schema.number().default(0),
  /**
   * Имя агента для строки тревоги (ворота В1). Умолчания НЕТ намеренно: угадать
   * агента изнутри нечем, а подставить чужое имя — уверенно ответить не про тот узел.
   * Пусто — в строке стоит «агент НЕ НАЗВАН», а не тишина.
   */
  agent: Schema.string().default(''),
})

/**
 * Окно контекста берётся У ПЛАТФОРМЫ, а не числом в настройке (ворота В5).
 *
 * 🔴 ПОЧЕМУ НЕ КОНСТАНТА. Число в конфиге описывает модель НА МОМЕНТ ЗАПИСИ. Сменят
 * модель — окно станет другим, а число останется прежним и разойдётся МОЛЧА: ступень
 * 85% посчитается от чужой ёмкости и будет то ранней, то поздней, не сказав об этом.
 * Платформа же объявляет окно вместе с маршрутом (событие request/context, поле
 * contextWindow), и `session.requestContext()` отдаёт последнее известное.
 *
 * ⚠️ ГРАНИЦА: поле НЕОБЯЗАТЕЛЬНОЕ — «when advertised» в объявлении платформы. Значит
 * «окна нет» — законное состояние, а не поломка, и различается от «спросить не смогли»:
 * первое про модель, второе про нас. Оба возвращают est:false, но с РАЗНОЙ причиной,
 * потому что чинить их надо разное.
 */
function oknoModeli(session) {
  let rc
  try {
    if (typeof session?.requestContext !== 'function') {
      return { est: false, prichina: 'у сессии нет requestContext() — спросить платформу нечем' }
    }
    rc = session.requestContext()
  } catch (e) {
    return { est: false, prichina: `спросить платформу не смог: ${e?.message ?? e}` }
  }
  if (!rc) return { est: false, prichina: 'платформа маршрута ещё не объявила (request/context не было)' }
  const w = rc.contextWindow
  if (!Number.isInteger(w) || w <= 0) {
    return { est: false, model: rc.model, provider: rc.provider,
             prichina: `модель ${rc.model ?? '?'} окна НЕ объявила (поле необязательное)` }
  }
  return { est: true, tokenov: w, model: rc.model, provider: rc.provider }
}

// 🔴 ЧТО РЕШАЕТ ИСХОД У КАЖДОЙ ТРЕВОГИ (ворота В9; класс «данные собраны и не участвуют
// в вердикте»). Сегодня этот класс нашёлся у двух приборов сразу: курьер подъёма печатал
// PID до/после и решал по коду конвейера; мой podyom-uzla печатал PID и число назвавшихся
// пакетов, а в код возврата их не брал. Поэтому здесь список пишется ДО кода:
//
//   тревога «сжатие»            решает: тип события compaction/end БЕЗ error.
//                               справочно: расход, модель, длительность, вытеснено —
//                               ни одна из этих величин не влияет на то, кричать ли.
//   тревога «обрезка»           решает: тип compaction/prune. Справочно: вытеснено, узлов.
//   тревога «провал»            решает: наличие error в данных end. Справочно: текст error.
//   тревога «ступень»           решают ДВЕ величины: доля vzyato/predel и то, что ступень
//                               ещё не отдана. Справочно: сами числа в скобках.
//   отказ стока                 решает: исключение из команды стока. Справочно: текст.
//
// ⚠️ Отсюда следствие, названное вслух: расход «не сообщён» тревоги НЕ поднимает и поднимать
// не должен — это свойство данных провайдера, а не беда памяти. Если однажды захотим кричать
// на него, это будет НОВАЯ тревога со своим решающим признаком, а не тихое расширение этой.
export function apply(ctx, config) {
  const krik = (s) => ctx.logger?.info?.(`[${name}] ${s}`) ?? console.log(`[${name}] ${s}`)

  krik(`подъём: ступени ${JSON.stringify(config.stupeni)}`
     + ` · окно контекста спрашивается У ПЛАТФОРМЫ в момент каждого замера`
     + ` (запасное число в настройке: ${config.predel || 'нет'})`
     + ` · агент ${config.agent || 'НЕ НАЗВАН (настройка agent пуста)'}`
     + ` · сток ${config.komandaStoka ? 'задан' : 'НЕ задан (только журнал)'}`)

  // 🔴 ОДНО ОПОВЕЩЕНИЕ ПОВЕРХ, А НЕ ПО СЛУШАТЕЛЮ НА СОБЫТИЕ. Замер до кода: событий
  // сжатия на этом узле слушают уже ЧЕТЫРЕ пакета (бюджет, нудж, восстановление,
  // секретарь). Пятый слушатель, кричащий своё, дал бы на одно сжатие пять сообщений —
  // и первый же шумный день научит их не читать.
  const nachala = new Map()   // compactionId → { ms, seq }
  const svodki = new Map()    // compactionId → data события summary

  ctx.on('session/event', (session, event) => {
    const t = event?.type
    if (t !== 'compaction/start' && t !== 'compaction/summary'
        && t !== 'compaction/end' && t !== 'compaction/prune') return

    const id = event?.data?.compactionId ?? null
    const ms = typeof event?.timestamp === 'number' ? event.timestamp
             : (Date.parse(event?.timestamp ?? '') || null)

    if (t === 'compaction/start') { if (id) nachala.set(id, { ms }); return }
    if (t === 'compaction/summary') { if (id) svodki.set(id, event.data); return }

    // 🔴 ОБРЕЗКА — ОТДЕЛЬНЫЙ ВИД, А НЕ «СЖАТИЕ ПОДЕШЕВЛЕ». У неё нет ни модели, ни
    // расхода: замена идёт без вызова. Складывать её со сводочными в одно число
    // «сжатий было N» значит сложить несравнимое.
    if (t === 'compaction/prune') {
      schet.obrezok++
      otdat(krik, config, `ОБРЕЗКА без модели: вытеснено ${event.data?.shadowedTokenCount ?? '?'} ток.`
        + ` · узлов ${event.data?.shadowedSeqs?.length ?? '?'} · расхода нет ПО ПРИРОДЕ (модель не звалась)`
        + ` · id ${id ?? 'нет (обрезка его не несёт)'}`)
      return
    }

    // compaction/end
    const vid = vidKonca(event.data)
    if (vid === 'proval') {
      schet.provalov++
      otdat(krik, config, `🔴 ПОПЫТКА СЖАТИЯ ПРОВАЛИЛАСЬ: ${event.data?.error}`
        + ` · история НЕ урезана, сводки нет · id ${id ?? '?'}`)
      nachala.delete(id); svodki.delete(id)
      return
    }

    const svodka = svodki.get(id)
    const marshrut = oknoModeli(session)
    const r = rashod(svodka?.usage)
    const d = dlitelnost(nachala.get(id)?.ms, ms)
    if (vid === 'prinuditelnoe') schet.prinuditelnyh++; else schet.estestvennyh++
    if (!r.est) schet.bezRashoda++
    if (d === null) schet.bezDliny++

    otdat(krik, config,
      `сжатие ${vid === 'prinuditelnoe' ? 'ПРИНУДИТЕЛЬНОЕ (команда человека)' : 'естественное'}`
      + ` · вытеснено ${svodka?.shadowedTokenCount ?? 'неизвестно'} ток.`
      + ` · расход ${r.est ? r.vsego + ' ток.' : 'НЕ СООБЩЁН (это не ноль)'}`
      + ` · модель ${svodka?.model ?? 'не названа'}`
      + ` · длительность ${d === null ? 'не измерима (нет метки начала)' : (d / 1000).toFixed(1) + ' с'
          + ' — между ЗАПИСЯМИ В ЖУРНАЛ, не работа модели'}`
      // 🔴 id — чтобы строку можно было сшить с журналом; провайдер — из МАРШРУТА СЕЙЧАС,
      // и это помечено: сжатие могло идти другим маршрутом, если его между делом сменили.
      + ` · id ${id ?? 'нет'}`
      + ` · маршрут сейчас ${marshrut.provider ?? 'не объявлен'}`
      + ` (маршрут НА МОМЕНТ ЧТЕНИЯ, не обязательно тот, которым сжимали)`)

    nachala.delete(id); svodki.delete(id)
  })

  // ── ВТОРАЯ СТУПЕНЬ ЗАПОЛНЕНИЯ ──────────────────────────────────────────────
  // 🔴 ПОЧЕМУ НЕ ЕДИНЫЙ СЧЁТЧИК С НУДЖЕМ. Нудж считает расход своей рукой и держит
  // свою долю (0.8). Второй счётчик неизбежно разойдётся с первым, и разойдётся
  // МОЛЧА. Поэтому здесь не «правильное число», а ВТОРАЯ ПАРА ГЛАЗ: своё число, своё
  // имя в строке, и прямо сказано, что оно независимо и может не совпасть.
  // ── СЧЁТ ДЛЯ СВОДКИ: ЧИСЛИТЕЛЬ И ЗНАМЕНАТЕЛЬ РЯДОМ (ворота В11) ─────────────
  // 🔴 ЗАЧЕМ ЗНАМЕНАТЕЛЬ. «Сжатий за сутки 3» без «ходов за сутки M» не значит ничего:
  // ноль тревог при четырёх ходах и ноль при четырёхстах — разные новости. Сегодня на
  // этом же классе едва не устоял вывод про лечение связи: 0 отказов в окне читалось как
  // успех, пока не выяснилось, сколько было попыток.
  // ⚠️ ЧТО ЭТО НЕ ЗНАЧИТ: ходы — знаменатель для СЖАТИЙ, а не для ступеней заполнения.
  // Для ступеней знаменателя нет вовсе (они про состояние, не про поток), и это сказано
  // в самой сводке, а не подразумевается.
  const schet = { estestvennyh: 0, prinuditelnyh: 0, obrezok: 0, provalov: 0, hodov: 0,
                  bezRashoda: 0, bezDliny: 0, stupenej: 0 }
  let vzyato = 0
  const otdannye = new Set()
  let skazanoORashozhdenii = false
  let skazanoOSlepote = false
  let skazanoOChuzhih = false
  const uchest = (usage, session) => {
    // 🔴 СТУПЕНИ — ПО ДАВЛЕНИЮ НА КОНТЕКСТ, А НЕ ПО РАСХОДУ ВЫЗОВА (06.09.2026).
    // Заполнение — это то, что уходит В ЗАПРОС: вход плюс кэш, без выхода (формула
    // платформы pressureFrom). Ответ модели попадёт в контекст только СЛЕДУЮЩИМ вызовом.
    // Прежде здесь стоял полный расход — доля завышалась на весь выход, то есть ступень
    // кричала раньше срока, и объяснить это было бы нечем.
    const r = davlenie(usage)
    if (r.chuzhie?.length && !skazanoOChuzhih) {
      skazanoOChuzhih = true
      krik(`⚠️ в usage поля, не объявленные платформой: ${r.chuzhie.join(', ')}.`
        + ` В счёт НЕ берутся — молчаливый учёт неизвестного даёт число, за которое никто не отвечает.`)
    }
    if (!r.est) return
    vzyato = r.vsego

    // 🔴 ОКНО — У ПЛАТФОРМЫ, НАСТРОЙКА ЗАПАСНАЯ (ворота В5).
    const o = oknoModeli(session)
    const predel = o.est ? o.tokenov : config.predel
    const istochnikOkna = o.est
      ? `платформа, модель ${o.model ?? '?'}`
      : `НАСТРОЙКА (платформой не подтверждена: ${o.prichina})`

    // 🔴 РАСХОЖДЕНИЕ НАСТРОЙКИ С ПЛАТФОРМОЙ НАЗЫВАЕТСЯ ВСЛУХ, ОДИН РАЗ. Молчаливое
    // «беру платформу, а число в конфиге игнорирую» оставило бы в профиле цифру, которая
    // выглядит действующей и ни на что не влияет — тот же класс, что метка, пережившая
    // свою правду. Кричим и продолжаем считать по платформе: она про модель СЕЙЧАС.
    if (o.est && config.predel && config.predel !== o.tokenov && !skazanoORashozhdenii) {
      skazanoORashozhdenii = true
      otdat(krik, config, `⚠️ предел в настройке ${config.predel} ток. РАСХОДИТСЯ с окном,`
        + ` объявленным платформой (${o.tokenov} ток., модель ${o.model ?? '?'}).`
        + ` Считаю по платформе; число в настройке пора убрать или поправить.`)
    }

    // 🔴 НЕТ НИ ТОГО НИ ДРУГОГО — ЭТО СЛЕПОТА, И ОНА ГОВОРИТСЯ. Прежде здесь стоял тихий
    // возврат: ступени молчали, и молчание было неотличимо от «заполнение низкое».
    if (!predel) {
      if (!skazanoOSlepote) {
        skazanoOSlepote = true
        krik(`ступени НЕ считаются: окна нет ни у платформы (${o.prichina}),`
          + ` ни в настройке (predel 0). Моё молчание тут означает «не мерил», а не «мало занято».`)
      }
      return
    }
    const dolya = vzyato / predel
    const vzyaty = []
    for (const st of config.stupeni) {
      if (dolya >= st && !otdannye.has(st)) { otdannye.add(st); vzyaty.push(st) }
    }
    // 🔴 ОДНО СООБЩЕНИЕ ПРО ВСЕ ПЕРЕЙДЁННЫЕ СТУПЕНИ, А НЕ ПО СООБЩЕНИЮ НА КАЖДУЮ (В2).
    // Один скачок расхода может перешагнуть обе ступени разом (800 000 → 950 000). Прежняя
    // редакция кричала дважды об ОДНОМ событии — и это ровно та беда, ради которой сторож
    // делался «одним оповещением поверх»: шум учит не читать.
    if (vzyaty.length) {
      schet.stupenej += vzyaty.length
      otdat(krik, config, `🔴 ЗАПОЛНЕНИЕ ${(dolya * 100).toFixed(0)}% (вход+кэш, БЕЗ выхода) — `
        + (vzyaty.length > 1 ? 'ступени ' : 'ступень ') + vzyaty.map((x) => x * 100 + '%').join(' и ')
        + (vzyaty.length > 1 ? ' перейдены ОДНИМ скачком' : '')
        + ` (${vzyato} из ${predel} ток.; окно — ${istochnikOkna})`
        + ` · счёт СВОЙ, с нуджем не сверяется`)
    }
  }
  ctx.on('session/event', (session, event) => {
    if (event?.type === 'turn/start') schet.hodov++
    // 🔴 СЧЁТ ОБНУЛЯЕТ ЛЮБОЕ СЖАТИЕ, А НЕ ТОЛЬКО СВОДОЧНОЕ (ворота В0, найдено 06.09.2026).
    // Было: сброс только на compaction/summary. Обрезка без модели (prune) контекст УРЕЗАЕТ
    // так же, а счёт после неё продолжал расти со старого значения — то есть заполнение
    // оставалось завышенным, и ступень могла сработать на объёме, которого в контексте уже нет.
    // Ворота В0 писались про другой источник (tokenMeter.measure() завышен после сжатия), но
    // корень тот же: ОПОРА УСТАРЕЛА ПОСЛЕ СЖАТИЯ. У нас measure() не берётся вовсе — считаем
    // по usage событий, — поэтому дефект #5632 нас не касается по построению; а вот его
    // близнец по prune был и лечится тем же сбросом.
    if (event?.type === 'compaction/summary' || event?.type === 'compaction/prune') {
      otdannye.clear(); vzyato = 0; return
    }
    uchest(event?.data?.usage, session)
  })

  // ── СВОДКА: ОБЛАСТЬ, ЧИСЛИТЕЛЬ, ЗНАМЕНАТЕЛЬ, «НЕ ПРОВЕРЯЛ» (ворота В10, В11) ─────
  // 🔴 ОБЛАСТЬ И «ЧЕГО НЕ ВИДЕЛ» ПЕЧАТАЮТСЯ ВСЕГДА, ДАЖЕ НУЛЁМ. Иначе «тревог 0» читается
  // как «всё хорошо», а означать может «мы туда не смотрели». Правило области: прибор
  // обязан говорить не только что проверил, но и ЧЕГО НЕ ПРОВЕРЯЛ, поимённо.
  // ⚠️ ГРАНИЦА СЧЁТА: он живёт в памяти процесса и обнуляется подъёмом. «За сутки» тут
  // сказать нельзя — только «с подъёма», и так и написано. Суточный счёт потребовал бы
  // своего хранилища, то есть второго места правды рядом с журналом.
  const svodkaStorozha = () => {
    const szhatij = schet.estestvennyh + schet.prinuditelnyh
    return [
      `сводка сторожа с подъёма процесса (НЕ за сутки: счёт в памяти, подъём его обнуляет)`,
      `  область: события ЭТОГО процесса — compaction/start, /summary, /end, /prune, turn/start`,
      `  НЕ проверял: сжатия других агентов машины · события до подъёма · то, что не дошло`,
      `    до нашего слушателя (молчание сторожа этих трёх случаев НЕ различает)`,
      `  сжатий ${szhatij} (естественных ${schet.estestvennyh} · принудительных ${schet.prinuditelnyh})`
        + ` · обрезок без модели ${schet.obrezok} · провалов ${schet.provalov}`,
      `  ЗНАМЕНАТЕЛЬ: ходов ${schet.hodov} — «сжатий N» без него не читается`,
      `  из ${szhatij} сжатий: без расхода ${schet.bezRashoda} (не сообщён ≠ ноль)`
        + ` · без длительности ${schet.bezDliny} (нет метки начала)`,
      `  ступеней заполнения отдано ${schet.stupenej}`
        + ` — у них знаменателя НЕТ: это состояние, а не поток`,
    ].join('\n')
  }

  return { uchest, svodkaStorozha, schet: () => ({ ...schet }),
           sostoyanie: () => ({ vzyato, stupeniOtdany: [...otdannye] }) }
}

/**
 * Отдать сообщение: всегда в журнал, дополнительно — во внешний сток.
 * 🔴 СТОК НЕОБЯЗАТЕЛЕН И ВЫКЛЮЧЕН ПО УМОЛЧАНИЮ. Адресат оповещения в задании не
 * назван, а угадывать его — значит зашить в пакет чужую раскладку. Пока команда не
 * задана, сторож пишет в журнал и ГОВОРИТ об этом при подъёме, а не молчит.
 */
function otdat(krik, config, tekst) {
  // 🔴 АГЕНТ В КАЖДОЙ ТРЕВОГЕ (ворота В1), И ПОДСТАВЛЕН ОДНИМ МЕСТОМ. Собирать имя в
  // каждой строке отдельно — значит однажды забыть его ровно в той строке, которую будут
  // читать. Пусто — пишем «НЕ НАЗВАН», а не молчим: у сообщения без адреса отправитель
  // выглядит известным, пока сообщений не станет два.
  const kto = config.agent ? `агент ${config.agent}` : 'агент НЕ НАЗВАН (настройка agent пуста)'
  krik(`${kto} · ${tekst}`)
  if (!config.komandaStoka) return
  try {
    execFileSync('/bin/sh', ['-c', config.komandaStoka], { input: `${kto} · ${tekst}`, timeout: 5000 })
  } catch (e) {
    // 🔴 ОТКАЗ СТОКА НЕ ГЛУШИТ ОПОВЕЩЕНИЕ: в журнал оно уже ушло выше. Кричим о самом
    // отказе — молчаливо потерянный сток неотличим от «тревог не было».
    krik(`🔴 сток не сработал (${e?.message ?? e}) — сообщение осталось только в журнале`)
  }
}
