/**
 * ВЕРСИЯ СХЕМЫ ВЫВОЗА — САМООПИСАНИЕ ФАЙЛА.
 *
 * 🔴 ЗАЧЕМ. Файл вывоза переживёт обе стороны: его сделают сегодня, а ввезут через месяц
 * другой редакцией пакета. Без объявленной версии ввоз читал бы чужой формат «как получится»
 * и молча терял поля — а потеря при переносе неотличима от «этого поля и не было».
 * Поэтому первая строка файла — ЗАГОЛОВОК, и ввоз отказывается работать, если версия чужая.
 *
 * ПОЧЕМУ ОТКАЗ, А НЕ ПОПЫТКА ПОНЯТЬ. Мы не знаем, что означает версия из будущего: поле
 * могло не появиться, а поменять смысл. Догадка здесь молчалива, отказ — нет.
 */

import { createHash } from 'node:crypto';

export const VERSIYA_SHEMY = 1;

/**
 * ПОЛЯ ЗАПИСИ, КОТОРЫЕ ПЕРЕНОСЯТСЯ.
 *
 * 🔴 `id` ЗДЕСЬ НЕТ НАМЕРЕННО, и это не упущение. Ввоз присваивает СВОИ номера. Причина
 * измерена: у ядра статус записи определяется рубежом по id (записи ниже рубежа —
 * «до протокола», они старше механизма отметки происхождения). Чужая запись с малым
 * номером легла бы ниже НАШЕГО рубежа и получила бы привилегию нашей старой памяти —
 * отмывание доверия через ввоз. Ограничение стоит и в шапке миграции ядра; здесь оно
 * исполняется ОТКАЗОМ, а не предупреждением: тот, кто заведёт перенос номеров, будет
 * править этот файл, а не соседний.
 */
export const POLYA = [
  'agent', 'klass', 'soderzhim', 'istochnik', 'sozdano',
  'bez_podtverzhdeniya', 'vera', 'ochistka', 'podozrenie',
];

/**
 * ЧЕГО ВЫВОЗ НЕ ВЫВОЗИТ — И ПОЧЕМУ (условие приёмки В11).
 * 🔴 Написано ПОЧЕМУ, а не только ЧТО: следующий увидит, что журнал не переносится,
 * и решит, что это забыли. Это не забыли, это решено.
 */
export const NE_VYVOZITSYA = {
  id: 'номер записи — свойство ЭТОЙ базы; перенос номеров открыл бы отмывание через рубеж',
  zhurnal: 'журнал операций — история ЭТОЙ машины: кто когда что записал и почему отказал. На другой машине он не описывает ничего',
  ochered_dolgovremennogo: 'очередь доставки — состояние доставки ЭТОЙ машины. Перенос сделал бы её источником ДВОЙНОЙ доставки: записи ушли бы в общую память дважды, с двух машин',
  nastrojki: 'рубеж происхождения принадлежит принимающей базе и снимается по ЕЁ ряду номеров',
};

export class OtkazShemy extends Error {
  constructor(prichina, kod = 'VYVOZ_CHUZHAYA_SHEMA') {
    super(`ввоз: ${prichina}`);
    this.code = kod;
    this.prichina = prichina;
  }
}

/**
 * Поля базы, о которых вывоз не знает ВОВСЕ: их нет ни в POLYA (вывозим), ни в
 * NE_VYVOZITSYA (решено не вывозить).
 *
 * 🔴 ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ «ПОЛЕЙ, КОТОРЫХ В БАЗЕ НЕТ». Те две проверки зеркальны, но
 * ловят разное. «Поля нет в базе» — база старше вывоза, потеря видна сразу. «Поле есть,
 * а вывоз о нём не знает» — СХЕМА УШЛА ВПЕРЁД, и знание теряется МОЛЧА: на той стороне
 * записи просто не будет этого поля, и никто не отличит «не переносили» от «не было».
 * Найдено 05.09.2026 на живой базе: полей 12, вывоз знал 10; `proishozhdenie` и
 * `proverka` (заведены миграцией ядра a32) не значились нигде.
 *
 * ⚠️ ПОЧЕМУ НАЗЫВАЕМ, А НЕ ОСТАНАВЛИВАЕМ — в отличие от незнакомого КЛАССА.
 * Незнакомый класс грозит выпустить секрет наружу: утечка необратима, поэтому вывоз
 * встаёт целиком. Незнакомое поле грозит НЕ перенести знание: исходная база цела,
 * перенести можно позже — потеря обратима. Разная цена — разный режим; уравнять их
 * значило бы останавливать перенос при каждой миграции схемы.
 */
export function neznakomye_polya(estVBaze) {
  const znaem = new Set([...POLYA, ...Object.keys(NE_VYVOZITSYA)]);
  return estVBaze.filter((p) => !znaem.has(p));
}

/**
 * Заголовок файла вывоза — первая строка.
 *
 * Поле `polya_neizvestnye_vyvozu` кладётся В ФАЙЛ, а не только в наш отчёт: принимающая
 * сторона обязана видеть, ЧЕГО в этом файле нет по нашему незнанию, а не гадать.
 */
export function zagolovok({ otkuda, uzel, kogda = Date.now(), zapisej,
                            zaderzhano = 0, summa, neizvestnye = [] }) {
  return {
    vyvoz: 'dsh-pamyat',
    versiya_shemy: VERSIYA_SHEMY,
    polya: POLYA,
    ...(neizvestnye.length ? { polya_neizvestnye_vyvozu: neizvestnye } : {}),
    // 🔴 otkuda И uzel — РАЗНЫЕ ВЕЛИЧИНЫ, И РАЗВОДИТЬ ИХ ОБЯЗАТЕЛЬНО (ворота В1).
    // otkuda — то, что назвал вызывающий: может быть чем угодно, вплоть до «неизвестно».
    // uzel — имя машины, снятое ОС в момент вывоза. Если их слить, читающий на той
    // стороне не отличит «файл сделан на машине X» от «кто-то написал в поле X».
    otkuda,
    uzel,
    kogda,
    zapisej,
    // 🔴 ЧИСЛО ЗАДЕРЖАННЫХ — В ЗАГОЛОВКЕ, А НЕ ТОЛЬКО В ОТЧЁТЕ (В1). Отчёт остаётся
    // у вывозящего, а файл уезжает; без этого числа принимающая сторона не знает, что
    // часть записей отсеяна фильтром, и «68 записей» читается как «вся память».
    zaderzhano,
    // 🔴 СУММА СОДЕРЖИМОГО — ЧТОБЫ ВВОЗ МОГ ПРОВЕРИТЬ, ЧТО ФАЙЛ ДОШЁЛ ЦЕЛИКОМ (В1).
    // Считается по строкам записей БЕЗ заголовка: заголовок содержит саму сумму, и
    // включить его значило бы считать сумму от суммы.
    ...(summa ? { summa } : {}),
  };
}

/**
 * Сумма содержимого файла вывоза: sha256 по строкам записей, без заголовка.
 * 🔴 ФУНКЦИЯ ОДНА НА ОБЕ СТОРОНЫ. Две реализации «одного и того же» разошлись бы молча —
 * этот класс у нас уже стоил трёх разошедшихся списков.
 */
export function summa_soderzhimogo(stroki) {
  return 'sha256:' + createHash('sha256').update(stroki.join('\n'), 'utf8').digest('hex').slice(0, 32);
}

/**
 * Разбор заголовка при ввозе. Чужая версия — ОТКАЗ, база не тронута.
 * Отсутствие заголовка — тоже отказ: файл без самоописания читать нечем.
 */
export function proverit_zagolovok(z) {
  if (!z || typeof z !== 'object') {
    throw new OtkazShemy('первая строка файла не заголовок — читать нечем', 'VYVOZ_NET_ZAGOLOVKA');
  }
  if (z.vyvoz !== 'dsh-pamyat') {
    throw new OtkazShemy(`это не файл вывоза памяти (vyvoz=${JSON.stringify(z.vyvoz)})`, 'VYVOZ_NE_NASH_FAJL');
  }
  if (z.versiya_shemy !== VERSIYA_SHEMY) {
    throw new OtkazShemy(
      `версия схемы файла ${JSON.stringify(z.versiya_shemy)}, а этот пакет знает ${VERSIYA_SHEMY}. `
      + 'Читать чужую версию догадкой нельзя: поле могло не появиться, а поменять смысл',
    );
  }
  return z;
}
