import { DatabaseSync } from 'node:sqlite';
/**
 * ЗАПИСЬ В ЖУРНАЛ ОПЕРАЦИЙ (ворота В8).
 *
 * 🔴 ЗАЧЕМ. Вывоз выносит память НАРУЖУ, ввоз МЕНЯЕТ базу — обе операции меняют
 * состояние машины и обе до сих пор не оставляли следа. Через неделю на вопрос
 * «эта запись пришла извне или родилась здесь» ответить было бы нечем, а на вопрос
 * «что и когда уезжало с машины» — тем более.
 *
 * 🔴 ОТКАЗ ЖУРНАЛА НЕ ОТМЕНЯЕТ ОПЕРАЦИЮ И НЕ МОЛЧИТ. Не смогли записать след — говорим
 * вслух и продолжаем: журнал сторожит историю, а не разрешает работу. Обратный порядок
 * (нет журнала — нет вывоза) сделал бы отказ журнала отказом всего, а это не та цена.
 * Но и глотать отказ нельзя: «в журнале ничего нет» читалось бы как «операций не было».
 *
 * ⚠️ ГРАНИЦА: журнал ведётся у ТОЙ базы, которую трогает операция. Вывоз читает базу
 * только на чтение, поэтому свою строку он пишет отдельным соединением на запись —
 * и если база чужая или недоступна на запись, след не появится, о чём будет сказано.
 */
export function zapisat_v_zhurnal({ baza, agent = 'vyvoz', klass, ishod, priroda, pochemu, istochnik, krik }) {
  let db;
  try {
    db = new DatabaseSync(baza);
    const est = db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name='zhurnal'").get();
    if (!est) {
      // Таблицы нет — это не поломка: база может быть чужой схемы. Но молчать нельзя.
      throw new Error('таблицы zhurnal в этой базе нет');
    }
    db.prepare('INSERT INTO zhurnal (kogda, agent, klass, ishod, priroda, pochemu, istochnik) VALUES (?,?,?,?,?,?,?)')
      .run(Date.now(), agent, klass, ishod, priroda ?? null, pochemu, istochnik ?? null);
    return true;
  } catch (e) {
    if (krik) krik(`⚠️ след в журнале НЕ записан (${e?.message ?? e}): операция состоялась, но истории о ней не осталось`);
    return false;
  } finally {
    try { db?.close(); } catch { /* закрывать нечего */ }
  }
}
