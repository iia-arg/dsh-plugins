# ── Разметка телеграма. Строка с «<» или «&» роняет отправку целиком (400
# «can't parse entities»). Обратная косая перед «&» обязательна: в правой части
# ${s//что/на_что} голый «&» значит «всё совпадение», как в sed, и «&lt;»
# превратилось бы в «<lt;» — текст выглядит почти верным, а телеграм отказывает.
esc() {
  local s="${1-}"
  s="${s//&/\&amp;}"; s="${s//</\&lt;}"; s="${s//>/\&gt;}"
  printf '%s' "$s"
}

# Обрезка сырья: сначала по строкам, потом по знакам. `cut -c` режет по БАЙТАМ
# и локаль игнорирует — на русском тексте обрыв приходится на середину буквы,
# и телеграм отвечает 400 «text must be encoded in UTF-8». ${l:0:N} считает
# знаки, потому что локаль задана выше.
# 🔴 printf '%s\n' в конце важен: `read` не отдаёт последнюю строку, если во
# входе нет завершающего перевода строки, — подаём вход через here-string,
# он перевод добавляет.
syroe() {
  local text="$1" n=0 l out=""
  while IFS= read -r l; do
    n=$((n+1)); [ "$n" -gt "$RAW_LINES" ] && { out+="… (дальше обрезано)"$'\n'; break; }
    out+="${l:0:$RAW_CHARS}"$'\n'
  done <<< "$text"
  printf '%s' "$out"
}

