    else
      slepota+=("живость: повторный ответ не разобран (вердиктов $h_verdikt, записей ${h_vsego:-?}, без id $h_bez_id); состав не сохранён")
      bylo_dvizhenie=0
    fi
    [ "$AVTO_MONTAZH" = 1 ] && [ -n "$h_defer" ] && otlozheno+=("$h_defer")
    if [ "$h_bez" -gt "$HEALTH_UNCHECKED_MAX" ]; then
      razoshlos+=("живость: записей без проверки $h_bez при пороге $HEALTH_UNCHECKED_MAX — непроверяемая запись не считается здоровой")
    fi
  fi
fi

# ── 4. Сторож машины: работает ли ОН. Взаимность, а не самопроверка.
#
# ЗАЧЕМ ЗДЕСЬ. Сторож машины стережёт наши таймеры (SERVICES в его настройке), а
# его самого не стерёг никто: его молчание неотличимо от «всё хорошо». Проверять
# себя он не может по устройству — мёртвый механизм не сообщает о своей смерти.
# Поэтому наблюдение вынесено в СОСЕДНИЙ механизм: он смотрит на нас каждые пять
# минут, мы на него — раз в сутки. Разные юниты, разные расписания, разные руки.
#
# ТРИ ПРИЗНАКА, И ОНИ ЛОВЯТ РАЗНОЕ — ни один не заменяет другой:
#   1. таймер числится активным      — ловит снятый или остановленный таймер сразу;
#   2. последняя запись не старше N  — ловит «числится активным, а не срабатывает»
#      (на этой машине такое было 21.08.2026: NextElapse=infinity при active);
#   3. заходов за сутки не меньше M  — ловит «работает рывками»: и таймер жив, и
#      последний заход свеж, а половина суток пропущена.
#
# 🔴 ПОЧЕМУ СЧЁТ ПО MESSAGE_ID, А НЕ ПО ТЕКСТУ ЖУРНАЛА. Считать строки «ok: всё
# проверенное в порядке» значило бы привязать наш предел к чужой формулировке:
# сосед поменяет слово — счёт молча упадёт до нуля, и мы пошлём ложную тревогу о
# его смерти. MESSAGE_ID ставит systemd, это постоянный идентификатор события
# «юнит успешно завершил заход», он не зависит ни от текста, ни от локали.
#
# 🔴 И ПОЧЕМУ НЕ ПО _SYSTEMD_INVOCATION_ID, хотя он тоже структурный и на первый
# взгляд точнее. Замер 24.08.2026: это поле несут ТОЛЬКО строки самого процесса
# службы (_COMM=bash), а строки systemd[1] «Starting/Finished» — нет. Значит счёт
# уникальных invocation меряет не «сколько было заходов», а «сколько заходов
# что-то напечатали»: у apt-daily.service, которая молчит, он дал 0 при двух
# настоящих заходах. Признак выглядел структурным, а держался на поведении
# соседа — ровно то, от чего я уходила, отказываясь считать по тексту.
#
# 🔴 ЧЕГО ЭТОТ БЛОК НЕ ЛОВИТ — читать до того, как счесть круг разорванным:
#   • одновременную смерть обоих сторожей (перезагрузка, не поднявшая таймеры;
#     загрузка, застрявшая на чужом юните). Оба молчат — сказать некому. Внутри
#     одной машины это не лечится: наблюдатель за смертью обязан жить снаружи
#     наблюдаемого, а снаружи у нас с 24.08.2026 никого нет по решению владельца;
#   • задержку до суток: сосед замечает нашу смерть за пять минут, мы его — на
#     следующем прогоне. Это цена того, что мы ходим раз в сутки, а не защита;
#   • «сторож машины запускается, но ничего не проверяет» — заходы идут, счёт
#     сходится, а внутри у него пустой список служб. Это его собственное дело.
peer_itog=""
if [ "$PEER_ENABLED" = "1" ]; then
  peer_beda=0
  peer_active="$(systemctl is-active "$PEER_TIMER" 2>&1 | head -1)"
  if [ "$peer_active" != "active" ]; then
    razoshlos+=("сторож машины: таймер $PEER_TIMER не активен ($peer_active) — беды машины ловить некому")
    peer_beda=1
  fi

  # Свежесть и полнота — из журнала. Отказ чтения журнала это СЛЕПОТА, а не
  # «сосед мёртв»: пустой ответ здесь чаще про наши права, чем про соседа.
  peer_ts="$(journalctl -u "$PEER_UNIT" -n 1 --no-pager -o short-unix 2>/dev/null | tail -1 | cut -d" " -f1 | cut -d. -f1)"
  if ! printf '%s' "${peer_ts:-}" | grep -qE '^[0-9]+$'; then
    slepota+=("сторож машины: журнал $PEER_UNIT не читается или пуст — измерить его работу нечем")
    peer_itog="сторож машины: НЕ ИЗМЕРЕН (журнал недоступен), таймер $peer_active"
  else
    peer_vozrast=$(( (now - peer_ts) / 60 ))
    peer_zahodov="$(journalctl -u "$PEER_UNIT" --since "-24 hours" "MESSAGE_ID=$PEER_DONE_MSGID" --no-pager -o cat 2>/dev/null | wc -l)"
    # 🔴 ТА ЖЕ БЕДА У СВЕЖЕСТИ. Сразу после загрузки последний заход соседа —
    # из ПРЕЖНЕЙ загрузки, и возраст его равен простою машины. Замер 28.08:
    # догоняющий прогон через 45 с после старта увидел «849 мин назад» и
    # объявил живого соседа мёртвым. Пока с загрузки не прошло столько же,
    # сколько мы даём соседу на заход, спрашивать не о чем — это СЛЕПОТА,
    # а не расхождение: сосед ещё не обязан был отработать.
    peer_uptime_min=$(( ( now - $(date -d "$(uptime -s)" +%s 2>/dev/null || echo "$now") ) / 60 ))
    if [ "$peer_uptime_min" -lt "$PEER_FRESH_MIN" ]; then
      peer_itog_pripiska=" | свежесть не проверялась: с загрузки $peer_uptime_min мин из $PEER_FRESH_MIN"
    elif [ "$peer_vozrast" -gt "$PEER_FRESH_MIN" ]; then
      razoshlos+=("сторож машины: последний заход $peer_vozrast мин назад при пороге $PEER_FRESH_MIN (таймер $peer_active) — числится живым, а не работает")
      peer_beda=1
    fi
    # 🔴 ПРОСТОЙ МАШИНЫ. Порог 250 выведен из суток непрерывной работы (288
    # заходов по 5 мин). После перезагрузки за сутки НЕ БЫЛО суток, и счёт
    # законно меньше — сторож сказал бы «работает рывками» об исправном
    # соседе. Замер 28.08.2026: машина стояла 14 ч, счёт дал 119 при пороге
    # 250, и это была ложная тревога. Разделитель между «работал рывками» и
    # «машины не было» один — ВРЕМЯ ЗАГРУЗКИ, поэтому порог считается от него.
    # ГДЕ НЕ ДЕЙСТВУЕТ: не спасает, если машина перезагружается постоянно —
    # тогда порог всегда мал и сторож слеп; за частыми перезагрузками следит
    # не эта проверка, а NRestarts и сам факт смены boot_id.
    if [ "$peer_uptime_min" -lt 1440 ] && [ "$peer_uptime_min" -ge 0 ]; then   # №35 аудита 16: -ge — минута 0 не даёт порог 250
      # столько же процентов от возможного, сколько 250 от 288
      peer_porog=$(( peer_uptime_min * PEER_MIN_PER_DAY / 1440 ))
      peer_porog_ist="от загрузки, машина работает $peer_uptime_min мин"
    else
      peer_porog="$PEER_MIN_PER_DAY"
      peer_porog_ist="за сутки"
    fi
    if [ "$peer_zahodov" -lt "$peer_porog" ]; then
      razoshlos+=("сторож машины: заходов $peer_zahodov при пороге $peer_porog ($peer_porog_ist) — работает рывками")
      peer_beda=1
    fi
    peer_itog="сторож машины: таймер $peer_active, последний заход $peer_vozrast мин назад, заходов $peer_zahodov (пороги $PEER_FRESH_MIN мин / $peer_porog $peer_porog_ist)${peer_itog_pripiska:-}"
  fi
  [ "$peer_beda" = "1" ] && syroe_bloki+="── journalctl -u ${PEER_UNIT} -n 5"$'\n'"$(syroe "$(journalctl -u "$PEER_UNIT" -n 5 --no-pager -o short-iso 2>&1)")"$'\n'
fi

# Перед вердиктом/каналом проверяем каждый названный ID общим parser; без локального JSON окон.
if [ "$AVTO_MONTAZH" = 1 ] && [ "${#otlozheno[@]}" -gt 0 ]; then
  _mo_markers=$(printf '%s\n' "${otlozheno[@]}")
  if [ -z "$_mo_markers" ] || printf '%s\n' "$_mo_markers" | grep -vEq '^ОТЛОЖЕНО [0-9a-f]{32}( .*)?$'; then
    echo 'СЛЕПОТА: форма отложенного результата не узнана' >&2; exit 2
  fi
  while read -r _mo_id; do
    [ -n "$_mo_id" ] || continue
    timeout -k 1s 6s "${MONTAZH_OKNO_BIN:-/usr/local/sbin/montazh-okno}" aktivno-id --avto-montazh "$_mo_id" >/dev/null 2>&1; _mo_code=$?
    if [ "$_mo_code" != 4 ]; then
      if [ "${REGWD_MO_RESCAN:-0}" = 0 ]; then
        export REGWD_MO_RESCAN=1; echo 'ПЕРЕСНИМАЮ: окно перестало действовать до отправки'; exec bash "$0" --avto-montazh
      fi
      echo 'СЛЕПОТА: отсрочка повторно изменилась после пересъёма' >&2; exit 2
    fi
  done < <(printf '%s\n' "${otlozheno[@]}" | sed -nE 's/^ОТЛОЖЕНО ([0-9a-f]{32})( .*)?$/\1/p' | sort -u)
fi

# ── Вердикт. Слепота сильнее расхождения: «не смог измерить» означает, что
# и про остальное мы знаем меньше, чем думаем.
if [ "${#slepota[@]}" -gt 0 ]; then verdikt=СЛЕПОТА; kod=2
elif [ "${#razoshlos[@]}" -gt 0 ]; then verdikt=РАСХОЖДЕНИЕ; kod=1
elif [ "${#health_slepota[@]}" -gt 0 ]; then verdikt="СЛЕПОТА ПРОВЕРОК"; kod=1
elif [ "$AVTO_MONTAZH" = 1 ] && [ "${#otlozheno[@]}" -gt 0 ]; then verdikt=ОТЛОЖЕНО; kod=4
else verdikt=ЗЕЛЕНО; kod=0
fi

# ── Разрыв: когда сторож запускался в прошлый раз.
razryv=""
if [ -r "$STATE/last-run.stamp" ]; then
  prev=$(cat "$STATE/last-run.stamp" 2>/dev/null || echo 0)
  sutok=$(( (now - prev) / 86400 ))
  if [ "$sutok" -ge "$GAP_DAYS" ]; then
    razryv="перерыв: прошлый прогон был $sutok сут. назад ($(date -d "@$prev" -Is)) — сторож всё это время не работал"
  fi
  pervyj_zapusk=0
else
  pervyj_zapusk=1
fi

# ── Что ставил apt за сутки. Это сырьё для человека: расхождение сразу читается
# вместе с причиной. Само по себе тревогой не является — обновление это норма.
apt_stroki=""
if [ -r "$DPKG_LOG" ]; then
  # 🔴 ЧИСЛО СЧИТАЕТСЯ ДО ОБРЕЗКИ (03.09.2026). Прежде список резался `head -12`,
  # число бралось от обрезанного, а в сообщение шли первые 6 — то есть печаталось
  # «12 пакетов» при 79 настоящих и шести показанных. Замер 03.09: настоящих 79.
  # Строка, которой нельзя верить, хуже отсутствующей: по числу принимают решение.
  apt_vse="$(awk -v d="$(date -d '25 hours ago' '+%Y-%m-%d %H:%M:%S')" \
    '$1" "$2 >= d && ($3=="upgrade"||$3=="install") {print $3" "$4" "$6}' "$DPKG_LOG" 2>/dev/null)"
  apt_stroki="$(printf '%s\n' "$apt_vse" | head -12)"
fi
apt_skolko=$( [ -n "${apt_vse:-}" ] && printf '%s\n' "$apt_vse" | wc -l || echo 0 )

# ── Печать в журнал: вердикт и сырьё рядом. Вердикт без сырья непроверяем —
# ложно-красное в нём живёт незамеченным до первого настоящего отказа.
echo "сторож реестров: $verdikt (код $kod)"
# «Запущен рукой» — КТО ПРОГНАЛ СТОРОЖА, а не кто правил реестр. Прежняя надпись
# «рукой:» читалась как свидетельство о чужом действии, по которому ищут виноватого.
echo "  запущен рукой: $ruka   время: $zapusk"
# Живость печатается ТРЕМЯ числами, а не одним: молчат — беда объекта; доложили
# находку и проверить нечем — доклады работающих проверок. Свести их в одно
# «красных N» значит потерять различение, ради которого коды и разведены.
echo "  реестр машины: код $v_code | реестр доработок: код $d_code | живость: молчат ${h_krasnyh:-—}, доложили находку ${h_nashli:-—}, проверить нечем ${h_nechem:-—} — из ${h_vsego:-—}"
# Движение состава печатается ОТДЕЛЬНОЙ строкой и ИМЕНАМИ: «столько же» скрывает подмену
# причины — 02.09 краснели расхождения реестров, 03.09 живость, а число не менялось.
[ -n "${dvizhenie:-}" ] && echo "  состав молчащих и слепых: $dvizhenie"
[ "${#propushcheno[@]}" -gt 0 ] && echo "  пропущено по настройке (НЕ проверялось): ${propushcheno[*]}"
[ -n "$zdorovie_itog" ] && echo "  $zdorovie_itog"
[ -n "$peer_itog" ] && echo "  $peer_itog"
[ -n "$razryv" ] && echo "  $razryv"
# 🔴 ОБЕЩАНИЕ СЧИТАЕТСЯ ОТ ФАКТИЧЕСКИ НАПЕЧАТАННОГО (03.09.2026, правка server).
# Прежде строка обещала «ниже показаны 12», а НИЖЕ не печаталось ничего: список уходил
# только в тревогу, и то первыми шестью. Три числа про один перечень — 79 настоящих,
# 12 обещанных, 6 доставленных, 0 в журнале. Теперь обещание и показ берутся из ОДНОЙ
# величины $pokaz, и при нуле список не обещается вовсе.
if [ "${apt_skolko:-0}" -eq 0 ]; then
  echo "  apt за сутки: 0 пакетов"
else
  pokaz=12
  [ "$apt_skolko" -lt "$pokaz" ] && pokaz="$apt_skolko"
  if [ "$apt_skolko" -gt "$pokaz" ]; then
    echo "  apt за сутки: $apt_skolko пакетов (ниже показаны $pokaz; полностью — $DPKG_LOG)"
  else
    echo "  apt за сутки: $apt_skolko пакетов (все показаны ниже)"
  fi
  printf '%s\n' "$apt_stroki" | head -"$pokaz" | sed 's/^/    /'
fi
for x in "${razoshlos[@]:-}"; do [ -n "$x" ] && echo "  РАСХОЖДЕНИЕ: $x"; done
for x in "${slepota[@]:-}"; do [ -n "$x" ] && echo "  СЛЕПОТА: $x"; done
for x in "${health_slepota[@]:-}"; do [ -n "$x" ] && echo "  СЛЕПОТА ПРОВЕРОК: $x"; done
for x in "${otlozheno[@]:-}"; do [ -n "$x" ] && printf '%s\n' "$x"; done
[ -n "$syroe_bloki" ] && { echo "── сырьё:"; printf '%s' "$syroe_bloki"; }

# ── Надо ли говорить человеку.
povod=""
if [ "$kod" -eq 4 ]; then povod=""
elif [ "$kod" -ne 0 ]; then povod="беда"
elif [ "$pervyj_zapusk" = "1" ]; then povod="заведён"
elif [ -n "$razryv" ]; then povod="разрыв"
else
  molchal=$(( (now - $(cat "$STATE/last-spoke.stamp" 2>/dev/null || echo 0)) / 86400 ))
  [ "$molchal" -ge "$HEARTBEAT_DAYS" ] && povod="жив"
fi

soobshenie=""
case "$povod" in
  беда)
    # 🔴 СРОЧНОЕ — ТОЛЬКО НА ДВИЖЕНИЕ. Ежедневное 🔴 про неизменившееся состояние
    # приучает не читать: длящееся не новость. Слепота самого прибора остаётся ⚠️ всегда — она
    # означает «не измерено», и её давность не делает её менее срочной.
    if [ "$verdikt" = СЛЕПОТА ]; then znak="⚠️"
    elif [ "${bylo_dvizhenie:-1}" -eq 0 ]; then znak="•"
    else znak="🔴"; fi
    soobshenie="$znak сторож реестров: <b>$verdikt</b>
рукой: $(esc "$ruka"), $(esc "$zapusk")"
    for x in "${razoshlos[@]:-}"; do [ -n "$x" ] && soobshenie+=$'\n'"• $(esc "$x")"; done
    for x in "${slepota[@]:-}"; do [ -n "$x" ] && soobshenie+=$'\n'"• $(esc "$x")"; done
    for x in "${health_slepota[@]:-}"; do [ -n "$x" ] && soobshenie+=$'\n'"• $(esc "$x")"; done
    [ -n "$razryv" ] && soobshenie+=$'\n'"• $(esc "$razryv")"
    soobshenie+=$'\n'"apt за сутки: $apt_skolko пакетов"
    # Обрезка НАЗЫВАЕТ СЕБЯ: молчаливая делает число и список разными сведениями.
    [ "$apt_skolko" -gt 0 ] && soobshenie+=$'\n'"<code>$(esc "$(printf '%s\n' "$apt_stroki" | head -6)")</code>"
    [ "$apt_skolko" -gt 6 ] && soobshenie+=$'\n'"(показаны 6 из $apt_skolko)"
    soobshenie+=$'\n'"сырьё:
<code>$(esc "$(syroe "$syroe_bloki")")</code>
Сторож не чинит и не судит, законно ли расхождение. Свести реестр после своей правки и восстановить после чужой — снаружи одно и то же."
    ;;
  заведён)
    soobshenie="🟢 сторож реестров заведён и прошёл первый круг: <b>$verdikt</b>
рукой: $(esc "$ruka"), $(esc "$zapusk")
Дальше говорю только при беде, при разрыве и раз в $HEARTBEAT_DAYS сут. — «жив». Молчание $HEARTBEAT_DAYS сут. подряд означает, что сторож умер."
    ;;
  разрыв)
    soobshenie="⚠️ сторож реестров: <b>$verdikt</b>, но был перерыв
рукой: $(esc "$ruka"), $(esc "$zapusk")
$(esc "$razryv")
Проверенное сошлось, но всё это время его никто не проверял."
    ;;
  жив)
    soobshenie="🟢 сторож реестров жив: <b>$verdikt</b>, молчал $molchal сут.
рукой: $(esc "$ruka"), $(esc "$zapusk")
apt за сутки: $apt_skolko пакетов. Это не отчёт о здоровье машины, а доказательство, что сам сторож работает."
    ;;
esac

if [ -n "$soobshenie" ]; then
  if [ ! -x "$ALERT" ]; then
    echo "🔴 нет помощника $ALERT — человеку НЕ сказано. Отметку не ставлю, повторю в следующий заход"
    kod=2
  else
    out="$("$ALERT" "$soobshenie" 2>&1)"; rc=$?
    if [ "$rc" -eq 0 ]; then
      echo "  сказано человеку (повод: $povod)"
      # 🔴 Отметка ставится ТОЛЬКО после подтверждённой доставки. Стояла бы до —
      # недоставленная тревога заглушила бы себя на HEARTBEAT_DAYS суток.
      date +%s > "$STATE/last-spoke.stamp"
    else
      echo "🔴 тревога НЕ доставлена (код $rc): $out — отметку не ставлю, повторю в следующий заход"
      kod=2
    fi
  fi
else
  if [ "$kod" -eq 4 ]; then
    echo "  человеку не сказано: сверки отложены в окне монтажа; это не зелёный результат"
  else
    echo "  человеку не сказано: зелено, разрыва нет, до отчёта о живости ещё $(( HEARTBEAT_DAYS - molchal )) сут."
  fi
fi

# Отметка о самом прогоне ставится всегда — она про то, что сторож РАБОТАЛ,
# а не про то, что он сумел дозвониться.
date +%s > "$STATE/last-run.stamp"
printf '%s\n' "$verdikt" > "$STATE/last-verdict"
exit "$kod"
