#!/usr/bin/env bash
# Сторож реестров: замечает, что НАС обновили.
#
# ЗАЧЕМ. Наши доработки лежат вне пакетов, и любое обновление способно затереть
# их молча: служба останется active, ошибки не будет, а механизм перестанет
# работать. Этот сторож раз в сутки спрашивает у двух реестров: совпадает ли
# записанное с тем, что на машине.
#
# 🔴 ЧТО ИЗМЕНИЛОСЬ 23.08.2026. Автоматическая УСТАНОВКА обновлений на машине
# выключена (apt-daily-upgrade.timer замаскирован, APT::Periodic::Unattended-
# Upgrade "0"), обновляем руками. Значит «день обновления» больше не наступает
# сам собой — но сторож нужен ровно так же: он ловит не только обновление, а
# ЛЮБУЮ порчу, включая нашу собственную несведённую правку. Прежнее обоснование
# («обновление приходит без нас, ежедневно») здесь стояло до этой даты и теперь
# неверно; время прогона осталось прежним по другой причине — см. таймер.
#
# ПРИНЦИП. Сторож не чинит и не судит, законно ли расхождение. Он меряет и зовёт
# человека. Решение — за человеком: сведение реестра после СВОЕЙ правки и
# восстановление после ЧУЖОЙ выглядят одинаково, различить их может только тот,
# кто знает намерение.
#
# ДИСЦИПЛИНА, РАДИ КОТОРОЙ ОН ЗАВЕДЁН (сформулирована координатором 23.08.2026):
#   В день обновления мы обязаны отличить «затёрло обновлением» от «мы сами не
#   свели». Отличить можно ТОЛЬКО если ДО обновления реестр был зелёным. Значит
#   намеренная правка не закончена, пока реестр не сведён. Ежедневный прогон
#   делает это правило самоподдерживающимся: не свёл — узнаешь назавтра, а не
#   в день беды.
#
# ТРИ ИСХОДА И ТРИ КОДА ВОЗВРАТА — «не смог измерить» это НЕ «сошлось»:
#   0  ЗЕЛЕНО      — всё проверенное сошлось
#   1  РАСХОЖДЕНИЕ — записанное разошлось с машиной
#   2  СЛЕПОТА     — измерить не удалось (инструмент не запустился, форма вывода
#                    не узнана, реестр не читается). Тревога уходит и здесь.
#     Код 2 ставится и тогда, когда мерить удалось, а СКАЗАТЬ человеку не вышло:
#     недоставленная тревога — это тоже «сторож не отработал», и юнит обязан
#     числиться упавшим, иначе молчание сойдёт за спокойствие.
#
# 🔴 ГДЕ ЭТОТ СТОРОЖ НЕ ПРИМЕНЯЕТСЯ — читать до того, как на него положиться:
#   • Он НЕ замечает собственной смерти. Выключенный таймер, снятый юнит, лежащая
#     машина — молчание, а молчание тут неотличимо от «всё хорошо». Поэтому:
#       — раз в HEARTBEAT_DAYS суток он говорит «жив, столько-то суток зелено»
#         (изнутри: доказывает, что запуски идут);
#       — при запуске после перерыва больше GAP_DAYS суток он говорит об этом
#         отдельно (изнутри: доказывает, что перерыв БЫЛ);
#       — снаружи за таймером следит сторож машины: registry-watchdog.timer
#         добавлен в SERVICES файла /etc/agent-watchdog/watchdog.conf, и его
#         неактивность замечается за пять минут.
#     🔴 Ни одно из трёх не ловит «таймер числится активным, но не срабатывает».
#     Этот случай виден только по разрыву — то есть ПОСЛЕ того, как сторож всё же
#     запустится. Полностью закрыть дыру изнутри нельзя: наблюдатель за смертью
#     обязан жить снаружи наблюдаемого.
#   • 🔴 ВЗАИМНОСТЬ (24.08.2026). Обратная половина заведена здесь же: блок 4
#     проверяет, что сторож машины работает — тремя признаками, а не одним
#     is-active. Круг это НЕ разрывает: одновременная смерть обоих сторожей
#     по-прежнему никем не замечается, потому что снаружи машины наблюдателя
#     нет и не будет (решение владельца 24.08.2026: всё, что обслуживает эту
#     машину, живёт на ней самой). Взаимность понижает вероятность, а не
#     устраняет случай — читать её как гарантию нельзя.
#   • Разбор живости НЕ отличает «объект мёртв» от «спрашивающий не вправе его
#     проверить»: инструмент печатает НЕ ОТВЕЧАЕТ в обоих случаях. Прогнанный
#     чужой рукой, сторож назовёт это расхождением. Вердикт от этого не портится
#     (чужой рукой краснеет и сам реестр, а слепота сильнее расхождения), но,
#     читая тревогу, смотри на строку «рукой:» — она затем и печатается.
#   • Он НЕ проверяет чужие дома, содержимое секретов и побайтную целость дерева
#     платформы. Первое — не наше, второе — нельзя, третье меряется по mtime и
#     подмену с сохранением времени не поймает.
#   • Он НЕ спрашивает источники, вышло ли новое (это `agent-plugins check`, ему
#     нужна сеть). Вопрос «цело ли наше» и вопрос «есть ли свежее» — разные.
#   • Окна тишины (cooldown) здесь НЕТ намеренно, в отличие от сторожа машины.
#     Прогон один в сутки; стоящее расхождение обязано повторяться каждый день,
#     иначе долг становится невидимым — а он и есть то, ради чего всё заведено.
