    for id in $(printf '%s\n' "$v_out" | sed -n 's/^СЛЕПОТА \([^ ]*\) .*/\1/p' | sort -u); do
      case " $VERIFY_IZVESTNAYA_SLEPOTA " in *" $id "*) v_izv="$v_izv $id" ;; *) v_novye="$v_novye $id" ;; esac
    done
    if [ -n "$v_izv$v_novye" ]; then
      v_slep_uznana=1
      [ -n "$v_izv" ] && echo "реестр машины: известная слепота verify (перечень VERIFY_IZVESTNAYA_SLEPOTA, без тревоги):$v_izv"
      [ -n "$v_novye" ] && slepota+=("реестр машины: код 2, СЛЕПОТА записей:$v_novye")
    fi
  fi
  # Ни одна примета не совпала, а код ненулевой — значит инструмент сломался или
  # сменил слова. Это слепота, а не «всё хорошо».
  if [ "${#razoshlos[@]}" -eq "$r_do" ] && [ "${#slepota[@]}" -eq "$s_do" ] && [ "$v_slep_uznana" -eq 0 ]; then
    slepota+=("реестр машины: код $v_code, вывод не узнан")
  fi
  # В сырьё идут ТОЛЬКО непустые строки-несовпадения: строк «совпадает» три
  # десятка, и они вытесняют из обрезанной тревоги именно то, ради чего она
  # послана. Отбор влияет на ПОКАЗ, а не на вердикт — вердикт уже решён кодом
  # возврата выше, так что смена слов в инструменте способна лишь показать
  # лишнее, но не спрятать беду.
  syroe_bloki+="── ${VERIFY_CMD} (код $v_code)"$'\n'"$(syroe "$(printf '%s' "$v_out" | grep -vE '^совпадает')")"$'\n'
fi

