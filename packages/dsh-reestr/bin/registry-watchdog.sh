  # B-N-1773: код 2 и строки «СЛЕПОТА <id> …» (форма verify с B-N-1765) — по именам. Известная — в журнал, новая — в тревогу.
  v_slep_uznana=0
  if [ "$v_code" -eq 2 ]; then
