#!/usr/bin/env bash
# srez-obshchego-kataloga — однозначный срез того, ЧТО ЗАГРУЗИТСЯ из общего каталога плагинов.
#
# ЗАЧЕМ. 04.09.2026 три человека дали три разных ответа про один каталог, и все три были
# верны — для своего момента. Спор стоил часа. Причина не в небрежности: срез снимают, письмо
# пишут, письмо читают — и между этими тремя моментами предмет успевает измениться.
#
# 🔴 ПОЭТОМУ ПЕРВЫМИ ПЕЧАТАЮТСЯ МАШИНА И ВРЕМЯ, А НЕ ЧИСЛА. Число без отметки момента
# неопровержимо и потому бесполезно: на него нельзя возразить и нельзя его перемерить.
#
# 🔴 И ВТОРОЕ: СПОСОБ ПОДКЛЮЧЕНИЯ У СОСЕДНИХ ПАКЕТОВ РАЗНЫЙ (находка Михалыча, 04.09).
#   по ИМЕНИ — лежит в node_modules, разрешается require.resolve
#   по ПУТИ  — лежит каталогом рядом, к node_modules отношения не имеет
# Один и тот же признак на них отвечает на РАЗНЫЕ вопросы: запрос по имени к пакету,
# подключённому путём, даёт MODULE_NOT_FOUND на совершенно исправном предмете.
#
# ГДЕ НЕ ПРИМЕНЯЕТСЯ: не говорит, что в БОЮ — только что загрузится при СЛЕДУЮЩЕМ подъёме.
# Работающая служба держит редакцию, прочитанную при своём старте; её версию спрашивают
# у журнала службы, а не у диска.
set -uo pipefail
# №9 аудита 16: довод — один каталог; ключ (--help и т.п.) — отказ, а не «каталог --help» с кодом 2.
case "${1-}" in
  -h|--help) echo "srez-obshchego-kataloga [каталог] — срез общего каталога модулей (умолчание /opt/agent-plugins). Коды: 0 срез снят · 2 каталога нет."; exit 0 ;;
  -*) echo "ОТКАЗ: неизвестный ключ ${1} — довод один: каталог" >&2; exit 2 ;;
esac
[ "$#" -le 1 ] || { echo "ОТКАЗ: доводов больше одного ($#) — довод один: каталог" >&2; exit 2; }
KAT="${1:-/opt/agent-plugins}"

echo "машина:  $(hostname)"
echo "время:   $(date -u '+%Y-%m-%d %H:%M:%SZ') (UTC)"
echo "каталог: $KAT"
[ -d "$KAT" ] || { echo "🔴 каталога нет на этой машине — срез не о нём"; exit 2; }

echo
echo "--- манифест (что ОБЪЯВЛЕНО), правлен $(stat -c '%y' "$KAT/package.json" 2>/dev/null | cut -d. -f1)"
if [ -f "$KAT/package.json" ]; then
  node -e '
    const j=require(process.argv[1]+"/package.json");
    const d=j.dependencies??{};
    const k=Object.entries(d).filter(([,v])=>String(v).startsWith("^"));
    for (const [i,v] of Object.entries(d)) console.log("    "+i.padEnd(26)+v);
    console.log("    крышек ^: "+k.length+(k.length?"  🔴 следующий npm install утянет метку: "+k.map(([i])=>i).join(", "):""));
  ' "$KAT"
else
  echo "    манифеста нет"
fi

echo
echo "--- ПО ИМЕНИ (node_modules): что разрешится"
node -e '
  const {createRequire}=require("node:module");
  const path=require("node:path"), fs=require("node:fs");
  const koren=process.argv[1];
  const nm=path.join(koren,"node_modules");
  let imena=[];
  try { imena=fs.readdirSync(nm).filter(x=>!x.startsWith(".")).flatMap(x=>
    x.startsWith("@") ? fs.readdirSync(path.join(nm,x)).map(y=>x+"/"+y) : [x]); } catch {}
  const trebuj=createRequire(path.join(koren,"x.js"));
  const versiya=(vhod,imya)=>{
    let d=path.dirname(vhod);
    let chuzhoe=null;
    for (let i=0;i<8;i++){
      try { const j=JSON.parse(fs.readFileSync(path.join(d,"package.json"),"utf8"));
            if (j.name===imya) return [j.version,d];
            if (!chuzhoe && j.name) chuzhoe=[j.name,j.version,d]; } catch {}
      d=path.dirname(d);
    }
    // 🔴 МАНИФЕСТ ЕСТЬ, НО ИМЯ В НЁМ ДРУГОЕ (09.09.2026). Прежде такой каталог печатался как
    // «версия не найдена?» — то есть прибор сомневался вслух, но беды НЕ НАЗЫВАЛ. А это
    // копия боевого пакета под другим именем каталога: шесть таких (.staryj) лежали в
    // области разрешения, и npm уже отвечал по ним ELSPROBLEMS, пока срез молчал знаком
    // вопроса. Имя каталога — соглашение, имя в манифесте — факт; печатаем факт.
    // ГДЕ НЕ ПРИМЕНЯЕТСЯ: расхождение имён САМО ПО СЕБЕ не дефект — у нас есть законные
    // (каталог claude-oauth несёт dsh-subscription-adapter, mcp-bridge несёт dsh-tool-bridge,
    // оба разрешаются ссылкой из профиля). Дефект — когда такое имя ДУБЛИРУЕТ боевое;
    // это видно строкой выше в том же выводе, и судит человек, а не прибор.
    if (chuzhoe) return ["🔴 копия, имя пакета: "+chuzhoe[0]+" "+chuzhoe[1]+"  ", chuzhoe[2]];
    return ["версия не найдена","?"];
  };
  for (const imya of imena) {
    try { const [v,d]=versiya(trebuj.resolve(imya),imya);
          console.log("    "+imya.padEnd(28)+String(v).padEnd(17)+d); }
    catch(e){
      // 🔴 «Не разрешается» — НЕ всегда дефект. Пакет-зонтик (объявляет зависимости, несёт
      // состав и описание) точки входа не имеет ПО ЗАМЫСЛУ, и запрос по имени к нему —
      // вопрос не о том. Различаем, иначе прибор поднимает ложную тревогу на исправном.
      let m={};
      try { m=JSON.parse(fs.readFileSync(path.join(nm,imya,"package.json"),"utf8")); } catch {}
      const vhoda_net = !m.main && !m.exports
        && !fs.existsSync(path.join(nm,imya,"index.js"))
        && !fs.existsSync(path.join(nm,imya,"index.mjs"));
      console.log("    "+imya.padEnd(28)
        + (vhoda_net
            ? String(m.version ?? "?").padEnd(17)+"зонтик: точки входа нет ПО ЗАМЫСЛУ, по имени не грузится"
            : "🔴 НЕ РАЗРЕШАЕТСЯ ("+(e.code??e.message)+")"));
    }
  }
' "$KAT"

echo "--- ПО ПУТИ (каталогом рядом, мимо node_modules)"
found=0
for d in "$KAT"/*/; do
  b=$(basename "$d"); [ "$b" = node_modules ] && continue
  [ -f "$d/package.json" ] || continue
  found=1
  echo "    $(basename "$d" | awk '{printf "%-26s",$0}')$(node -p 'require(process.argv[1]+"/package.json").version' "$d" 2>/dev/null || echo '?')"
done
[ "$found" = 1 ] || echo "    таких нет"

echo
echo "--- ВЛОЖЕННЫЕ копии (пакет внутри пакета — грузится он, а не верхний)"
find "$KAT/node_modules" -mindepth 3 -maxdepth 4 -name package.json -path '*/node_modules/*/node_modules/*' 2>/dev/null \
  | while read -r f; do
      node -e 'const j=require(process.argv[1]);console.log("    "+String(j.name).padEnd(28)+String(j.version).padEnd(17)+process.argv[1].replace("/package.json",""))' "$f" 2>/dev/null
    done | sort -u
echo
echo
echo "--- ССЫЛКИ, ВЕДУЩИЕ НА СТРАХОВКУ (а не на предмет)"
# 🔴 ЗАЧЕМ (п.314, порядок Забавы 09.09.2026). Страховка монтажа несёт ТО ЖЕ имя пакета, что
# и боевой, — по построению: она обязана быть побайтной копией. Само по себе это не дефект.
# Дефект — когда на страховку СМОТРИТ живая ссылка: тогда служба поднимется на откате, и
# отличить это от исправного состояния будет нечем.
# ⚠️ БЕЗ ЭТОЙ ПРОВЕРКИ «ссылок на страховку нет» и «ссылка ведёт на страховку» выглядят
# ОДИНАКОВО — прибор молчит в обоих случаях, и молчание читается как здоровье.
# ГДЕ НЕ ПРИМЕНЯЕТСЯ: смотрим только ссылки из профилей агентов (PROFILI) и только на цели
# внутри этого каталога. Ссылку, заведённую в чужом месте или вне профиля, прибор не увидит —
# это его граница, а не доказательство отсутствия.
# 🔴 ОХВАТ ПЕЧАТАЕТСЯ ЧИСЛОМ (находка Вениамина 09.09.2026, снята с ЧУЖОЙ учётки).
# Шаблон /opt/*/.dsh/profiles разворачивается ПО ПРАВАМ ЗОВУЩЕГО: под iskra в ОДИН профиль,
# под root в ДВА (/opt/petrovich — drwxr-x--- petrovich:petrovich, для меня непроходим). Прибор обходил
# половину области и печатал «ссылок на страховки нет» — то есть уверенное «чисто» про то,
# куда не заглядывал. Это наш класс: пустой ответ — факт о ЗАПРОСЕ, а не о данных.
# ЛЕЧЕНИЕ: считаем, сколько домов ЕСТЬ и сколько удалось открыть. Молчание перестаёт
# читаться как «чисто», когда рядом стоит «обойдено 1 из 2».
# ⚠️ ГРАНИЦА: расширять права ради отчёта НЕ будем — честная строка о недоступном лучше.
# 🔴 РЕШЕНИЕ РАЗВИЛКИ В1 (Забава, 09.09.2026): ПРИБОР ОДИН, ПРОГОН НА КАЖДОМ УЗЛЕ СВОЕЙ РУКОЙ.
# Прежняя редакция лезла в ЧУЖОЙ профиль через sudo. Негодно по двум причинам, и обе наши:
#  (1) ПРОБА ПРО ЧУЖОЕ ОКРУЖЕНИЕ ОБЯЗАНА БЫТЬ ПРОГНАНА ТЕМ, ЧЬЁ ОНО (правило с 03.09, на нём
#      Михалыч поймал Забаву: она проверяла курьера «из окружения server», подставив переменную,
#      которой у него нет вовсе). Читая чужой каталог правами root, видишь НЕ ТО, что видит
#      его процесс своими правами;
#  (2) зависимость от прав — механизм, работающий ПО СОВПАДЕНИЮ: сегодня sudo есть, завтра
#      каталог закроют плотнее, прибор ослепнет и напечатает ноль, неотличимый от «чисто».
# ⇒ Обходим ТОЛЬКО СВОЙ профиль. Чужой обходит его владелец ЭТИМ ЖЕ прибором, два числа сводит
#   тот, у кого они оба на руках.
#
# 🔴 ЗНАМЕНАТЕЛЬ БЕРЁТСЯ ИЗ ОБЪЯВЛЕНИЯ, А НЕ ИЗ ПРАВ (условие У5 Вениамина про число источников).
# Считать дома по /opt/*/ нельзя: /opt/petrovich/.dsh БЕЗ sudo не виден вовсе, и знаменатель молча
# стал бы «1 из 1» — прибор скрыл бы само существование соседа. Объявленный источник, читаемый
# без особых прав, — systemd: служба агента опознаётся по WorkingDirectory вида /opt/*/workspace.
# ⚠️ ГДЕ НЕ ПРИМЕНЯЕТСЯ: агент без службы systemd этим знаменателем не считается. Признак
# объявленный, а не всеобъемлющий, и врёт он в сторону ЗАНИЖЕНИЯ знаменателя — то есть в
# сторону «покрытие выглядит полнее». Кто заведёт агента иначе, обязан поправить признак здесь.
JA="${SREZ_JA:-$(id -un)}"
PROFILI="${SREZ_PROFILI:-/opt/$JA/.dsh/profiles}"
najdeno_ssylok=0
obhod=""
agentov_obyavleno=0
agenty_imena=""
for u in $(systemctl list-units --type=service --all --no-legend --no-pager 2>/dev/null | awk '{print $1}' | grep -vE '^●'); do
  wd=$(systemctl show "$u" -p WorkingDirectory --value 2>/dev/null)
  case "$wd" in
    /opt/*/workspace)
      agentov_obyavleno=$((agentov_obyavleno+1))
      agenty_imena="$agenty_imena $(systemctl show "$u" -p User --value 2>/dev/null)"
      ;;
  esac
done
if [ "$agentov_obyavleno" -eq 0 ]; then
  echo "⚠️  агентов по systemd не опознано — знаменатель НЕ УСТАНОВЛЕН (это не «агент один»)"
fi
domov_vsego=$agentov_obyavleno
domov_obojdeno=0
nedostupny=""
if [ -r "$PROFILI" ]; then
  domov_obojdeno=1
  obhod="$PROFILI"
else
  nedostupny="$PROFILI"
  echo "⚠️  свой профиль ($PROFILI) не читается — обходить нечего, и это НЕ «чисто»"
fi
# 🔴 ОБХОД ПО ТОМУ ЖЕ СПИСКУ, ЧТО И СЧЁТ. Первая редакция этой правки считала дома
# через sudo (выходило 2), а обходила по glob (выходил 1) — и печатала «обойдено 2 из 2»,
# не осмотрев 540 ссылок соседа. Счётчик и предмет обязаны браться из одного источника,
# иначе охват врёт ровно там, где его завели, чтобы он не врал.
for koren in $obhod; do
  # Свой профиль читается СВОИМИ правами: sudo здесь был бы возвратом к чужому окружению.
  [ -d "$koren" ] || continue
  while IFS= read -r ln; do
    [ -n "$ln" ] || continue
    cel=$(readlink -f "$ln" 2>/dev/null || readlink "$ln")
    case "$cel" in
      *.bak-*|*.staryj|*.old)
        najdeno_ssylok=$((najdeno_ssylok+1))
        echo "    🔴 $ln"
        echo "        ведёт на: $cel"
        ;;
    esac
  done <<< "$(find "$koren" -type l 2>/dev/null)"
done
# 🔴 СТРОКА ОХВАТА НАЗЫВАЕТ УЗЕЛ И ЧЕЙ ПРОФИЛЬ ОБОЙДЁН. Без имени узла и агента число
# «обойдено 1 из 2» читается как «прибор не доработал», хотя это ПОЛНОЕ покрытие СВОЕЙ руки:
# остальных обходит их владелец этим же прибором.
echo "    охват: свой профиль обойдён ($domov_obojdeno) · агентов на узле объявлено $domov_vsego ·$agenty_imena"
echo "    узел: $(id -un)@$(hostname) · профиль: $PROFILI"
echo "    чужие профили обходит ИХ ВЛАДЕЛЕЦ этим же прибором — сюда прибор НЕ ходит намеренно"
[ -n "$nedostupny" ] && echo "    🔴 СВОЙ профиль не обойден:$nedostupny — про него прибор не говорит НИЧЕГО"
if [ "$najdeno_ssylok" = 0 ]; then
  echo "    ссылок на страховки нет В СВОЁМ профиле (агентов на узле $domov_vsego — про чужие молчу)"
else
  echo "    🔴 живых ссылок на страховки: $najdeno_ssylok — служба поднимется на ОТКАТЕ"
fi

echo "🔴 это срез ДИСКА. Что работает СЕЙЧАС — спрашивать у журнала службы, а не отсюда."
