#!/bin/bash
# СВЕРКА «СМОНТИРОВАНО ПРОТИВ ЗАПИСАНО». Искра, 09.09.2026, поручение Забавы.
#
# ЗАЧЕМ. Реестр машины наполняется РУКОЙ и по построению слеп к тому, чего в нём нет:
# он честно стережёт вписанное, а невписанное для него не существует. Снаружи «всё
# сходится» и «половины предметов тут нет» выглядят ОДИНАКОВО. Полноту нельзя
# проверить изнутри реестра — только обходом извне, и это делает прибор.
#
# ЧТО ПЕЧАТАЕТ: обе стороны и число. Не «сошлось», а сколько с каждой стороны и что
# именно расходится — чтобы читающий видел предмет, а не вердикт.
#
# ⚠️ ГРАНИЦЫ, ГДЕ НЕ ПРИМЕНЯЕТСЯ:
#   · Перечень мест монтажа MESTA — РУЧНОЙ. Плагин, положенный в НЕОБЪЯВЛЕННЫЙ каталог,
#     прибор не увидит: он переносит слепоту на одну ступень выше, а не устраняет её.
#   · Не проверяет СОДЕРЖИМОЕ — только факт записи. Подмена файлов внутри записанного
#     пакета ловится не здесь, а `agent-plugins verify`.
#   · Каталоги .bak-* и node_modules пропускаются намеренно: это не монтаж.
set -u
# №14 аудита 16 (10.10.2026): пути — из окружения, а не зашиты. Реестр — PLUGINS_REGISTRY, как у agent-plugins;
# места монтажа — SVERKA_MESTA (через пробел), умолчания НЕТ: перечень свой у каждой машины, пусто — отказ.
REESTR="${PLUGINS_REGISTRY:-/etc/agent-registry/plugins.yaml}"
MESTA="${SVERKA_MESTA:-}"
[ -n "$MESTA" ] || { echo "СЛЕПОТА: места монтажа не заданы (SVERKA_MESTA пуст) — обходить нечего." >&2; exit 2; }

vrem=$(mktemp -d) || exit 2
trap 'rm -rf "$vrem"' EXIT

# №14: реестр читается НАПРЯМУЮ; sudo -n — только запасной путь, и его отказ — слепота, а не «записано 0 путей».
# Прежде `sudo grep` без -n при отказе sudo давал пустой список, и смонтированное шло «🔴 ВНЕ РЕЕСТРА» — ложное расхождение.
if [ -r "$REESTR" ]; then
  cat -- "$REESTR" > "$vrem/reestr" 2>/dev/null || { echo "СЛЕПОТА: реестр не прочитан ($REESTR)." >&2; exit 2; }
elif ! sudo -n cat -- "$REESTR" > "$vrem/reestr" 2>/dev/null; then
  echo "СЛЕПОТА: реестр не читается ($REESTR), sudo -n отказал — сверять не с чем." >&2; exit 2
fi
grep -oE "path: .*" "$vrem/reestr" \
  | sed 's/^path: //' | tr ',' '\n' | sed 's/^ *//; s/ *$//; s#/$##' \
  | grep -v '^$' | sort -u > "$vrem/zapisano"
[ -s "$vrem/zapisano" ] || { echo "СЛЕПОТА: из реестра $REESTR прочитано 0 путей (path:) — сверять не с чем." >&2; exit 2; }

for m in $MESTA; do
  [ -d "$m" ] || { echo "⚠️ место монтажа отсутствует: $m (пропущено)" >&2; continue; }
  find "$m" -mindepth 1 -maxdepth 1 -type d 2>/dev/null
done | grep -vE '\.bak-|/node_modules$' | sed 's#/$##' | sort -u > "$vrem/smontirovano"

vsego=$(wc -l < "$vrem/smontirovano")
zapisej=$(wc -l < "$vrem/zapisano")
comm -23 "$vrem/smontirovano" "$vrem/zapisano" > "$vrem/vne"
vne=$(wc -l < "$vrem/vne")
svereno=$(( vsego - vne ))

echo "── СВЕРКА МОНТАЖА С РЕЕСТРОМ ($(date -u '+%F %T UTC') на $(hostname))"
echo "   места монтажа (объявлены): $MESTA"
echo "   СМОНТИРОВАНО каталогов: $vsego"
echo "   ЗАПИСАНО путей в реестре: $zapisej"
echo
if [ "$vne" -gt 0 ]; then
  echo "🔴 ВНЕ РЕЕСТРА — подмена этих файлов пройдёт МОЛЧА:"
  sed 's/^/     /' "$vrem/vne"
  echo
fi
# 🔴 ПРИЗНАК «РАЗЛИЧЕНИЯ НЕТ» (правило Забавы 09.09.2026). Если ВСЕ кандидаты ответили
# одинаково — это чаще про прибор, чем про предмет: не прочитался реестр, не та маска пути,
# пустой обход. Ряд одинаковых ответов НЕЛЬЗЯ выдавать за результат: «13 дыр» и «реестр не
# прочитан» выглядят снаружи одинаково, и второе вероятнее.
# ⚠️ ГДЕ НЕ ПРИМЕНЯЕТСЯ: при vsego=1 различать нечего — один кандидат не образует ряда,
# и молчание здесь честнее ложной тревоги.
if [ "$vsego" -gt 1 ] && { [ "$vne" -eq "$vsego" ] || { [ "$vne" -eq 0 ] && [ "$zapisej" -eq 0 ]; }; }; then
  echo "🔴 РАЗЛИЧЕНИЯ НЕТ: все $vsego кандидатов ответили одинаково."
  echo "   Это замер ПРО ИНСТРУМЕНТ либо условие не наступило, а не ряд находок."
  echo "   Проверьте: читается ли реестр ($zapisej путей прочитано), та ли маска пути."
  exit 2
fi
echo "   сверено $svereno смонтированных из $vsego (Y — обход объявленных мест, не выборка)"
[ "$vne" -gt 0 ] && { echo "   🔴 вне реестра: $vne"; exit 1; }
echo "   ✅ всё смонтированное записано"
exit 0
