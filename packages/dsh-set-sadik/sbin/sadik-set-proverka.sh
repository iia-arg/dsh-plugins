#!/bin/bash
# Проверка сети sadik ПО СВОЙСТВУ, а не по коду возврата применяющего скрипта.
# Заведена 02.09.2026 (Искра) после того, как обновление ОС перезапустило
# systemd-networkd, смыло правила политики, и туннели умерли ТИХО: код возврата
# применяющего скрипта был бы 0 и в этом случае — он ставит правила, а не проверяет их.
#
# Коды: 0 сошлось · 1 расхождение · 2 проверять нечем (слепота).
#
# 🔴 ГРАНИЦА. Ловит «правила и маршруты смыло». НЕ ловит:
#   — точка подключения СМЕНИЛАСЬ на той стороне, а конфиг прежний (адрес есть,
#     маршрут есть, туннель мёртв). Молчание этой проверки не значит «связь жива»;
#   — качество канала: потери, задержки, MTU;
#   — что во внешний мир вообще есть выход — это отдельная проба.
set -u
CONF_DIR=${SET_CONF_DIR:-/etc/amnezia/amneziawg}
EXT_IF=${SET_EXT_IF:-wan0}
bad=0; slep=0; ok=0

TOCHKI=$(sed -n 's/^ *Endpoint *= *\([^:]*\):.*/\1/p' "$CONF_DIR"/*.conf 2>/dev/null | sort -u)
if [ -z "$TOCHKI" ]; then
  echo "СЛЕПОТА: точек подключения не прочитано ($CONF_DIR) — проверять нечего. Это НЕ «всё хорошо»"
  exit 2
fi

for T in $TOCHKI; do
  R=$(ip route get "$T" 2>/dev/null | head -1)
  if [ -z "$R" ]; then
    echo "🔴 РАСХОЖДЕНИЕ $T: маршрута НЕТ вовсе — пакетам рукопожатия идти некуда"; bad=$((bad+1))
  elif echo "$R" | grep -q "dev $EXT_IF"; then
    ok=$((ok+1))
  else
    # Самый ядовитый случай: маршрут ЕСТЬ, но ведёт в сам туннель — петля,
    # рукопожатие не уходит, туннель умирает молча.
    echo "🔴 РАСХОЖДЕНИЕ $T: маршрут идёт НЕ через $EXT_IF, а «$R» — петля через туннель"; bad=$((bad+1))
  fi
done

# Правила политики: проверяем не число, а наличие каждой роли по признаку.
for PR in "lookup 100" "suppress_prefixlength" "lookup 51820"; do
  if ip rule show 2>/dev/null | grep -q "$PR"; then ok=$((ok+1))
  else echo "🔴 РАСХОЖДЕНИЕ: правила политики «$PR» нет"; bad=$((bad+1)); fi
done

# --- Дубль данных: те же адреса записаны КОНСТАНТАМИ в киллсвитче ---
# Найдено 02.09.2026. Источник адресов — конфиги туннелей, но файрвол знает их
# отдельным списком. Сменится Endpoint в конфиге: маршрут подхватится сам, а файрвол
# заблокирует пакет — отказ ТИХИЙ, оба механизма при этом «работают».
# 🔴 Лечим не синхронизацией (файрвол трогать опаснее, чем терпеть дубль), а видимостью:
# расхождение двух списков объявляется здесь. Свести их — отдельная работа со своей приёмкой.
KS=${SET_KILLSWITCH:-/usr/local/sbin/sadik-vpn-only-killswitch.sh}
if [ -r "$KS" ]; then
  KS_ADR=$(grep -oE '\-d [0-9]+\.[0-9]+\.[0-9]+\.[0-9]+' "$KS" 2>/dev/null | awk '{print $2}' | sort -u)
  for T in $TOCHKI; do
    if echo "$KS_ADR" | grep -qx "$T"; then ok=$((ok+1))
    else
      echo "🔴 РАСХОЖДЕНИЕ $T: точка подключения есть в конфиге, но её НЕТ в киллсвитче — файрвол её заблокирует"
      bad=$((bad+1))
    fi
  done
else
  echo "СЛЕПОТА киллсвитч: $KS не прочитан — сверка списков адресов не сделана"
  slep=$((slep+1))
fi

echo "ИТОГО: сошлось $ok, расхождений $bad, слепот $slep (точек подключения: $(echo "$TOCHKI" | wc -w))"
[ "$bad" -gt 0 ] && exit 1
# Слепота НЕ равна «сошлось»: проверить нечем — это отдельный исход, иначе
# отсутствие данных читается как исправность (наш класс, лечен в стендах 02.09).
[ "$slep" -gt 0 ] && exit 2
exit 0
