          // 🔴 СВОЙ ВИД ИСТОЧНИКА ДЛЯ СЛУЖЕБНОГО КАНАЛА (21.08.2026, распоряжение
          // главной). Раньше тут стоял kind: 'user' — и это была НЕПРАВДА в слое
