/**
 * Call the native body of a tool registered on the live agent.
 *
 * 🔴 WHY NOT registry.execute(), BUT THE DEFINITION DIRECTLY. registry.execute
 * runs the call through the tools/pre-execute waterfall — that is, through
 * asking the user for permission. On our layout there is no answerer, and the
 * policy fails closed: the tool would refuse ALWAYS, and it would look like
 * "the schedule is broken". Besides, registry.execute materialises the result
 * into content blocks, while the bridge needs JSON. The tool body itself is
 * wrapped by the platform (defineTool): schema validation of arguments, the
 * ToolArgsError refusal and the agent-identity check are all inside, and the
 * bridge repeats none of it.
 *
 * WHAT WE LOSE BY DOING SO, SAID PLAINLY: the call time limit (timeoutMs), the
 * registry's concurrency queue and cancellation by the turn signal. For the
 * three schedule tools that is nothing: they declare no timeoutMs, their bodies
 * are serialised by their own transaction, and the bridge cannot provide
 * cancellation — loopback HTTP knows nothing of the turn signal. We pass an
 * honest non-cancellable signal: a fake "already cancelled" would turn every
 * call into a silent refusal.
 *
 * A MISSING DEFINITION IS BLINDNESS, NOT A REFUSAL. If the tool is not
 * registered on the agent, then the schedule layer is not mounted, or the agent
 * is the wrong one. We shout about it on its own line: a silent "not found" is
 * read by the model as "nothing to schedule", and we would be hunting the
 * defect in the schedule instead of in the mounting.
 */
async function nativeCall(ctx, agent, toolName, args) {
  const registry = ctx.get('tools')
  if (!registry || typeof registry.get !== 'function') {
    throw new Error('the platform tool registry is unavailable — the native path cannot run')
  }
  // get(name, scope) — "how THIS agent sees the tool". The scope is what
  // matters: schedule is registered in the scope of a SPECIFIC agent, and a
  // definition taken without it would belong to a different closure — that is,
  // it would refuse on agent identity.
  const def = registry.get(toolName, agent)
  if (!def || typeof def.execute !== 'function') {
    log(`🔴 BLINDNESS: "${toolName}" is not registered on agent ${agent?.id ?? '?'} — the layer is not mounted`)
    throw new Error(`"${toolName}" is not registered on the live agent: the platform layer is not mounted`)
  }
  return await def.execute(args, { agent, signal: new AbortController().signal })
}

/** Is a text argument meaningful — verbatim hasText from dsh-tool-goal. */
const hasText = (v) => v !== undefined && v !== ''
/** Is a round cap meaningful — verbatim hasRoundCap: zero here is a schema filler. */
const hasRoundCap = (v) => v !== undefined && v !== 0

/**
 * update_goal — one name, five actions, and that is the native route's shape,
 * not ours. Each action has its own authority, copied verbatim from
 * dsh-tool-goal: edit/pause/resume — direct human turn only; complete/blocked —
 * a human OR the current goal round.
 *
 * 🔴 THE ONLY MUTATING ACTION THAT BYPASSES THE BOUNDARY IS blocked: the block
 * method is not marked Remote in dsh-goal, so it does not exist from outside.
 * That means the check the boundary performs for the other actions is repeated
 * here by the host.
 *
 * 🔴 THE blocked THRESHOLD APPLIES ONLY UNDER ROUND AUTHORITY. In the original
 * the condition includes authority.kind === "goal-round": the threshold guards
 * against an agent giving up on itself at the first self-wake, and nothing else.
 * In a human turn the block goes through immediately, at round zero. The first
 * version of this bridge applied the threshold ALWAYS — that is, a human could
 * not get the answer "I am stuck". Home-grown tightening breaks work as much as
 * loosening does; fixed 2026-08-22 on an operational correction.
 */
async function updateGoal(ctx, agents, agentId, a, limits) {
  const execution = bridgeExecution(agents, agentId)
  const ref = { id: String(a.goal_id), revision: a.revision }
  const action = a.action

  if (action === 'edit') {
    requireDirectHuman(agents, execution)
    if (hasText(a.blocked_reason)) throw new Error('blocked_reason is allowed only with action blocked')
    const capped = capRounds(ctx, hasRoundCap(a.max_goal_rounds) ? a.max_goal_rounds : undefined)
    const request = {
      ...(hasText(a.objective) ? { objective: a.objective } : {}),
      ...(capped === undefined ? {} : { maxGoalRounds: capped }),
    }
    return remoteCall(ctx, 'goals', 'edit', { ref, request }, agentId)
  }

  if (action === 'pause' || action === 'resume') {
    requireDirectHuman(agents, execution)
    if (hasText(a.objective) || hasRoundCap(a.max_goal_rounds) || hasText(a.blocked_reason)) {
      throw new Error('objective and max_goal_rounds are allowed only with action edit; blocked_reason only with blocked')
    }
    return remoteCall(ctx, 'goals', action, { ref }, agentId)
  }

  if (action !== 'complete' && action !== 'blocked') {
    throw new Error(`unknown action "${action}"`)
  }

  const authority = completionAuthority(ctx, agents, execution)
  if (hasText(a.objective) || hasRoundCap(a.max_goal_rounds)) {
    throw new Error('objective and max_goal_rounds are allowed only with action edit')
  }
  if (action === 'complete') {
    if (hasText(a.blocked_reason)) throw new Error('blocked_reason is allowed only with action blocked')
    return remoteCall(ctx, 'goals', 'complete', { ref }, agentId)
  }

  const reason = typeof a.blocked_reason === 'string' ? a.blocked_reason.trim() : ''
  if (!reason) throw new Error('blocked_reason is required with action blocked')
  if (authority.kind === 'goal-round' && authority.goal.roundsStarted < limits.blockedAfterRounds) {
    throw new Error(
      `blocked requires at least ${limits.blockedAfterRounds} consecutive autonomous rounds; `
      + `${authority.goal.roundsStarted} have started so far`,
    )
  }
  return ctx.get('goals').block(execution.agent, ref, { code: 'model-reported', message: reason })
}

/**
 * The only place where identity reaches the wire.
 * 🔴 KEY ORDER MATTERS: identity comes AFTER the arguments. In the opposite
 * order a build() that passed the model's arguments through would silently
 * overwrite the identity — that is, the model would be assigning it itself.
 */
function remoteCall(ctx, namespace, method, args, agentId) {
  return ctx.get('typertGateway').invoke({
    namespace,
    method,
    args: { ...args, agentId: String(agentId) },
  })
}

/**
 * 🔴 THE GOAL-CREATION CEILING (an operational decision).
 *
 * WHY. The round limit is PER GOAL, not per agent: close a goal, create a new
 * one, and the round counter starts over. So the creation tool is able to
 * bypass the limit from inside and produce an unbounded runaway. Engine
 * subagents are invisible to the platform and arrive with the root's identity,
 * with nothing to tell them apart (verified 2026-08-22: BUILT-IN subagent types
 * cannot have the bridge server taken away) — therefore the limit sits not at
 * the model but here, on our side of the wire. Neither the model nor a subagent
 * can reach this far: they see only a tool name and its schema.
 *
 * WHAT IT PROTECTS AGAINST: a loop the mechanism entered by itself, a bug in
 * the code, an avalanche of retries.
 * WHERE IT DOES NOT APPLY: it is no protection against a deliberate act by an
 * agent with full sudo, and does not claim to be — the counter lives in the
 * memory of the platform process, and that process is mine.
 * IT NEVER OBSTRUCTS CLOSING A GOAL: only creation is under the ceiling, and
 * that is not a caveat but the design — the other tools do not touch the counter.
 * IT IS RESET BY A PLATFORM RESTART: the state is in memory and is not written
 * to disk.
 * IT REPAIRS NOTHING BY ITSELF: on hitting the ceiling it refuses and writes a
 * log line; there are no other actions.
 *
 * 🔴 WHAT THE COUNTER IS KEYED BY (an operational requirement, check this first).
 * The key is THE IDENTITY OF THE LIVE AGENT, which the host obtains by itself:
 *   provider adapter → ctx.get('agents').currentInitiator().id → the bridge
 *   issues a ONE-TIME TICKET for that identity → the request body to the gateway
 *   carries the ticket, not the identity → the gateway keeps the ticket in the
 *   server CLOSURE → presents it at the door → the bridge looks into its own
 *   table and retrieves the identity.
 *   The model takes no part anywhere in this chain, and identity is NOT ON THE
 *   WIRE AT ALL.
 * NOT from the tool arguments: the bridge reads neither identity, nor owner, nor
 * session from args — there are only subject fields there (objective, goal id,
 * revision).
 * NOT by the ENGINE session id: that one is born in the gateway on every request
 * (crypto.randomUUID), and there would be no counter at all — every call would
 * produce a new key.
 * AN HONEST CAVEAT: the key's value COINCIDES with the PLATFORM session id — for
 * the platform that is an invariant (agent.id === agent.session.id, checked with
 * a throw in dsh-agent enter()). The difference is not in the value but in the
 * source: it is taken from the registry of live agents, not from the body. There
 * is nothing to bypass it with by switching sessions: platform sessions are
 * created only by the channel module, keyed <channel>-<id>, so a new session is
 * a new chat, which a human starts, not the model.
 * ENGINE SUBAGENTS fall into the ROOT's counter: they inherit the root's server
 * instance, and the identity lies in its closure. A hole that cannot be closed
 * (built-in types cannot be stripped of the server) works in our favour here.
 *
 * Counted per session identity, not machine-wide: every agent has its own ceiling.
 */
const creations = new Map()

/**
 * Reserve a slot for creating a goal. The slot is taken BEFORE the call and
 * released if the call fails — otherwise two concurrent calls would both pass
 * the check, each seeing state the other had not written yet.
 */
function reserveCreate(agentId, limit, windowMs, now) {
  const kept = (creations.get(agentId) ?? []).filter((t) => now - t < windowMs)
  if (kept.length >= limit) {
    creations.set(agentId, kept)
    return { allowed: false, used: kept.length }
  }
  kept.push(now)
  creations.set(agentId, kept)
  return { allowed: true, used: kept.length }
}

/** Release a taken slot: the call failed, no goal was created. */
function releaseCreate(agentId, now) {
  const kept = (creations.get(agentId) ?? []).filter((t) => t !== now)
  creations.set(agentId, kept)
}

/**
 * 🔴 WAKE-UPS ARE COUNTED FROM THE SESSION LOG, NOT FROM MEMORY. THIS IS LOAD-BEARING.
 *
 * The operational requirement read "the counter must survive a platform
 * restart, otherwise a restart resets the protection". It is met NOT by storage
 * but by construction: there is no counter at all, it is DERIVED from
 * agent.session.events — the very log the schedule restores itself from. There
 * is nothing for a restart to reset: the hole has structurally nowhere to appear.
 *
 * That events do come back from disk into agent.session.events is not an
 * assumption but a measurement from 2026-08-22: reminder schedule-2, set before
 * a platform restart (PID 1874902 -> 1885447 at 19:26:20), fired after it with a
 * deviation of 1 ms over 900 s, and the seq numbering in the log continued
 * instead of resetting to zero.
 *
 * THE SIGN OF AN AUTONOMOUS TURN was read off a live log, not invented:
 *     turn/end -> agent/inbox/spliced -> schedule/change(dispatch) -> turn/start
 * against a human one:
 *     turn/end -> agent/inbox/spliced -> turn/start -> user/message(kind=<kind>)
 * 🔴 The naive check "was there a message from a human" DOES NOT WORK: a
 * reminder and a letter arrive identically — through agent/inbox/spliced with
 * role user. Exactly one thing tells them apart: whether there is a dispatch
 * BETWEEN the previous turn/end and this turn/start. That is why the flag is
 * cleared both on turn/start (spent) and on turn/end (a dispatch in the middle
 * of somebody else's turn woke nobody and does not count).
 */

/**
 * Message kinds that count as a word from a human and break the streak.
 *
 * 🔴 THIS IS A SETTING, NOT A CONSTANT, AND HERE IS WHY. The kind 'user' is the
 * platform's — everyone has it. Any other kind is introduced by whichever module
 * receives messages: on our installation the service channel between agents
 * arrives with its own kind, and it too is a word from a live human. Had we
 * hard-coded this list, on somebody else's build only one kind out of two would
 * break the streak — and SILENTLY: a superfluous wake-up is indistinguishable
 * from an honest one.
 *
 * 🔴 AND SEPARATELY: goal authority has its own, DIFFERENT list — there a service
 * kind does NOT grant human rights. This is not inconsistency. There the question
 * is "may a service channel dispose of the goal", here it is "is anybody alive
 * nearby". Different questions, different answers; changing one without touching
 * the other is legitimate.
 */
const HEARTBEAT_HUMAN_KINDS_DEFAULT = ['user']

/** A ledger of the session's turns: what started each one. Event order matters. */
function turnLedger(events, humanKinds) {
  const turns = []
  let dispatched = false
  let current
  for (const e of events) {
    const t = e?.type
    if (t === 'schedule/change') {
      if (e.data?.operation === 'dispatch') dispatched = true
      continue
    }
    if (t === 'turn/start') {
      current = { turn: e.data?.turn, autonomous: dispatched, human: false }
      turns.push(current)
      dispatched = false
      continue
    }
    if (t === 'turn/end') { current = undefined; dispatched = false; continue }
    if (t === 'user/message' && current !== undefined
      && humanKinds.has(e.data?.source?.kind)) current.human = true
  }
  return turns
}

/** The day key in the named zone. Through Intl rather than offset arithmetic:
 *  let the library, not us, work out daylight saving. */
function dayKeyFactory(zone) {
  const fmt = new Intl.DateTimeFormat('en-CA', {
    timeZone: zone, year: 'numeric', month: '2-digit', day: '2-digit',
  })
  return (ms) => fmt.format(ms)
}

/**
 * The streak of consecutive autonomous wake-ups and the count for the current day.
 * The streak is broken by ANY non-autonomous turn, not only a human one: a turn
 * that our reminder did not start spent no wake-up. Wake-ups from background
 * jobs do not appear here at all — they have their own limit (maxConsecutiveWakes).
 */
function heartbeatCounters(events, zone, now, humanKinds) {
  const turns = turnLedger(events, humanKinds)
  let streak = 0
  for (let i = turns.length - 1; i >= 0; i -= 1) {
    const t = turns[i]
    if (t.human || !t.autonomous) break
    streak += 1
  }
  const dayKey = dayKeyFactory(zone)
  const today = dayKey(now)
  let perDay = 0
  for (const e of events) {
    if (e?.type === 'schedule/change' && e.data?.operation === 'dispatch'
      && dayKey(e.time) === today) perDay += 1
  }
  return { streak, perDay, turns: turns.length }
}

/**
 * The check performed when a RECURRING reminder is CREATED.
 * 🔴 A DEPARTURE FROM THE RULE "the bridge does not execute schedule, it only
 * delivers" — said out loud. There is exactly one policy of ours on top of
 * theirs, and this is it: the interval. One-shot reminders (after_seconds / at)
 * are NOT TOUCHED by it — they have no interval.
 */
function heartbeatGuard(args, limits) {
  const every = args?.every_seconds
  if (every === undefined) return
  if (typeof every === 'number' && every >= limits.heartbeatMinIntervalSeconds) return
  throw new Error(
    `a recurring reminder may run no more often than once every ${limits.heartbeatMinIntervalSeconds} s — `
    + `this is a host limit, not an error (requested ${every}). The platform minimum of 300 s comes from a different problem: `
    + 'it is meant for short supervised work cycles, whereas background self-waking every five minutes is 288 turns a day. '
    + 'If you need a tighter cycle, it must run under human supervision, not on an alarm clock.',
  )
}

/**
 * Stop the cycle and say so. The order is exactly this: FIRST the stop, then the
 * notice. Stopping matters more than notifying — but silence is not allowed in
 * any outcome, so the notice is written even when the stop failed, and then it
 * will have to be finished by hand.
 */
async function stopHeartbeat(ctx, agent, why, counters, limits, rootCount) {
  const sid = String(agent?.id ?? '?')
  const removed = []
  let failure
  try {
    const list = await nativeCall(ctx, agent, 'schedule_list', {})
    if (!Array.isArray(list)) throw new Error(`schedule_list returned a non-list: ${JSON.stringify(list).slice(0, 200)}`)
    for (const rec of list) {
      // 🔴 WE REMOVE ALL ACTIVE ONES, NOT ONLY THE RECURRING ONES. This follows
      // from counting WAKE-UPS rather than rule types: a chain in which every
      // self-wake sets itself a fresh one-shot alarm bypasses the limit in one
      // line. So one-shots are removed as well — but every one of them is named
      // by id in the log and in the notice, so that nothing disappears silently.
      const r = await nativeCall(ctx, agent, 'schedule_delete', { id: rec.id })
      removed.push(`${rec.id} (${rec.kind}${rec.everySeconds === undefined ? '' : `, every ${rec.everySeconds} s`})`
        + ` — ${r?.deleted ? 'removed' : `NOT removed: ${r?.code ?? '?'}`}`)
    }
  } catch (e) {
    failure = String(e?.message ?? e)
    log(`🔴 self-wake limit: stopping for ${sid} FAILED: ${failure}`)
  }
  log(`🔴 self-wake limit for ${sid}: ${why}; reminders removed ${removed.length}`
    + (removed.length ? `: ${removed.join('; ')}` : ''))

  const text = [
    `[stop limit] session ${sid}`,
    '',
    `Stopped on the self-wake limit: ${why}.`,
    `Counted from the session log: autonomous wake-ups in a row ${counters.streak} `
      + `(limit ${limits.heartbeatMaxConsecutive}), for the current day ${counters.perDay} `
      + `(limit ${limits.heartbeatMaxPerDay} PER SESSION, zone ${limits.heartbeatDayZone}).`,
    `🔴 The limit of 48 a day is PER SESSION, not per agent. Live root sessions right now: ${rootCount}, `
      + `so the agent's total ceiling is ${rootCount * limits.heartbeatMaxPerDay} wake-ups a day.`,
    '',
    removed.length
      ? `Active reminders removed: ${removed.length}: ${removed.join('; ')}.`
      : 'There were no active reminders at the moment of stopping — nothing to remove.',
    failure === undefined
      ? ''
      : `🔴 STOPPING FAILED: ${failure}. Reminders may still be alive — remove them by hand.`,
    '',
    'What was done during the streak is in my reports and in the session log. I will continue on your word.',
  ].filter((l) => l !== '').join('\n')

  if (limits.heartbeatNoticeDir === '') {
    // No directory set — that is a configured outcome, not a loss. But the text
    // of the notice must still be spoken in full: silence is indistinguishable
    // from a breakage.
    log(`self-wake limit: no notice directory configured, full notice to the log: ${text.replace(/\n/g, ' | ')}`)
    return
  }
  try {
    mkdirSync(limits.heartbeatNoticeDir, { recursive: true })
    const file = `${limits.heartbeatNoticeDir}/${Date.now()}-heartbeat-limit.txt`
    writeFileSync(file, `${text}\n`)
    log(`self-wake limit: notice to the owner written to ${file}`)
  } catch (e) {
    // 🔴 WE DO NOT CRASH. The cycle is already stopped, and that is the main
    // thing; but we do not stay silent either — silence here is
    // indistinguishable from a breakage. The whole notice goes to the log.
    log(`🔴 self-wake limit: the notice was NOT WRITTEN to ${limits.heartbeatNoticeDir} (${e?.message ?? e}). Full text: ${text.replace(/\n/g, ' | ')}`)
  }
}

/** One shared handler for both local and remote tools. */
async function callTool(ctx, agents, toolName, agentId, args, limits) {
  const exec = EXEC[toolName]
  if (!exec) throw new Error(`tool "${toolName}" is not exposed by the bridge`)

  // 🔴 AUTHORITY IS CHECKED FIRST — before the ceiling. A refusal on rights must
  // not occupy a slot in the creation counter: otherwise an unauthorised call
  // would spend somebody else's ceiling. Each tool has its own level, copied
  // from the original:
  //   none     — like job_* on the native route: a live agent only, no turn required;
  //   turn     — like get_goal: a live agent and an open turn, no authority;
  //   human    — like create_goal: plus a direct human turn on the root;
  //   dispatch — like update_goal: authority depends on the action, see updateGoal.
  let execution
  if (exec.authority === 'turn' || exec.authority === 'human') {
    execution = bridgeExecution(agents, agentId)
    if (exec.authority === 'human') requireDirectHuman(agents, execution)
  }

  // Our own limit is checked after rights and before the platform, for the same
  // reason: a refusal must cost zero calls into it. There is one guard right
  // now, and it is on the interval of a recurring reminder (see heartbeatGuard).
  if (exec.guard) exec.guard(args, limits)

  // The ceiling is checked after rights but before the platform: a refusal must
  // cost zero calls into it.
  let reserved
  if (exec.counted) {
    const now = Date.now()
    const r = reserveCreate(agentId, limits.createLimit, limits.createWindowMs, now)
    // 🔴 Every creation is a log line, both the allowed and the refused one. A
    // silent refusal is inadmissible here: the cycle would simply not start and
    // we would be guessing why. The session identity in the line is mandatory —
    // otherwise it is invisible whose it was.
    if (!r.allowed) {
      log(`🔴 goal creation: session=${agentId} — REFUSED, ceiling ${limits.createLimit} per ${limits.createWindowMs / 60000} min exhausted (${r.used} taken)`)
      throw new Error(
        `the goal-creation ceiling is exhausted: ${limits.createLimit} per ${limits.createWindowMs / 60000} min. ` +
        'This is a host limit, not an error: it frees up as old entries leave the window. ' +
        'There is nothing to bypass it with and no need to — work on the goal you already have, or wait for the window.',
      )
    }
    reserved = now
    log(`goal creation: session=${agentId} — allowed (${r.used} of ${limits.createLimit} taken per ${limits.createWindowMs / 60000} min)`)
  }

  try {
    if (exec.dispatch) return await exec.dispatch(ctx, agents, agentId, args, limits)
    if (exec.remote) return await remoteCall(ctx, exec.remote.namespace, exec.remote.method, exec.remote.build(args, ctx), agentId)

    // The local path. We look the live agent up in the registry by the same
    // identity the boundary uses; not found — a refusal, not silence: otherwise
    // reading somebody else's session would look like "there is no goal".
    // agents.get(id) — "Look up a live agent", returns undefined if no live
    // agent has that id. Live specifically: that is the same sign the remote
    // boundary's refusal rests on, so the local path is no softer than the
    // remote one.
    const agent = execution?.agent ?? agents.get(String(agentId))
    if (!agent) throw new Error(`live agent "${agentId}" not found in the registry`)
    // The native path requires the same live agent and for the same reason:
    // without it the schedule would be written into somebody else's session, or
    // not written at all.
    if (exec.native) return await nativeCall(ctx, agent, toolName, args)
    return await exec.local(ctx, agent, args)
  } catch (e) {
    if (reserved !== undefined) {
      releaseCreate(agentId, reserved)
      log(`goal creation: session=${agentId} — failed, slot released`)
    }
    throw e
  }
}

/**
 * 🔴 ONE ENTRY POINT PER PROCESS. cordis calls apply on every rebuild of the
 * plugin set, and the instances stay alive: without this flag one more
 * listening socket would come up per mount (four were observed). It is cleared
 * on dispose — a legitimate remount still works.
 */
let mounted = false

export function apply(ctx, config) {
  if (mounted) {
    log('repeated mount while the entry point is alive — skipping')
    return
  }
  mounted = true
  /**
   * 🔴 A ONE-TIME TICKET INSTEAD OF IDENTITY ON THE WIRE (an operational design).
   * There is NO identity at our door at all: the gateway carries an opaque
   * random string and knows nothing about goals or agents. The platform knows
   * the identity — and it is the platform that substitutes it, looking into its
   * own table. The difference is fundamental: previously the caller ASSERTED the
   * identity (whoever reached the door and knew the secret could call themselves
   * anyone), now it is ISSUED by the one who knows it.
   * The ticket doubles as the secret: it is random (24 bytes of crypto), so
   * there is no separate door secret any more — one field instead of two.
   *
   * THE TICKET IS BOUND TO A TURN, NOT TO AN AGENT. This is a fix: the earlier
   * revision kept one ticket per identity and revoked the previous one when
   * issuing a new one — and concurrent turns of one agent DO HAPPEN here
   * (on 2026-08-21 an interrupted turn lived for five minutes alongside a new
   * one and edited the same files). Back then a new turn silently took the tools
   * away from the live earlier one.
   *
   * BOUNDARIES, without which the protection turns into its own opposite:
   *  • ONE TICKET PER (identity, turn). Two concurrent turns are two different
   *    tickets, and revoking one does not touch the other.
   *  • IT DIES AT THE END OF ITS OWN TURN, any end: the platform writes turn/end
   *    both on a normal finish and on an abort (interruptedTurnClosers appends
   *    an interrupted turn/end when restoring the log).
   *  • AN UPPER LIFETIME AS A NUMBER — for the case where turn/end never arrives
   *    at all (the process dies before the write). Without it "one-time" would
   *    degenerate into "lives as long as the process", that is, into a
   *    long-lived password.
   *  • ROOT AGENTS ONLY. A platform subagent would receive its own ticket with
   *    its own identity — that is, its own goal-creation counter, and the
   *    ceiling would be bypassed by way of the boundary. There are no platform
   *    subagents at all right now (agents are created only by the channel
   *    module), so the check is free and stops their appearance from quietly
   *    widening rights. ENGINE subagents are unaffected: they have no separate
   *    call to the gateway, they work inside the root's turn and carry its
   *    ticket — and their creations land in the root's counter.
   *  • THE TICKET IS NOT WRITTEN TO DISK, TO THE LOG OR TO THE ENVIRONMENT. It
   *    lives in the platform's memory and in the closure of the gateway handler;
   *    with the sdk transport nothing goes into a command line (measured: 0 hits
   *    across 275 inspected processes). Log lines carry only identity and turn.
   *  • WHAT IT DOES NOT PROTECT AGAINST: reading the process memory, and anyone
   *    with root. The ticket has no OS rights; all that guards it is that it is
   *    written down nowhere.
   */
  const TICKET_TTL_MS = (config?.ticketTtlMinutes ?? TICKET_TTL_MINUTES_DEFAULT) * 60000
  /** ticket → { agentId, turn, issuedAt } */
  const tickets = new Map()
  /**
   * `identity#turn` → the SET of live tickets of that turn.
   * 🔴 A set, precisely, not a single one. Within ONE platform turn more than
   * one request goes to the provider (the turn itself and, for example,
   * generating the session header), and each asks for its own bridge
   * descriptor. While there was a single ticket, the second request revoked the
   * first one's ticket — which had already gone to the engine, so the model got
   * "ticket unknown or already revoked" at the door in the middle of a live turn
   * (run at 10:57, turn 1). One-time-ness is held at the level of the TURN:
   * turn/end revokes all tickets of that turn at once.
   */
  const ticketOf = new Map()
  /** identity → the number of the open turn; maintained from session events */
  const openTurnOf = new Map()

  const turnKey = (agentId, turn) => `${agentId}#${turn ?? '-'}`

  /** Drop the expired ones. Called on issue: a separate timer here would be a
   *  mechanism without a stop condition, for the sake of two map entries. */
  const dropExpired = () => {
    const now = Date.now()
    for (const [t, rec] of tickets) {
      if (now - rec.issuedAt <= TICKET_TTL_MS) continue
      tickets.delete(t)
      const set = ticketOf.get(turnKey(rec.agentId, rec.turn))
      if (set) { set.delete(t); if (!set.size) ticketOf.delete(turnKey(rec.agentId, rec.turn)) }
    }
  }

  const issueTicket = (agentId, turn) => {
    dropExpired()
    const key = turnKey(agentId, turn)
    // Earlier tickets of THIS SAME turn are NOT revoked: they may already be
    // with the engine (see the note on ticketOf). They all die with the turn.
    const ticket = randomBytes(24).toString('hex')
    tickets.set(ticket, { agentId, turn, issuedAt: Date.now() })
    let set = ticketOf.get(key)
    if (!set) { set = new Set(); ticketOf.set(key, set) }
    set.add(ticket)
    log(`ticket issued: ${agentId} turn ${turn ?? '-'}; live tickets of this turn ${set.size}`)
    return ticket
  }

  /** Revoke the tickets of a finished turn. */
  const revokeTurn = (agentId, turn) => {
    const key = turnKey(agentId, turn)
    const set = ticketOf.get(key)
    if (!set || !set.size) return false
    for (const t of set) tickets.delete(t)
    const n = set.size
    ticketOf.delete(key)
    return n
  }

  /**
   * Returns the identity for a ticket, or the reason for refusal. We fail
   * CLOSED: an unknown, revoked or expired ticket is a refusal with a clear
   * reason, not an empty identity passed off as success.
   */
  const resolveTicket = (ticket) => {
    if (typeof ticket !== 'string' || !ticket) return { error: 'no ticket presented' }
    const rec = tickets.get(ticket)
    if (!rec) return { error: 'ticket unknown or already revoked' }
    if (Date.now() - rec.issuedAt > TICKET_TTL_MS) {
      tickets.delete(ticket)
      const set = ticketOf.get(turnKey(rec.agentId, rec.turn))
      if (set) { set.delete(ticket); if (!set.size) ticketOf.delete(turnKey(rec.agentId, rec.turn)) }
      return { error: 'ticket expired' }
    }
    return { agentId: rec.agentId }
  }

  // A turn opened / closed. The number of the open turn is needed to bind a
  // ticket to it; turn/end revokes the tickets of exactly its own turn.
  ctx.on('session/event', (session, event) => {
    const sid = String(session?.id ?? '')
    if (!sid) return
    if (event?.type === 'turn/start') openTurnOf.set(sid, event.data?.turn)
    else if (event?.type === 'turn/end') {
      if (openTurnOf.get(sid) === event.data?.turn) openTurnOf.delete(sid)
      const n = revokeTurn(sid, event.data?.turn)
      if (n) {
        log(`tickets of turn ${event.data?.turn} for ${sid} revoked: ${n} (${event.data?.reason?.kind ?? 'end of turn'})`)
      }
      // Deferred, and kept clear of ticket revocation: an error in our own limit
      // has no right to deprive the turn of its normal ticket cleanup.
      // checkHeartbeat is declared BELOW in this file — it needs agents and
      // limits, which are assembled after this subscription. By the time the
      // first event arrives, apply has long finished, so the forward reference
      // resolves.
      setTimeout(() => {
        checkHeartbeat(sid).catch((e) => log(`🔴 self-wake limit: the check for ${sid} threw: ${e?.message ?? e}`))
      }, 0)
    }
  })

  const agents = ctx.get('agents')
  const limits = {
    createLimit: config?.createLimit ?? CREATE_LIMIT_DEFAULT,
    createWindowMs: (config?.createWindowMinutes ?? CREATE_WINDOW_MINUTES_DEFAULT) * 60000,
    blockedAfterRounds: config?.blockedAfterRounds ?? BLOCKED_AFTER_ROUNDS_DEFAULT,
    serverName: config?.serverName ?? SERVER_NAME_DEFAULT,
    heartbeatMinIntervalSeconds: config?.heartbeatMinIntervalSeconds ?? HEARTBEAT_MIN_INTERVAL_SECONDS_DEFAULT,
    heartbeatMaxConsecutive: config?.heartbeatMaxConsecutive ?? HEARTBEAT_MAX_CONSECUTIVE_DEFAULT,
    heartbeatMaxPerDay: config?.heartbeatMaxPerDay ?? HEARTBEAT_MAX_PER_DAY_DEFAULT,
    heartbeatDayZone: config?.heartbeatDayZone ?? HEARTBEAT_DAY_ZONE_DEFAULT,
    heartbeatNoticeDir: config?.heartbeatNoticeDir ?? HEARTBEAT_NOTICE_DIR_DEFAULT,
    heartbeatHumanKinds: new Set(config?.heartbeatHumanKinds ?? HEARTBEAT_HUMAN_KINDS_DEFAULT),
  }

  /**
   * 🔴 THE LIMIT IS CHECKED AT THE END OF A TURN, AND THAT IS A BOUNDARY, NOT A
   * CONVENIENCE. The operational requirement: "the limit stops the CYCLE but
   * does not touch a turn already started — unfinished work is not aborted".
   * turn/end means the turn is finished; stopping earlier is dishonest, and
   * later there is nothing to stop on.
   *
   * THE MOUNTING POINT WAS TAKEN ALREADY PROVEN. In the design I named
   * agent/status and said I had not checked it live. Checking turned out to be
   * unnecessary: this same plugin has been holding ticket revocation on
   * session/event since 2026-08-21, so the subscription demonstrably reaches us
   * at this very mounting point. A new mounting point next to a working one is a
   * superfluous entity.
   *
   * DEFERRED WITH setTimeout(0) DELIBERATELY. The platform publishes the event
   * SYNCHRONOUSLY and holds a lock while publishing: "session append cannot
   * reenter while another append is being published" (dsh-session,
   * lib/index.js:1456). Stopping writes to the log (schedule/change delete) —
   * that is, it cannot be called from inside the event handler. A deferred call
   * lands outside the publication.
   */
  const stopped = new Set()
  const checkHeartbeat = async (sid) => {
    const agent = agents.get(sid)
    if (!agent) return
    // Root agents only: a subagent has no schedule of its own, and the streak is
    // counted from the root's log. The same boundary as for the ticket.
    if (typeof agents.roots !== 'function' || !agents.roots().includes(agent)) return
    const c = heartbeatCounters(agent.session.events, limits.heartbeatDayZone, Date.now(),
      limits.heartbeatHumanKinds)
    const overStreak = c.streak >= limits.heartbeatMaxConsecutive
    const overDay = c.perDay >= limits.heartbeatMaxPerDay
    // A line on EVERY end of turn. A mechanism that says nothing is
    // indistinguishable from a switched-off one — we have already been through
    // that with persistence.
    log(`self-wake ${sid}: in a row ${c.streak}/${limits.heartbeatMaxConsecutive}, `
      + `per day ${c.perDay}/${limits.heartbeatMaxPerDay} (zone ${limits.heartbeatDayZone})`)
    if (!overStreak && !overDay) {
      // 🔴 THE CONDITION THAT REARMS THE GUARD, without which it would fire once
      // in the lifetime of the process: the streak was broken by a human, or a
      // new day has begun.
      if (stopped.delete(sid)) log(`self-wake limit: the streak for ${sid} is broken — the guard is armed again`)
      return
    }
    // Once per streak, not once per turn: a stop notice repeated on every turn
    // would itself become the noise the limit protects against.
    if (stopped.has(sid)) return
    stopped.add(sid)
    const why = overStreak
      ? `${c.streak} autonomous wake-ups in a row without a word from a human (limit ${limits.heartbeatMaxConsecutive})`
      : `${c.perDay} wake-ups in a day in this session (limit ${limits.heartbeatMaxPerDay})`
    await stopHeartbeat(ctx, agent, why, c, limits, agents.roots().length)
  }

  const server = createServer(async (req, res) => {
    const reply = (code, body) => {
      res.writeHead(code, { 'content-type': 'application/json; charset=utf-8' })
      res.end(JSON.stringify(body))
    }
    if (req.method !== 'POST' || req.url !== '/invoke') return reply(404, { ok: false, error: 'only POST /invoke exists' })
    const pass = resolveTicket(req.headers['x-bridge-ticket'])
    if (pass.error) {
      log(`\u{1F534} refused at the door: ${pass.error}`)
      return reply(403, { ok: false, error: pass.error })
    }

    let payload
    try {
      const chunks = []
      for await (const c of req) chunks.push(c)
      payload = JSON.parse(Buffer.concat(chunks).toString('utf8'))
    } catch { return reply(400, { ok: false, error: 'body could not be parsed' }) }

    try {
      const value = await callTool(ctx, agents, payload.tool, pass.agentId, payload.args ?? {}, limits)
      // Every call is a log line. It is the sign that the bridge is alive and
      // that the call actually reached it: without it, "the model did not call
      // the tool" and "the tool did not arrive" look identical.
      log(`call ${payload.tool} for ${pass.agentId}: success`)
      reply(200, { ok: true, value })
    } catch (e) {
      // The reason goes back out: a silent tool refusal is read by the model as
      // "the tool is broken", and it starts looking for a way around.
      log(`🔴 ${payload?.tool} for ${pass.agentId}: ${e?.message}`)
      reply(200, { ok: false, error: String(e?.message ?? e).slice(0, 500) })
    }
  })

  let port
  server.listen(config.port, '127.0.0.1', () => {
    port = server.address().port
    // 🔴 The numbers in the line are mandatory, and so is the mark saying where
    // they came from: our values coincide with the defaults, so a bare number
    // does not tell "the config arrived" from "the field was lost".
    const src = (k) => (config?.[k] === undefined ? 'default' : 'configured')
    // Two counts apart rather than one total: the layers differ in origin and in
    // execution, and the loss of a whole layer must be visible in the startup line.
    log(`entry point 127.0.0.1:${port}; tools ${TOOLS.length}`
      + ` (parity with the native route ${PARITY.length}: ${PARITY.map((t) => t.name).join(', ')};`
      + ` platform schedule ${SCHEDULE.length}: ${SCHEDULE.map((t) => t.name).join(', ')})`)
    log(`goal-creation ceiling: ${limits.createLimit} (${src('createLimit')}) `
      + `per ${limits.createWindowMs / 60000} min (${src('createWindowMinutes')}); `
      + `under the ceiling: ${Object.entries(EXEC).filter(([, e]) => e.counted).map(([n]) => n).join(', ') || 'nothing'}`)
    log(`blocked threshold: ${limits.blockedAfterRounds} (${src('blockedAfterRounds')}) autonomous rounds`)
    log(`ticket: per (identity, turn), dies on turn/end; upper lifetime ${TICKET_TTL_MS / 60000} min (${src('ticketTtlMinutes')}); issued to root agents only`)
    log(`server name: "${limits.serverName}" (${src('serverName')}); the model sees the tools as mcp__${limits.serverName}__<name>`)
    // 🔴 Two lines, not one: the limit and its BOUNDARIES. A protection that does
    // not name where it does not apply will sooner or later produce exactly the
    // harm it was protecting against.
    // 🔴 The source mark is placed right after ITS OWN value, not as two words in
    // a row at the end: "(configured, configured)" keeps the meaning but does not
    // read — it is unclear whether the mark belongs to the number or to the zone.
    // There are still two sources.
    //
    // 🔴 The number 96 is printed as a written-out number on purpose. A stop
    // notice is read AFTER the event, whereas the startup line is read while
    // working out "what is actually configured"; a spoken "48 per session" would
    // be forgotten exactly as "per agent" would have been. It is computed from
    // the setting (×2) rather than typed in, so that it does not drift when the
    // limit changes.
    //
    // The live number of sessions is NOT taken here: an agent is created LAZILY,
    // on its first message, and at startup time agents.roots() is empty — on
    // 2026-08-22 the startup lines were at 22:55:55 and the agent was created at
    // 22:57:12, a gap of 77 seconds. The live number would always be 0 and would
    // lie. The live one is taken in the stop notice, where sessions already exist.
    log(`self-wake limit: no more often than ${limits.heartbeatMinIntervalSeconds} s (${src('heartbeatMinIntervalSeconds')}); `
      + `no more than ${limits.heartbeatMaxConsecutive} in a row without a word from a human (${src('heartbeatMaxConsecutive')}); `
      + `no more than ${limits.heartbeatMaxPerDay} per day PER SESSION, not per agent (${src('heartbeatMaxPerDay')}), `
      + `in zone ${limits.heartbeatDayZone} (${src('heartbeatDayZone')}); `
      + `the agent's total ceiling = number of live root sessions × ${limits.heartbeatMaxPerDay} `
      + `(two sessions already make ${2 * limits.heartbeatMaxPerDay} a day); `
      + `counted from the session log — a restart does not reset it; `
      + `a word from a human = source kinds [${[...limits.heartbeatHumanKinds].join(', ')}] (${src('heartbeatHumanKinds')}); `
      + `stop notice ${limits.heartbeatNoticeDir === '' ? 'to the log only: no directory configured' : `to ${limits.heartbeatNoticeDir}`} (${src('heartbeatNoticeDir')})`)
    log('self-wake limit DOES NOT APPLY: to goal rounds (they have their own defaultMaxGoalRounds), '
      + 'to wake-ups from background jobs (they have their own maxConsecutiveWakes), to an agent without the bridge '
      + '(on the native route the schedule runs on the native platform loop — it needs a guard of its own) '
      + 'and against anyone who has sudo: the isolation here is behavioural, and the counter is read from the log of my own process')
  })

  // The service is declared IMMEDIATELY rather than in the callback: cordis
  // requires provide before set, and the consumer must see the service from the
  // first moment. Until the port is taken, the descriptor is empty — and a line
  // is written about that, otherwise "there is no bridge" and "the bridge has
  // not come up yet" would look identical.
  ctx.provide('mcpBridge', {
    /** The server name — so that consumers do not assemble the prefix from memory. */
    serverName: limits.serverName,
    /**
     * The tool name AS THE MODEL SEES IT. The base name is literally the
     * platform's own; the prefix is added by the MCP protocol (exactly as for any
     * external MCP server). Needed by system prompts: text that names a tool
     * without the prefix sends the model to a name that does not exist.
     */
    modelToolName(base) { return `mcp__${limits.serverName}__${base}` },
    /** Base names of all exposed tools — for system prompts and checks. */
    toolNames() { return TOOLS.map((t) => t.name) },
    /**
     * A bridge descriptor for ONE turn of ONE identity. The identity is passed
     * in here by the host (the adapter takes it from the live initiator) and does
     * NOT LEAVE: the response contains only a ticket. Each call issues a new
     * ticket.
     */
    descriptor(agentId) {
      if (port === undefined) {
        log('🔴 a descriptor was requested before the entry point came up — tools are not connected')
        return undefined
      }
      if (typeof agentId !== 'string' || !agentId) {
        // Fail closed and loudly: a descriptor without an identity would mean a
        // ticket bound to nobody — that is, a door left wide open.
        log('🔴 a descriptor was requested without an identity — no ticket issued')
        return undefined
      }
      // 🔴 ROOT AGENTS ONLY. A platform subagent would receive its own ticket
      // with its own identity — that is, its own goal-creation counter, and the
      // ceiling would be bypassed by way of the boundary. The check is the same
      // one the platform makes in tool-goal: object identity, not name equality.
      const owner = agents?.get?.(agentId)
      if (!owner) {
        log(`🔴 descriptor for ${agentId}: no live agent with that identity — no ticket issued`)
        return undefined
      }
      if (typeof agents.roots === 'function' && !agents.roots().includes(owner)) {
        log(`🔴 descriptor for ${agentId}: the agent is not a root — no ticket issued`)
        return undefined
      }
      // The turn is taken from the map maintained by session events. There may be
      // no turn (the descriptor was requested outside a turn) — then the ticket
      // lives only until its deadline and no turn/end will revoke it; we mark
      // that with the key '-'.
      const turn = openTurnOf.get(agentId)
      return {
        // The server name is decided by the BRIDGE, not the gateway: the gateway
        // is generic, knows nothing about our domains, and its own default is a
        // generic word.
        name: limits.serverName,
        url: `http://127.0.0.1:${port}/invoke`,
        ticket: issueTicket(agentId, turn),
        // Schemas go to the model as JSON Schema: zod cannot travel over the
        // wire, and the gateway rebuilds it with its own adapter.
        // Names, descriptions and schemas come from parity.json and
        // schedule.json, that is, literally the ones the platform packages
        // register. The bridge hands them to the engine as they are.
        tools: TOOLS.map((t) => ({
          name: t.name,
          description: t.description,
          inputSchema: t.parameters,
        })),
      }
    },
  })

  ctx.on('dispose', () => {
    mounted = false
    try { server.close() } catch { /* the platform is shutting down, nobody to complain to */ }
  })
}
