/**
 * Execution, keyed by parity names.
 *
 * `remote` — an operation of the platform's remote boundary (namespace/method).
 * Identity resolution, argument validation and result validation are done by
 * the boundary itself; the bridge neither duplicates nor weakens them.
 * `local` — a direct service call in this same process. Defined only where
 * there is NO boundary (verified against the Remote decorators in dsh-goal:
 * edit, pause, resume, complete, clear, create are exposed, while get and block
 * are NOT; the jobs service has no remote methods at all).
 * 🔴 The isolation of the local path rests not on a check of ours but on the
 * service itself: both goals.get and every jobs.* take a LIVE agent and work
 * only with its own state.
 */
/**
 * 🔴 THE TURN-AUTHORITY LAYER (an operational decision, layer 1 of three).
 *
 * WHY. The identity in a call answers "whose agent", not "by what right". An
 * engine subagent arrives with the root's identity (built-in types cannot have
 * the bridge server taken away from them — verified 2026-08-22), so what must
 * be distinguished is not the caller but the AUTHORITY OF THE TURN the call is
 * made inside: was the turn opened by a human, or by a round of the current
 * goal?
 *
 * 🔴 THIS REPRODUCES SOMEONE ELSE'S POLICY, IT IS NOT OUR OWN. It is copied
 * verbatim from @deepseek-ai/dsh-tool-goal (lib/types/authority.js of the same
 * installed version), together with its BOUNDARIES, not only its prohibitions:
 * where the native route does not require authority, it is not required here
 * either. Home-grown tightening breaks work exactly as much as loosening does:
 * an agent whose human just asked "so how is it going" must be able to answer
 * "I am stuck".
 *
 * WHAT CANNOT BE REPRODUCED, AND WHY. The original additionally requires
 * `ctx.agents.currentInitiator() === agent`. The initiator lives in the turn's
 * AsyncLocalStorage, and this handler is loopback HTTP — a different async
 * context, where there is no initiator at all (established 2026-08-21).
 * Therefore the check is written as "if an initiator IS visible and it is not
 * our agent — refuse": when it is available the policy is not weakened, and
 * when it is not, it does not produce a false refusal. The gap is closed by
 * agent liveness and by the open turn.
 */

/** The current turn's window: events after the last turn/start. Turn closed — refuse. */
function openTurn(agent) {
  const events = agent.session.events
  for (let i = events.length - 1; i >= 0; i -= 1) {
    const b = events[i]
    if (b?.type === 'turn/end') throw new Error('goal tools require an open model turn')
    if (b?.type === 'turn/start') return events.slice(i + 1)
  }
  throw new Error('goal tools require an open model turn')
}

/**
 * A live agent and its turn window. Instance identity, running state and an
 * open turn — the same three signs as on the native route, minus the initiator.
 */
function bridgeExecution(agents, agentId) {
  const agent = agents.get(String(agentId))
  if (!agent) throw new Error(`live agent "${agentId}" not found in the registry`)
  if (agent.status !== 'running') throw new Error(`agent "${agentId}" is not running (${agent.status})`)
  let initiator
  try { initiator = agents.currentInitiator() } catch { initiator = undefined }
  if (initiator !== undefined && initiator !== agent) {
    throw new Error('the call arrived outside the turn of the calling agent')
  }
  return { agent, events: openTurn(agent) }
}

/**
 * Human authority: a root agent and a human message inside this turn.
 * 🔴 Only kind === 'user' — verbatim as in the original. A service channel, if
 * you have one, carries ITS OWN source kind and does NOT grant human authority:
 * the right to dispose of a goal comes as a direct command to the host, and we
 * deliberately declined to give it a second, implicit path (an operational
 * decision).
 * 🔴 Separately: the self-wake limit uses a DIFFERENT list of kinds, and it is
 * configurable — see HEARTBEAT_HUMAN_KINDS_DEFAULT. There the question is "is
 * anybody alive nearby", here it is "is this allowed to dispose of the goal".
 * Different questions, different answers.
 */
function hasDirectHumanInput(agents, execution) {
  if (!agents.roots().includes(execution.agent)) return false
  return execution.events.some((e) => e.type === 'user/message' && e.data?.source?.kind === 'user')
}

/** The turn is exactly the admitted round of the current goal: goal, revision and number. */
function isMatchingGoalRound(execution, goal) {
  return execution.events.some((e) =>
    e.type === 'user/message'
    && e.data?.source?.kind === 'goal'
    && e.data.source.goalId === goal.id
    && e.data.source.revision === goal.revision
    && e.data.source.round === goal.roundsStarted)
}

/** create, edit, pause, resume — a direct human turn on the root, and nothing else. */
function requireDirectHuman(agents, execution) {
  if (hasDirectHumanInput(agents, execution)) return
  throw new Error('this operation requires a direct human turn on the root agent')
}

/** complete and blocked — a human OR exactly the current goal round. */
function completionAuthority(ctx, agents, execution) {
  if (hasDirectHumanInput(agents, execution)) return { kind: 'direct-human' }
  const goal = ctx.get('goals').get(execution.agent)
  if (goal !== undefined && isMatchingGoalRound(execution, goal)) return { kind: 'goal-round', goal }
  throw new Error('complete and blocked require a direct human turn or the current goal round')
}

/**
 * 🔴 CLAMPING THE ROUND LIMIT PASSED IN (an operational decision).
 *
 * THIS IS A DEPARTURE FROM PARITY, AND IT IS DELIBERATE — said out loud: the
 * native route has no such clamp. The reason is in the platform's shape: create
 * takes `request.maxGoalRounds ?? defaultMaxGoalRounds`, that is, WHAT THE MODEL
 * PASSES WINS over the configuration, and our limit of 5 rounds is removed by a
 * single argument. The tool schema stays at parity: the field is there, the type
 * is the same.
 *
 * THE BOUNDARY WHEN THE READ FAILS. The ceiling is taken from the live goals
 * service. If the field disappears (it belongs to the library, an upgrade may
 * remove it), the passed value is DISCARDED entirely — the goal gets the host
 * default. That is fail-closed in substance: the limit is not raised, and the
 * tool stays alive.
 */
function capRounds(ctx, requested) {
  if (requested === undefined) return undefined
  const cap = ctx.get('goals')?.resolved?.defaultMaxGoalRounds
  if (typeof cap !== 'number') {
    log(`🔴 host round limit could not be read — the passed value ${requested} was discarded`)
    return undefined
  }
  if (requested > cap) {
    log(`round limit clamped: requested ${requested}, host ceiling ${cap}`)
    return cap
  }
  return requested
}

