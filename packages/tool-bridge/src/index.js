/**
 * Bridge that carries platform tools onto an engine-driven route.
 *
 * WHY. On a subscription route the loop is driven by the Claude Code engine,
 * and the model's tool registry is the engine's own. Platform plugin tools do
 * not reach the model AT ALL: the platform has an MCP client but no MCP server
 * of its own (established 2026-08-22, confirmed by two independent readings —
 * zero tool/* events in the platform log, while the actual calls appear only in
 * the engine transcript). The bridge gives platform tools the same path that
 * tools of external MCP servers arrive by.
 *
 * SHAPE. Three parts in three processes:
 *   1. THIS plugin — inside the platform process. Owns a loopback entry point
 *      and executes calls. Goal state lives here too, which is why execution
 *      belongs here and not in the gateway.
 *   2. provider adapter — tells the gateway the identity of the live agent and
 *      the address of that entry point, on every request.
 *   3. subscription gateway — assembles an MCP server (sdk transport) and hands
 *      it to the engine.
 * The gateway knows nothing about goals: it receives the tool DESCRIPTION from
 * here and proxies calls back. That is a requirement of a general solution —
 * the next agent, with a different tool set, connects without editing the
 * gateway.
 *
 * 🔴 WHAT IS NOT REIMPLEMENTED HERE. Identity resolution, argument validation
 * and result validation are the platform's own; ctx.typertGateway (the
 * platform's remote boundary) does them. Operation schemas are generated by the
 * platform and live in each package's typert.host.js. The bridge neither
 * duplicates nor weakens them: on a made-up identity the boundary refuses
 * ("lookup provider \"agent\" did not resolve the requested identity"), verified
 * by a live run on 2026-08-22.
 *
 * 🔴 A BOUNDARY YOU MUST KNOW. Only MUTATING goal operations are exposed across
 * the remote boundary (clear, complete, create, edit, pause, resume). There are
 * no reads there at all: goals/get answers "no active Remote method exports
 * this endpoint". So the reading tool is executed by a direct service call in
 * this same process — and that is the only place where the bridge acts around
 * the boundary. There is not a single mutating operation around it.
 *
 * ACCESS BOUNDARIES. The entry point listens on loopback (127.0.0.1) only and
 * requires a ONE-TIME TICKET — not a shared secret. The ticket is born here for
 * a pair (identity, turn), travels to the gateway in the adapter's response
 * body, lives in the closure of the server instance and dies on turn/end of its
 * own turn. Identity is NEVER SENT over the gateway→bridge wire: the bridge
 * looks it up in its own table by ticket, so the caller has nothing to assert
 * an identity with.
 * 🔴 HISTORY, so that this header does not drift from the code again: until
 * 10:03 on 2026-08-22 there was a LONG-LIVED shared secret here, and identity
 * travelled as a separate field. That design is gone; its description outlived
 * the code by several hours, and a wrong conclusion about the design was drawn
 * from the description. If you change the design, fix this paragraph in the
 * same pass.
 * The ticket never reaches a command line: the sdk transport spawns no child
 * process, and everything the SDK passes as an argument (--mcp-config) is
 * readable by any user of the machine through /proc/<pid>/cmdline (mode 444) —
 * verified with a live observer on 2026-08-22.
 */
