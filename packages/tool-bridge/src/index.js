/**
 * 🔴 СЛОЙ ПОЛНОМОЧИЯ ХОДА (решение главной 22.08.2026, слой 1 из трёх).
 *
 * ЗАЧЕМ. Личность в вызове — это «чей агент», а не «по какому праву». Помощник
 * движка приходит с личностью корня (у встроенных типов сервер моста не
 * отнять — проверено 22.08), поэтому различать надо не звонящего, а ПОЛНОМОЧИЕ
 * ХОДА, внутри которого зовут: открыт ли ход человеком или раундом текущей цели.
 *
 * 🔴 ЭТО ВОСПРОИЗВЕДЕНИЕ ЧУЖОЙ ПОЛИТИКИ, А НЕ СВОЯ. Повторено дословно по
 * @deepseek-ai/dsh-tool-goal (lib/types/authority.js той же установленной
 * версии), вместе с ГРАНИЦАМИ, а не только запретами: где у соседнего агента
 * полномочие не требуется — оно не требуется и здесь. Самодельное ужесточение
 * так же ломает работу, как ослабление: агент, которого человек спросил «ну
 * что там», обязан мочь ответить «застрял».
 *
 * ЧТО ПОВТОРИТЬ НЕЛЬЗЯ И ПОЧЕМУ. Оригинал требует ещё
 * `ctx.agents.currentInitiator() === agent`. Инициатор живёт в
 * AsyncLocalStorage хода, а этот обработчик — HTTP на петле, то есть другой
 * асинхронный контекст: там инициатора нет вовсе (установлено 21.08.2026).
 * Поэтому проверка стоит в форме «если инициатор ВИДЕН и это не наш агент —
 * отказ»: когда она доступна, политика не ослаблена; когда нет — не даёт
 * ложного отказа. Разницу закрывают живость агента и открытый ход.
 */

/** Окно текущего хода: события после последнего turn/start. Ход закрыт — отказ. */
function openTurn(agent) {
  const events = agent.session.events
  for (let i = events.length - 1; i >= 0; i -= 1) {
    const b = events[i]
    if (b?.type === 'turn/end') throw new Error('инструменты целей требуют открытого хода модели')
    if (b?.type === 'turn/start') return events.slice(i + 1)
  }
  throw new Error('инструменты целей требуют открытого хода модели')
}

/**
 * Живой агент и окно его хода. Тождество экземпляра, состояние running и
 * открытый ход — те же три признака, что у соседнего агента, минус инициатор.
 */
function bridgeExecution(agents, agentId) {
  const agent = agents.get(String(agentId))
  if (!agent) throw new Error(`живой агент "${agentId}" не найден в реестре`)
  if (agent.status !== 'running') throw new Error(`агент "${agentId}" не в состоянии running (${agent.status})`)
  let initiator
  try { initiator = agents.currentInitiator() } catch { initiator = undefined }
  if (initiator !== undefined && initiator !== agent) {
    throw new Error('вызов пришёл вне хода вызывающего агента')
  }
  return { agent, events: openTurn(agent) }
}

/**
 * Человеческое полномочие: корневой агент и человеческое сообщение в этом ходе.
 * 🔴 Только kind === 'user' — дословно как в оригинале. Служебный канал носит
 * свой вид ('a2a') и человеческого полномочия НЕ даёт: право координатора
 * останавливать цель идёт прямой командой хосту, и заводить ему второй,
 * неявный путь мы отказались осознанно (решение главной 21.08.2026).
 */
function hasDirectHumanInput(agents, execution) {
  if (!agents.roots().includes(execution.agent)) return false
  return execution.events.some((e) => e.type === 'user/message' && e.data?.source?.kind === 'user')
}

/** Ход — в точности допущенный раунд текущей цели: цель, ревизия и номер. */
function isMatchingGoalRound(execution, goal) {
  return execution.events.some((e) =>
    e.type === 'user/message'
    && e.data?.source?.kind === 'goal'
    && e.data.source.goalId === goal.id
    && e.data.source.revision === goal.revision
    && e.data.source.round === goal.roundsStarted)
}

/** create, edit, pause, resume — только прямой человеческий ход на корне. */
function requireDirectHuman(agents, execution) {
  if (hasDirectHumanInput(agents, execution)) return
  throw new Error('эта операция требует прямого человеческого хода на корневом агенте')
}

/** complete и blocked — человек ИЛИ в точности текущий раунд цели. */
function completionAuthority(ctx, agents, execution) {
  if (hasDirectHumanInput(agents, execution)) return { kind: 'direct-human' }
  const goal = ctx.get('goals').get(execution.agent)
  if (goal !== undefined && isMatchingGoalRound(execution, goal)) return { kind: 'goal-round', goal }
  throw new Error('complete и blocked требуют прямого человеческого хода или текущего раунда цели')
}

/**
 * 🔴 ЗАЖИМ ПЕРЕДАННОГО ПРЕДЕЛА РАУНДОВ (решение главной 22.08.2026).
 *
 * ЭТО ОТСТУПЛЕНИЕ ОТ ПАРИТЕТА, И ОНО НАМЕРЕННОЕ — называю прямо: у соседнего агента
 * такого зажима нет. Причина в устройстве платформы: create берёт
 * `request.maxGoalRounds ?? defaultMaxGoalRounds`, то есть ПЕРЕДАННОЕ МОДЕЛЬЮ
 * ПОБЕЖДАЕТ настройку, и наш предел в 5 раундов снимается одним аргументом.
 * Схема инструмента при этом остаётся паритетной: поле есть, тип тот же.
 *
 * ГРАНИЦА ПРИ ОТКАЗЕ ЧТЕНИЯ. Потолок берётся из живого сервиса целей. Если
 * поле исчезнет (своё у библиотеки, обновление может его убрать), переданное
 * значение ОТБРАСЫВАЕТСЯ целиком — цель получит хостовое умолчание. Это
 * fail-закрыто по существу: предел не задирается, а инструмент остаётся жив.
 */
function capRounds(ctx, requested) {
  if (requested === undefined) return undefined
  const cap = ctx.get('goals')?.resolved?.defaultMaxGoalRounds
  if (typeof cap !== 'number') {
    log(`🔴 предел раундов хоста не прочитан — переданное значение ${requested} отброшено`)
    return undefined
  }
  if (requested > cap) {
    log(`предел раундов зажат: запрошено ${requested}, хостовый потолок ${cap}`)
    return cap
  }
  return requested
}

