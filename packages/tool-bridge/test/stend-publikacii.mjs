// Три проверки на файл состава: есть в составе / адресов установки нет / имён нет.
// Число ВЫЧИСЛЯЕТСЯ из состава, а не вписано: вписанное отстанет от первого же
// добавленного файла и покраснеет на исправном предмете.
// Число вычисляется из состава: три проверки на живой файл, ноль на собираемый при
// публикации (он вне проверки), две слепоты на пропавший. Вписанное число отстало бы.
// 4 проверки на существующий файл: состав, нейтральность, копии правок и
// (с 02.09) внешние команды жёстким путём. Число ВЫЧИСЛЯЕТСЯ из состава, а не
// вписано: иначе оно устаревает при первом же изменении перечня файлов.
const ZHDYOM = SOSTAV.reduce((n, f) => n + (existsSync(path.join(KORNI, f)) ? 4 : (sobiraetsya(f) ? 0 : 2)), 0)
  + ISKLYUCHENIYA.length * 2 + 4 + 3
  + 3  // раздел 7: переход с частной сборки (см. там же)
const vsego = ok + bad + slep
console.log(`ИТОГО: сошлось ${ok}, расхождений ${bad}, слепот ${slep}`)
if (vsego !== ZHDYOM) {
  console.log(`СЛЕПОТА: проверок ${vsego}, ждали ${ZHDYOM} — часть не состоялась`)
  process.exit(2)
}
