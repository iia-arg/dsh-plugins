// Стенд: модуль готов к выкладке наружу.
// Проверяет СОСТАВ публикации и НЕЙТРАЛЬНОСТЬ: ни одного частного имени —
// ни пути с чужой машины, ни имени человека, ни имени агента.
//
// Коды: 0 сошлось | 1 расхождение | 2 слепота (проверить не удалось).
//
// 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ СТЕНД. Обезличивание делается один раз, а расходится
// постепенно: кто-нибудь допишет пояснение со своим путём, и никто не заметит,
// пока пакет не окажется у постороннего. Проверка должна ехать вместе с кодом.
//
// ГДЕ НЕ ПРИМЕНЯЕТСЯ:
//   * не судит о содержании: нейтральный текст может быть неверным;
//   * ловит имена по образцу — новое частное имя, не попавшее в образец,
//     пройдёт мимо. Это нижняя оценка, а не доказательство чистоты;
//   * не проверяет, что модуль РАБОТАЕТ: для этого соседние стенды.
import { readFileSync, existsSync, readdirSync } from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'

const KORNI = process.env.MOST_KORNI
  || path.dirname(path.dirname(new URL(import.meta.url).pathname))

// Состав публикации. Перечень, а не каталог: рядом с предметом лежат копии
// прежних правок, и выложить каталог целиком значит отдать наружу всю историю.
// 🔴 СОСТАВ ЧИТАЕТСЯ ИЗ МАНИФЕСТА, А НЕ ДЕРЖИТСЯ КОПИЕЙ (02.09.2026).
// Здесь был рукописный перечень из одиннадцати файлов. Он отстал молча: в files
// добавился новый стенд, а в перечне его не было — и стенд публикации НЕ ПРОВЕРЯЛ
// его вовсе. Порча (частное имя, вписанное в тот файл) не ловилась, и зелёное
// означало «не смотрел туда». Перечень-копия отстаёт от источника всегда; вопрос
// только в том, заметят ли. Теперь источник один: files манифеста.
const SOSTAV = (() => {
  try {
    const m = JSON.parse(readFileSync(path.join(KORNI, 'package.json'), 'utf-8'))
    const f = Array.isArray(m.files) ? m.files.filter((x) => typeof x === 'string') : []
    // package.json в files не указывают — он едет всегда; проверять его надо.
    return f.includes('package.json') ? f : ['package.json', ...f]
  } catch (e) {
    console.log(`СЛЕПОТА: состав не прочитан из манифеста (${e?.message ?? e}) — проверять нечего`)
    process.exit(2)
  }
})()


// 🔴 Образец собирается ИЗ КУСКОВ: написанный целиком, он содержал бы те самые
// имена, которые ищет, и стенд ловил бы сам себя.
// 🔴 02.09.2026: здесь был ВТОРОЙ список частных имён — в коде, точными формами.
// Он разошёлся с общим файлом-списком и пропустил склонение имени агента в
// комментарии: латинская основа в образце была, кириллической не было, а падежная
// форма точным именем не ловится вовсе.
// Теперь основы берутся из файла-списка; путь задаётся переменной SPISOK_IMYON,
// потому что список общий на машину и лежит НЕ у этого пакета, а адрес нашей
// машины в пакет ехать не должен. Нет файла — остаётся встроенный образец, и об
// этом сказано вслух: у постороннего файла и не бывает, но он должен знать, чем
// именно его проверили.
const VSTROENNOE = ['/opt/[a-z]', '/home/[a-z]', 'sa' + 'dik', 'clau' + 'declaw']
const PUT_SPISKA = process.env.SPISOK_IMYON
let OSNOVY = null
try {
  if (PUT_SPISKA && existsSync(PUT_SPISKA)) {
    const d = JSON.parse(readFileSync(PUT_SPISKA, 'utf-8'))
    if (Array.isArray(d.osnovy) && d.osnovy.length) OSNOVY = d.osnovy
  }
} catch { /* остаётся встроенное; причина названа строкой ниже */ }
// 🔴 ДВА НАБОРА ВРОЗЬ, А НЕ ОДИН СКЛЕЕННЫЙ (02.09.2026).
// Прежняя редакция склеивала встроенные пути и основы имён в одно выражение. Нет
// списка — выражение оставалось непустым (пути-то на месте), проверка проходила и
// говорила «чисто» ПРО ИМЕНА, которых не искала. Пустой искомый набор совпадает ни
// с чем и красит зелёным что угодно; снаружи это неотличимо от честной проверки.
// Теперь пути проверяются всегда, а имена — только когда есть чем: иначе СЛЕПОТА.
const PUTI = new RegExp(VSTROENNOE.join('|'), 'gi')
const IMENA = OSNOVY ? new RegExp(OSNOVY.join('|'), 'gi') : null
// 🔴 СУММА СПИСКА ПЕЧАТАЕТСЯ ВСЕГДА, В ТОМ ЧИСЛЕ НА ЗЕЛЁНОМ (02.09.2026).
// Эталона суммы нет нигде намеренно: эталон — тоже копия, и он отстанет от списка
// так же, как отставали все перечни-копии до него. Вместо сверки с эталоном —
// видимость: расхождение обнаруживается там, где встречаются ОТЧЁТЫ разных
// проверяющих. Печать только при беде вернула бы «пустота неотличима от
// исправности»: одинаковое молчание у совпавших и у несравнимых списков.
// Считается от основ, по одной на строку, без комментариев и пустых.
/** Сумма списка — тождество СОСТАВА, а не файла: считается по отсортированному
 *  уникальному набору. Иначе тот же список, набранный в другом порядке, даёт другую
 *  сумму, и сличение отчётов показывает расхождение там, где его нет (02.09.2026:
 *  два прибора с одинаковым составом дали разные суммы, и порядок подгонялся
 *  перебором — подгонка сумм поиском вместо общего источника).
 *  Сортировка по кодам символов, без учёта локали: локальный порядок зависел бы
 *  от машины и вернул бы то же расхождение через другую дверь. */
const SUMMA_SPISKA = OSNOVY
  ? createHash('sha256')
      .update(`${[...new Set(OSNOVY)].sort().join('\n')}\n`)
      .digest('hex').slice(0, 16)
  : 'нет списка'
const ISTOCHNIK_OBRAZCA = OSNOVY
  ? `основы из файла-списка (${OSNOVY.length}) плюс встроенные пути (${VSTROENNOE.length})`
  : `🔴 списка основ НЕТ (SPISOK_IMYON ${PUT_SPISKA ? 'указывает на негодный файл' : 'не задан'}): `
    + `проверка на ИМЕНА не выполняется вовсе, останутся только встроенные пути (${VSTROENNOE.length})`

/** Все совпадения обоих наборов. Имена возвращаются отдельно: их отсутствие —
 *  не «чисто», а «не проверяли», и это разные новости. */
const najti = (tekst) => ({
  puti: tekst.match(PUTI) || [],
  imena: IMENA ? (tekst.match(IMENA) || []) : null,
})

// Объявленные исключения. Список обязан УБЫВАТЬ: каждая строка здесь — долг,
// а не разрешение. Молча оставить исключение и молча его забыть — одно и то же.
// Объявленные исключения — ДАННЫЕ в файле рядом, а не список в коде.
//
// 🔴 ПОЧЕМУ НЕ КОНСТАНТА. Список писался для РАБОЧЕГО каталога, где частные имена
// ещё остаются до переименования. В собранном пакете их ноль по построению — и
// стенд с зашитым списком честно краснел бы у поставившего модуль, требуя, чтобы
// частные имена там были. Проверка, требующая присутствия того, чего быть не
// должно, хуже отсутствующей.
//
// Файл исключений в пакет НЕ КЛАДЁТСЯ: нет файла — значит исключений нет, и
// проверяется голый факт «частных имён ноль». Есть файл — применяются его допуски,
// и тогда же проверяется, что список не разошёлся с предметом: исключение,
// переставшее быть нужным, обязано мешать, иначе список растёт и не убывает.
const FAJL_ISK = path.join(KORNI, 'test', 'isklyucheniya-nejtralnosti.json')
const ISKLYUCHENIYA = existsSync(FAJL_ISK)
  ? JSON.parse(readFileSync(FAJL_ISK, 'utf-8'))
  : []

// 🔴 ФАЙЛЫ, КОТОРЫХ В ЖИВОМ НЕТ ПО ПОСТРОЕНИЮ. Часть состава собирается при
// выпуске: образец настроек для ставящего. Его отсутствие в рабочем каталоге —
// норма, а не пропажа, и путать эти два случая нельзя ни в ту, ни в другую
// сторону. Список — ДАННЫМИ с причиной; нет файла списка — считаем, что таких
// нет вовсе, и всякое отсутствие становится бедой (строгий исход по умолчанию).
const FAJL_SOB = path.join(KORNI, 'test', 'sobiraemye-pri-publikacii.json')
const SOBIRAEMYE = existsSync(FAJL_SOB)
  ? JSON.parse(readFileSync(FAJL_SOB, 'utf-8'))
  : []
const sobiraetsya = (f) => SOBIRAEMYE.some((x) => x.fajl === f)

let ok = 0, bad = 0, slep = 0
const sud = (uslovie, imya, fakt) => {
  if (uslovie) { ok += 1; return }
  bad += 1
  console.log(`FAIL ${imya}: ${fakt ?? ''}`)
}

console.log(`образец частных имён: ${ISTOCHNIK_OBRAZCA}; сумма списка ${SUMMA_SPISKA}`)

// --- 1. Состав на месте ----------------------------------------------------
for (const f of SOSTAV) {
  if (sobiraetsya(f) && !existsSync(path.join(KORNI, f))) {
    // 🔴 НЕ СЛЕПОТА, А СВЕДЕНИЕ. Слепота означает «проверить не удалось» и красит
    // общий исход; здесь же мы ЗНАЕМ, что файла нет, и знаем почему. Считать это
    // слепотой значило бы держать стенд вечно жёлтым и потерять разницу между
    // «всё сошлось» и «часть не проверена».
    console.log(`вне проверки ${f}: собирается при публикации, в рабочем каталоге его нет — это норма`)
    continue
  }
  sud(existsSync(path.join(KORNI, f)), `в составе публикации есть ${f}`, 'файла нет')
}

// --- 2. Нейтральность ------------------------------------------------------
for (const f of SOSTAV) {
  const put = path.join(KORNI, f)
  if (!existsSync(put)) {
    if (sobiraetsya(f)) { console.log(`вне проверки ${f}: собирается при публикации`); continue }
    slep += 1
    console.log(`СЛЕПОТА ${f}: файла нет, проверять нечего`)
    continue
  }
  const n = najti(readFileSync(put, 'utf-8'))
  const isk = ISKLYUCHENIYA.find((i) => i.fajl === f)
  const dopusk = isk ? isk.skolko : 0
  sud(n.puti.length === 0, `${f}: адресов установки нет`,
    `найдено ${n.puti.length}: ${[...new Set(n.puti)].join(', ')}`)
  if (n.imena === null) {
    slep += 1
    console.log(`СЛЕПОТА ${f}: частные ИМЕНА не проверены — списка основ нет, `
      + 'проверять нечем. Это не «чисто»')
  } else {
    sud(n.imena.length <= dopusk, `${f}: частных имён не больше объявленного`,
      `найдено ${n.imena.length}, допущено ${dopusk}: ${[...new Set(n.imena)].join(', ')}`)
  }
}

// --- 3. Исключения объявлены с причиной ------------------------------------
for (const i of ISKLYUCHENIYA) {
  sud(i.pochemu.length > 40, `исключение ${i.fajl} объяснено, а не просто разрешено`,
    `причина короче сорока знаков — это отговорка, а не довод`)
  // 🔴 Исключение, переставшее быть нужным, обязано мешать: иначе список растёт
  // и никогда не убывает. Но судить об этом можно только имея список основ:
  // без него число всегда выйдет нулевым, и живое исключение прочтётся как
  // пережившее свою причину — ложная беда на исправном предмете.
  const n = najti(readFileSync(path.join(KORNI, i.fajl), 'utf-8'))
  if (n.imena === null) {
    slep += 1
    console.log(`СЛЕПОТА исключение ${i.fajl}: списка основ нет — судить о том, `
      + 'нужно ли исключение, нечем')
  } else {
    sud(n.imena.length === i.skolko, `исключение ${i.fajl} ровно на своё число`,
      `объявлено ${i.skolko}, а в файле ${n.imena.length} — список исключений разошёлся с предметом`)
  }
}

// --- 4. Копии правок в состав не попали ------------------------------------
const kopij = SOSTAV.filter((f) => /\.bak|\.orig|\.tmp|\.limits$/.test(f)).length
sud(kopij === 0, 'в составе нет копий и черновиков', `${kopij} штук`)
const vsegoNaDiske = ['src', 'test'].reduce((n, d) => {
  try { return n + readdirSync(path.join(KORNI, d)).length } catch { return n }
}, 0)
// 🔴 Эта проверка про РАБОЧИЙ каталог, где рядом с предметом лежат копии правок.
// В собранном пакете лежит ровно состав, и «на диске больше» там ложно по
// построению. Признак рабочего каталога — наличие копий; нет их — проверять нечего.
const estKopij = ['src', 'test'].some((d) => {
  try { return readdirSync(path.join(KORNI, d)).some((f) => /\.bak-pre-|\.limits$/.test(f)) }
  catch { return false }
})
if (estKopij) {
  sud(vsegoNaDiske > SOSTAV.length,
    'на диске файлов БОЛЬШЕ, чем в составе — публикуется перечень, а не каталог',
    `на диске ${vsegoNaDiske}, в составе ${SOSTAV.length}`)
} else {
  slep += 1
  console.log('СЛЕПОТА состав против диска: копий правок рядом нет — это собранный '
    + 'пакет, а не рабочий каталог, и лишним файлам тут взяться неоткуда')
}

// --- 5. Внешние команды по абсолютному пути ---------------------------------
// 🔴 Заведено 02.09.2026 по случаю, который проверка нейтральности пропустила
// ФОРМАЛЬНО ПРАВИЛЬНО: путь /usr/local/bin/agent-alert — не частное имя, он
// общесистемный. А у постороннего его нет, и вызов молча не сработает никогда:
// тревога не уйдёт, и никто об этом не узнает.
//
// Признак: абсолютный путь в каталог исполняемых внутри публикуемого файла.
// Законен ровно один случай — когда путь стоит УМОЛЧАНИЕМ при настройке, то есть
// в той же строке есть process.env. Тогда поставивший может задать свой путь.
// Граница: проверка смотрит СТРОКУ, а не выражение. Настройка, разнесённая на две
// строки, будет названа — это ложно-красное, лечится объявлением в исключениях,
// и лучше так, чем пропуск.
// Собирается из кусков — иначе строка со списком САМА попадает под признак.
// Тот же приём, что у VSTROENNOE выше: проверка не должна содержать искомое
// целиком, иначе она находит себя и краснеет на исправном предмете.
const KATALOGI_ISP = ['/usr/local/' + 'bin/', '/usr/local/' + 'sbin/',
  '/usr/' + 'bin/', '/usr/' + 'sbin/', '/' + 'bin/', '/' + 'sbin/']
for (const f of SOSTAV) {
  const put = path.join(KORNI, f)
  if (!existsSync(put)) continue
  const stroki = readFileSync(put, 'utf-8').split('\n')
  const zhyostkie = []
  stroki.forEach((l, i) => {
    // 🔴 Комментарии не исполняются, и путь в них безвреден. Без этого стенд
    // находит САМ СЕБЯ — объяснение признака содержит искомый путь (поймано
    // порчей 02.09: первый же прогон дал FAIL на собственном комментарии).
    // Граница: узнаём комментарий по началу строки. Путь внутри блочного
    // комментария без ведущей звёздочки будет назван — ложно-красное, лечится
    // объявлением в исключениях; пропуск был бы хуже.
    const t = l.trim()
    if (t.startsWith('//') || t.startsWith('*') || t.startsWith('/*')) return
    if (!KATALOGI_ISP.some((k) => l.includes(k))) return
    if (l.includes('process.env')) return
    zhyostkie.push(`${i + 1}: ${l.trim().slice(0, 90)}`)
  })
  sud(zhyostkie.length === 0, `${f}: внешних команд жёстким путём нет`,
    zhyostkie.length ? `${zhyostkie.length} шт. — у постороннего этих путей нет, вызов молча не сработает: ${zhyostkie[0]}` : '')
}

// --- 5б. АБСОЛЮТНЫЕ ПУТИ: признак ищет, перечень исключений судит ------------
// 🔴 ПОЧЕМУ НЕ ПРОСТО КРАСНОЕ (03.09.2026). Сплошной обход моих трёх предметов дал
// СЕМЬ путей, из которых настоящая утечка ОДНА: остальные шесть законны —
// обезличенные примеры в справке, служебная первая строка исполняемого файла и
// умолчания с переменной окружения и проверкой существования. Признак в лоб
// краснел бы на исправном шесть раз из семи, и его загасили бы — проба, кричащая
// не по делу, умирает от привыкания вернее, чем от отключения.
// И обратное тоже проверено: греп по НАШИМ ИМЕНАМ нашёл бы 1 из 7 — перечень
// имён слеп к шести случаям. Работает только связка: признак для ПОИСКА,
// объяснённые исключения для ВЕРДИКТА.
//
// ПОРЯДОК РАБОТЫ: новый путь — красный, пока не объяснён здесь. Объяснить один
// раз дешевле, чем гасить пробу каждый раз.
// ГДЕ НЕ ПРИМЕНЯЕТСЯ: ищем пути с ХОТЯ БЫ ОДНИМ сегментом после корня. Голый
// корень («/usr/local/») — это кусок склейки в самой пробе, а не путь.
// 🔴 СОБИРАЕТСЯ ИЗ КУСКОВ — тем же приёмом, что KATALOGI_ISP ниже, и по той же
// причине: список, содержащий искомое целиком, находит САМ СЕБЯ и краснеет на
// исправном предмете. Наступила на это через десять строк после того, как
// прочла здесь предупреждение о нём — оно про соседнюю проверку, и «моё новое»
// не показалось местом того же класса.
const OBYASNENNYE_PUTI = [
  ['/etc/' + 'agent-limits',
   'каталог пределов; умолчание, переопределяется AGENT_LIMITS_DIR (src:935)'],
  ['/usr/local/' + 'bin/' + 'agent-alert',
   'команда тревоги; умолчание, переопределяется DSH_ALERT_CMD, наличие проверяется existsSync (src:457-460)'],
]
{
  const KORNI_FS = ['/etc/', '/usr/', '/opt/', '/var/', '/home/', '/srv/', '/root/']
  const najdeno = new Map()
  for (const f of SOSTAV) {
    const put = path.join(KORNI, f)
    if (!existsSync(put)) continue
    let t
    try { t = readFileSync(put, 'utf-8') } catch { continue }
    for (const m of t.matchAll(/\/(?:etc|usr|opt|var|home|srv|root)\/[A-Za-z0-9._-][A-Za-z0-9._/-]*/g)) {
      const p = m[0].replace(/[.,;:]$/, '')
      // Путь, кончающийся слэшем, — кусок склейки или корень каталога, а не файл.
      if (p.endsWith('/')) continue
      if (!najdeno.has(p)) najdeno.set(p, f)
    }
  }
  const neobyasnyonnye = [...najdeno.entries()]
    .filter(([p]) => !OBYASNENNYE_PUTI.some(([o]) => p === o || p.startsWith(o + '/')))
  sud(neobyasnyonnye.length === 0, `абсолютные пути: все ${najdeno.size} объяснены`,
    neobyasnyonnye.map(([p, f]) => `${p} (в ${f})`).join('; '))
  // Контроль зрячести: если признак ничего не находит, вердикт «все объяснены»
  // ничего не стоит — он был бы зелёным и на предмете, полном чужих путей.
  sud(najdeno.size > 0, 'признак зряч: пути вообще находятся',
    'ни одного пути не найдено — проверять было нечего, вердикт выше пустой')
  // И обратное: объяснение, пережившее свой путь, — тот же призрак в комментарии.
  const lishnie = OBYASNENNYE_PUTI.filter(([o]) => ![...najdeno.keys()].some((p) => p === o || p.startsWith(o + '/')))
  sud(lishnie.length === 0, 'нет объяснений для путей, которых уже нет',
    lishnie.map(([o, z]) => `${o} — «${z}»`).join('; '))
}

// --- 6. Документация не пустая ---------------------------------------------
const doc = path.join(KORNI, 'SAMOPROBUZHDENIE.md')
if (existsSync(doc)) {
  const t = readFileSync(doc, 'utf-8')
  sud(t.length > 3000, 'описание механизма не заглушка', `${t.length} знаков`)
  sud(/умолчание/i.test(t) && /границ/i.test(t),
    'описание называет умолчания и границы', 'нет одного из двух')
} else { slep += 2; console.log('СЛЕПОТА: описания механизма нет') }

// --- 7. Предупреждение о переезде имени сервера -----------------------------
// 🔴 ЗАЧЕМ. Имя сервера — ПРИСТАВКА к имени каждого инструмента у модели
// (mcp__<имя>__create_goal). Частная сборка могла жить на умолчании; у пакета
// умолчание своё. Сменил пакет, не закрепив serverName — приставка сменилась
// молча, и модель перестала узнавать инструменты. Отказа при этом нет: набор
// исправен, просто зовётся иначе.
//
// ПРОВЕРЯЕТСЯ СВЯЗЬ README С КОДОМ, А НЕ НАЛИЧИЕ ТЕКСТА. Умолчание ВЫРЕЗАЕТСЯ
// из предмета: перепишут SERVER_NAME_DEFAULT — покраснеет здесь, а не у того,
// кто поставит пакет. Проверка «в README есть слово bridge» этого бы не дала:
// она осталась бы зелёной на разошедшемся тексте.
{
  const rm = path.join(KORNI, 'README.md')
  const kod = readFileSync(path.join(KORNI, 'src/index.js'), 'utf-8')
  const m = kod.match(/const SERVER_NAME_DEFAULT = '([^']+)'/)
  if (!existsSync(rm)) { slep += 3; console.log('СЛЕПОТА: README.md нет — предупреждение проверять негде') }
  else if (!m) { slep += 3; console.log('СЛЕПОТА: умолчание имени сервера не вырезалось из кода') }
  else {
    const t = readFileSync(rm, 'utf-8')
    // 🔴 ПРОВЕРЯЕМ ВНУТРИ РАЗДЕЛА, А НЕ ПО ВСЕМУ ФАЙЛУ. Порча «убрать имя ключа
    // из предупреждения» прошла зелёной: слово serverName есть в README и в
    // другом месте, а проверка по всему тексту этого не различает. Зелень
    // означала «слово где-то есть», а не «предупреждение полное».
    const razdel = (t.match(/##[^\n]*Переход с частной сборки[\s\S]*?(?=\n## |$)/) ?? [''])[0]
    sud(razdel.length > 0,
      'README предупреждает о переходе с частной сборки',
      'раздела нет — ставящий поверх своей сборки потеряет имена инструментов молча')
    sud(razdel.includes('`' + m[1] + '`'),
      `предупреждение называет умолчание «${m[1]}», вырезанное из кода`,
      `в разделе нет значения ${m[1]} — текст разошёлся с SERVER_NAME_DEFAULT`)
    sud(/mcp__/.test(razdel) && /serverName/.test(razdel),
      'предупреждение называет и приставку инструментов, и ключ настройки',
      'без имени ключа предупреждение не говорит, ЧТО закреплять')
  }
}

