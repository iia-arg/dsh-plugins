// Стенд: модуль готов к выкладке наружу.
// Проверяет СОСТАВ публикации и НЕЙТРАЛЬНОСТЬ: ни одного частного имени —
// ни пути с чужой машины, ни имени человека, ни имени агента.
//
// Коды: 0 сошлось | 1 расхождение | 2 слепота (проверить не удалось).
//
// 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ СТЕНД. Обезличивание делается один раз, а расходится
// постепенно: кто-нибудь допишет пояснение со своим путём, и никто не заметит,
// пока пакет не окажется у постороннего. Проверка должна ехать вместе с кодом.
//
// ГДЕ НЕ ПРИМЕНЯЕТСЯ:
//   * не судит о содержании: нейтральный текст может быть неверным;
//   * ловит имена по образцу — новое частное имя, не попавшее в образец,
//     пройдёт мимо. Это нижняя оценка, а не доказательство чистоты;
//   * не проверяет, что модуль РАБОТАЕТ: для этого соседние стенды.
import { readFileSync, existsSync, readdirSync } from 'node:fs'
import path from 'node:path'

const KORNI = process.env.MOST_KORNI
  || path.dirname(path.dirname(new URL(import.meta.url).pathname))

// Состав публикации. Перечень, а не каталог: рядом с предметом лежат копии
// прежних правок, и выложить каталог целиком значит отдать наружу всю историю.
const SOSTAV = [
  'package.json',
  'SAMOPROBUZHDENIE.md',
  'src/index.js',
  'src/paritet.json',
  'src/raspisanie.json',
  'test/stend-rezhimov.mjs',
  'test/stend-heartbeat.mjs',
  'test/stend-ostanovki.mjs',
  'test/stend-predelov-iz-fajla.mjs',
  'test/stend-cel-mosta.mjs',
  'test/stend-publikacii.mjs',
]

// 🔴 Образец собирается ИЗ КУСКОВ: написанный целиком, он содержал бы те самые
// имена, которые ищет, и стенд ловил бы сам себя.
const CHASTNOE = new RegExp([
  '/opt/[a-z]', '/home/[a-z]', 'Петр' + 'ович', 'Алекс' + 'андр',
  'Заб' + 'ава', 'is' + 'kra', 'sa' + 'dik', 'clau' + 'declaw',
].join('|'), 'g')

// Объявленные исключения. Список обязан УБЫВАТЬ: каждая строка здесь — долг,
// а не разрешение. Молча оставить исключение и молча его забыть — одно и то же.
// Объявленные исключения — ДАННЫЕ в файле рядом, а не список в коде.
//
// 🔴 ПОЧЕМУ НЕ КОНСТАНТА. Список писался для РАБОЧЕГО каталога, где частные имена
// ещё остаются до переименования. В собранном пакете их ноль по построению — и
// стенд с зашитым списком честно краснел бы у поставившего модуль, требуя, чтобы
// частные имена там были. Проверка, требующая присутствия того, чего быть не
// должно, хуже отсутствующей.
//
// Файл исключений в пакет НЕ КЛАДЁТСЯ: нет файла — значит исключений нет, и
// проверяется голый факт «частных имён ноль». Есть файл — применяются его допуски,
// и тогда же проверяется, что список не разошёлся с предметом: исключение,
// переставшее быть нужным, обязано мешать, иначе список растёт и не убывает.
const FAJL_ISK = path.join(KORNI, 'test', 'isklyucheniya-nejtralnosti.json')
const ISKLYUCHENIYA = existsSync(FAJL_ISK)
  ? JSON.parse(readFileSync(FAJL_ISK, 'utf-8'))
  : []

let ok = 0, bad = 0, slep = 0
const sud = (uslovie, imya, fakt) => {
  if (uslovie) { ok += 1; return }
  bad += 1
  console.log(`FAIL ${imya}: ${fakt ?? ''}`)
}

// --- 1. Состав на месте ----------------------------------------------------
for (const f of SOSTAV) {
  sud(existsSync(path.join(KORNI, f)), `в составе публикации есть ${f}`, 'файла нет')
}

// --- 2. Нейтральность ------------------------------------------------------
for (const f of SOSTAV) {
  const put = path.join(KORNI, f)
  if (!existsSync(put)) { slep += 1; console.log(`СЛЕПОТА ${f}: нечего проверять`); continue }
  const najdeno = (readFileSync(put, 'utf-8').match(CHASTNOE) || [])
  const isk = ISKLYUCHENIYA.find((i) => i.fajl === f)
  const dopusk = isk ? isk.skolko : 0
  sud(najdeno.length <= dopusk, `${f}: частных имён не больше объявленного`,
    `найдено ${najdeno.length}, допущено ${dopusk}: ${[...new Set(najdeno)].join(', ')}`)
}

// --- 3. Исключения объявлены с причиной ------------------------------------
for (const i of ISKLYUCHENIYA) {
  sud(i.pochemu.length > 40, `исключение ${i.fajl} объяснено, а не просто разрешено`,
    `причина короче сорока знаков — это отговорка, а не довод`)
  const najdeno = (readFileSync(path.join(KORNI, i.fajl), 'utf-8').match(CHASTNOE) || []).length
  // 🔴 Исключение, переставшее быть нужным, обязано мешать: иначе список растёт
  // и никогда не убывает.
  sud(najdeno === i.skolko, `исключение ${i.fajl} ровно на своё число`,
    `объявлено ${i.skolko}, а в файле ${najdeno} — список исключений разошёлся с предметом`)
}

// --- 4. Копии правок в состав не попали ------------------------------------
const kopij = SOSTAV.filter((f) => /\.bak|\.orig|\.tmp|\.limits$/.test(f)).length
sud(kopij === 0, 'в составе нет копий и черновиков', `${kopij} штук`)
const vsegoNaDiske = ['src', 'test'].reduce((n, d) => {
  try { return n + readdirSync(path.join(KORNI, d)).length } catch { return n }
}, 0)
// 🔴 Эта проверка про РАБОЧИЙ каталог, где рядом с предметом лежат копии правок.
// В собранном пакете лежит ровно состав, и «на диске больше» там ложно по
// построению. Признак рабочего каталога — наличие копий; нет их — проверять нечего.
const estKopij = ['src', 'test'].some((d) => {
  try { return readdirSync(path.join(KORNI, d)).some((f) => /\.bak-pre-|\.limits$/.test(f)) }
  catch { return false }
})
if (estKopij) {
  sud(vsegoNaDiske > SOSTAV.length,
    'на диске файлов БОЛЬШЕ, чем в составе — публикуется перечень, а не каталог',
    `на диске ${vsegoNaDiske}, в составе ${SOSTAV.length}`)
} else {
  slep += 1
  console.log('СЛЕПОТА состав против диска: копий правок рядом нет — это собранный '
    + 'пакет, а не рабочий каталог, и лишним файлам тут взяться неоткуда')
}

// --- 5. Документация не пустая ---------------------------------------------
const doc = path.join(KORNI, 'SAMOPROBUZHDENIE.md')
if (existsSync(doc)) {
  const t = readFileSync(doc, 'utf-8')
  sud(t.length > 3000, 'описание механизма не заглушка', `${t.length} знаков`)
  sud(/умолчание/i.test(t) && /границ/i.test(t),
    'описание называет умолчания и границы', 'нет одного из двух')
} else { slep += 2; console.log('СЛЕПОТА: описания механизма нет') }

// --- КАНАРЕЙКА -------------------------------------------------------------
const ZHDYOM = SOSTAV.length * 2 + ISKLYUCHENIYA.length * 2 + 4
const vsego = ok + bad + slep
console.log(`ИТОГО: сошлось ${ok}, расхождений ${bad}, слепот ${slep}`)
if (vsego !== ZHDYOM) {
  console.log(`СЛЕПОТА: проверок ${vsego}, ждали ${ZHDYOM} — часть не состоялась`)
  process.exit(2)
}
// 🔴 ТРИ ИСХОДА, А НЕ ДВА. Ноль — только когда всё сошлось и слепот нет.
// Слепота с нулевым кодом проходит у постороннего как успех: он не читает
// текст, он пишет «node стенд && дальше» — и не узнает, что не проверено ничего.
process.exit(bad > 0 ? 1 : (slep > 0 ? 2 : 0))
