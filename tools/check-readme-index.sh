#!/usr/bin/env bash
# Проверка, что корневой README и каталог packages/ не разошлись — в ОБЕ стороны.
#
# 🔴 ЗАЧЕМ. 03.09.2026 в репозитории лежали семь опубликованных пакетов семейства памяти,
# а корневой README не называл НИ ОДНОГО. Машина при этом молчала: перечень в README —
# для человека, и сверять его было нечем. Зелёный учёт тем убедительнее, чем меньше
# он покрывает.
#
# Проверяются два несовпадения, и они разные по смыслу:
#   ссылка есть, каталога нет  — README обещает то, чего в репозитории не существует;
#   каталог есть, ссылки нет   — пакет опубликован и невидим для читающего.
#
# ГДЕ НЕ ПРИМЕНЯЕТСЯ: проверяются ИМЕНА, а не содержание. О том, верно ли README
# описывает пакет, эта проба не говорит ничего.
#
# Коды: 0 — сошлось · 1 — расхождение · 2 — проверять нечем.
# Контроль зрячести: ключ --kontrol.
set -uo pipefail
KOREN="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
[ "$KOREN" = "--kontrol" ] && KOREN="$(cd "$(dirname "$0")/.." && pwd)"

R="$KOREN/README.md"; P="$KOREN/packages"
echo "область: $R против $P (сверяются ИМЕНА каталогов, не содержание)"
[ -r "$R" ] || { echo "СЛЕПОТА: корневой README не прочитан — $R"; exit 2; }
[ -d "$P" ] || { echo "СЛЕПОТА: каталога packages нет — $P"; exit 2; }

bed=0; ssylok=0; katalogov=0
while read -r d; do
  ssylok=$((ssylok+1))
  [ -d "$KOREN/$d" ] || { echo "  🔴 README ссылается на $d — каталога НЕТ"; bed=$((bed+1)); }
done < <(grep -o '(packages/[a-z0-9-]*)' "$R" | tr -d '()' | sort -u)

for d in "$P"/*/; do
  n="packages/$(basename "$d")"; katalogov=$((katalogov+1))
  grep -q "($n)" "$R" || { echo "  🔴 $n есть в репозитории, но в README НЕ НАЗВАН"; bed=$((bed+1)); }
done

if [ "$ssylok" -eq 0 ] && [ "$katalogov" -gt 0 ]; then
  echo "СЛЕПОТА: в README нет ни одной ссылки на packages/ — сверять не с чем, а каталогов $katalogov"
  exit 2
fi
echo "ИТОГО (сверяю имена в обе стороны): ссылок $ssylok, каталогов $katalogov, расхождений $bed"
[ "$bed" -eq 0 ] || exit 1
echo "сошлось: каждая ссылка ведёт в каталог, каждый каталог назван"
